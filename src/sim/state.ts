/**
 * Сборка начального состояния партии.
 *
 * Единственное место, где GameState рождается из статических данных мира.
 * Дальше состояние только меняется тиком: всё, чего нет здесь, не появится
 * в игре ниоткуда.
 *
 * Функция чистая и детерминированная — один и тот же сид даёт побайтово
 * одинаковый JSON. Это не украшение: сохранение, репорт о баге и прогон
 * баланса воспроизводятся ровно потому, что старт партии не зависит ни от
 * времени запуска, ни от порядка обхода объектов.
 *
 * ГРАНИЦА «ДАННЫЕ / СОСТОЯНИЕ» ПРОХОДИТ ЗДЕСЬ. src/data описывает, какой мир
 * есть: где стоит Тула, куда ведёт М-2, какой элеватор в каком городе. Каким
 * этот мир СТАНОВИТСЯ — население, склады, загрузка предприятий — живёт только
 * в GameState. Поэтому города приезжают сюда как CityStatic и превращаются в
 * City, а у предприятий обнуляется всё, что меняется по ходу партии.
 *
 * СРЕЗ 4 ИЗМЕНИЛ ЗДЕСЬ ОДНО ПРАВИЛО, и оно важнее всех остальных правок файла:
 * характеристики машины больше НЕ ПИШУТСЯ ЧИСЛАМИ. Они берутся из справочника
 * техники (src/data/vehicles.ts), потому что именно там каждый класс проверен
 * на главный инвариант игры. Выписанная здесь руками «шестёрка тонн» означала бы
 * вторую копию баланса — и первая же перебалансировка справочника разошлась бы
 * со стартовой машиной молча, не уронив ни одного теста.
 */

