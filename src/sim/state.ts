/**
 * Класс из справочника или громкая ошибка.
 *
 * Неизвестный идентификатор класса — это опечатка в коде или в сохранении, и
 * тихо подставить умолчание нельзя: машина с нулевым расходом топлива возит
 * бесплатно, а с нулевой грузоподъёмностью не возит вовсе. И то, и другое
 * выглядит как «странный баланс», а не как ошибка, и ищется неделю.
 */
function requireClass(classId: string): VehicleClass {
  const found = VEHICLE_CLASS_BY_ID[classId]
  if (found === undefined) {
    throw new Error(`нет класса техники «${classId}» в справочнике`)
  }
  return found
}

/**
 * Новая машина у ворот города — единственное место, где рождается транспорт.
 *
 * Вынесено из createInitialState нарочно: машину ещё и покупают (buyVehicle в
 * app/store.ts), и купленная обязана быть той же самой, что стартовая. Два
 * места сборки означали бы, что однажды у купленной машины забудут проставить
 * расход топлива — и она поедет возить бесплатно, потому что ноль литров на сто
 * километров стоит ноль рублей. Такой дефект не падает, он просто делает вторую
 * машину выгоднее первой.
 *
 * ВСЕ ХАРАКТЕРИСТИКИ ПРИЕЗЖАЮТ ИЗ СПРАВОЧНИКА и ни одна не пишется числом.
 * Копии в Vehicle всё же лежат (cruiseKmh, fuelPer100Km, capacity), и это не
 * дублирование ради удобства: сохранение обязано пережить перебалансировку
 * справочника, иначе машина, купленная в прошлой версии, задним числом сменит
 * грузоподъёмность посреди рейса.
 *
 * Функция чистая: ни счётчиков, ни генерации идентификатора внутри. Кто зовёт —
 * тот и отвечает за уникальность id, потому что только он видит остальной парк.
 */
export function createVehicle(
  id: VehicleId,
  ownerId: CompanyId,
  at: CityId,
  classId: string = STARTER_CLASS_ID,
  trailer: TrailerType | null = null,
): Vehicle {
  const vehicleClass = requireClass(classId)

  return {
    id,
    ownerId,
    // Стоит в узле, а не на ребре: машина появляется у ворот, а не в середине
    // чужого рейса.
    position: { kind: 'узел', nodeId: at },
    route: [],

    // Без линии. Назначение на линию — отдельное решение игрока, и делать его
    // за него при покупке значило бы отобрать то самое решение, ради которого
    // срез 3 и делался.
    lineId: null,
    stopIndex: 0,
    blockedTicks: 0,

    classId: vehicleClass.id,
    // Прицеп и водитель — ОТДЕЛЬНЫЕ покупки и отдельные решения. Купленный
    // тягач физически не может взять груз и не может тронуться с места, и это
    // ровно то, что игрок должен почувствовать: машина в этой игре — не только
    // тягач.
    trailer,
    driverId: null,

    wear: 0,
    kmSinceService: 0,
    brokenDown: false,

    cruiseKmh: vehicleClass.cruiseKmh,
    fuelPer100Km: vehicleClass.fuelPer100Km,
    odometer: 0,

    capacity: vehicleClass.capacity,
    // Порожняком. Дать машине стартовый груз значило бы подарить игроку первую
    // выручку — а она должна быть заработана рейсом, иначе первое же число в
    // отчёте ничего про игрока не говорит.
    cargo: null,
    // Оба счётчика с нуля. Пробег раскладывается по ним в фазе движения
    // (logistics/vehicle.ts), а разность одометра и их суммы служит фазе
    // прибытия отметкой «сколько проехали с погрузки», по которой считается
    // плечо доставки. Ноль на старте — единственное значение, при котором эта
    // разность с первого километра означает то, что должна.
    loadedKm: 0,
    emptyKm: 0,
  }
}

/**
 * ЗИЛ в стартовой комплектации: класс из справочника и тент.
 *
 * Отдельное имя нужно ровно затем, чтобы «машина, с которой начинается партия»
 * была ОДНИМ объектом на весь проект: её собирает createInitialState, ею же
 * интерфейс оценивает плечо, ещё не зная, на какой машине игрок поедет
 * (ui/lineEconomy.ts). Прицеп здесь есть, в отличие от покупки: стартовая
 * машина обязана уметь работать с первого тика, а купленную игрок комплектует
 * сам.
 */
export function createZil(
  id: VehicleId,
  ownerId: CompanyId,
  at: CityId,
): Vehicle {
  return createVehicle(id, ownerId, at, STARTER_CLASS_ID, STARTER_TRAILER)
}

/**
 * Водитель стартовой машины.
 *
 * Один, а не два: водитель — это постоянный расход (см. DRIVER_WAGE_PER_DAY в
 * data/operating.ts), и запасной человек в резерве проедал бы капитал, ничего
 * не давая. Резерв становится осмысленным, когда машин больше одной, — и тогда
 * игрок нанимает его сам.
 *
 * Ставка считается ТОЙ ЖЕ ФОРМУЛОЙ, что и при найме (wageFor в
 * logistics/driver.ts), а не берётся плоской базой из данных. Вписать сюда
 * DRIVER_WAGE_PER_DAY было бы соблазнительно — баланс среза 3 сошёлся бы до
 * рубля, — но это завело бы в игре две зарплатные формулы: стартовый водитель
 * стоил бы дешевле точно такого же нанятого, и первый же наём выглядел бы
 * несправедливо дорогим. Базовая ставка в данных — это ставка НОВИЧКА, надбавка
 * за навык поверх неё есть у всех, включая своего.
 */
export function createStarterDriver(
  id: DriverId,
  employerId: CompanyId,
  vehicle: VehicleId | null,
): Driver {
  return {
    id,
    name: STARTER_DRIVER_NAME,
    employerId,
    vehicleId: vehicle,
    skill: STARTER_DRIVER_SKILL,
    licenses: [...STARTER_DRIVER_LICENSES],
    // Отдохнувший и не за рулём: партия начинается утром, а не в конце смены.
    fatigue: 0,
    hoursOnDuty: 0,
    wagePerDay: wageFor(STARTER_DRIVER_SKILL, STARTER_DRIVER_LICENSES),
    loyalty: STARTER_DRIVER_LOYALTY,
  }
}

// ─── Начальное состояние ───────────────────────────────────────────────────

/**
 * Начальное состояние партии.
 *
 * Сид — единственный вход. Всё остальное в мире на старте одинаково: разброс
 * начинается с первого тика, а не с расстановки городов.
 */
export function createInitialState(seed: number): GameState {
  const cities = cloneCities()
  const edges = cloneEdges()
  const industries = cloneIndustries()

  // Данные о мире набиваются руками, и опечатка в идентификаторе города иначе
  // всплыла бы только в рендере пустой сценой. Здесь она падает сразу.
  if (!cities[HOME_CITY]) {
    throw new Error(`createInitialState: нет города ${HOME_CITY} в данных мира`)
  }

  // Предприятие в несуществующем городе — не «просто невидимое предприятие»:
  // производство будет исправно копить продукцию, которую физически некуда
  // подать машине, и цепочка порвётся в месте, никак не связанном с опечаткой.
  for (const industry of Object.values(industries)) {
    if (!cities[industry.cityId]) {
      throw new Error(
        `createInitialState: предприятие ${industry.id} стоит в неизвестном городе ${industry.cityId}`,
      )
    }
  }

  const driver = createStarterDriver(
    STARTER_DRIVER_ID,
    PLAYER_ID,
    STARTER_VEHICLE_ID,
  )

  const player: Company = {
    id: PLAYER_ID,
    // ТОО, а не ООО: общества с ограниченной ответственностью появились в
    // законе только в 1998-м, а в 1994-м частная контора на одну машину
    // регистрировалась товариществом. Мелочь, но она задаёт тон эпохи.
    name: 'ТОО «Плечо»',
    money: START_MONEY,
    controller: 'человек',

    // Ни одной линии. Первую сеть проектирует игрок, и предложить ему готовое
    // кольцо значило бы отдать даром ровно то решение, которым срез 3 и
    // отличается от разовых рейсов среза 2.
    lines: {},

    drivers: { [driver.id]: driver },

    // Суточный итог ещё не подводился: первые сутки не прошли. Ноль здесь —
    // это «данных нет», и интерфейс покажет их такими, а не выдумает прибыль.
    dailyRevenue: 0,
    dailyCosts: 0,

    // Партия начинается не в долгах. Счётчик суток в минусе отсчитывается с
    // нуля и обнуляется, как только компания выбралась, — см. Company в
    // types.ts о том, почему банкротство это отдельный флаг, а не проверка
    // «деньги меньше нуля».
    bankrupt: false,
    daysInDebt: 0,
  }

  // Связь машины и водителя ДВУСТОРОННЯЯ, как и связь машины с линией: машина
  // помнит, кто за рулём, водитель — за какой машиной закреплён. Первому вопрос
  // задаёт фаза движения, второму — интерфейс парка, и обход всех машин ради
  // второго ответа на каждый кадр того не стоит.
  const truck: Vehicle = {
    ...createZil(STARTER_VEHICLE_ID, PLAYER_ID, HOME_CITY),
    driverId: driver.id,
  }

  return {
    // Сид прогоняется через тот же конструктор, что и рабочий генератор: он
    // приводит число к 32 битам, и сиды 1 и 2^32+1 дают одинаковое состояние —
    // а значит и одинаковый JSON, на который опираются тесты детерминизма.
    rngState: Rng.from(seed).seed,
    tick: 0,
    startYear: START_YEAR,
    world: { cities, edges, industries },
    companies: { [PLAYER_ID]: player },
    playerId: PLAYER_ID,
    vehicles: { [STARTER_VEHICLE_ID]: truck },
  }
}
