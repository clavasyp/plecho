/**
 * Сборка начального состояния партии.
 *
 * Единственное место, где GameState рождается из статических данных мира.
 * Дальше состояние только меняется тиком: всё, чего нет здесь, не появится
 * в игре ниоткуда.
 *
 * Функция чистая и детерминированная — один и тот же сид даёт побайтово
 * одинаковый JSON. Это не украшение: сохранение, репорт о баге и прогон
 * баланса воспроизводятся ровно потому, что старт партии не зависит ни от
 * времени запуска, ни от порядка обхода объектов.
 *
 * ГРАНИЦА «ДАННЫЕ / СОСТОЯНИЕ» ПРОХОДИТ ЗДЕСЬ. src/data описывает, какой мир
 * есть: где стоит Тула, куда ведёт М-2, какой элеватор в каком городе. Каким
 * этот мир СТАНОВИТСЯ — население, склады, загрузка предприятий — живёт только
 * в GameState. Поэтому города приезжают сюда как CityStatic и превращаются в
 * City, а у предприятий обнуляется всё, что меняется по ходу партии.
 */

import { CITIES } from '../data/cities'
import { INDUSTRIES } from '../data/industries'
import { DRIVER_WAGE_PER_DAY } from '../data/operating'
import { EDGES } from '../data/roads'
import { Rng } from './rng'
import { cityId, companyId, vehicleId } from './types'
import type {
  City,
  CityId,
  Company,
  CompanyId,
  Edge,
  EdgeId,
  GameState,
  Industry,
  IndustryId,
  Vehicle,
  VehicleId,
} from './types'

/**
 * Год начала партии. 1994-й — исходная точка кампании: разваленный автопарк,
 * работающие ещё советские заводы и пустая ниша частных перевозок.
 */
export const START_YEAR = 1994

/** Компания игрока. Идентификатор говорящий: в отладке видно, чей объект. */
export const PLAYER_ID: CompanyId = companyId('player')

/** Единственная машина на старте. */
export const STARTER_VEHICLE_ID: VehicleId = vehicleId('zil-1')

/**
 * Домашний город. Москва — не только крупнейший узел графа, но и город, из
 * которого выходят семь федеральных лучей: новичок физически не может
 * заблудиться, а порожнее обратное плечо чувствует с первого же рейса.
 */
export const HOME_CITY: CityId = cityId('moscow')

/**
 * Крейсерская скорость стартовой машины, км/ч.
 *
 * ЗИЛ-130 из девяностых. Паспортный максимум 90 км/ч — это порожняком и на
 * ровном; гружёная машина держит меньше, а ПДД разрешают грузовику вне
 * населённых пунктов те самые 70. Берём 70 как скорость по ИДЕАЛЬНОЙ дороге:
 * класс трассы и качество покрытия срежут её дальше, в логистике движения.
 * Числом выше пришлось бы компенсировать штрафами, и старый ЗИЛ поехал бы
 * по М-2 быстрее, чем ездил в жизни.
 */
export const STARTER_CRUISE_KMH = 70

/**
 * Грузоподъёмность стартовой машины, тонн.
 *
 * ЗИЛ-130 поздних серий берёт 6 тонн. Цифра менялась вместе с машиной: первые
 * выпуски 1964 года возили 4 тонны, с 1966-го 5, и только с 1986 года
 * паспортная грузоподъёмность стала 6. В 1994-м на вторичном рынке ходили
 * именно поздние машины, поэтому 6 — не «примерно шесть», а конкретная модель.
 *
 * Это число задаёт масштаб всей экономики среза. Элеватор отгружает 60 тонн в
 * сутки (data/recipes.ts) — значит один ЗИЛ вывозит его суточный выпуск ровно
 * за десять ходок, а таких ходок за сутки не сделать ни на каком плече. Игра
 * сообщает главное про себя без единой строчки текста: одной машиной цепочку
 * не удержать, и вторая нужна не для красоты.
 */
export const STARTER_CAPACITY_TONS = 6

/**
 * Расход топлива стартовой машины, литров на 100 км.
 *
 * ЗИЛ-130 с карбюраторным ЗИЛ-508: контрольный расход по паспорту 29 л/100 км
 * при 60 км/ч, эксплуатационная норма Минтранса для этой модели — 31. Разница
 * между «по паспорту на ровном» и «как ездит» здесь невелика, поэтому берём 30
 * без всяких поправочных коэффициентов: круглое число, лежащее ровно между
 * двумя настоящими, и по нему же посчитана сходимость в data/operating.ts.
 *
 * Расход НЕ зависит от загрузки, и это не упрощение ради простоты. Порожний
 * рейс должен жечь ровно столько же, сколько гружёный, — иначе главный урок
 * игры размывается: холостое плечо станет «дешевле», и порожний пробег снова
 * превратится в число из отчёта вместо денег. Разница в расходе гружёной и
 * порожней машины в жизни есть, но она порядка десяти процентов и не стоит
 * того, чтобы притуплять единственную механику, ради которой всё затевалось.
 */
export const STARTER_FUEL_PER_100KM = 30

/**
 * Какую долю новой машины даёт стартовый капитал.
 *
 * Две трети — это «вторая машина видна, но не куплена». Полная цена на старте
 * убила бы первое решение игры (расширяться или сначала научиться возить),
 * четверть цены сделала бы вторую машину настолько далёкой, что копить на неё
 * пришлось бы вслепую. Две трети означают: одно удачное кольцо — и покупка
 * реальна, одно неудачное — и она отодвинулась.
 */
/**
 * Стартовый капитал считается в СУТКАХ ПРОСТОЯ, а не в долях цены машины.
 *
 * Привязка к цене грузовика выглядела логично, но означала не то: цена машины
 * выводится из окупаемости кольца и меняется при каждой перебалансировке
 * тарифа, утаскивая за собой стартовый капитал. Когда ЗИЛ подешевел с сорока
 * пяти тысяч до двадцати, у игрока осталось девять с половиной суток на то,
 * чтобы разобраться в интерфейсе, — вместо двух недель, заложенных замыслом.
 *
 * Капитал отвечает на вопрос «сколько у игрока времени до первой выручки»,
 * поэтому и измеряется временем. Три недели: хватает разобраться и построить
 * первое кольцо, не хватает пересидеть партию в гараже.
 */
const START_IDLE_DAYS = 21

/**
 * Стартовый капитал, рублей.
 *
 * ЕДИНИЦА. Игровой рубль — деноминированный, то есть образца 1998 года и
 * позже. В 1994-м таких денег не было, счёт шёл на миллионы, но игра идёт до
 * 2030-х, и номинал 1994 года пришлось бы делить на тысячу посреди партии.
 * Множитель 1/1000 держим один раз здесь, в исторической справке, а не в
 * экономике.
 *
 * СУММА ПЕРЕСМОТРЕНА ПОД СРЕЗ 3. Прежние 6 000 были выведены из выручки одного
 * рейса в мире, где расходов не существовало вовсе. Теперь машина жжёт топливо
 * (30 л/100 км × 35 руб = 10.5 руб/км), изнашивается (4.5 руб/км) и платит
 * водителю 1 400 руб в сутки независимо от того, едет она или стоит. На этой
 * шкале 6 000 — это четыре часа хода: партия кончалась бы раньше, чем игрок
 * дочитал бы правила.
 *
 * Сумма выведена ОТ ЦЕНЫ МАШИНЫ, а не от выручки рейса, и это осознанная смена
 * меры. Выручка рейса перестала быть содержательной величиной — сама по себе
 * она ничего не говорит, пока не вычтешь из неё расходы того же рейса. А вот
 * цена машины — это ровно та цель, к которой игрок идёт весь первый час, и
 * привязка к ней держится при любой перебалансировке: подорожает ЗИЛ —
 * подорожает и старт, и смысл «второй машины сразу не купить» уцелеет.
 *
 * Что 30 000 означают на практике, с трёх сторон:
 *
 *   вторая машина     45 000 — не хватает ровно на треть, копить надо работой
 *   плохое кольцо     около 10 000 руб/сутки убытка — столько теряет линия с
 *                     порожним обратным плечом (замер в tick.test.ts). Трое
 *                     суток на то, чтобы понять, что сеть спроектирована
 *                     неверно, и ещё месяц отсрочки на её перестройку
 *   полный простой    1 400 руб/сутки зарплаты — три недели до нуля и ещё
 *                     месяц отсрочки до банкротства (BANKRUPTCY_GRACE_DAYS)
 *
 * Последняя строка — самая важная. «Ничего не делать» теперь тоже проигрыш, а
 * не бесконечное ожидание: сидящая в гараже машина проедает капитал сама. Это
 * проверяется прогоном в tick.test.ts, где партия без единой линии доходит до
 * банкротства.
 */
export const START_MONEY = Math.round(START_IDLE_DAYS * DRIVER_WAGE_PER_DAY)

/**
 * Копия справочника городов, развёрнутая в игровое состояние.
 *
 * Данные копируются, а не берутся ссылкой на модуль. Города пока неизменяемы,
 * но население уже растёт в срезе 2, и общий объект означал бы, что рост в
 * одной партии протекает в следующую и в соседний тест. Сохранение обязано
 * быть самодостаточным: JSON.parse не должен зависеть от того, что лежит в
 * модуле данных этой сборки.
 *
 * Здесь же CityStatic становится City. Пустой склад и нулевой suppliedDays —
 * не «данные по умолчанию», а утверждение: партия начинается в мире, где ещё
 * ничего не привезли. Всё, что появится на городских складах, доставит игрок.
 */
function cloneCities(): Record<CityId, City> {
  const cities: Record<CityId, City> = {}
  for (const city of CITIES) {
    cities[city.id] = {
      ...city,
      coord: { ...city.coord },
      stock: {},
      // Ноль, а не «город как-то жил до нас»: право на рост нужно заслужить
      // поставками, и отсчёт начинается с первой из них.
      suppliedDays: 0,
    }
  }
  return cities
}

/** Копия графа дорог — по той же причине: качество покрытия будет меняться. */
function cloneEdges(): Record<EdgeId, Edge> {
  const edges: Record<EdgeId, Edge> = {}
  for (const edge of EDGES) {
    edges[edge.id] = { ...edge }
  }
  return edges
}

/**
 * Копия справочника предприятий.
 *
 * Склад копируется отдельным объектом, а не спредом верхнего уровня: `{...ind}`
 * оставил бы обе партии с ОДНИМ И ТЕМ ЖЕ объектом stock, и первая же тонна
 * зерна, произведённая в одной игре, появилась бы во второй. Ошибка тихая —
 * состояние выглядит правильным, пока кто-нибудь не запустит два прогона
 * подряд, — поэтому она закрыта тестом, а не только этим комментарием.
 *
 * СОДЕРЖИМОЕ СКЛАДА ЗДЕСЬ НЕ ОБНУЛЯЕТСЯ, в отличие от городского. Разница не в
 * непоследовательности, а в том, что эти два склада описывают разное. Городской
 * склад — это привезённое игроком, и до первого рейса привезти его никто не мог.
 * Складом предприятия данные описывают САМ МИР: заводы работали и до 1994 года,
 * у них лежит вчерашняя невывезенная смена и запас сырья на несколько суток.
 * Обоснование величин — в src/data/industries.ts, и переопределять их здесь
 * значило бы держать баланс в двух местах. Партия начинается в живом мире,
 * которому нужен транспорт, а не на пепелище.
 */
function cloneIndustries(): Record<IndustryId, Industry> {
  const industries: Record<IndustryId, Industry> = {}
  for (const industry of INDUSTRIES) {
    industries[industry.id] = { ...industry, stock: { ...industry.stock } }
  }
  return industries
}

/**
 * Новый ЗИЛ у ворот города — единственное место, где рождается машина.
 *
 * Вынесено из createInitialState нарочно: в срезе 3 машину покупают (buyVehicle
 * в app/store.ts), и купленная обязана быть той же самой, что стартовая. Два
 * места сборки означали бы, что однажды у купленной машины забудут проставить
 * расход топлива — и она поедет возить бесплатно, потому что ноль литров на сто
 * километров стоит ноль рублей. Такой дефект не падает, он просто делает вторую
 * машину выгоднее первой.
 *
 * Функция чистая: ни счётчиков, ни генерации идентификатора внутри. Кто зовёт —
 * тот и отвечает за уникальность id, потому что только он видит остальной парк.
 */
export function createZil(
  id: VehicleId,
  ownerId: CompanyId,
  at: CityId,
): Vehicle {
  return {
    id,
    ownerId,
    // Стоит в узле, а не на ребре: машина появляется у ворот, а не в середине
    // чужого рейса.
    position: { kind: 'узел', nodeId: at },
    route: [],

    // Без линии. Назначение на линию — отдельное решение игрока, и делать его
    // за него при покупке значило бы отобрать то самое решение, ради которого
    // срез и делался.
    lineId: null,
    stopIndex: 0,
    blockedTicks: 0,

    cruiseKmh: STARTER_CRUISE_KMH,
    fuelPer100Km: STARTER_FUEL_PER_100KM,
    odometer: 0,

    capacity: STARTER_CAPACITY_TONS,
    // Порожняком. Дать машине стартовый груз значило бы подарить игроку первую
    // выручку — а она должна быть заработана рейсом, иначе первое же число в
    // отчёте ничего про игрока не говорит.
    cargo: null,
    // Оба счётчика с нуля. Пробег раскладывается по ним в фазе движения
    // (logistics/vehicle.ts), а разность одометра и их суммы служит фазе
    // прибытия отметкой «сколько проехали с погрузки», по которой считается
    // плечо доставки. Ноль на старте — единственное значение, при котором эта
    // разность с первого километра означает то, что должна.
    loadedKm: 0,
    emptyKm: 0,
  }
}

/**
 * Начальное состояние партии.
 *
 * Сид — единственный вход. Всё остальное в мире на старте одинаково: разброс
 * начинается с первого тика, а не с расстановки городов.
 */
export function createInitialState(seed: number): GameState {
  const cities = cloneCities()
  const edges = cloneEdges()
  const industries = cloneIndustries()

  // Данные о мире набиваются руками, и опечатка в идентификаторе города иначе
  // всплыла бы только в рендере пустой сценой. Здесь она падает сразу.
  if (!cities[HOME_CITY]) {
    throw new Error(`createInitialState: нет города ${HOME_CITY} в данных мира`)
  }

  // Предприятие в несуществующем городе — не «просто невидимое предприятие»:
  // производство будет исправно копить продукцию, которую физически некуда
  // подать машине, и цепочка порвётся в месте, никак не связанном с опечаткой.
  for (const industry of Object.values(industries)) {
    if (!cities[industry.cityId]) {
      throw new Error(
        `createInitialState: предприятие ${industry.id} стоит в неизвестном городе ${industry.cityId}`,
      )
    }
  }

  const player: Company = {
    id: PLAYER_ID,
    // ТОО, а не ООО: общества с ограниченной ответственностью появились в
    // законе только в 1998-м, а в 1994-м частная контора на одну машину
    // регистрировалась товариществом. Мелочь, но она задаёт тон эпохи.
    name: 'ТОО «Плечо»',
    money: START_MONEY,
    controller: 'человек',

    // Ни одной линии. Первую сеть проектирует игрок, и предложить ему готовое
    // кольцо значило бы отдать даром ровно то решение, которым срез 3 и
    // отличается от разовых рейсов среза 2.
    lines: {},

    // Суточный итог ещё не подводился: первые сутки не прошли. Ноль здесь —
    // это «данных нет», и интерфейс покажет их такими, а не выдумает прибыль.
    dailyRevenue: 0,
    dailyCosts: 0,

    // Партия начинается не в долгах. Счётчик суток в минусе отсчитывается с
    // нуля и обнуляется, как только компания выбралась, — см. Company в
    // types.ts о том, почему банкротство это отдельный флаг, а не проверка
    // «деньги меньше нуля».
    bankrupt: false,
    daysInDebt: 0,
  }

  const truck = createZil(STARTER_VEHICLE_ID, PLAYER_ID, HOME_CITY)

  return {
    // Сид прогоняется через тот же конструктор, что и рабочий генератор: он
    // приводит число к 32 битам, и сиды 1 и 2^32+1 дают одинаковое состояние —
    // а значит и одинаковый JSON, на который опираются тесты детерминизма.
    rngState: Rng.from(seed).seed,
    tick: 0,
    startYear: START_YEAR,
    world: { cities, edges, industries },
    companies: { [PLAYER_ID]: player },
    playerId: PLAYER_ID,
    vehicles: { [STARTER_VEHICLE_ID]: truck },
  }
}
