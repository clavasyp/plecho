/**
 * Стартовый капитал считается в СУТКАХ ПРОСТОЯ, а не в долях цены машины.
 *
 * Привязка к цене грузовика выглядела логично, но означала не то: цена машины
 * выводится из окупаемости кольца и меняется при каждой перебалансировке
 * тарифа, утаскивая за собой стартовый капитал. Когда ЗИЛ подешевел с сорока
 * пяти тысяч до двадцати, у игрока осталось девять с половиной суток на то,
 * чтобы разобраться в интерфейсе, — вместо двух недель, заложенных замыслом.
 *
 * Капитал отвечает на вопрос «сколько у игрока времени до первой выручки»,
 * поэтому и измеряется временем. Три недели: хватает разобраться и построить
 * первое кольцо, не хватает пересидеть партию в гараже.
 */

/**
 * Запас на смену специализации, рубли.
 *
 * ВТОРАЯ РОЛЬ СТАРТОВОГО КАПИТАЛА, ПОЯВИВШАЯСЯ В СРЕЗЕ 4. До прицепов машина
 * могла взять любой груз, и решение «что возить» ничего не стоило. Теперь оно
 * стоит прицепа: игрок, начавший с тентом на зерновой цепочке и решивший, что
 * ошибся, обязан иметь возможность купить зерновоз — иначе первое же решение
 * партии оказывается необратимым, а необратимое решение, принятое до того, как
 * игрок понял правила, это не решение, а ловушка.
 *
 * Берётся САМЫЙ ДОРОГОЙ прицеп стартового класса, а не средний и не тот, что
 * стоит на машине: запас обязан покрывать любую смену специализации, какая
 * машине доступна, иначе он покрывает не все, и игрок узнаёт об этом в момент
 * покупки.
 */
export const RESPEC_RESERVE = Math.max(
  ...STARTER_CLASS.trailers.map((trailer) => TRAILER_PRICE[trailer] ?? 0),
)

/**
 * Стартовый капитал, рублей.
 *
 * ЕДИНИЦА. Игровой рубль — деноминированный, то есть образца 1998 года и
 * позже. В 1994-м таких денег не было, счёт шёл на миллионы, но игра идёт до
 * 2030-х, и номинал 1994 года пришлось бы делить на тысячу посреди партии.
 * Множитель 1/1000 держим один раз здесь, в исторической справке, а не в
 * экономике.
 *
 * СУММА = ВРЕМЯ ПРОСТОЯ + ОДИН ПРИЦЕП. Три недели зарплаты (14 700) отвечают за
 * «сколько у игрока времени до первой выручки», запас на прицеп (9 000) — за
 * «можно ли передумать». Складывать их в одно необъяснимое число нельзя: они
 * меняются от разных причин и по-разному, а объяснить итог задним числом уже не
 * получится.
 *
 * ВРЕМЯ СЧИТАЕТСЯ В БАЗОВЫХ СУТКАХ ВОДИТЕЛЯ, а не в ставке того конкретного
 * человека, который сидит за рулём. Причина простая: капитал — величина мира, а
 * не свойство одного водителя, и привязать его к чьей-то персональной надбавке
 * значило бы менять стартовые условия партии от того, кому какой навык выпал.
 * Реальный запас времени при этом чуть иной, чем написано в START_IDLE_DAYS, и
 * это нормально — обе величины проверяются тестом на своих границах.
 *
 * ЧЕМ ЭТО ОБЕРНУЛОСЬ ДЛЯ ВТОРОЙ МАШИНЫ. Прежнее правило звучало «капитала
 * меньше, чем стоит ЗИЛ», и держало игрока от покупки в первый же день. С
 * прицепами оно перестало быть верным ПО ФОРМЕ и осталось верным ПО СУТИ:
 * 23 700 больше цены голого ЗИЛа (20 000), но меньше цены РАБОТАЮЩЕЙ машины —
 * тягач плюс самый дешёвый прицеп это 26 000, а на ней ещё должен кто-то
 * ездить. Купивший «вторую машину» в первый день получает железо, которое не
 * может взять ни одного груза, и остаётся без денег на зарплату. Это честная
 * ловушка ровно в той мере, в какой игра про парк обязана учить, что машина —
 * это не только тягач; проверяется тестом в state.test.ts.
 */
/**
 * Стартовый капитал зажат между двумя требованиями, и это его и определяет.
 *
 *   СНИЗУ  — обязан хватать на смену специализации: самый дорогой прицеп
 *            (реф, 24 000) игрок должен мочь купить сразу, иначе первое
 *            решение «под что затачивать машину» превращается в накопление.
 *   СВЕРХУ — не должен хватать на вторую РАБОТАЮЩУЮ машину, то есть на
 *            дешёвый класс вместе с дешёвым прицепом (20 000 + 6 000).
 *
 * Окно узкое, 24 000…26 000, и другого нет: это прямое следствие цен из
 * справочника техники. Двадцать пять тысяч — его середина. Прежняя формула
 * «столько-то суток простоя плюс резерв» давала 35 700 и разрешала купить
 * второй грузовик на старте, убивая первое решение игры.
 *
 * Побочно это тридцать пять суток простоя вместо задуманных двадцати одного:
 * многовато, но пересидеть партию в гараже по-прежнему нельзя, а нарушать
 * ценовое окно ради круглого числа суток было бы хуже.
 */
export const START_MONEY = 25_000

// ─── Копии данных мира ─────────────────────────────────────────────────────

/**
 * Копия справочника городов, развёрнутая в игровое состояние.
 *
 * Данные копируются, а не берутся ссылкой на модуль. Города пока неизменяемы,
 * но население уже растёт в срезе 2, и общий объект означал бы, что рост в
 * одной партии протекает в следующую и в соседний тест. Сохранение обязано
 * быть самодостаточным: JSON.parse не должен зависеть от того, что лежит в
 * модуле данных этой сборки.
 *
 * Здесь же CityStatic становится City. Пустой склад и нулевой suppliedDays —
 * не «данные по умолчанию», а утверждение: партия начинается в мире, где ещё
 * ничего не привезли. Всё, что появится на городских складах, доставит игрок.
 */
function cloneCities(): Record<CityId, City> {
  const cities: Record<CityId, City> = {}
  for (const city of CITIES) {
    cities[city.id] = {
      ...city,
      coord: { ...city.coord },
      stock: {},
      // Ноль, а не «город как-то жил до нас»: право на рост нужно заслужить
      // поставками, и отсчёт начинается с первой из них.
      suppliedDays: 0,
    }
  }
  return cities
}

/** Копия графа дорог — по той же причине: качество покрытия будет меняться. */
function cloneEdges(): Record<EdgeId, Edge> {
  const edges: Record<EdgeId, Edge> = {}
  for (const edge of EDGES) {
    edges[edge.id] = { ...edge }
  }
  return edges
}

/**
 * Копия справочника предприятий.
 *
 * Склад копируется отдельным объектом, а не спредом верхнего уровня: `{...ind}`
 * оставил бы обе партии с ОДНИМ И ТЕМ ЖЕ объектом stock, и первая же тонна
 * зерна, произведённая в одной игре, появилась бы во второй. Ошибка тихая —
 * состояние выглядит правильным, пока кто-нибудь не запустит два прогона
 * подряд, — поэтому она закрыта тестом, а не только этим комментарием.
 *
 * СОДЕРЖИМОЕ СКЛАДА ЗДЕСЬ НЕ ОБНУЛЯЕТСЯ, в отличие от городского. Разница не в
 * непоследовательности, а в том, что эти два склада описывают разное. Городской
 * склад — это привезённое игроком, и до первого рейса привезти его никто не мог.
 * Складом предприятия данные описывают САМ МИР: заводы работали и до 1994 года,
 * у них лежит вчерашняя невывезенная смена и запас сырья на несколько суток.
 * Обоснование величин — в src/data/industries.ts, и переопределять их здесь
 * значило бы держать баланс в двух местах. Партия начинается в живом мире,
 * которому нужен транспорт, а не на пепелище.
 */
function cloneIndustries(): Record<IndustryId, Industry> {
  const industries: Record<IndustryId, Industry> = {}
  for (const industry of INDUSTRIES) {
    industries[industry.id] = { ...industry, stock: { ...industry.stock } }
  }
  return industries
}

// ─── Сборка машины ─────────────────────────────────────────────────────────

/**
 * Класс из справочника или громкая ошибка.
 *
 * Неизвестный идентификатор класса — это опечатка в коде или в сохранении, и
 * тихо подставить умолчание нельзя: машина с нулевым расходом топлива возит
 * бесплатно, а с нулевой грузоподъёмностью не возит вовсе. И то, и другое
 * выглядит как «странный баланс», а не как ошибка, и ищется неделю.
 */
function requireClass(classId: string): VehicleClass {
  const found = VEHICLE_CLASS_BY_ID[classId]
  if (found === undefined) {
    throw new Error(`нет класса техники «${classId}» в справочнике`)
  }
  return found
}

/**
 * Новая машина у ворот города — единственное место, где рождается транспорт.
 *
 * Вынесено из createInitialState нарочно: машину ещё и покупают (buyVehicle в
 * app/store.ts), и купленная обязана быть той же самой, что стартовая. Два
 * места сборки означали бы, что однажды у купленной машины забудут проставить
 * расход топлива — и она поедет возить бесплатно, потому что ноль литров на сто
 * километров стоит ноль рублей. Такой дефект не падает, он просто делает вторую
 * машину выгоднее первой.
 *
 * ВСЕ ХАРАКТЕРИСТИКИ ПРИЕЗЖАЮТ ИЗ СПРАВОЧНИКА и ни одна не пишется числом.
 * Копии в Vehicle всё же лежат (cruiseKmh, fuelPer100Km, capacity), и это не
 * дублирование ради удобства: сохранение обязано пережить перебалансировку
 * справочника, иначе машина, купленная в прошлой версии, задним числом сменит
 * грузоподъёмность посреди рейса.
 *
 * Функция чистая: ни счётчиков, ни генерации идентификатора внутри. Кто зовёт —
 * тот и отвечает за уникальность id, потому что только он видит остальной парк.
 */
export function createVehicle(
  id: VehicleId,
  ownerId: CompanyId,
  at: CityId,
  classId: string = STARTER_CLASS_ID,
  trailer: TrailerType | null = null,
): Vehicle {
  const vehicleClass = requireClass(classId)

  return {
    id,
    ownerId,
    // Стоит в узле, а не на ребре: машина появляется у ворот, а не в середине
    // чужого рейса.
    position: { kind: 'узел', nodeId: at },
    route: [],

    // Без линии. Назначение на линию — отдельное решение игрока, и делать его
    // за него при покупке значило бы отобрать то самое решение, ради которого
    // срез 3 и делался.
    lineId: null,
    stopIndex: 0,
    blockedTicks: 0,

    /*
     * СЧЁТЧИКИ ОБСЛУЖИВАНИЯ С НУЛЯ, И НОЛЬ ЗДЕСЬ ЗНАЧИМ.
     *
     * serviceTicksLeft = 0 читается всей игрой как «машина свободна»: фаза
     * прибытия по этому нулю решает, что тонны можно переваливать, а
     * диспетчеризация — что машину можно отправлять (разбор стыка — в шапках
     * logistics/loading.ts и logistics/service.ts). Ненулевое значение у новой
     * машины означало бы грузовик, который приехал с завода уже стоящим под
     * чужой погрузкой, и первые часы партии он бы просто не двигался.
     *
     * queuedTicks — диагностика, и её ноль означает «эта машина ещё нигде не
     * стояла в очереди». Начать с ненулевого значения значило бы показать игроку
     * узкое место, которого он не создавал.
     */
    serviceTicksLeft: 0,
    queuedTicks: 0,

    classId: vehicleClass.id,
    // Прицеп и водитель — ОТДЕЛЬНЫЕ покупки и отдельные решения. Купленный
    // тягач физически не может взять груз и не может тронуться с места, и это
    // ровно то, что игрок должен почувствовать: машина в этой игре — не только
    // тягач.
    trailer,
    driverId: null,

    wear: 0,
    kmSinceService: 0,
    brokenDown: false,

    cruiseKmh: vehicleClass.cruiseKmh,
    fuelPer100Km: vehicleClass.fuelPer100Km,
    odometer: 0,

    capacity: vehicleClass.capacity,
    // Порожняком. Дать машине стартовый груз значило бы подарить игроку первую
    // выручку — а она должна быть заработана рейсом, иначе первое же число в
    // отчёте ничего про игрока не говорит.
    cargo: null,
    // Оба счётчика с нуля. Пробег раскладывается по ним в фазе движения
    // (logistics/vehicle.ts), а разность одометра и их суммы служит фазе
    // прибытия отметкой «сколько проехали с погрузки», по которой считается
    // плечо доставки. Ноль на старте — единственное значение, при котором эта
    // разность с первого километра означает то, что должна.
    loadedKm: 0,
    emptyKm: 0,
  }
}

/**
 * ЗИЛ в стартовой комплектации: класс из справочника и тент.
 *
 * Отдельное имя нужно ровно затем, чтобы «машина, с которой начинается партия»
 * была ОДНИМ объектом на весь проект: её собирает createInitialState, ею же
 * интерфейс оценивает плечо, ещё не зная, на какой машине игрок поедет
 * (ui/lineEconomy.ts). Прицеп здесь есть, в отличие от покупки: стартовая
 * машина обязана уметь работать с первого тика, а купленную игрок комплектует
 * сам.
 */
export function createZil(
  id: VehicleId,
  ownerId: CompanyId,
  at: CityId,
): Vehicle {
  return createVehicle(id, ownerId, at, STARTER_CLASS_ID, STARTER_TRAILER)
}

/**
 * Водитель стартовой машины.
 *
 * Один, а не два: водитель — это постоянный расход (см. DRIVER_WAGE_PER_DAY в
 * data/operating.ts), и запасной человек в резерве проедал бы капитал, ничего
 * не давая. Резерв становится осмысленным, когда машин больше одной, — и тогда
 * игрок нанимает его сам.
 *
 * Ставка считается ТОЙ ЖЕ ФОРМУЛОЙ, что и при найме (wageFor в
 * logistics/driver.ts), а не берётся плоской базой из данных. Вписать сюда
 * DRIVER_WAGE_PER_DAY было бы соблазнительно — баланс среза 3 сошёлся бы до
 * рубля, — но это завело бы в игре две зарплатные формулы: стартовый водитель
 * стоил бы дешевле точно такого же нанятого, и первый же наём выглядел бы
 * несправедливо дорогим. Базовая ставка в данных — это ставка НОВИЧКА, надбавка
 * за навык поверх неё есть у всех, включая своего.
 */
export function createStarterDriver(
  id: DriverId,
  employerId: CompanyId,
  vehicle: VehicleId | null,
  /**
   * Имя. По умолчанию — водитель игрока.
   *
   * Единственное, чем стартовые водители компаний отличаются друг от друга.
   * Навык, допуски, усталость и ставка обязаны совпадать до последнего знака:
   * иначе кто-то начинает партию с более экономичным водителем, а это фора,
   * которую никто не выбирал.
   */
  name: string = STARTER_DRIVER_NAME,
): Driver {
  return {
    id,
    name,
    employerId,
    vehicleId: vehicle,
    skill: STARTER_DRIVER_SKILL,
    licenses: [...STARTER_DRIVER_LICENSES],
    // Отдохнувший и не за рулём: партия начинается утром, а не в конце смены.
    fatigue: 0,
    hoursOnDuty: 0,
    wagePerDay: wageFor(STARTER_DRIVER_SKILL, STARTER_DRIVER_LICENSES),
    loyalty: STARTER_DRIVER_LOYALTY,
  }
}

// ─── Основание компании ────────────────────────────────────────────────────

/** Чем одна компания на старте отличается от другой. Список исчерпывающий. */
type CompanySeed = {
  id: CompanyId
  name: string
  controller: Company['controller']
  personality: CompetitorPersonality | null
  vehicleId: VehicleId
  driverId: DriverId
  driverName: string
}

/**
 * Компания у ворот в первый день: контора, машина и человек за рулём.
 *
 * ОДНА СБОРКА НА ИГРОКА И НА КОНКУРЕНТА, И ЭТО ГЛАВНОЕ ТРЕБОВАНИЕ СРЕЗА 6,
 * выраженное в коде, а не в обещании. Равенство стартовых условий проверяется
 * тестом, но держится не тестом: второго места, где записано, сколько у компании
 * денег и какая у неё машина, в проекте нет. Дай конкуренту собственную сборку —
 * и однажды кто-то поправит одну из двух, а разойдутся они молча, потому что обе
 * останутся правдоподобными.
 *
 * ВСЕ ГАРАЖИ В МОСКВЕ, включая конкурентские. Соблазн развести конторы по разным
 * городам («так живее») — это ровно та фора, которой быть не должно: контора в
 * Орле стоит у элеватора, контора в Смоленске — у нефтебазы, и стартовое
 * расстояние до цепочки становится преимуществом, которое никто не выбирал.
 * Москва одинаково удалена от всех трёх цепочек и из неё выходят семь федеральных
 * лучей — единственная точка карты, где «одинаково» означает именно одинаково.
 *
 * ОЧЕРЕДЬ КОМАНД И ЛЕНТА МЫСЛЕЙ ПУСТЫ. Пустая очередь означает «решений ещё не
 * принимали»: первую партию команд конкурент получит от фазы решений в конце
 * первых игровых суток. Заполнить её здесь значило бы дать конкуренту ход до
 * начала партии.
 */
function foundCompany(seed: CompanySeed): { company: Company; vehicle: Vehicle } {
  const driver = createStarterDriver(
    seed.driverId,
    seed.id,
    seed.vehicleId,
    seed.driverName,
  )

  // Связь машины и водителя ДВУСТОРОННЯЯ, как и связь машины с линией: машина
  // помнит, кто за рулём, водитель — за какой машиной закреплён. Первому вопрос
  // задаёт фаза движения, второму — интерфейс парка, и обход всех машин ради
  // второго ответа на каждый кадр того не стоит.
  const vehicle: Vehicle = {
    ...createZil(seed.vehicleId, seed.id, HOME_CITY),
    driverId: driver.id,
  }

  const company: Company = {
    id: seed.id,
    name: seed.name,
    money: START_MONEY,
    controller: seed.controller,

    // Ни одной линии. Первую сеть проектирует и игрок, и конкурент — каждый
    // сам. Раздать готовые кольца значило бы отобрать у игрока то решение, ради
    // которого срез 3 и делался, а у конкурента — его характер: агрессивный и
    // осторожный отличаются как раз тем, КАКОЕ кольцо они себе построят.
    lines: {},

    drivers: { [driver.id]: driver },

    /*
     * НИ ОДНОЙ ПОСТРОЙКИ, И ЭТО ГЛАВНОЕ УСЛОВИЕ СРЕЗА 5.
     *
     * Пустой список означает, что на старте у компании в каждом городе ровно
     * BASE_POSTS постов — один (см. data/infrastructure.ts). Вторая машина,
     * поставленная на тот же завод, немедленно встаёт в очередь, и узкое место
     * обнаруживается на ВТОРОМ грузовике, пока сеть ещё маленькая и понятная.
     *
     * Подарить стартовый терминал значило бы отложить это открытие до той поры,
     * когда у компании двадцать машин и разбираться уже поздно, — а заодно
     * отобрать первое решение среза: расшивать ли узкое место постройкой или
     * перестройкой линий.
     */
    buildings: {},

    personality: seed.personality,
    pendingCommands: [],
    thinking: [],

    // Суточный итог ещё не подводился: первые сутки не прошли. Ноль здесь —
    // это «данных нет», и интерфейс покажет их такими, а не выдумает прибыль.
    dailyRevenue: 0,
    dailyCosts: 0,

    // Партия начинается не в долгах. Счётчик суток в минусе отсчитывается с
    // нуля и обнуляется, как только компания выбралась, — см. Company в
    // types.ts о том, почему банкротство это отдельный флаг, а не проверка
    // «деньги меньше нуля».
    bankrupt: false,
    daysInDebt: 0,
  }

  return { company, vehicle }
}

// ─── Начальное состояние ───────────────────────────────────────────────────

/**
 * Начальное состояние партии.
 *
 * Сид — единственный вход. Всё остальное в мире на старте одинаково: разброс
 * начинается с первого тика, а не с расстановки городов.
 */
export function createInitialState(seed: number): GameState {
  const cities = cloneCities()
  const edges = cloneEdges()
  const industries = cloneIndustries()

  // Данные о мире набиваются руками, и опечатка в идентификаторе города иначе
  // всплыла бы только в рендере пустой сценой. Здесь она падает сразу.
  if (!cities[HOME_CITY]) {
    throw new Error(`createInitialState: нет города ${HOME_CITY} в данных мира`)
  }

  // Предприятие в несуществующем городе — не «просто невидимое предприятие»:
  // производство будет исправно копить продукцию, которую физически некуда
  // подать машине, и цепочка порвётся в месте, никак не связанном с опечаткой.
  for (const industry of Object.values(industries)) {
    if (!cities[industry.cityId]) {
      throw new Error(
        `createInitialState: предприятие ${industry.id} стоит в неизвестном городе ${industry.cityId}`,
      )
    }
  }

  const companies: Record<CompanyId, Company> = {}
  const vehicles: Record<VehicleId, Vehicle> = {}

  const found = (companySeed: CompanySeed): void => {
    const founded = foundCompany(companySeed)
    companies[founded.company.id] = founded.company
    vehicles[founded.vehicle.id] = founded.vehicle
  }

  /*
   * ИГРОК ЗАВОДИТСЯ ПЕРВЫМ, И ПОРЯДОК ЗДЕСЬ ЗНАЧИМ ПО ДВУМ ПОВОДАМ СРАЗУ.
   *
   * Первый — воспроизводимость: фаза прибытия разбирает парк в порядке вставки
   * ключей (разбор — в шапке logistics/loading.ts), поэтому порядок обязан быть
   * записан явно, а не получаться сам собой из порядка полей в литерале.
   *
   * Второй — честная оговорка, а не оправдание. Когда машины РАЗНЫХ компаний
   * стоят в одном городе, обе свободны в один и тот же тик, а на складе лежит
   * меньше одного кузова, первая по списку заберёт партию целиком. Это остаток
   * форы, и он у игрока. Расстановкой он не убирается — любой фиксированный
   * порядок кому-нибудь достаётся, — а лечится не здесь, а в самой фазе прибытия
   * (дележом партии между претендентами). Величина при этом мала: совпасть
   * должны город, тик, свободные посты у обеих компаний и подсохший склад.
   */
  found({
    id: PLAYER_ID,
    // ТОО, а не ООО: общества с ограниченной ответственностью появились в
    // законе только в 1998-м, а в 1994-м частная контора на одну машину
    // регистрировалась товариществом. Мелочь, но она задаёт тон эпохи.
    name: 'ТОО «Плечо»',
    controller: 'человек',
    // У игрока характера нет: он и есть тот, кто решает. Заполненная строка
    // здесь означала бы, что за игрока кто-то думает.
    personality: null,
    vehicleId: STARTER_VEHICLE_ID,
    driverId: STARTER_DRIVER_ID,
    driverName: STARTER_DRIVER_NAME,
  })

  for (const spec of COMPETITORS) {
    /*
     * СКРИПТ, А НЕ МОДЕЛЬ, И ЭТО НЕ ЗАГЛУШКА.
     *
     * Симуляция обязана быть полной и детерминированной БЕЗ единого сетевого
     * вызова: без ключа, без интернета, в прогоне баланса на сотни игровых лет.
     * Значит мир, который рождается здесь, — это мир, где конкурентов ведёт
     * эвристика, и она же остаётся запасным путём навсегда.
     *
     * Модель подключает слой приложения: он переводит компанию в 'модель' и
     * начинает класть ответы в pendingCommands сам (deliverPlan в app/store.ts).
     * Не дозвонился, нет ключа, невалидный ответ — кладёт туда же то, что
     * предложил скрипт, и симуляция разницы не замечает.
     */
    found({
      id: spec.id,
      name: spec.name,
      controller: 'скрипт',
      personality: spec.personality,
      vehicleId: starterVehicleIdOf(spec.id),
      driverId: starterDriverIdOf(spec.id),
      driverName: spec.driverName,
    })
  }

  return {
    // Сид прогоняется через тот же конструктор, что и рабочий генератор: он
    // приводит число к 32 битам, и сиды 1 и 2^32+1 дают одинаковое состояние —
    // а значит и одинаковый JSON, на который опираются тесты детерминизма.
    rngState: Rng.from(seed).seed,
    /*
     * ПАРТИЯ НАЧИНАЕТСЯ УТРОМ, А НЕ В ПОЛНОЧЬ.
     *
     * Ноль означал первое января в 00:00 — то есть зимнюю полночь, самый тёмный
     * кадр из всех возможных. С появлением света суток (render/sky.ts) это
     * перестало быть безобидным: игра открывалась чёрным экраном с подписями
     * городов, на котором не видно ни дорог, ни застройки, и первое впечатление
     * от неё было «ничего не нарисовано».
     *
     * Девять утра — зимний рассвет: солнце низкое, тени длинные, тёплый свет
     * скользит по карте. Тот самый кадр, ради которого свет суток и делался.
     *
     * Величина выражена через TICKS_PER_HOUR, а не числом: ритм тика уже менялся
     * однажды, и вписанное «36» разъехалось бы с ним молча.
     */
    tick: 9 * TICKS_PER_HOUR,
    startYear: START_YEAR,
    world: { cities, edges, industries },
    companies,
    playerId: PLAYER_ID,
    vehicles,
  }
}
