/**
 * Фаза обслуживания: посты, очередь и время под погрузкой.
 *
 * ЗАЧЕМ ЭТА ФАЗА СУЩЕСТВУЕТ. До неё погрузка была МГНОВЕННОЙ, а значит
 * бесплатной: машина приезжала, забирала тонны в том же тике и уезжала. Из
 * этого следовало ровно одно, зато губительное — десятая машина на линии стоила
 * столько же, сколько первая, и правильным ответом на любую задачу игры было
 * «купить ещё грузовик». Сеть не имела ПРОПУСКНОЙ СПОСОБНОСТИ: узел принимал
 * сколько угодно машин одновременно, и уплотнять кольцо можно было до
 * бесконечности.
 *
 * Здесь у узла появляется конечное число постов, а у погрузки — часы. Вторая
 * машина на том же заводе встаёт в очередь, и у игрока впервые появляется
 * задача, которую нельзя решить покупкой машины: расшить узкое место —
 * терминалом, складом, хабом или перестройкой линий.
 *
 * ЧТО ЭТА ФАЗА ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ.
 *
 *   Делает: раздаёт посты, отсчитывает время стоянки, копит очередь.
 *
 *   НЕ делает саму погрузку — тонны переходят со склада в кузов в фазе прибытия
 *   (logistics/loading.ts) и только там. Здесь нет ни одной строчки, меняющей
 *   склад, груз или деньги: две фазы, перекладывающие тонны, — это две формулы
 *   переполнения, которые однажды разойдутся (разбор такого расхождения — в
 *   шапке loading.ts, про потолок склада).
 *
 * КОНТРАКТ С СОСЕДНИМИ ФАЗАМИ, и он держится на одном поле.
 *
 *   • Фаза стоит ПОСЛЕ движения и ПЕРЕД прибытием. Машина, доехавшая до узла в
 *     этом тике, в этом же тике встаёт под погрузку — иначе каждая остановка
 *     стоила бы лишний тик неизвестно за что.
 *   • `Vehicle.serviceTicksLeft > 0` означает «машина стоит под погрузкой».
 *     Прибытие такую машину пропускает, диспетчеризация её не трогает. Ноль —
 *     обслуживание закончено, и прибытие в этом же тике перекладывает тонны.
 *   • `Vehicle.queuedTicks` — счётчик ожидания поста. Растёт у того, кому поста
 *     не хватило, и обнуляется в момент, когда пост достался.
 *
 * ПРИБЫТИЮ МАЛО ОДНОГО СЧЁТЧИКА, И ЭТО ЛЕГКО ПРОСМОТРЕТЬ. Условие «грузим, если
 * serviceTicksLeft === 0» пропускает не только отстоявшую своё машину, но и ту,
 * что стоит в ОЧЕРЕДИ: поста ей не досталось, обслуживание не начиналось, и
 * счётчик у неё честный ноль. С таким условием очередь не значила бы ничего —
 * ждущая машина грузилась бы мгновенно, то есть срез отменял бы сам себя.
 * Правильное условие складывается из обоих полей и звучит так:
 *
 *     грузим тогда и только тогда, когда serviceTicksLeft === 0 И
 *     queuedTicks === 0
 *
 * Оно работает как раз потому, что пост, доставшись машине, обнуляет ожидание:
 * «отстояла» и «не начинала» различаются вторым счётчиком. Погрузка в один тик
 * (партия меньше полутора тонн) при этом остаётся мгновенной — оба счётчика
 * нулевые уже в тик выдачи поста, — и это верно: тик и есть её длительность.
 *
 * СКОЛЬКО ТИКОВ ЗАНИМАЕТ ОБСЛУЖИВАНИЕ. serviceTicksFor возвращает ПОЛНУЮ
 * длительность, а поле хранит остаток ПОСЛЕ текущего тика — поэтому при выдаче
 * поста в него пишется на единицу меньше. Тик, в который машина встала под
 * погрузку, и есть первый тик работы: считать его пустым значило бы растянуть
 * любую погрузку на лишние пятнадцать минут, а погрузку в один тик — вдвое.
 * Шесть тонн (четыре тика) выглядят так:
 *
 *   тик 1  пост выдан, serviceTicksLeft = 3   ← машина занимает пост
 *   тик 2  serviceTicksLeft = 2
 *   тик 3  serviceTicksLeft = 1
 *   тик 4  serviceTicksLeft = 0               ← пост ещё занят, прибытие грузит
 *   тик 5  работы в узле нет, пост свободен для следующей машины
 *
 * ПОРЯДОК В ОЧЕРЕДИ ДЕТЕРМИНИРОВАН: кто дольше ждёт, тот и заходит на пост
 * первым, а при равном ожидании — тот, кто раньше в парке. Это не формальность
 * и не вкусовщина. Очередь, раздающая посты в произвольном порядке, наказывает
 * случайную машину: игрок видит, что одна и та же линия то работает, то стоит,
 * и никакого правила за этим не стоит. Хуже того, при невезении машина может
 * голодать сколь угодно долго. Обслуживание по времени ожидания даёт и
 * понятную картину («кто дольше стоял, тот и поехал»), и гарантию: ждущий
 * дольше всех рано или поздно оказывается первым.
 *
 * ПОСТЫ СЧИТАЮТСЯ ПО КОМПАНИЯМ, а не по узлу целиком. Базовый пост завода
 * достаётся каждой компании свой, и машины конкурента не занимают очередь
 * игрока. Это упрощение, и оно намеренное: общая очередь означала бы, что
 * конкурент, поставивший на кольцо десять машин, наглухо запирает завод игрока,
 * а расшить это игрок не может ничем — терминал добавляет посты только своему
 * владельцу (Building.ownerId). Пробка без единого способа её расшить — это
 * наказание без решения, а срез сделан ровно ради решений.
 *
 * ОЦЕНКА РАБОТЫ ГРУБАЯ И ЩЕДРАЯ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА. Чтобы выдать пост,
 * надо знать ДО погрузки, будет ли она и на сколько тонн, — а решает это фаза
 * прибытия, которая идёт следом. Точной эта оценка быть не может, и не должна:
 * ошибки в две стороны стоят разного.
 *
 *   Сказать «работа есть», когда прибытие ничего не сделает (получатель
 *   переполнился в этом же тике), — потерянный простой на несколько тиков.
 *   Неприятно, но не смертельно, и машина уедет: диспетчеризация в следующем
 *   тике увидит нулевой счётчик и выдаст маршрут.
 *
 *   Сказать «работы нет», когда прибытие погрузит, — ВОЗВРАТ БЕСПЛАТНОЙ
 *   ПОГРУЗКИ. Машина минует очередь, тонны переходят мгновенно, и весь срез
 *   отменяется для того случая, который не угадали.
 *
 * Поэтому оценка сознательно завышает: считает, что весь груз выгрузится
 * (вместимость получателя не проверяется — это работа прибытия), и берёт тоннаж
 * по тому, что реально лежит на складах узла.
 *
 * ВЫГРУЗКА ТОЖЕ ЗАНИМАЕТ ПОСТ. Тонны идут через ту же рампу, что и погрузка,
 * поэтому остановка, где машина и разгружается, и грузится, держит пост вдвое
 * дольше. Это не мелочь учёта, а то, что делает узловые города дорогими: кольцо
 * с двумя гружёными плечами — главная фигура игры — на каждой своей остановке
 * перекладывает и туда, и обратно, и именно там первым делом вырастает очередь.
 *
 * Все функции чистые: входное состояние не меняется, включая вложенные объекты.
 */

import { BASE_POSTS, TONS_PER_POST_HOUR } from '../../data/infrastructure'
import { RECIPE_BY_INDUSTRY } from '../../data/recipes'
import { TICKS_PER_HOUR } from '../types'
import type {
  CargoType,
  CityId,
  Company,
  CompanyId,
  GameState,
  Industry,
  IndustryId,
  Line,
  Stop,
  Tons,
  TrailerType,
  Vehicle,
  VehicleId,
} from '../types'
import { canCarry } from './trailer'

/**
 * Порог значимости тоннажа. Тот же, что в фазе прибытия, и по той же причине:
 * после частичных разгрузок в кузове остаётся что-нибудь вроде 4.4e-16, и без
 * порога машина занимала бы пост ради нанограмма.
 */
const TONS_EPSILON = 1e-9

/**
 * Порог значимости при округлении времени вверх.
 *
 * Нужен ровно в одном месте — в serviceTicksFor. Ровно шесть тонн при
 * TONS_PER_POST_HOUR = 6 обязаны давать целый час, но арифметика с плавающей
 * точкой на другом наборе констант легко даст 4.000000000000001, и округление
 * вверх подарит машине лишний тик из-за последнего бита мантиссы. Тот же приём
 * и по той же причине — KM_EPSILON в line.ts и FATIGUE_EPSILON в driver.ts.
 */
const TICK_EPSILON = 1e-9

// ─── Посты узла ────────────────────────────────────────────────────────────

/** Целое неотрицательное число постов. Битые данные дают ноль, а не NaN. */
function wholePosts(value: number): number {
  if (!Number.isFinite(value) || value <= 0) return 0
  return Math.floor(value)
}

/** Целое неотрицательное число тиков. Битые данные дают ноль. */
function wholeTicks(value: number): number {
  if (!Number.isFinite(value) || value <= 0) return 0
  return Math.floor(value)
}

/**
 * Сколько машин компании узел обслуживает одновременно.
 *
 * Базовый пост есть у любого узла и без единой постройки (BASE_POSTS): завод
 * умеет отгружать сам, просто по одной машине зараз. Всё сверх этого игрок
 * строит сам.
 *
 * ПОСТРОЙКИ БЕРУТСЯ ТОЛЬКО У СПРОШЕННОЙ КОМПАНИИ, и лежат они в её собственном
 * реестре (Company.buildings) — терминал конкурента в этом же городе не
 * добавляет игроку ни одного поста, потому что это его терминал. Иначе
 * строительство перестало бы быть решением: достаточно было бы дождаться, пока
 * узел застроит кто-нибудь другой.
 *
 * Сейв прошлой версии мог не знать про постройки вовсе — тогда у компании есть
 * только базовый пост, и падать на этом фаза не должна.
 */
export function postsAt(
  state: GameState,
  cityId: CityId,
  companyId: CompanyId,
): number {
  const company: Company | undefined = state.companies[companyId]
  const buildings = company?.buildings
  if (buildings === undefined) return BASE_POSTS

  let posts = BASE_POSTS
  for (const building of Object.values(buildings)) {
    if (building.cityId !== cityId) continue
    posts += wholePosts(building.posts)
  }

  return posts
}

// ─── Время под погрузкой ───────────────────────────────────────────────────

/**
 * Сколько тиков занимает перекладка такого количества тонн.
 *
 * Пропускная способность поста задана в данных одним числом (TONS_PER_POST_HOUR
 * в data/infrastructure.ts), и всё время выводится из него: шесть тонн ЗИЛа —
 * час, двадцать тонн тягача — три с половиной. Тяжёлая техника перестаёт быть
 * бесплатно лучшей — везёт втрое больше, но и грузится втрое дольше.
 *
 * ОКРУГЛЕНИЕ ТОЛЬКО ВВЕРХ, И ЭТО НЕ АККУРАТНОСТЬ, А ЗАЩИТА ОТ ЭКСПЛОЙТА. Тик —
 * неделимая единица времени симуляции: занять пост «на три четверти тика»
 * нельзя, машина или стоит в этот тик, или нет. Округление ВНИЗ дало бы ноль
 * тиков всему, что меньше TONS_PER_POST_HOUR / TICKS_PER_HOUR (полторы тонны),
 * то есть вернуло бы мгновенную погрузку — а вместе с ней и способ обойти
 * пропускную способность целиком: возить мелкими партиями стало бы выгоднее,
 * чем строить терминал. Округление вверх делает мелкую партию не бесплатной, а
 * минимальной: один тик, пятнадцать минут — быстрее не подъедешь под рампу и не
 * оформишь бумаги.
 *
 * Ноль тонн — ноль тиков: машине, которой в узле нечего делать, пост не нужен.
 */
export function serviceTicksFor(tons: Tons): number {
  if (!Number.isFinite(tons) || tons <= 0) return 0

  const ticks = (tons / TONS_PER_POST_HOUR) * TICKS_PER_HOUR
  return Math.max(1, Math.ceil(ticks - TICK_EPSILON))
}

// ─── Что машине делать в этом узле ─────────────────────────────────────────

/**
 * Инструкция на город, где машина стоит. Смысл вариантов — как в loading.ts:
 * 'остановка' — работать по спискам остановки, 'мимо' — работы нет вовсе,
 * 'разовый' — прежняя автоматика без линии.
 */
type Orders =
  | { kind: 'остановка'; stop: Stop }
  | { kind: 'мимо' }
  | { kind: 'разовый' }

/**
 * Остановка кольца, отвечающая городу, в котором машина стоит.
 *
 * Повторяет stopAt из loading.ts буква в букву, и это осознанное дублирование, а
 * не забывчивость: та функция приватная, а обе фазы обязаны понимать инструкцию
 * ОДИНАКОВО. Разойдись они — и машина встала бы под погрузку по одной остановке,
 * а погрузилась бы по другой. Дублируется здесь именно ПОИСК остановки, то есть
 * чтение данных игрока, а не решение о тоннах: решение принимает прибытие.
 *
 * Обход идёт ВПЕРЁД от stopIndex, потому что город может стоять в кольце дважды
 * с разными инструкциями, и правильная из двух — ближайшая по ходу линии.
 */
function stopAt(line: Line, stopIndex: number, nodeId: CityId): Stop | null {
  const count = line.stops.length
  if (count === 0) return null

  const start =
    Number.isInteger(stopIndex) && stopIndex >= 0 && stopIndex < count
      ? stopIndex
      : 0

  for (let i = 0; i < count; i++) {
    const stop = line.stops[(start + i) % count]
    if (stop.nodeId === nodeId) return stop
  }

  return null
}

/** Инструкция для машины в этом городе. Линия ищется у владельца машины. */
function ordersFor(
  companies: Record<CompanyId, Company>,
  vehicle: Vehicle,
  nodeId: CityId,
): Orders {
  const assigned = vehicle.lineId
  if (!assigned) return { kind: 'разовый' }

  const line = companies[vehicle.ownerId]?.lines?.[assigned]
  // Кольцо меньше чем из двух остановок не работает — по нему и не грузят.
  if (line === undefined || line.stops.length < 2) return { kind: 'разовый' }

  const stop = stopAt(line, vehicle.stopIndex, nodeId)
  return stop === null ? { kind: 'мимо' } : { kind: 'остановка', stop }
}

/**
 * Сколько тонн готово к вывозу у одного предприятия.
 *
 * Правила ровно те же, что у pickupFrom в loading.ts: берётся только ГОТОВАЯ
 * ПРОДУКЦИЯ (иначе привезённое сырьё можно было бы увезти обратно и получать
 * деньги за круг), и только то, что влезает в кузов (canCarry). `wanted === null`
 * — режим разового рейса, «что угодно, что готово».
 */
function readyTons(
  industry: Industry,
  nodeId: CityId,
  capacity: Tons,
  wanted: CargoType | null,
  trailer: TrailerType | null,
): Tons {
  if (industry.cityId !== nodeId) return 0

  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  if (recipe === undefined) return 0
  if (wanted !== null && recipe.output !== wanted) return 0
  if (!canCarry(trailer, recipe.output)) return 0

  const available = industry.stock[recipe.output] ?? 0
  if (!Number.isFinite(available)) return 0

  const tons = Math.min(capacity, available)
  return tons > TONS_EPSILON ? tons : 0
}

/**
 * Сколько тонн машина возьмёт в этом узле.
 *
 * Порядок перебора совпадает с findPickup в loading.ts: внешний цикл по грузам
 * (порядок в списке остановки — это приоритет игрока), внутренний по
 * предприятиям в порядке вставки ключей. Совпадение обязательно — иначе фаза
 * оценит время по одной партии, а прибытие возьмёт другую.
 *
 * Складов построек (Building.stock) здесь нет по той же причине: их не знает и
 * фаза прибытия. Научится брать оттуда — придётся дописать и сюда, и это
 * единственное место, где две фазы обязаны знать друг о друге.
 */
function pickupTons(
  industries: Record<IndustryId, Industry>,
  nodeId: CityId,
  capacity: Tons,
  wanted: readonly CargoType[] | null,
  trailer: TrailerType | null,
): Tons {
  if (wanted === null) {
    for (const industry of Object.values(industries)) {
      const tons = readyTons(industry, nodeId, capacity, null, trailer)
      if (tons > 0) return tons
    }
    return 0
  }

  for (const cargo of wanted) {
    for (const industry of Object.values(industries)) {
      const tons = readyTons(industry, nodeId, capacity, cargo, trailer)
      if (tons > 0) return tons
    }
  }

  return 0
}

/**
 * Сколько тонн машина переложит в этом узле. Ноль — работы нет, пост не нужен.
 *
 * Выгрузка и погрузка складываются: и то, и другое идёт через пост. Порядок тот
 * же, что в прибытии, — сначала выгрузка, потом погрузка, — поэтому машина,
 * которая здесь отдаёт груз, считается пустой и может ещё и взять обратный.
 *
 * Оценка ЗАВЫШАЮЩАЯ, разбор — в шапке файла: вместимость получателя не
 * проверяется, весь груз считается выгруженным. Ошибка в эту сторону стоит
 * простоя, ошибка в обратную возвращает бесплатную погрузку.
 */
function serviceTons(state: GameState, vehicle: Vehicle, nodeId: CityId): Tons {
  const orders = ordersFor(state.companies, vehicle, nodeId)
  // Машина на линии стоит не на своей остановке: линия сказала «здесь работы
  // нет», и пост ей не нужен.
  if (orders.kind === 'мимо') return 0

  const stop = orders.kind === 'остановка' ? orders.stop : null

  let unloadTons = 0
  // Пустой кузов после выгрузки — условие погрузки, ровно как в прибытии.
  let emptyAfter = true

  const cargo = vehicle.cargo
  if (cargo !== null && Number.isFinite(cargo.tons) && cargo.tons > TONS_EPSILON) {
    // Линия выгружает только перечисленное; сдать груз там, где его и взяли,
    // нельзя (в прибытии это закрывает бесплатное снабжение своего города).
    const ordered = stop === null || stop.unload.includes(cargo.type)
    if (ordered && cargo.originId !== nodeId) unloadTons = cargo.tons
    else emptyAfter = false
  }

  const capacity =
    Number.isFinite(vehicle.capacity) && vehicle.capacity > 0
      ? vehicle.capacity
      : 0

  const loadTons =
    emptyAfter && capacity > TONS_EPSILON
      ? pickupTons(
          state.world.industries,
          nodeId,
          capacity,
          stop === null ? null : stop.load,
          vehicle.trailer,
        )
      : 0

  return unloadTons + loadTons
}

// ─── Фаза целиком ──────────────────────────────────────────────────────────

/** Машина, которой в этом узле есть что делать, но пост ещё не достался. */
type Candidate = {
  id: VehicleId
  /** Место в парке. Разрывает ничью по времени ожидания — см. шапку файла. */
  rank: number
  /** Сколько тиков уже ждёт. */
  queued: number
  /** Оценка работы, тонн. */
  tons: Tons
}

/** Узел глазами одной компании: её посты, её машины. */
type NodeQueue = {
  ownerId: CompanyId
  nodeId: CityId
  /** Постов занято машинами, которые уже стоят под погрузкой. */
  busy: number
  waiting: Candidate[]
}

/**
 * Фаза обслуживания целиком. Возвращает НОВОЕ состояние.
 *
 * Проход первый: машины, которые уже стоят под погрузкой, отсчитывают время и
 * держат свои посты; остальные, если им есть что делать, становятся кандидатами.
 * Проход второй: по каждому узлу свободные посты раздаются кандидатам в порядке
 * очереди, остальным растёт счётчик ожидания.
 *
 * Два прохода, а не один, ровно потому, что решение про КАЖДУЮ машину зависит от
 * ВСЕХ машин в её узле. Раздавай посты по ходу единственного обхода — и
 * результат зависел бы от порядка ключей объекта, то есть детерминизм тика
 * держался бы ни на чём (то же требование, что в шапке moveVehicles в tick.ts).
 */
export function runService(state: GameState): GameState {
  const ids = Object.keys(state.vehicles) as VehicleId[]
  const vehicles: Record<VehicleId, Vehicle> = { ...state.vehicles }
  const nodes = new Map<string, NodeQueue>()
  let changed = false

  /** Записать счётчики. Ничего не изменилось — машина остаётся по ссылке. */
  const apply = (id: VehicleId, service: number, queued: number): void => {
    const before = state.vehicles[id]
    if (before.serviceTicksLeft === service && before.queuedTicks === queued) {
      return
    }
    vehicles[id] = {
      ...before,
      serviceTicksLeft: service,
      queuedTicks: queued,
    }
    changed = true
  }

  for (let rank = 0; rank < ids.length; rank++) {
    const id = ids[rank]
    const vehicle = state.vehicles[id]

    // Обслуживание бывает только в узле. Ненулевой счётчик у едущей машины —
    // след битого сейва или ручного перегона, и оставить его нельзя: пока он
    // больше нуля, диспетчеризация машину не трогает, то есть она подвиснет.
    if (vehicle.position.kind !== 'узел') {
      apply(id, 0, 0)
      continue
    }

    const nodeId = vehicle.position.nodeId
    // Косая черта в идентификаторах не встречается, а дефис склеил бы пары
    // «a» + «b-c» и «a-b» + «c» в один ключ (тот же довод, что в line.ts).
    const key = `${vehicle.ownerId}/${nodeId}`

    let node = nodes.get(key)
    if (node === undefined) {
      node = { ownerId: vehicle.ownerId, nodeId, busy: 0, waiting: [] }
      nodes.set(key, node)
    }

    const left = wholeTicks(vehicle.serviceTicksLeft)
    if (left > 0) {
      // Стоит под погрузкой: пост занят ею весь текущий тик, включая тот, в
      // котором счётчик доходит до нуля, — в этот тик прибытие и перекладывает
      // тонны, а рампа всё ещё занята.
      node.busy++
      apply(id, left - 1, 0)
      continue
    }

    const tons = serviceTons(state, vehicle, nodeId)
    if (tons <= TONS_EPSILON) {
      // Работы в узле нет: ни поста, ни очереди. Транзитная остановка, порожняя
      // машина у пустого склада и машина, только что здесь погрузившаяся, —
      // всё это стоянка, а не простой в очереди, и показывать её игроку как
      // узкое место значило бы врать в главной диагностической панели.
      apply(id, 0, 0)
      continue
    }

    node.waiting.push({
      id,
      rank,
      queued: wholeTicks(vehicle.queuedTicks),
      tons,
    })
  }

  for (const node of nodes.values()) {
    if (node.waiting.length === 0) continue

    const free = Math.max(
      0,
      postsAt(state, node.nodeId, node.ownerId) - node.busy,
    )

    // Кто дольше ждёт — тот первый; при равном ожидании — кто раньше в парке.
    // Обе части порядка обязаны быть определены: сортировка по одному ключу
    // оставила бы ничьи на усмотрение движка.
    const queue = [...node.waiting].sort(
      (a, b) => b.queued - a.queued || a.rank - b.rank,
    )

    for (let i = 0; i < queue.length; i++) {
      const candidate = queue[i]
      if (i < free) {
        // Пост достался: счётчик ожидания обнуляется, потому что ждать больше
        // нечего. Хранить «сколько ждала в прошлый раз» было бы хуже, чем не
        // хранить вовсе: игрок пошёл бы расшивать узел по вчерашнему числу,
        // которого сегодня уже нет.
        apply(candidate.id, Math.max(0, serviceTicksFor(candidate.tons) - 1), 0)
      } else {
        apply(candidate.id, 0, candidate.queued + 1)
      }
    }
  }

  return changed ? { ...state, vehicles } : state
}
