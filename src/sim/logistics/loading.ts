/**
 * Порог значимости тоннажа.
 *
 * Тонны — числа с плавающей точкой, и после нескольких частичных разгрузок в
 * кузове остаётся что-нибудь вроде 4.4e-16. Без порога машина считается
 * гружёной этим нанограммом: она не берёт новый груз, ищет под него получателя
 * и в отчёте выглядит занятой. Порог превращает такой остаток в «пусто».
 */
const TONS_EPSILON = 1e-9

/**
 * Сколько суток потребления вмещает склад города.
 *
 * Потолок у города нужен по совершенно другой причине, чем у предприятия. Он не
 * создаёт логистическую задачу, он закрывает вырождение: без него игрок один раз
 * завалил бы Москву мукой на десять лет вперёд и уехал, а город продолжал бы
 * расти сам по себе. Рост должен требовать УСТОЙЧИВОГО снабжения — так прямо
 * сказано про suppliedDays в types.ts, — и вместимость склада это требование
 * физически обеспечивает.
 *
 * Тридцать суток, а не три, как у предприятия (STOCK_DAYS в
 * economy/production.ts). Заводу тесный склад нужен как раз затем, чтобы он
 * задыхался без вывоза; городу — наоборот.
 *
 * Число упирается в грузоподъёмность, а не в правдоподобие запаса. Норма
 * потребления описывает лишь ту долю спроса, которую закрывает автодоставка из
 * ЦФО (см. CONSUMPTION_PER_1K), и она невелика: Орлу нужно 0.46 тонны муки в
 * сутки. При пяти сутках склад вмещал бы 2.3 тонны — меньше половины кузова
 * ЗИЛа, и город физически не мог бы принять ОДНУ ходку: приняли бы треть, а
 * остальное увезли обратно. Игра ломалась бы на первом же рейсе.
 *
 * Тридцать суток дают самому маленькому городу запас в две полные ходки. Это
 * нижняя граница, при которой доставка вообще имеет смысл, и она же задаёт
 * ритм: малый город обслуживается раз в пару недель, Москва — постоянно.
 */
export const CITY_STOCK_DAYS = 30

/**
 * Сколько игровых суток машина возит невостребованный груз до списания.
 *
 * Трое суток: достаточно, чтобы переждать временно полный склад — завод
 * потребляет непрерывно и освобождает место, — и мало, чтобы машина не возила
 * мёртвый груз до конца партии. Списание идёт за счёт перевозчика, как
 * невостребованная партия в отрасли.
 */
export const DEAD_CARGO_DAYS = 3

/**
 * Вместимость склада города под конкретный груз, тонн.
 *
 * Считается от населения через demandPerDay — ту же функцию, по которой город
 * потребляет. Складывать «сколько влезет» и «сколько съедят» по двум разным
 * формулам нельзя: разойдясь на проценты, они дадут город, который физически не
 * может принять свою же суточную норму, и причину такого голода не найдёт никто.
 *
 * Динамика тоже отсюда: спрос растёт вместе с населением, значит и склад растёт.
 * Фиксированный потолок упёрся бы ровно в тот момент, когда игрок наконец
 * вырастил город, и снабжать выросший город стало бы невозможно.
 */
export function cityCapacity(city: City, cargo: CargoType): Tons {
  if (!CONSUMER_CARGO.includes(cargo)) return 0

  const capacity = demandPerDay(city.population, cargo) * CITY_STOCK_DAYS

  return Number.isFinite(capacity) && capacity > 0 ? capacity : 0
}

/**
 * Тарифное расстояние плеча, километры.
 *
 * Считается как КРАТЧАЙШИЙ путь от города погрузки до города выгрузки, а не
 * как фактический пробег машины. Так устроен тариф в перевозках, и так же
 * закрываются сразу два способа печатать деньги из воздуха:
 *
 *   1. Кружение. Раньше платили за весь пробег с момента погрузки, ничем не
 *      ограниченный. Прогон ревизии: 60 суток катания по кольцу без единой
 *      разгрузки давали 1 328 600 руб за одну и ту же партию в 6 тонн.
 *   2. Возврат домой. Груз можно было сдать в городе, где его же и взяли, и
 *      кольцо оплачивалось вдвое против честного рейса в один конец.
 *
 * Оба исчезают сами собой: накрутить одометр можно, накрутить кратчайший путь
 * между двумя точками — нельзя. Ноль километров означает, что везти было
 * некуда, и такая «доставка» не оплачивается вовсе.
 */
function tariffKm(graph: RoadGraph, from: CityId, to: CityId): number {
  const km = shortestKm(graph, from, to)
  return Number.isFinite(km) && km > 0 ? km : 0
}

// ─── Инструкция на этот город ──────────────────────────────────────────────

/**
 * Что машине делать в городе, где она стоит.
 *
 *   'остановка' — машина на линии стоит на своей остановке, работает по её
 *                 спискам и только по ним.
 *   'мимо'      — машина на линии стоит в городе, которого в её кольце нет
 *                 (транзитный узел, ручной перегон, город удалён из линии).
 *                 Не делает ничего: линия сказала «здесь работы нет», и
 *                 подменять её решение автоматикой значит стирать разницу
 *                 между спроектированной сетью и «вози что дают».
 *   'разовый'   — линии нет, работает прежняя автоматика.
 */
type Orders =
  | { kind: 'остановка'; stop: Stop }
  | { kind: 'мимо' }
  | { kind: 'разовый' }

/**
 * Остановка кольца, отвечающая городу, в котором машина стоит.
 *
 * Обычно это ровно stops[stopIndex]: индекс показывает остановку, к которой
 * машина ехала, и на границе тика она стоит именно на ней. Но фаза
 * диспетчеризации идёт ПЕРЕД движением и может успеть перевести индекс на
 * следующую остановку в том же тике, в котором машина ещё стоит на прежней
 * (маршрут не построился, дорога непроезжая). Поэтому индекс — не приговор, а
 * точка отсчёта: дальше кольцо просматривается ВПЕРЁД до первого совпадения по
 * городу.
 *
 * Направление обхода тоже не случайно. Город может стоять в кольце дважды с
 * разными инструкциями — узловая база, куда заезжают и по дороге туда, и по
 * дороге обратно, — и из двух одноимённых остановок правильной всегда будет
 * БЛИЖАЙШАЯ ВПЕРЁД по ходу линии, а не первая в списке.
 */
function stopAt(line: Line, stopIndex: number, nodeId: CityId): Stop | null {
  const count = line.stops.length
  if (count === 0) return null

  // Битый индекс (сохранение старой версии, укоротившаяся линия) — не повод
  // ронять тик: начинаем обход с начала кольца.
  const start =
    Number.isInteger(stopIndex) && stopIndex >= 0 && stopIndex < count
      ? stopIndex
      : 0

  for (let i = 0; i < count; i++) {
    const stop = line.stops[(start + i) % count]
    if (stop.nodeId === nodeId) return stop
  }

  return null
}

/**
 * Инструкция для машины в этом городе.
 *
 * Линия ищется у ВЛАДЕЛЬЦА машины: линии принадлежат компаниям (Company.lines),
 * и конкурент со своей сетью обслуживается ровно этим же кодом.
 *
 * Потерянная линия (её удалили, а машину не отвязали; сейв, где lineId ссылается
 * в пустоту) роняет машину в режим разовых рейсов, а не останавливает её
 * навсегда. Парализованная машина, продолжающая жечь зарплату и не подающая
 * признаков жизни, — худший из возможных ответов на дыру в данных.
 */
function ordersFor(
  companies: Record<CompanyId, Company>,
  vehicle: Vehicle,
  nodeId: CityId,
): Orders {
  const assigned = vehicle.lineId
  if (!assigned) return { kind: 'разовый' }

  const line = companies[vehicle.ownerId]?.lines?.[assigned]
  // Линии меньше чем из двух остановок не существует как кольца (types.ts),
  // и работать по ней нельзя — это заготовка, которую игрок ещё редактирует.
  if (line === undefined || line.stops.length < 2) return { kind: 'разовый' }

  const stop = stopAt(line, vehicle.stopIndex, nodeId)
  return stop === null ? { kind: 'мимо' } : { kind: 'остановка', stop }
}

// ─── Разгрузка ─────────────────────────────────────────────────────────────

/** Кто в городе готов принять груз и сколько ещё влезет на его склад. */
type Receiver =
  | { kind: 'предприятие'; id: IndustryId; free: Tons }
  | { kind: 'город'; id: CityId; free: Tons }

/**
 * Найти в городе того, кто примет этот груз.
 *
 * ПРЕДПРИЯТИЯ ИМЕЮТ ПРИОРИТЕТ НАД ГОРОДОМ. В нынешних данных пересечения нет —
 * города потребляют только готовую продукцию, а она никому не сырьё, — но
 * порядок зафиксирован заранее и в нужную сторону: как только появится груз,
 * который и потребляется городом, и перерабатывается (топливо для АЗС — первый
 * кандидат), приоритет города означал бы, что провезти его в переработку
 * физически нельзя. Цепочка всегда должна иметь возможность продолжиться.
 *
 * Предприятие с полным складом ПРОПУСКАЕТСЯ, а не блокирует разгрузку. Иначе
 * задохнувшийся завод в городе перекрывал бы дорогу голодному соседу, и
 * причину этого игрок не увидел бы никак.
 */
function findReceiver(
  industries: Record<IndustryId, Industry>,
  cities: Record<CityId, City>,
  cityId: CityId,
  cargo: CargoType,
): Receiver | null {
  for (const industry of Object.values(industries)) {
    if (industry.cityId !== cityId) continue

    const recipe = RECIPE_BY_INDUSTRY[industry.type]
    if (recipe === undefined) continue
    if (!recipe.inputs.some((input) => input.type === cargo)) continue

    // Потолок берётся у производства, а не считается здесь заново: правило
    // переполнения в игре обязано быть ровно одно. Разойдись эти две формулы —
    // и завод душился бы на одном числе, а машины сыпали бы в него до другого.
    const free = stockCapacity(industry, cargo) - (industry.stock[cargo] ?? 0)
    if (free > TONS_EPSILON) {
      return { kind: 'предприятие', id: industry.id, free }
    }
  }

  if (CONSUMER_CARGO.includes(cargo)) {
    const city = cities[cityId]
    if (city !== undefined) {
      const free = cityCapacity(city, cargo) - (city.stock[cargo] ?? 0)
      if (free > TONS_EPSILON) {
        return { kind: 'город', id: city.id, free }
      }
    }
  }

  return null
}

// ─── Погрузка ──────────────────────────────────────────────────────────────

/** Найденная партия к погрузке: у кого берём, что и сколько. */
type Pickup = { industryId: IndustryId; cargo: CargoType; tons: Tons }

/**
 * Взять груз у одного предприятия, если он у него есть.
 *
 * БЕРЁТСЯ ТОЛЬКО ГОТОВАЯ ПРОДУКЦИЯ (recipe.output), и это правило общее для
 * обоих режимов. Сырьё, лежащее на складе переработки, уже доставлено и уже
 * оплачено; разреши его забрать — и появляется вечный двигатель: увёз с
 * мукомольного привезённое туда зерно, вернул на элеватор, привёз обратно, и
 * так до бесконечности с оплатой каждого плеча.
 *
 * `wanted === null` означает «что угодно, что готово к вывозу» — режим разовых
 * рейсов.
 */
function pickupFrom(
  industry: Industry,
  nodeId: CityId,
  capacity: Tons,
  wanted: CargoType | null,
): Pickup | null {
  if (industry.cityId !== nodeId) return null

  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  if (recipe === undefined) return null
  if (wanted !== null && recipe.output !== wanted) return null

  const available = industry.stock[recipe.output] ?? 0
  const tons = Math.min(capacity, available)
  if (tons <= TONS_EPSILON) return null

  return { industryId: industry.id, cargo: recipe.output, tons }
}

/**
 * Что грузить в этом городе.
 *
 * `wanted === null` — автоматика разового рейса: берётся первое, что нашлось у
 * местных предприятий в порядке вставки.
 *
 * Непустой список — инструкция остановки, и ПОРЯДОК В НЁМ ЗАДАЁТ ПРИОРИТЕТ:
 * внешний цикл идёт по грузам, а не по предприятиям. Игрок пишет «сначала
 * топливо, если нет — мука», и получает ровно это. Пустой список (и список, по
 * которому в городе ничего нет) даёт null: машина уйдёт порожней, и её порожний
 * пробег будет виден в отчёте.
 *
 * Кузов один и груз в нём один: набрать по паре тонн разного нельзя. Смешанные
 * партии — это уже сборный груз, у него своя экономика, и её пока нет.
 */
function findPickup(
  industries: Record<IndustryId, Industry>,
  nodeId: CityId,
  capacity: Tons,
  wanted: readonly CargoType[] | null,
): Pickup | null {
  if (wanted === null) {
    for (const industry of Object.values(industries)) {
      const pickup = pickupFrom(industry, nodeId, capacity, null)
      if (pickup !== null) return pickup
    }
    return null
  }

  for (const cargo of wanted) {
    for (const industry of Object.values(industries)) {
      const pickup = pickupFrom(industry, nodeId, capacity, cargo)
      if (pickup !== null) return pickup
    }
  }

  return null
}

/**
 * Склад с изменённым остатком по одному грузу. Новый объект — вход не меняется.
 *
 * Одна функция и на приёмку, и на отгрузку: знак у delta. Склад города и склад
 * предприятия устроены одинаково (types.ts объясняет, почему у предприятия он
 * общий на вход и выход), поэтому и функция одна.
 */
function stockWith(
  stock: Partial<Record<CargoType, Tons>>,
  cargo: CargoType,
  delta: Tons,
): Partial<Record<CargoType, Tons>> {
  const next: Partial<Record<CargoType, Tons>> = { ...stock }
  next[cargo] = (stock[cargo] ?? 0) + delta
  return next
}

/**
 * Фаза прибытия целиком. Возвращает НОВОЕ состояние.
 *
 * Правила ровно два, и оба про машину, стоящую в узле:
 *
 *   1. Гружёная отдаёт груз, если этот груз ей велено здесь выгрузить (или,
 *      без линии, если в городе есть кому его принять), и получает деньги за
 *      тонны и километры от места погрузки.
 *   2. Пустая берёт то, что велено взять здесь (или, без линии, первое, что
 *      готово к вывозу).
 *
 * Взять обратно собственный груз машина при этом не может: грузится только
 * ГОТОВАЯ ПРОДУКЦИЯ предприятия, а привезённое сырьё продукцией не является ни
 * для кого в этом городе.
 */
export function runArrivals(state: GameState): GameState {
  // Граф строится один раз на фазу: тарифное расстояние спрашивают все
  // разгружающиеся машины, а сеть за тик не меняется.
  const graph = buildGraph(state.world.edges)

  // Рабочие копии верхнего уровня. Записи внутри либо остаются исходными по
  // ссылке, либо заменяются НОВЫМИ объектами — исходное состояние не
  // затрагивается ни на одном уровне вложенности.
  const vehicles: Record<VehicleId, Vehicle> = { ...state.vehicles }
  const industries: Record<IndustryId, Industry> = { ...state.world.industries }
  const cities: Record<CityId, City> = { ...state.world.cities }
  const companies: Record<CompanyId, Company> = { ...state.companies }

  let changed = false

  for (const id of Object.keys(vehicles) as VehicleId[]) {
    const before = vehicles[id]

    // Машина в пути ничего не грузит: погрузка бывает только в узле.
    if (before.position.kind !== 'узел') continue
    const nodeId = before.position.nodeId

    const orders = ordersFor(companies, before, nodeId)
    // Машина на линии стоит не на своей остановке — здесь для неё работы нет.
    if (orders.kind === 'мимо') continue

    // Дальше режим отличает ровно одно: null — прежняя автоматика, объект —
    // инструкция остановки. Обе ветки ниже читаются как одна процедура с
    // разным источником решения о том, что выгружать и что грузить.
    const stop = orders.kind === 'остановка' ? orders.stop : null

    let vehicle = before

    // ─── Выгрузка ────────────────────────────────────────────────────────
    const cargo = vehicle.cargo
    if (
      cargo !== null &&
      cargo.tons > TONS_EPSILON &&
      // Линия выгружает ТОЛЬКО перечисленное. Груз, которого нет в списке,
      // едет дальше, даже если в городе его ждут: остановка — это инструкция,
      // а не пожелание. Иначе транзит через город-потребитель разбирал бы
      // машину на полпути, и сквозные плечи были бы невозможны.
      (stop === null || stop.unload.includes(cargo.type))
    ) {
      // Сдать груз там, где его и взяли, нельзя. Перевозки не было — значит
      // и разгрузки нет. Без этого запрета появлялся тихий способ снабжать
      // собственный город даром: погрузить у своего же завода, покататься и
      // сдать обратно. Денег это уже не приносит (тарифное расстояние нулевое),
      // но город рос бы без единого честного рейса.
      const receiver =
        cargo.originId === nodeId
          ? null
          : findReceiver(industries, cities, nodeId, cargo.type)

      if (receiver !== null) {
        // Влезает не всё — отдаём сколько влезет. Остаток едет дальше искать
        // второго получателя. Альтернатива «или всё, или ничего» проще, но
        // намертво запирает цепочку: полный склад останавливал бы поставки
        // ровно тогда, когда завод вот-вот начнёт потреблять.
        const delivered = Math.min(cargo.tons, receiver.free)

        if (delivered > TONS_EPSILON) {
          if (receiver.kind === 'предприятие') {
            const target = industries[receiver.id]
            industries[receiver.id] = {
              ...target,
              stock: stockWith(target.stock, cargo.type, delivered),
            }
          } else {
            const target = cities[receiver.id]
            cities[receiver.id] = {
              ...target,
              stock: stockWith(target.stock, cargo.type, delivered),
            }
          }

          const legKm = tariffKm(graph, cargo.originId, nodeId)
          const rest = cargo.tons - delivered

          vehicle = {
            ...vehicle,
            cargo:
              rest > TONS_EPSILON
                ? { type: cargo.type, tons: rest, originId: cargo.originId }
                : null,
          }

          // Остаток, если он есть, поедет дальше и будет оплачен уже от этой
          // точки — то есть НЕДОплачен. Так и задумано: недоплата обидна, а
          // лишние деньги в замкнутой экономике — это дыра, через которую
          // утекает весь баланс, и находится она обычно к концу партии.
          const money = deliveryRevenue(cargo.type, delivered, legKm)
          const owner = companies[vehicle.ownerId]
          if (money > 0 && owner !== undefined) {
            // Через creditRevenue, а не прибавкой к money напрямую. Деньги на
            // счету в обоих случаях правильные, и юнит-тесты обеих сторон
            // стыка оставались зелёными — а dailyRevenue не пополнялся никогда.
            // Панель компании показывала нулевую выручку и вечный убыток даже
            // тогда, когда одна машина приносила миллион за два месяца: то
            // есть единственный поток, по которому игрок судит о своей сети,
            // врал в одну сторону.
            companies[vehicle.ownerId] = creditRevenue(owner, money)
          }
        }
      }
    }

    // ─── Погрузка ────────────────────────────────────────────────────────
    if (vehicle.cargo === null || vehicle.cargo.tons <= TONS_EPSILON) {
      const capacity = Number.isFinite(vehicle.capacity) ? vehicle.capacity : 0

      if (capacity > TONS_EPSILON) {
        const pickup = findPickup(
          industries,
          nodeId,
          capacity,
          stop === null ? null : stop.load,
        )

        if (pickup !== null) {
          const source = industries[pickup.industryId]
          industries[pickup.industryId] = {
            ...source,
            stock: stockWith(source.stock, pickup.cargo, -pickup.tons),
          }
          vehicle = {
            ...vehicle,
            cargo: { type: pickup.cargo, tons: pickup.tons, originId: nodeId },
          }
        }
      }
    }

    // ─── Мёртвый груз ────────────────────────────────────────────────────
    // Машина, простоявшая с непринятым грузом дольше порога, списывает его.
    // Ждать при полном складе получателя правильно, ждать вечно — нет: без
    // этого машина до конца партии возила бы ненужную партию по кругу, жгла
    // зарплату и топливо и показывала при этом идеальный гружёный пробег.
    if (vehicle.cargo !== null && vehicle.cargo.tons > TONS_EPSILON) {
      const blocked = vehicle.blockedTicks + 1
      vehicle =
        blocked >= DEAD_CARGO_DAYS * TICKS_PER_DAY
          ? { ...vehicle, cargo: null, blockedTicks: 0 }
          : { ...vehicle, blockedTicks: blocked }
    } else if (vehicle.blockedTicks !== 0) {
      vehicle = { ...vehicle, blockedTicks: 0 }
    }

    if (vehicle !== before) {
      vehicles[id] = vehicle
      changed = true
    }
  }

  // Ни одна машина ничего не сделала — возвращаем то же состояние по ссылке.
  // Любое изменение складов, денег и грузов всегда сопровождается изменением
  // машины, поэтому одного флага достаточно.
  if (!changed) return state

  return {
    ...state,
    world: { ...state.world, cities, industries },
    companies,
    vehicles,
  }
}
