/**
 * Что машине делать в городе, где она стоит.
 *
 *   'остановка' — машина на линии стоит на своей остановке, работает по её
 *                 спискам и только по ним.
 *   'мимо'      — машина на линии стоит в городе, которого в её кольце нет
 *                 (транзитный узел, ручной перегон, город удалён из линии).
 *                 Не делает ничего: линия сказала «здесь работы нет», и
 *                 подменять её решение автоматикой значит стирать разницу
 *                 между спроектированной сетью и «вози что дают».
 *   'разовый'   — линии нет, работает прежняя автоматика.
 */
type Orders =
  | { kind: 'остановка'; stop: Stop }
  | { kind: 'мимо' }
  | { kind: 'разовый' }

/**
 * Остановка кольца, отвечающая городу, в котором машина стоит.
 *
 * Обычно это ровно stops[stopIndex]: индекс показывает остановку, к которой
 * машина ехала, и на границе тика она стоит именно на ней. Но фаза
 * диспетчеризации идёт ПЕРЕД движением и может успеть перевести индекс на
 * следующую остановку в том же тике, в котором машина ещё стоит на прежней
 * (маршрут не построился, дорога непроезжая). Поэтому индекс — не приговор, а
 * точка отсчёта: дальше кольцо просматривается ВПЕРЁД до первого совпадения по
 * городу.
 *
 * Направление обхода тоже не случайно. Город может стоять в кольце дважды с
 * разными инструкциями — узловая база, куда заезжают и по дороге туда, и по
 * дороге обратно, — и из двух одноимённых остановок правильной всегда будет
 * БЛИЖАЙШАЯ ВПЕРЁД по ходу линии, а не первая в списке.
 */
function stopAt(line: Line, stopIndex: number, nodeId: CityId): Stop | null {
  const count = line.stops.length
  if (count === 0) return null

  // Битый индекс (сохранение старой версии, укоротившаяся линия) — не повод
  // ронять тик: начинаем обход с начала кольца.
  const start =
    Number.isInteger(stopIndex) && stopIndex >= 0 && stopIndex < count
      ? stopIndex
      : 0

  for (let i = 0; i < count; i++) {
    const stop = line.stops[(start + i) % count]
    if (stop.nodeId === nodeId) return stop
  }

  return null
}

/**
 * Инструкция для машины в этом городе.
 *
 * Линия ищется у ВЛАДЕЛЬЦА машины: линии принадлежат компаниям (Company.lines),
 * и конкурент со своей сетью обслуживается ровно этим же кодом.
 *
 * Потерянная линия (её удалили, а машину не отвязали; сейв, где lineId ссылается
 * в пустоту) роняет машину в режим разовых рейсов, а не останавливает её
 * навсегда. Парализованная машина, продолжающая жечь зарплату и не подающая
 * признаков жизни, — худший из возможных ответов на дыру в данных.
 */
function ordersFor(
  companies: Record<CompanyId, Company>,
  vehicle: Vehicle,
  nodeId: CityId,
): Orders {
  const assigned = vehicle.lineId
  if (!assigned) return { kind: 'разовый' }

  const line = companies[vehicle.ownerId]?.lines?.[assigned]
  // Линии меньше чем из двух остановок не существует как кольца (types.ts),
  // и работать по ней нельзя — это заготовка, которую игрок ещё редактирует.
  if (line === undefined || line.stops.length < 2) return { kind: 'разовый' }

  const stop = stopAt(line, vehicle.stopIndex, nodeId)
  return stop === null ? { kind: 'мимо' } : { kind: 'остановка', stop }
}

// ─── Разгрузка ─────────────────────────────────────────────────────────────

/**
 * Кто в городе готов принять груз и сколько ещё влезет на его склад.
 *
 * У склада нет идентификатора постройки: тонны раскладывает по ангарам сам
 * economy/buildings.ts (acceptToStorage), потому что построек со вместимостью в
 * городе может быть две — склад и хаб. Знать, в какую именно они лягут, фазе
 * прибытия незачем, а держать здесь вторую копию правила раскладки — значит
 * однажды разойтись с ним.
 */
type Receiver =
  | { kind: 'предприятие'; id: IndustryId; free: Tons }
  | { kind: 'город'; id: CityId; free: Tons }
  | { kind: 'склад'; free: Tons }

/**
 * Найти в городе того, кто примет этот груз.
 *
 * ПРЕДПРИЯТИЯ ИМЕЮТ ПРИОРИТЕТ НАД ГОРОДОМ. В нынешних данных пересечения нет —
 * города потребляют только готовую продукцию, а она никому не сырьё, — но
 * порядок зафиксирован заранее и в нужную сторону: как только появится груз,
 * который и потребляется городом, и перерабатывается (топливо для АЗС — первый
 * кандидат), приоритет города означал бы, что провезти его в переработку
 * физически нельзя. Цепочка всегда должна иметь возможность продолжиться.
 *
 * Предприятие с полным складом ПРОПУСКАЕТСЯ, а не блокирует разгрузку. Иначе
 * задохнувшийся завод в городе перекрывал бы дорогу голодному соседу, и
 * причину этого игрок не увидел бы никак.
 *
 * СВОЙ СКЛАД — ПОСЛЕДНИЙ В ОЧЕРЕДИ, и это единственный разумный порядок. Завод
 * и город груз ПОТРЕБЛЯЮТ: не отдай им тонны сейчас — завод встанет, город
 * недоест, и оба сообщат об этом игроку. Склад не потребляет ничего, он ждёт.
 * Поставь его вперёд — и машина, приехавшая на мукомольный, ссыпала бы зерно в
 * соседний ангар, завод бы голодал при полном складе через дорогу, а игрок
 * видел бы остановленное производство и не понимал, почему поставки идут.
 */
function findReceiver(
  industries: Record<IndustryId, Industry>,
  cities: Record<CityId, City>,
  owner: Company | undefined,
  cityId: CityId,
  cargo: CargoType,
  /**
   * Груз взят В ЭТОМ ЖЕ ГОРОДЕ.
   *
   * Заводу и городу отдать его нельзя — иначе появляется тихий способ снабжать
   * собственный город даром: погрузить у своего же завода, покататься и сдать
   * обратно. А вот СВОЙ СКЛАД принять может, и это не поблажка: плечо нулевое,
   * значит и выручка нулевая (deliveryRevenue не платит за ноль километров), а
   * смысл операции совсем другой — снять продукцию с задыхающегося завода, пока
   * игрок собирает под цепочку парк. Правило сформулировано в шапке
   * economy/buildings.ts, пункт 5.
   */
  fromHere: boolean,
): Receiver | null {
  if (fromHere) return storageReceiver(owner, cityId)

  for (const industry of Object.values(industries)) {
    if (industry.cityId !== cityId) continue

    const recipe = RECIPE_BY_INDUSTRY[industry.type]
    if (recipe === undefined) continue
    if (!recipe.inputs.some((input) => input.type === cargo)) continue

    // Потолок берётся у производства, а не считается здесь заново: правило
    // переполнения в игре обязано быть ровно одно. Разойдись эти две формулы —
    // и завод душился бы на одном числе, а машины сыпали бы в него до другого.
    const free = stockCapacity(industry, cargo) - (industry.stock[cargo] ?? 0)
    if (free > TONS_EPSILON) {
      return { kind: 'предприятие', id: industry.id, free }
    }
  }

  if (CONSUMER_CARGO.includes(cargo)) {
    const city = cities[cityId]
    if (city !== undefined) {
      const free = cityCapacity(city, cargo) - (city.stock[cargo] ?? 0)
      if (free > TONS_EPSILON) {
        return { kind: 'город', id: city.id, free }
      }
    }
  }

  return storageReceiver(owner, cityId)
}

/**
 * Свои склады города как приёмник, если в них ещё есть место.
 *
 * Склады берутся ТОЛЬКО У ВЛАДЕЛЬЦА МАШИНЫ. Сгружать груз в чужой ангар нельзя
 * ни за деньги, ни бесплатно: это была бы готовая дыра, через которую
 * конкуренту можно забить хранилище ненужным ему грузом.
 *
 * Вместимость спрашивается у economy/buildings.ts, а не считается здесь: там же
 * живёт правило, что вместимость общая на все грузы, и вторая его копия
 * разошлась бы с первой при первой же правке.
 */
function storageReceiver(
  owner: Company | undefined,
  cityId: CityId,
): Receiver | null {
  if (owner === undefined) return null

  const free = freeStorageIn(owner, cityId)
  return free > TONS_EPSILON ? { kind: 'склад', free } : null
}

// ─── Погрузка ──────────────────────────────────────────────────────────────

/** Найденная партия к погрузке: у кого берём, что и сколько. */
type Pickup =
  | { kind: 'предприятие'; id: IndustryId; cargo: CargoType; tons: Tons }
  | { kind: 'склад'; cargo: CargoType; tons: Tons }

/**
 * Взять груз у одного предприятия, если он у него есть.
 *
 * БЕРЁТСЯ ТОЛЬКО ГОТОВАЯ ПРОДУКЦИЯ (recipe.output), и это правило общее для
 * обоих режимов. Сырьё, лежащее на складе переработки, уже доставлено и уже
 * оплачено; разреши его забрать — и появляется вечный двигатель: увёз с
 * мукомольного привезённое туда зерно, вернул на элеватор, привёз обратно, и
 * так до бесконечности с оплатой каждого плеча.
 *
 * `wanted === null` означает «что угодно, что готово к вывозу» — режим разовых
 * рейсов.
 *
 * СВЕРКА С КУЗОВОМ ЖИВЁТ ЗДЕСЬ, в единственной точке, через которую проходят
 * оба режима. Разложи её по веткам вызывающего — и однажды линия начала бы
 * возить в цистерне зерно, потому что проверку добавили только в автоматику.
 * Тягач без прицепа отсекается тем же вызовом: canCarry(null, …) — всегда
 * «нет», отдельного условия для этого не требуется.
 */
function pickupFrom(
  industry: Industry,
  nodeId: CityId,
  capacity: Tons,
  wanted: CargoType | null,
  trailer: TrailerType | null,
): Pickup | null {
  if (industry.cityId !== nodeId) return null

  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  if (recipe === undefined) return null
  if (wanted !== null && recipe.output !== wanted) return null
  if (!canCarry(trailer, recipe.output)) return null

  const available = industry.stock[recipe.output] ?? 0
  const tons = Math.min(capacity, available)
  if (tons <= TONS_EPSILON) return null

  return { kind: 'предприятие', id: industry.id, cargo: recipe.output, tons }
}

/**
 * Взять груз со своего склада, если он там лежит.
 *
 * ЗДЕСЬ НЕТ ПРАВИЛА «ТОЛЬКО ГОТОВАЯ ПРОДУКЦИЯ», в отличие от предприятия, и это
 * не послабление. У завода склад общий на вход и выход, поэтому запрет забирать
 * привезённое сырьё — единственное, что мешает возить одну и ту же партию между
 * элеватором и мукомольным с оплатой каждого плеча. У склада игрока входа и
 * выхода не существует вовсе: всё, что там лежит, туда привезли, и «забрать
 * своё» — это ровно та операция, ради которой склад и строится. Вечного
 * двигателя из этого не выходит по другой причине: перевалка в свой склад не
 * оплачивается (разбор — в разделе выгрузки внутри runArrivals).
 *
 * Кузов сверяется тем же canCarry, что и у предприятия: цистерна не увезёт муку
 * из ангара так же, как не увезёт её с мельницы.
 *
 * ЗДЕСЬ ЖЕ ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЭТОТ ФАЙЛ ЗАБЕГАЕТ ВПЕРЁД ФАЗЫ ОБСЛУЖИВАНИЯ.
 * Оценка работы в logistics/service.ts (pickupTons) считает тонны только по
 * складам ПРЕДПРИЯТИЙ и про Building.stock не знает — там про это оставлена
 * прямая пометка. Значит машина, которой в узле нечего делать, кроме как забрать
 * груз со своего же ангара, поста не получает и грузится за один тик. Это
 * последний остаток мгновенной погрузки в игре, и чинится он одной строкой в
 * pickupTons: тоннаж обязан учитывать storedIn(owner, nodeId, cargo).
 */
function pickupFromStorage(
  owner: Company | undefined,
  nodeId: CityId,
  capacity: Tons,
  wanted: CargoType | null,
  trailer: TrailerType | null,
): Pickup | null {
  if (owner === undefined) return null

  const offered = wanted !== null ? [wanted] : storedCargoAt(owner, nodeId)

  for (const cargo of offered) {
    if (!canCarry(trailer, cargo)) continue

    // Остаток спрашивается у economy/buildings.ts и суммируется по всем
    // постройкам города: склад и хаб рядом — это одно хранилище с точки зрения
    // машины, и делить между ними одну ходку игрок не нанимался.
    const tons = Math.min(capacity, storedIn(owner, nodeId, cargo))
    if (tons > TONS_EPSILON) return { kind: 'склад', cargo, tons }
  }

  return null
}

/**
 * Какие грузы лежат на складах компании в этом городе, в порядке вставки.
 *
 * Нужно только автоматике разового рейса: линия называет груз сама. Порядок
 * обязан быть воспроизводимым, поэтому берётся порядок ключей — тот же довод,
 * что и для порядка обхода машин в шапке файла.
 */
function storedCargoAt(owner: Company, cityId: CityId): CargoType[] {
  const found: CargoType[] = []
  for (const building of buildingsIn(owner, cityId)) {
    for (const key of Object.keys(building.stock) as CargoType[]) {
      if (!found.includes(key)) found.push(key)
    }
  }
  return found
}

/**
 * Что грузить в этом городе.
 *
 * `wanted === null` — автоматика разового рейса: берётся первое, что нашлось у
 * местных предприятий в порядке вставки.
 *
 * Непустой список — инструкция остановки, и ПОРЯДОК В НЁМ ЗАДАЁТ ПРИОРИТЕТ:
 * внешний цикл идёт по грузам, а не по предприятиям. Игрок пишет «сначала
 * топливо, если нет — мука», и получает ровно это. Пустой список (и список, по
 * которому в городе ничего нет) даёт null: машина уйдёт порожней, и её порожний
 * пробег будет виден в отчёте.
 *
 * Кузов один и груз в нём один: набрать по паре тонн разного нельзя. Смешанные
 * партии — это уже сборный груз, у него своя экономика, и её пока нет.
 *
 * НЕПОДХОДЯЩИЙ ПОД КУЗОВ ГРУЗ ПРОСТО ПРОПУСКАЕТСЯ, как и отсутствующий в
 * городе. Для списка остановки это значит, что машина с цистерной, которой
 * велено «топливо, если нет — зерно», возьмёт топливо и никогда зерно: список
 * остаётся приоритетом игрока, а кузов — физикой. Обе причины уйти порожней
 * выглядят для игрока одинаково (пустой кузов в отчёте), и это правильно —
 * различать их должен он сам, глядя на линию и на машину.
 *
 * ПРЕДПРИЯТИЕ ВПЕРЁД СВОЕГО СКЛАДА, и порядок тут ровно обратный тому, что у
 * приёмки, — по той же причине. Невывезенный завод ЗАДЫХАЕТСЯ: склад забивается,
 * выпуск падает, простой копится (см. Industry.idleTicks в types.ts). Склад
 * игрока не портится ничем, он ждёт сколько угодно. Значит первым обслуживают
 * того, кому промедление стоит производства, а свой ангар разбирают тем, что
 * осталось. Обратный порядок дал бы линию, которая бесконечно перекладывает
 * тонны из ангара в ангар мимо стоящего рядом завода.
 *
 * СВОЙ СКЛАД ЗАКРЫТ, ЕСЛИ МАШИНА В ЭТОМ ЖЕ ТИКЕ В НЕГО ВЫГРУЗИЛАСЬ (`justStored`).
 * Иначе разгрузка и погрузка на складе схлопываются: машина ссыпала шесть тонн
 * муки в ангар и тут же забрала их обратно. Пользы ноль, зато cargo.originId
 * переехал в этот город, и тарифное плечо следующей доставки молча укоротилось —
 * то есть игрок потерял деньги там, где ничего не делал. Закрыты при этом ВСЕ
 * склады города, а не только тот, куда легли тонны: склад и хаб рядом — это одно
 * хранилище (см. pickupFromStorage), и перекладывать между ними по кругу машине
 * незачем.
 */
function findPickup(
  industries: Record<IndustryId, Industry>,
  owner: Company | undefined,
  nodeId: CityId,
  capacity: Tons,
  wanted: readonly CargoType[] | null,
  trailer: TrailerType | null,
  justStored: boolean,
): Pickup | null {
  const fromStorage = (cargo: CargoType | null): Pickup | null =>
    justStored ? null : pickupFromStorage(owner, nodeId, capacity, cargo, trailer)

  if (wanted === null) {
    for (const industry of Object.values(industries)) {
      const pickup = pickupFrom(industry, nodeId, capacity, null, trailer)
      if (pickup !== null) return pickup
    }
    return fromStorage(null)
  }

  for (const cargo of wanted) {
    for (const industry of Object.values(industries)) {
      const pickup = pickupFrom(industry, nodeId, capacity, cargo, trailer)
      if (pickup !== null) return pickup
    }

    const stored = fromStorage(cargo)
    if (stored !== null) return stored
  }

  return null
}

/**
 * Склад с изменённым остатком по одному грузу. Новый объект — вход не меняется.
 *
 * Одна функция и на приёмку, и на отгрузку: знак у delta. Склад города и склад
 * предприятия устроены одинаково (types.ts объясняет, почему у предприятия он
 * общий на вход и выход), поэтому и функция одна.
 */
function stockWith(
  stock: Partial<Record<CargoType, Tons>>,
  cargo: CargoType,
  delta: Tons,
): Partial<Record<CargoType, Tons>> {
  const next: Partial<Record<CargoType, Tons>> = { ...stock }
  next[cargo] = (stock[cargo] ?? 0) + delta
  return next
}

/**
 * Отсчитать машине ещё один ОТКАЗ в разгрузке.
 *
 * Машина, получившая отказ подряд больше порога, списывает груз: ждать при
 * полном складе получателя правильно, ждать вечно — нет. Без этого машина до
 * конца партии возила бы ненужную партию по кругу, жгла зарплату и топливо и
 * показывала при этом идеальный гружёный пробег.
 *
 * СЧЁТ ИДЁТ ПО ОТКАЗАМ, А НЕ ПО ТИКАМ, и это обещание шапка давала с среза 5,
 * а код не выполнял: он прибавлял единицу за КАЖДЫЙ тик, в котором в кузове
 * что-нибудь лежало. Разбор потерь за игровой год, по причинам приращения:
 *
 *   успешная выгрузка на этом же тике        2 995
 *   свежая погрузка на этом же тике             66
 *   груз просто не для этой остановки       14 197
 *   НАСТОЯЩИЙ ОТКАЗ (некому сдать)               0
 *
 * То есть счётчик не поймал ни одного случая, ради которого написан, зато
 * уничтожил 311.5 тонны ЖИВОГО груза за 55 списаний у исправно работающих
 * сетей — ровно та поломка, которую шапка называла самой дорогой из возможных,
 * потому что выглядит она как «почему-то стало меньше выручки». Все девять
 * машин конкурентов доходили до `blockedTicks = 287` из 288.
 *
 * Механизм был прост: на кольце с двумя гружёными плечами кузов не пустеет
 * никогда, а обнуление стояло единственное — по пустому кузову.
 *
 * ЧТО СЧИТАЕТСЯ ОТКАЗОМ. Ровно один случай: машина стояла в узле, груз в
 * кузове предназначался ЭТОЙ остановке (или машина идёт без линии), и сдать
 * его было некому — получателя нет вовсе либо у него нет ни тонны свободного
 * места. Всё остальное обнуляет счётчик: сдал хоть сколько-нибудь, взял новый
 * груз, везёт транзитом мимо этой остановки.
 *
 * ПОРОГ ВЫРАЖЕН В ПОПЫТКАХ, А НЕ В СУТКАХ. Прежнее `DEAD_CARGO_DAYS × 96`
 * означало трое суток непрерывного стояния, но попытка разгрузки случается
 * не каждый тик: машина под погрузкой и в очереди на пост их не делает вовсе.
 * Три попытки подряд — это три подъезда к получателю, у которого нет места;
 * на любом реальном кольце это несколько суток и есть.
 *
 * Плата известна и не изменилась: машина с по-настоящему мёртвым грузом каждый
 * раз заново получает пост (оценка работы в logistics/service.ts завышающая и
 * вместимость получателя не проверяет), поэтому всё это время занимает рампу.
 * Лечится это не здесь, а в оценке работы: пост не нужен тому, кому некому
 * сдать груз.
 */
function markBlocked(vehicle: Vehicle, refused: boolean): Vehicle {
  if (!refused) {
    return vehicle.blockedTicks !== 0 ? { ...vehicle, blockedTicks: 0 } : vehicle
  }

  const blocked = vehicle.blockedTicks + 1
  return blocked >= DEAD_CARGO_ATTEMPTS
    ? { ...vehicle, cargo: null, blockedTicks: 0 }
    : { ...vehicle, blockedTicks: blocked }
}

/**
 * Фаза прибытия целиком. Возвращает НОВОЕ состояние.
 *
 * Правила ровно три, и все про машину, стоящую в узле:
 *
 *   0. Машина под погрузкой и машина в очереди на пост пропускаются: их время
 *      считает фаза обслуживания, а тонны двигаются только когда счётчик
 *      обнулился. Это стык среза 5, разобранный у readyForWork.
 *   1. Гружёная отдаёт груз, если этот груз ей велено здесь выгрузить (или,
 *      без линии, если в городе есть кому его принять), и получает деньги за
 *      тонны и километры от места погрузки. Свой склад принимает груз последним
 *      и оплачивается ПОЛОВИНОЙ тарифа: это перевалка, а не продажа, и полная
 *      оплата сделала бы из двух складов вечный двигатель.
 *   2. Пустая берёт то, что велено взять здесь (или, без линии, первое, что
 *      готово к вывозу), — но только если это влезает в её кузов. Тягач без
 *      прицепа не берёт ничего и уходит порожним. Свой склад отдаёт груз после
 *      предприятий: завод без вывоза задыхается, ангар ждёт сколько угодно.
 *
 * Взять обратно собственный груз машина при этом не может: у предприятия
 * грузится только ГОТОВАЯ ПРОДУКЦИЯ, а привезённое сырьё продукцией не является
 * ни для кого в этом городе; из своего же склада нельзя забрать то, что в него
 * ссыпали в этом же тике.
 */
export function runArrivals(state: GameState): GameState {
  // Граф строится один раз на фазу: тарифное расстояние спрашивают все
  // разгружающиеся машины, а сеть за тик не меняется.
  const graph = buildGraph(state.world.edges)

  // Рабочие копии верхнего уровня. Записи внутри либо остаются исходными по
  // ссылке, либо заменяются НОВЫМИ объектами — исходное состояние не
  // затрагивается ни на одном уровне вложенности.
  const vehicles: Record<VehicleId, Vehicle> = { ...state.vehicles }
  const industries: Record<IndustryId, Industry> = { ...state.world.industries }
  const cities: Record<CityId, City> = { ...state.world.cities }
  const companies: Record<CompanyId, Company> = { ...state.companies }

  let changed = false

  for (const id of Object.keys(vehicles) as VehicleId[]) {
    const before = vehicles[id]

    // Машина в пути ничего не грузит: погрузка бывает только в узле.
    if (before.position.kind !== 'узел') continue
    const nodeId = before.position.nodeId

    /*
     * БАНКРОТ НЕ ВОЗИТ И НЕ ЗАРАБАТЫВАЕТ.
     *
     * Расходы обанкротившейся конторе уже не начисляют — фаза расходов зовёт
     * для неё freeze() (см. economy/operating.ts), — а фаза прибытия её никак
     * не выделяла. Получалась контора с НУЛЕВОЙ СЕБЕСТОИМОСТЬЮ: замер A/B на
     * живом мире дал платёжеспособному нишевому +149 658 за 120 суток против
     * +477 821 у объявленного банкротом за 30. Деньги при этом мёртвые —
     * банкроту незаконна любая команда, и флаг с него не снимается никогда, —
     * то есть это не выигрышная стратегия, а враньё в отчёте плюс парк-призрак,
     * бесплатно выбирающий груз с чужих складов у живых компаний.
     */
    const owner = companies[before.ownerId]
    if (owner !== undefined && owner.bankrupt) continue

    const orders = ordersFor(companies, before, nodeId)
    // Машина на линии стоит не на своей остановке — здесь для неё работы нет.
    // Транзит не считается стоянием с непринятым грузом: машина едет дальше.
    if (orders.kind === 'мимо') continue

    // Пост ещё не отработал или машина стоит в очереди — тонны не двигаются.
    // Разбор стыка с фазой обслуживания — у readyForWork и в шапке файла.
    if (!readyForWork(before)) continue

    // Дальше режим отличает ровно одно: null — прежняя автоматика, объект —
    // инструкция остановки. Обе ветки ниже читаются как одна процедура с
    // разным источником решения о том, что выгружать и что грузить.
    const stop = orders.kind === 'остановка' ? orders.stop : null

    let vehicle = before

    /**
     * Машина в этом тике выгрузилась на свой склад.
     *
     * Нужно ровно затем, чтобы погрузка ниже не забрала обратно то, что
     * разгрузка только что положила, — разбор у findPickup.
     */
    let justStored = false

    /*
     * БЫЛ ЛИ ЭТО ОТКАЗ — решается здесь и только здесь.
     *
     * Отказ — это «груз предназначался ЭТОЙ остановке, а сдать его оказалось
     * некому». Всё остальное отказом не является и обязано обнулять счётчик:
     * транзитный груз мимо остановки, успешная выгрузка любого объёма, свежая
     * погрузка. Разбор, чем кончилось смешение этих случаев, — у markBlocked.
     */
    let refused = false

    // ─── Выгрузка ────────────────────────────────────────────────────────
    const cargo = vehicle.cargo
    if (
      cargo !== null &&
      cargo.tons > TONS_EPSILON &&
      // Линия выгружает ТОЛЬКО перечисленное. Груз, которого нет в списке,
      // едет дальше, даже если в городе его ждут: остановка — это инструкция,
      // а не пожелание. Иначе транзит через город-потребитель разбирал бы
      // машину на полпути, и сквозные плечи были бы невозможны.
      (stop === null || stop.unload.includes(cargo.type))
    ) {
      const receiver = findReceiver(
        industries,
        cities,
        companies[vehicle.ownerId],
        nodeId,
        cargo.type,
        cargo.originId === nodeId,
      )

      // Влезает не всё — отдаём сколько влезет. Остаток едет дальше искать
      // второго получателя. Альтернатива «или всё, или ничего» проще, но
      // намертво запирает цепочку: полный склад останавливал бы поставки
      // ровно тогда, когда завод вот-вот начнёт потреблять.
      const room = receiver === null ? 0 : Math.min(cargo.tons, receiver.free)

      // Приехали сдавать — и сдать некому. Вот это и есть отказ, единственный
      // случай, ради которого счётчик написан. Ниже он снимется, если хоть
      // сколько-нибудь тонн всё же легло.
      refused = true

      if (receiver !== null && room > TONS_EPSILON) {
        let delivered = room

        if (receiver.kind === 'предприятие') {
          const target = industries[receiver.id]
          industries[receiver.id] = {
            ...target,
            stock: stockWith(target.stock, cargo.type, delivered),
          }
        } else if (receiver.kind === 'город') {
          const target = cities[receiver.id]
          cities[receiver.id] = {
            ...target,
            stock: stockWith(target.stock, cargo.type, delivered),
          }
        } else {
          // Раскладку по ангарам делает economy/buildings.ts: построек со
          // вместимостью в городе может быть две, и правило, в какую класть
          // первой, обязано жить в одном месте. Оттуда же берётся ФАКТИЧЕСКИ
          // принятое — свободное место могло измениться между вопросом и
          // ответом только у нас в голове, но полагаться на это нельзя: платить
          // машине надо ровно за те тонны, которые действительно легли.
          const owner = companies[vehicle.ownerId]
          const result =
            owner === undefined
              ? null
              : acceptToStorage(owner, nodeId, cargo.type, delivered)

          if (result === null) {
            delivered = 0
          } else {
            companies[result.company.id] = result.company
            delivered = result.accepted
            justStored = delivered > TONS_EPSILON
          }
        }

        if (delivered > TONS_EPSILON) {
          // Хоть сколько-нибудь легло — это не отказ. Остаток поедет дальше и
          // будет предложен следующему получателю; счёт отказов начнётся
          // заново, потому что мерить надо ПОДРЯД идущие неудачи.
          refused = false

          const legKm = tariffKm(graph, cargo.originId, nodeId)
          const rest = cargo.tons - delivered

          vehicle = {
            ...vehicle,
            cargo:
              rest > TONS_EPSILON
                ? { type: cargo.type, tons: rest, originId: cargo.originId }
                : null,
          }

          /*
           * ПЕРЕВАЛКА В СВОЙ СКЛАД ОПЛАЧИВАЕТСЯ НЕ ПОЛНОСТЬЮ, И ЭТО НЕ СКУПОСТЬ,
           * А ЕДИНСТВЕННОЕ, ЧТО ДЕРЖИТ СКЛАДЫ ВНУТРИ ГЛАВНОГО ИНВАРИАНТА.
           *
           * Груз, сданный на склад, можно оттуда забрать. Значит два своих
           * склада в разных городах — это кольцо, по которому одни и те же
           * тонны ездят вечно, ничего никому не доставляя. Оба его плеча
           * гружёные, а инвариант из data/operating.ts прямо утверждает, что
           * кольцо с двумя гружёными плечами прибыльно, — то есть при полной
           * оплате получился бы вечный двигатель, и находился бы он не игроком,
           * а первым же оптимизатором.
           *
           * Доля выведена, а не подобрана на глаз: разбор с неравенствами — у
           * TRANSSHIPMENT_SHARE в economy/buildings.ts. Здесь важно другое —
           * ставка спрашивается ТАМ ЖЕ, где живёт её обоснование, и своей копии
           * множителя в этом файле нет.
           */
          // Тариф — у КЛАССА машины, а не глобальный: ставка за
          // тонно-километр падает с размером партии, и на этом держится
          // главный инвариант на тяжёлой технике. Класс неизвестен (битый
          // сейв) — платить не за что, иначе неизвестная машина получила бы
          // самый выгодный тариф молча.
          const vehicleClass = VEHICLE_CLASS_BY_ID[vehicle.classId]
          const money =
            vehicleClass === undefined
              ? 0
              : receiver.kind === 'склад'
                ? transshipmentRevenue(
                    cargo.type,
                    delivered,
                    legKm,
                    vehicleClass.tariffPerTonKm,
                    vehicleClass.handlingPerTon,
                  )
                : deliveryRevenue(
                    cargo.type,
                    delivered,
                    legKm,
                    vehicleClass.tariffPerTonKm,
                    vehicleClass.handlingPerTon,
                  )

          // Остаток, если он есть, поедет дальше и будет оплачен уже от этой
          // точки — то есть НЕДОплачен. Так и задумано: недоплата обидна, а
          // лишние деньги в замкнутой экономике — это дыра, через которую
          // утекает весь баланс, и находится она обычно к концу партии.
          const owner = companies[vehicle.ownerId]
          if (money > 0 && owner !== undefined) {
            // Через creditRevenue, а не прибавкой к money напрямую. Деньги на
            // счету в обоих случаях правильные, и юнит-тесты обеих сторон
            // стыка оставались зелёными — а dailyRevenue не пополнялся никогда.
            // Панель компании показывала нулевую выручку и вечный убыток даже
            // тогда, когда одна машина приносила миллион за два месяца: то
            // есть единственный поток, по которому игрок судит о своей сети,
            // врал в одну сторону.
            companies[vehicle.ownerId] = creditRevenue(owner, money)
          }
        }
      }
    }

    // ─── Погрузка ────────────────────────────────────────────────────────
    if (vehicle.cargo === null || vehicle.cargo.tons <= TONS_EPSILON) {
      const capacity = Number.isFinite(vehicle.capacity) ? vehicle.capacity : 0

      if (capacity > TONS_EPSILON) {
        const pickup = findPickup(
          industries,
          companies[vehicle.ownerId],
          nodeId,
          capacity,
          stop === null ? null : stop.load,
          vehicle.trailer,
          justStored,
        )

        if (pickup !== null) {
          let taken = pickup.tons

          if (pickup.kind === 'предприятие') {
            const source = industries[pickup.id]
            industries[pickup.id] = {
              ...source,
              stock: stockWith(source.stock, pickup.cargo, -pickup.tons),
            }
          } else {
            // Сколько удалось СНЯТЬ со складов, а не сколько собирались: тонны
            // могут лежать в двух ангарах города, и разбирает их по кускам
            // economy/buildings.ts. Взять в кузов больше, чем оттуда выдали,
            // значило бы напечатать груз из воздуха.
            const owner = companies[vehicle.ownerId]
            const result =
              owner === undefined
                ? null
                : releaseFromStorage(owner, nodeId, pickup.cargo, pickup.tons)

            if (result === null) {
              taken = 0
            } else {
              companies[result.company.id] = result.company
              taken = result.released
            }
          }

          if (taken > TONS_EPSILON) {
            // Свежий груз — счёт отказов начинается с нуля: это уже другая
            // партия, и прошлые неудачи к ней отношения не имеют.
            refused = false
            vehicle = {
              ...vehicle,
              cargo: { type: pickup.cargo, tons: taken, originId: nodeId },
            }
          }
        }
      }
    }

    // ─── Мёртвый груз ────────────────────────────────────────────────────
    // Считается ОТКАЗ, а не тик со следами груза в кузове, — см. markBlocked.
    vehicle = markBlocked(vehicle, refused)

    if (vehicle !== before) {
      vehicles[id] = vehicle
      changed = true
    }
  }

  // Ни одна машина ничего не сделала — возвращаем то же состояние по ссылке.
  // Любое изменение складов (предприятия, города, постройки), денег и грузов
  // всегда сопровождается изменением машины — тонны не переходят никуда, кроме
  // как из кузова и в кузов, — поэтому одного флага достаточно.
  if (!changed) return state

  return {
    ...state,
    world: { ...state.world, cities, industries },
    companies,
    vehicles,
  }
}
