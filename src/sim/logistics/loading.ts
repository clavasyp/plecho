/**
 * Фаза прибытия: погрузка и разгрузка машин, стоящих в узлах.
 *
 * Здесь мир и транспорт наконец встречаются. Движение (logistics/vehicle.ts)
 * ничего не знает про грузы, производство (economy/production.ts) ничего не
 * знает про машины — а тонны переходят со склада в кузов и обратно ровно в этом
 * файле, и деньги начисляются тоже здесь.
 *
 * ДВА РЕЖИМА, И ЭТО ГЛАВНОЕ ПРО ФАЙЛ.
 *
 *   МАШИНА НА ЛИНИИ работает строго по инструкции остановки: выгружает
 *   перечисленное в stop.unload, грузит перечисленное в stop.load, и ничего
 *   сверх этого. Здесь и живёт единственное настоящее решение игрока — он
 *   проектирует поток груза по сети, а не отправляет отдельные рейсы. Указано
 *   грузить то, чего в этом городе нет, — машина уходит ПОРОЖНЕЙ. Это не
 *   ошибка и не повод «помочь» игроку, подсунув что-нибудь другое: порожний
 *   пробег стоит ровно столько же топлива, сколько гружёный (см.
 *   Vehicle.fuelPer100Km), и он обязан появиться в отчёте как деньги. Молча
 *   исправленная плохая линия ничему не учит.
 *
 *   МАШИНА БЕЗ ЛИНИИ сохраняет прежнее автоматическое поведение: отдаёт груз
 *   тому, кому он нужен, и берёт то, что готово к вывозу. Это не пережиток
 *   среза 2, а нужный режим — разовыми рейсами игрок пробует плечо до того,
 *   как строить под него сеть, и перегоняет машину на новую линию.
 *
 * СКЛАД ИГРОКА — ТРЕТЬЯ СТОРОНА ПЕРЕВАЛКИ, появившаяся в срезе 5. Постройка со
 * storage > 0 и принимает груз, и отдаёт его обратно, разрывая плечо надвое:
 * одна машина привезла и уехала, другая забрала позже. Правила, которыми склад
 * отличается от завода и от города, разобраны у findReceiver и у findPickup, а
 * самое важное — что перевалка в СВОЙ склад не оплачивается — в разделе
 * выгрузки внутри runArrivals.
 *
 * КУЗОВ ОГРАНИЧИВАЕТ ОБА РЕЖИМА. Машина грузится только тем, что влезает в её
 * прицеп (совместимость — logistics/trailer.ts), а тягач без прицепа не берёт
 * ничего. Это не третий режим, а фильтр поверх обоих: сначала решается, ЧТО
 * грузить — по инструкции остановки или автоматикой, — и только потом груз
 * сверяется с кузовом. Порядок именно такой, потому что подмена на «тот груз,
 * что подойдёт» стёрла бы разницу между специализированным парком и случайным:
 * игрок, повесивший цистерну и оставивший в линии зерно, обязан увидеть
 * порожний пробег, а не тихо поехать с зерном.
 *
 * ВЫГРУЗКА КУЗОВОМ НЕ ОГРАНИЧЕНА, и это не забывчивость. Груз уже в машине;
 * запрет выгрузить его «неподходящим» кузовом означал бы, что партия заперта в
 * прицепе навсегда — машина возила бы её кругами до списания по мёртвому
 * грузу. Совместимость решает, что МОЖНО ВЗЯТЬ, и только это.
 *
 * ВЫГРУЗКА СТРОГО РАНЬШЕ ПОГРУЗКИ в обоих режимах. Причина не в аккуратности, а
 * в конкретном дефекте: машина, привёзшая зерно на мукомольный, стоит в городе,
 * где на складе теперь лежит её же зерно. Погрузка, идущая первой, увидела бы
 * полный кузов и промолчала, машина уехала бы порожней и вернулась бы за тем же
 * грузом — рейс вхолостую, который выглядит как нормальная работа. Порядок даёт
 * разворот в один тик: приехал, отдал, взял, поехал.
 *
 * ПОГРУЗКА БЫВАЕТ ТОЛЬКО НА СТОЯНКЕ. advanceVehicle доедает остаток тика и
 * проходит промежуточные города НАСКВОЗЬ, поэтому машина грузится там, где её
 * маршрут кончается. Для линии это ровно то, что нужно: диспетчеризация
 * (logistics/line.ts) выдаёт маршрут до ОДНОЙ следующей остановки, машина
 * встаёт на ней, отрабатывает инструкцию и на следующем тике получает маршрут
 * дальше.
 *
 * ─── СТЫК С ФАЗОЙ ОБСЛУЖИВАНИЯ: ГЛАВНОЕ ИЗМЕНЕНИЕ СРЕЗА 5 ──────────────────
 *
 * ПОГРУЗКА БОЛЬШЕ НЕ МГНОВЕННАЯ, и это меняет игру целиком. Пока тонны
 * перекладывались за ноль времени, десятая машина на линии стоила ровно
 * столько же, сколько первая, и правильным ответом на любую задачу было
 * «купить ещё грузовик». Теперь машина занимает пост на несколько часов, постов
 * у игрока в городе конечное число (BASE_POSTS в data/infrastructure.ts плюс
 * постройки), и вторая машина на том же заводе встаёт в очередь.
 *
 * ВРЕМЯ СЧИТАЕТ НЕ ЭТОТ ФАЙЛ. Разделение обязанностей такое:
 *
 *   service.ts  решает, КОГДА машина освободится. Занимает пост, кладёт в
 *               Vehicle.serviceTicksLeft длительность работ, отсчитывает тики,
 *               освобождает пост. Машине, которой поста не хватило, наращивает
 *               queuedTicks.
 *   loading.ts  (этот файл) решает, ЧТО машина погрузит и выгрузит, и делает
 *               это РОВНО В ТОТ ТИК, когда счётчик обслуживания дошёл до нуля.
 *   line.ts     не выпускает машину с остановки, пока счётчик не ноль.
 *
 * Фаза обслуживания идёт непосредственно ПЕРЕД этой (порядок в sim/tick.ts),
 * поэтому здесь достаточно посмотреть на счётчики: их значение уже относится к
 * текущему тику. Условие «машина готова к работе» вынесено в одну функцию
 * readyForWork — стык между двумя файлами обязан быть одной строкой, потому что
 * разъехавшись, эти два файла ломаются ТИХО. Слишком мягкое условие даёт
 * машину, которая грузится мгновенно, — то есть отменяет весь срез, не уронив
 * ни одного теста экономики. Слишком строгое даёт машину, которая стоит вечно,
 * и выглядит это как «линия почему-то ничего не везёт».
 *
 * ПОРЯДОК ОБХОДА ЗДЕСЬ ЗНАЧИМ, в отличие от фазы движения. Две машины в одном
 * городе тянут тонны из одного и того же склада, и вторая обязана видеть
 * результат первой — иначе обе увезут одну и ту же партию и тонны родятся из
 * ниоткуда. Поэтому машины обслуживаются ПОСЛЕДОВАТЕЛЬНО по рабочей копии
 * состояния, а не от общего снимка, как в moveVehicles.
 *
 * Раз порядок значим, он обязан быть воспроизводимым. Берётся порядок вставки
 * ключей: идентификаторы машин и предприятий — строки вида 'zil-1', 'elev-tula',
 * а для нечисловых ключей спецификация языка гарантирует обход в порядке
 * добавления, и JSON.parse этот порядок сохраняет. Единственный способ это
 * сломать — завести идентификаторы, выглядящие как целые числа ('1', '42'):
 * такие ключи движок поднимает наверх и сортирует численно, и порядок поедет.
 * Если это когда-нибудь случится, обход придётся явно сортировать; сейчас
 * достаточно не заводить числовых идентификаторов.
 *
 * СЧЁТЧИКИ ПРОБЕГА ЗДЕСЬ НЕ ТРОГАЮТСЯ. loadedKm и emptyKm разносит движение —
 * только оно знает, гружёной ли машина ехала. Разбор, почему это оказалось
 * важно, — в шапке advanceVehicle.
 *
 * Все функции чистые: входное состояние не меняется, включая вложенные объекты.
 */

