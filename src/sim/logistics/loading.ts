/**
 * Готова ли машина переваливать тонны ПРЯМО СЕЙЧАС.
 *
 * ЕДИНСТВЕННАЯ ТОЧКА, В КОТОРОЙ ЭТОТ ФАЙЛ ЗАВИСИТ ОТ ФАЗЫ ОБСЛУЖИВАНИЯ. Оба
 * счётчика ведёт logistics/service.ts, а она отрабатывает непосредственно перед
 * фазой прибытия, поэтому здесь читается уже сегодняшнее их значение.
 *
 *   serviceTicksLeft > 0 — машина стоит под погрузкой, работы идут. Тонны
 *                          перекладываются в ПОСЛЕДНИЙ тик обслуживания, когда
 *                          счётчик дошёл до нуля, а не в первый: иначе груз
 *                          оказывался бы в кузове раньше, чем машина отработала
 *                          своё время на посту, и весь простой был бы
 *                          декорацией — линия возила бы столько же, сколько при
 *                          мгновенной погрузке.
 *   queuedTicks > 0      — поста не хватило, машина ждёт очереди. Ноль постов
 *                          свободных означает, что переваливать физически негде,
 *                          и это ровно та ситуация, ради которой срез сделан:
 *                          вторая машина на том же заводе не работает вместе с
 *                          первой, а СТОИТ. Пропусти эту проверку — и очередь
 *                          превратилась бы в свою противоположность: машина, до
 *                          которой очередь не дошла, грузилась бы мгновенно,
 *                          пока стоящая на посту честно отсчитывает часы.
 *
 * Оба счётчика обнуляются фазой обслуживания в тот момент, когда работа на этой
 * остановке закончена, — и ровно тогда сюда попадает машина, которую можно
 * грузить.
 */
function readyForWork(vehicle: Vehicle): boolean {
  return !(vehicle.serviceTicksLeft > 0) && !(vehicle.queuedTicks > 0)
}

