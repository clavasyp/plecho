/**
 * Привести долю к 0..1, а битое число — к нулю.
 *
 * NaN, попавший в износ, отравляет его навсегда и молча: все последующие
 * сравнения с ним ложны, машина никогда не ломается и никогда не списывается.
 * Тот же довод — в шапке deliveryRevenue.
 */
function clamp01(value: number): number {
  if (!Number.isFinite(value)) return 0
  if (value <= 0) return 0
  if (value >= 1) return 1
  return value
}

/** Неотрицательное конечное число или ноль. Для счётчиков из старых сейвов. */
function positive(value: number): number {
  return Number.isFinite(value) && value > 0 ? value : 0
}

// ─── Износ ─────────────────────────────────────────────────────────────────

/** Во сколько раз дорога данного качества изнашивает машину сильнее идеальной. */
export function roadWearFactor(quality: number): number {
  // Качество вне 0..1 — битые данные. Ноль означает непроезжее ребро, и
  // множитель там максимальный, но машина по нему всё равно не поедет
  // (speedKmh даёт ноль), так что на игру это не влияет.
  return 1 + ROAD_WEAR_GAIN * (1 - clamp01(quality))
}

/**
 * Насколько просрочено ТО: 0 — вовремя, 1 — просрочено на полный интервал.
 *
 * Величина РАСТЁТ ПЛАВНО, а не включается на пороге. Порог означал бы, что
 * машина, проехавшая на километр больше норматива, мгновенно становится вдвое
 * прожорливее, — и игрок, поймавший этот скачок, справедливо счёл бы игру
 * несправедливой. Плавность же делает опоздание на пару сотен километров
 * пустяком, каким оно и является.
 *
 * ОГРАНИЧЕНИЕ СВЕРХУ. Просрочка на два интервала не хуже просрочки на один: у
 * запущенности есть потолок. Без потолка машина, забытая на полгода, уходила бы
 * в неограниченный износ и умирала бы мгновенно — наказание, несоразмерное
 * ошибке, и вдобавок непредсказуемое.
 */
export function serviceNeglect(kmSinceService: number): number {
  const overdue = positive(kmSinceService) - SERVICE_INTERVAL_KM
  return clamp01(overdue / SERVICE_INTERVAL_KM)
}

/** Машине пора на ТО. Нужно интерфейсу — счётчик игрок видеть обязан. */
export function needsService(vehicle: Vehicle): boolean {
  return positive(vehicle.kmSinceService) >= SERVICE_INTERVAL_KM
}

/**
 * Доля ресурса, съедаемая одним километром.
 *
 * Три сомножителя и ни одного лишнего: базовый ресурс, качество дороги,
 * состояние обслуживания. Водителя здесь СОЗНАТЕЛЬНО НЕТ, хотя аккуратность за
 * ним записана (см. Driver.skill в types.ts). Аккуратность проявляется в
 * поломках, там она и учтена; размазав одно свойство по двум формулам, мы бы
 * получили эффект, который игрок не может ни увидеть, ни оценить — а решение
 * «кого посадить на убитую машину» должно читаться по одному числу.
 */
export function wearPerKm(quality: number, kmSinceService: number): number {
  const rate =
    (roadWearFactor(quality) *
      (1 + NEGLECT_WEAR_GAIN * serviceNeglect(kmSinceService))) /
    WEAR_LIFE_KM

  return positive(rate)
}

// ─── Деньги ────────────────────────────────────────────────────────────────

/**
 * Во сколько раз дороже обслуживать машину с таким износом.
 *
 * Обоснование формы и величины — у MAINTENANCE_WEAR_GAIN. Здесь важно, что
 * функция ОДНА на всё: по ней дорожает и километр пробега, и ТО, и ремонт.
 * Три разные кривые старения означали бы, что игрок не может составить о
 * машине одно суждение.
 */
export function maintenanceMultiplier(wear: number): number {
  const w = clamp01(wear)
  return 1 + MAINTENANCE_WEAR_GAIN * w * w
}

/**
 * Ставка обслуживания конкретной машины прямо сейчас, рубли за километр.
 *
 * ЭТО ТО ЧИСЛО, ПО КОТОРОМУ ПРИНИМАЕТСЯ РЕШЕНИЕ О СПИСАНИИ, и его же обязана
 * спрашивать фаза расходов вместо плоского MAINTENANCE_PER_KM.
 *
 * Неизвестный класс (сейв, записанный до появления справочника; машина из
 * данных, которых уже нет) откатывается к прежней плоской ставке. Ноль здесь
 * означал бы бесплатную машину — то есть машину ВЫГОДНЕЕ всех остальных, и
 * дефект данных превратился бы в доминирующую стратегию.
 */
export function maintenancePerKm(vehicle: Vehicle): number {
  const vc = VEHICLE_CLASS_BY_ID[vehicle.classId]
  const base = vc === undefined ? MAINTENANCE_PER_KM : vc.maintenancePerKm

  return positive(base) * maintenanceMultiplier(vehicle.wear)
}

/** Цена планового ТО для этой машины, рубли. */
export function serviceCost(vehicle: Vehicle): number {
  return SERVICE_COST_KM * maintenancePerKm(vehicle)
}

/**
 * Цена ремонта после поломки, рубли.
 *
 * Машина, стоящая на ребре, сломалась в пути — за неё платят как за эвакуацию
 * и выездной ремонт. Положение и есть то место, где эта разница записана; см.
 * ROADSIDE_REPAIR_MULTIPLIER.
 */
export function repairCost(vehicle: Vehicle): number {
  const roadside =
    vehicle.position.kind === 'ребро' ? ROADSIDE_REPAIR_MULTIPLIER : 1

  return REPAIR_COST_KM * maintenancePerKm(vehicle) * roadside
}

// ─── Вероятность поломки ───────────────────────────────────────────────────

/**
 * Вероятность сломаться на ближайших `km` километрах, 0..1.
 *
 * МОДЕЛЬ ЭКСПОНЕНЦИАЛЬНАЯ: p = 1 − e^(−λ·km), где λ — частота отказов на
 * километр. Прямая пропорция (λ·km) выглядела бы проще, но врёт ровно там, где
 * важнее всего: у изношенной машины с просроченным ТО произведение переваливает
 * за единицу, и дальнейший рост износа перестаёт что-либо менять — то есть
 * самая опасная машина в игре становится не опаснее просто старой. Экспонента
 * не имеет ни этого потолка, ни разрыва, и вдобавок это правильная модель для
 * «отказ может случиться в любой точке пути с постоянной частотой».
 *
 * Множителя три: износ, запущенность и человек. Первые два — про железо и
 * считаются здесь; третий целиком отдан фазе водителей (breakdownFactor), и
 * своей копии его правил тут нет намеренно.
 *
 * Водителя может не быть (машина в резерве) — тогда множитель человека
 * единичный. Это не «худший случай», а отсутствие человека в формуле; сама по
 * себе машина без водителя никуда не едет и не рискует даже попытками её
 * завести (IDLE_EXPOSURE_KM), потому что заводить её некому.
 */
export function breakdownChance(
  vehicle: Vehicle,
  driver: Driver | null,
  km: number,
): number {
  const exposure = positive(km)
  if (exposure === 0) return 0

  const wear = clamp01(vehicle.wear)
  const neglect = serviceNeglect(vehicle.kmSinceService)

  const rate =
    (1 / BREAKDOWN_MTBF_KM) *
    (1 + BREAKDOWN_WEAR_GAIN * wear * wear) *
    (1 + BREAKDOWN_NEGLECT_GAIN * neglect) *
    breakdownFactor(driver)

  if (!Number.isFinite(rate) || rate <= 0) return 0

  return 1 - Math.exp(-rate * exposure)
}

// ─── Фаза ──────────────────────────────────────────────────────────────────

/**
 * Сколько машина проехала за этот тик, километров.
 *
 * Пробег БЕРЁТСЯ У ФАЗЫ РАСХОДОВ (tickKm), а не измеряется заново: за те же
 * километры, что жгут топливо, тратится и ресурс, и любое расхождение между
 * этими двумя числами игрок увидел бы как машину, которая изнашивается не от
 * работы.
 *
 * РАЗРЕШЕНИЕ НА ВЫЕЗД СПРАШИВАЕТСЯ У ФАЗЫ ВОДИТЕЛЕЙ (canDepart), а не
 * проверяется здесь по полям машины. Условий там уже три — сломана, некому
 * вести, водитель на отдыхе, — и все они про то, ЕДЕТ ЛИ машина, то есть не про
 * износ. Своя копия этой проверки отстала бы от чужой ровно в тот день, когда
 * к ней добавят четвёртое условие.
 *
 * Спрашивать всё-таки приходится: tickKm отвечает на вопрос «сколько бы она
 * проехала по своему положению», и для машины, брошенной посреди ребра, ответ у
 * него не нулевой. Без этой строки сломанный грузовик продолжал бы стирать
 * ресурс, стоя на обочине, — тихий дефект, который замечают через месяц по
 * кривой отчёта.
 */
function drivenKm(vehicle: Vehicle, state: GameState): number {
  if (!canDepart(state, vehicle)) return 0

  return positive(tickKm(vehicle, state))
}

/** Качество дороги под машиной. Стоящая в узле считается стоящей на идеальной. */
function roadQuality(vehicle: Vehicle, state: GameState): number {
  if (vehicle.position.kind !== 'ребро') return 1

  const edge = state.world.edges[vehicle.position.edgeId]
  return edge === undefined ? 1 : edge.quality
}

/**
 * Фаза износа целиком. Возвращает НОВОЕ состояние.
 *
 * ГПСЧ ДЁРГАЕТСЯ РОВНО ОДИН РАЗ НА КАЖДУЮ МАШИНУ, включая сломанные, стоящие и
 * заведомо безопасные. Так число обращений к генератору зависит только от
 * размера парка — не от того, кто сегодня в пути, и не от коэффициентов риска.
 * Это не педантизм: бросай мы только «когда есть шанс», любая перебалансировка
 * порогов сдвигала бы всю последовательность, и старые сохранения перестали бы
 * воспроизводиться, хотя ни одного правила в них не поменялось.
 *
 * Порядок обхода — порядок ключей парка, тот же довод про воспроизводимость,
 * что расписан в шапке loading.ts. Машины друг на друга здесь не влияют, так
 * что порядок важен только для генератора.
 *
 * Банкротство владельца не проверяется: износ — это физика, а не счёт. Денег
 * фаза не трогает вовсе, их берут serviceVehicle и repairVehicle по команде
 * игрока.
 */
export function runWear(state: GameState): GameState {
  const ids = Object.keys(state.vehicles) as VehicleId[]
  // Парка нет — нечего изнашивать и незачем трогать генератор.
  if (ids.length === 0) return state

  const rng = Rng.from(state.rngState)
  const vehicles: Record<VehicleId, Vehicle> = {}
  let changed = false

  for (const id of ids) {
    const before = state.vehicles[id]
    const roll = rng.float()

    const km = drivenKm(before, state)
    const driver = driverOf(state, before)

    let after = before

    if (km > 0) {
      const rate = wearPerKm(roadQuality(before, state), before.kmSinceService)
      after = {
        ...after,
        wear: clamp01(clamp01(before.wear) + km * rate),
        kmSinceService: positive(before.kmSinceService) + km,
      }
    }

    if (!before.brokenDown) {
      /*
       * Стоящая машина рискует не пробегом, а попытками её завести. Ноль для
       * машины без водителя: то, что никто не заводит, не ломается.
       */
      const exposure = km > 0 ? km : driver === null ? 0 : IDLE_EXPOSURE_KM

      // Риск считается по состоянию НА НАЧАЛО тика, а не по уже начисленному
      // износу: машина ломается от того, в каком состоянии выехала, а не от
      // сотой доли процента, которую стёрла за последние пятнадцать минут.
      if (roll < breakdownChance(before, driver, exposure)) {
        after = { ...after, brokenDown: true }
      }
    }

    vehicles[id] = after
    if (after !== before) changed = true
  }

  // Состояние генератора изменилось в любом случае — его записать обязаны, а
  // вот подменять запись парка, в котором никто не сдвинулся, незачем: по
  // совпадению ссылок рендер отличает изменившееся от нетронутого.
  return {
    ...state,
    rngState: rng.seed,
    vehicles: changed ? vehicles : state.vehicles,
  }
}

// ─── Команды игрока ────────────────────────────────────────────────────────

/**
 * Списать с компании разовый счёт за работы по машине.
 *
 * СЧЁТ ПРОХОДИТ ДАЖЕ В МИНУС, в отличие от покупки техники (store.buyVehicle
 * отказывает, когда денег не хватает). Разница по существу: покупка —
 * добровольное решение, и отказ по нехватке средств честен. Ремонт — расход
 * вынужденный, и отказать в нём значит запереть игрока намертво: машина стоит
 * сломанной, зарплата идёт, денег не прибавляется никогда. Механизм для
 * временного минуса в игре уже есть — тридцать суток отсрочки до банкротства
 * (BANKRUPTCY_GRACE_DAYS), — и это ровно тот случай, ради которого он заведён.
 *
 * Счёт попадает и в dailyCosts, а не только в остаток. Симметрично creditRevenue
 * из economy/operating.ts и по той же причине: суточный итог — единственный
 * поток, по которому игрок судит о своей сети, и молча пропущенный в нём расход
 * ломает не деньги, а способность игрока понять, что происходит.
 */
function charge(company: Company, amount: number): Company {
  if (!Number.isFinite(amount) || amount <= 0) return company

  return {
    ...company,
    money: company.money - amount,
    dailyCosts: company.dailyCosts + amount,
  }
}

/** Общая часть обеих команд: подменить машину и выставить счёт её владельцу. */
function applyWork(
  state: GameState,
  vehicle: Vehicle,
  next: Vehicle,
  cost: number,
): GameState {
  const vehicles = { ...state.vehicles, [vehicle.id]: next }
  const owner = state.companies[vehicle.ownerId]

  // Машина без хозяина работы получает, счёт — нет: выставлять его некому.
  if (owner === undefined) return { ...state, vehicles }

  return {
    ...state,
    vehicles,
    companies: { ...state.companies, [vehicle.ownerId]: charge(owner, cost) },
  }
}

/**
 * Провести ТО: обнулить счётчик пробега до обслуживания за деньги.
 *
 * ИЗНОС ПРИ ЭТОМ НЕ ПАДАЕТ, и это главное про функцию. ТО — регламентные
 * работы, а не капитальный ремонт: оно возвращает машину в график, но не
 * возвращает ей ресурс. Обнуляй ТО износ — и списывать технику не пришлось бы
 * никогда, а весь смысл среза свёлся бы к напоминалке раз в три недели.
 *
 * Проводится в любой момент и в любом месте: очереди на сервис и простой под
 * ремонтом в игре пока не смоделированы, и выдумывать их в одной этой команде
 * значило бы получить правило, которого нет больше нигде.
 */
export function serviceVehicle(state: GameState, id: VehicleId): GameState {
  const vehicle = state.vehicles[id]
  if (vehicle === undefined) return state

  // Счётчик уже на нуле — работы нет, и денег брать не за что. Возвращаем то же
  // состояние по ссылке: двойное нажатие кнопки не должно стоить вторых денег.
  if (positive(vehicle.kmSinceService) === 0) return state

  return applyWork(
    state,
    vehicle,
    { ...vehicle, kmSinceService: 0 },
    serviceCost(vehicle),
  )
}

/**
 * Отремонтировать сломанную машину: снять флаг поломки за деньги.
 *
 * Счётчик ТО не обнуляется — ремонт и обслуживание разные работы, и машина,
 * которую вытащили с обочины, на ТО опоздала ровно так же, как опаздывала до
 * поломки. Износ тоже остаётся: сломалась она как раз потому, что изношена.
 *
 * Целая машина возвращается как есть, без счёта. «Отремонтировать исправную» —
 * это не платная услуга, а промах интерфейса, и брать за него деньги нечестно.
 */
export function repairVehicle(state: GameState, id: VehicleId): GameState {
  const vehicle = state.vehicles[id]
  if (vehicle === undefined) return state
  if (!vehicle.brokenDown) return state

  // Цена считается ДО подмены машины: она читает положение, а положение при
  // ремонте не меняется — но порядок фиксируем явно, чтобы завтрашняя правка
  // («ремонт возвращает машину в ближайший город») не удешевила эвакуацию.
  const cost = repairCost(vehicle)

  return applyWork(state, vehicle, { ...vehicle, brokenDown: false }, cost)
}

// ─── Порог списания ────────────────────────────────────────────────────────

/**
 * Потолок выручки машины за километр, рубли: полный кузов на нейтральном грузе.
 *
 * ЭТО ЛЕВАЯ ГРАНИЦА ГЛАВНОГО ИНВАРИАНТА, записанная на одну машину: m·t, где
 * m — грузоподъёмность, t — тариф её класса. Больше этого машина не заработает
 * ни на каком плече, а значит с этим числом и надо сравнивать её расходы.
 *
 * НАДБАВКА ЗА ГРУЗ СЮДА НЕ ВХОДИТ, и это честнее, чем входила бы: заранее
 * неизвестно, что машина повезёт завтра, а взять самый дорогой груз карты
 * значило бы обещать выручку, которой у неё может не быть никогда — наливные
 * требуют цистерны и допуска. Нейтральный груз даёт множитель ровно единицу,
 * поэтому число не «средняя температура», а конкретный случай.
 *
 * Плата за погрузку тоже не входит: она не зависит от километров, а здесь
 * сравниваются именно километровые величины.
 *
 * Неизвестный класс (сейв старше справочника) откатывается к общему тарифу —
 * тот же приём, что в maintenancePerKm. Ноль означал бы машину, которая не
 * зарабатывает вовсе, то есть «списать немедленно» из-за дефекта данных.
 */
export function revenuePerKm(vehicle: Vehicle): number {
  const vc = VEHICLE_CLASS_BY_ID[vehicle.classId]
  const tariff = vc === undefined ? TARIFF_PER_TON_KM : vc.tariffPerTonKm
  const value = vehicle.capacity * tariff
  return Number.isFinite(value) && value > 0 ? value : 0
}

/**
 * Сколько шагов деления пополам делает поиск порога списания.
 *
 * Двадцать четыре шага сужают отрезок 0..1 до 6e-8 — точность, заведомо лишняя
 * для числа, которое показывается в процентах. Дешевле взять с запасом, чем
 * потом объяснять дрожание последнего процента.
 */
const WRITE_OFF_STEPS = 24

/** Расходы на километр у той же машины с другим износом. */
function costAtWear(vehicle: Vehicle, wear: number): number {
  // Копия, а не правка машины: функция обязана быть чистой, а вход — остаться
  // нетронутым на всех уровнях вложенности.
  return distanceCost({ ...vehicle, wear }, 1, null)
}

/**
 * Износ, при котором машина перестаёт отбивать даже идеальный рейс. null —
 * не перестаёт до конца ресурса.
 *
 * ЖИВЁТ В СИМУЛЯЦИИ, А НЕ В ПАНЕЛИ, И ЭТО ПРИНЦИПИАЛЬНО. Прежде порог считался
 * в ui/fleetReadout.ts — то есть его знал игрок и не знал конкурент, который
 * принимал решение о замене техники по числу, вписанному отдельно. Правила у
 * человека и у соперника обязаны быть одни и те же (шапка sim/ai/commands.ts),
 * а значит и число, по которому принимается решение, обязано быть одно.
 *
 * ПОЧЕМУ ПОИСК, А НЕ ФОРМУЛА. Алгебраическое решение известно и выписано в
 * шапке этого файла: w* = √((m·t·p − c(0)) / (G·maint)). Вписать его сюда
 * значило бы завести ВТОРУЮ запись модели износа, и первая же правка формы
 * кривой (сегодня квадрат, завтра куб) разошлась бы с ней молча: число
 * оставалось бы правдоподобным, но неверным. Деление пополам зовёт те же
 * функции, которыми списываются деньги, и остаётся верным при любой монотонной
 * модели старения — а монотонность гарантирована смыслом: изношенная машина не
 * может обслуживаться дешевле новой.
 *
 * ВОДИТЕЛЬ В ПОРОГ НЕ ВХОДИТ. Порог — свойство ЖЕЛЕЗА: водителя пересаживают за
 * пятнадцать минут, а машина остаётся. Иначе одна и та же машина «списывалась»
 * бы то раньше, то позже от того, кто сегодня за рулём.
 *
 * Ноль означает, что машина невыгодна уже новой, — состояние невозможное для
 * справочника, проверенного тестом инварианта, но возможное для битого
 * сохранения, и молчать о нём нельзя.
 */
export function writeOffWear(vehicle: Vehicle): number | null {
  const revenue = revenuePerKm(vehicle)
  if (!(revenue > 0)) return null

  if (costAtWear(vehicle, 0) >= revenue) return 0
  if (costAtWear(vehicle, 1) < revenue) return null

  let low = 0
  let high = 1
  for (let step = 0; step < WRITE_OFF_STEPS; step++) {
    const mid = (low + high) / 2
    if (costAtWear(vehicle, mid) < revenue) low = mid
    else high = mid
  }
  return high
}
