/**
 * Износ, техобслуживание и поломки.
 *
 * До этого среза машина была вечной. Купил — и она возит одинаково хорошо до
 * конца партии, а единственным решением про парк оставалось «сколько штук».
 * Здесь у техники появляется ВОЗРАСТ, и вместе с ним второе решение, которого
 * в игре не было: когда машину пора списывать.
 *
 * ТРИ МЕХАНИЗМА И ОДНО РЕШЕНИЕ.
 *
 *   ИЗНОС тратится километрами. Это ресурс, а не настроение: стоящая машина не
 *   стареет, а разбитая дорога отнимает ресурс быстрее ровной.
 *
 *   ОБСЛУЖИВАНИЕ дорожает с износом — maintenancePerKm класса умножается на
 *   maintenanceMultiplier(wear). Вот это и есть число, по которому игрок решает
 *   «пора списывать», и разбор ниже показывает, почему у этого решения нет
 *   universal-порога.
 *
 *   ПОЛОМКА — редкое событие с дорогими последствиями. Её вероятность растёт с
 *   износом, с пропущенным ТО и с усталостью водителя и падает с его навыком.
 *
 * ПОЧЕМУ РЕШЕНИЕ О СПИСАНИИ НЕТРИВИАЛЬНО. Машина перестаёт быть нужной не
 * когда «износ больше N», а когда переменные расходы догоняют выручку за
 * километр. Условие ровно то же, из которого выведен главный инвариант игры
 * (шапка src/data/operating.ts): пока m·t·p > c, кольцо с двумя гружёными
 * плечами прибыльно; как только c дорос до m·t·p — машина не отбивает даже
 * идеальный рейс. С износом c растёт:
 *
 *     c(w) = топливо/км + maintenancePerKm · (1 + G · w²)
 *
 * Приравняв c(w) к m·t·p, получаем точку списания w* = √((m·t·p − c(0)) / (G·maint)).
 * Она зависит и от класса, и от ГРУЗА, который машина возит:
 *
 *   ЗИЛ-130       зерно 1.00 → 0.73    мука 1.05 → 0.80
 *   КамАЗ-5320    кругляк 0.95 → 0.53  мука 1.05 → 0.68
 *   тягач         кругляк 0.95 → 0.52  топливо 1.20 → 0.76
 *
 * То есть убитый ЗИЛ на муке ещё работает там, где новый КамАЗ на кругляке уже
 * убыточен, и никакого одного числа «списывай на 70%» не существует. Больше
 * того: порог сдвигает и сам игрок — доля порожнего пробега входит в выручку на
 * километр напрямую, и машина на плохо спроектированном кольце становится
 * лишней вдвое раньше. Ровно этого от механики и хотелось: возраст техники
 * обязан стать ещё одним входом в задачу про сеть, а не отдельным таймером.
 *
 * ГЛАВНЫЙ ИНВАРИАНТ ИГРЫ ЭТИМ НЕ ЛОМАЕТСЯ, и это проверяется тестом. Инвариант
 * записан как c < m·t·p < 2c. Износ двигает только c и только ВВЕРХ, поэтому
 * правая половина («кольцо с одним гружёным плечом убыточно») от него может
 * стать лишь надёжнее; ломается левая — и это не поломка, а сам смысл
 * механики: изношенная машина перестаёт окупаться даже в идеальном кольце.
 * Порог короткого плеча m·h·p / (2c − m·t·p) с ростом c тоже только опускается,
 * то есть уходит дальше от самого короткого ребра карты.
 *
 * ФАЗА СТОИТ СРАЗУ ПОСЛЕ ДВИЖЕНИЯ (tick.ts, фаза 6). Раньше нельзя: пробег
 * этого тика ещё не пройден. Позже — можно, но бессмысленно: чем ближе к
 * движению, тем очевиднее, что износ считается по тем же километрам, за
 * которые фаза расходов возьмёт деньги.
 *
 * ПРОБЕГ ТИКА НЕ СЧИТАЕТСЯ ЗДЕСЬ ЗАНОВО. Он берётся у tickKm из
 * economy/operating.ts — той самой функции, по которой начисляется топливо.
 * Своя копия «сколько машина проехала» разошлась бы с денежной так же тихо, как
 * когда-то разошлись две формулы скорости (разбор — в шапке world/speed.ts), и
 * разъезд был бы виден только по тому, что ресурс кончается не тогда, когда
 * набежал счёт за солярку.
 *
 * ВСЯ СЛУЧАЙНОСТЬ — ЧЕРЕЗ ГПСЧ СОСТОЯНИЯ. Math.random сделал бы сохранение
 * невоспроизводимым, а поломку — неотлаживаемой: «у меня сломалось, а у тебя
 * нет» на одном и том же сейве.
 *
 * Все функции чистые: входное состояние не меняется ни на одном уровне
 * вложенности.
 *
 * ГДЕ ЖИВУТ КОНСТАНТЫ. Ставки игры собраны в src/data/operating.ts, и это
 * правильно. Числа ниже описывают не ставку, а ФОРМУ модели износа — показатель
 * степени, длину ресурса, во сколько раз дорожает обслуживание, — и в отрыве от
 * формул рядом не читаются вовсе. Поэтому они здесь; переехать в данные им
 * стоит тогда же, когда там появится раздел про парк.
 */

