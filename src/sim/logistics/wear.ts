/**
 * Во сколько раз дорожает обслуживание к полному износу.
 *
 *     множитель = 1 + MAINTENANCE_WEAR_GAIN · w²
 *
 * ПОЧЕМУ КВАДРАТ, А НЕ ПРЯМАЯ. Причин две, и обе про игру, а не про эстетику.
 *
 * Первая — то, как выглядит владение машиной. При линейной функции каждые
 * десять процентов износа стоят одинаково, и машина дорожает ровным фоном, за
 * которым не надо следить: посчитал один раз порог, поставил напоминание.
 * Квадрат делает первую половину ресурса почти бесплатной (при w = 0.3 надбавка
 * 18%), а последнюю четверть — разорительной (при w = 0.9 надбавка 162%).
 * Именно так стареет техника в жизни, и именно так возникает то ощущение, ради
 * которого механика затевалась: машина долго «нормальная», а потом вдруг
 * «сколько-сколько?».
 *
 * Вторая, менее очевидная: квадрат УДЕРЖИВАЕТ решение в игровом диапазоне.
 * Точка списания w* = √((m·t·p − c(0)) / (G·maint)) — корень, то есть разброс
 * выручки между классами и грузами сжимается. При линейной функции тот же
 * разброс проходил бы напрямую, и пороги разъезжались бы по краям: одни машины
 * оказывались бы «списывать сразу», другие — «не списывать никогда». Корень
 * сводит все классы игры в живую полосу 0.5…0.8, где решение действительно
 * принимается.
 *
 * ВЕЛИЧИНА. Двойка означает, что обслуживание к концу ресурса ВТРОЕ дороже
 * нового. Она подобрана так, чтобы точки списания легли в эту самую полосу:
 * при единице тягач дотягивал бы до 0.74…1.0 (то есть на дорогих грузах не
 * списывался бы вовсе), при тройке ЗИЛ выходил бы в убыток уже на 0.6.
 */
export const MAINTENANCE_WEAR_GAIN = 2

