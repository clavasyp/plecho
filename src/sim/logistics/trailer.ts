/**
 * Совместимость груза и кузова.
 *
 * До этого среза машина была универсальной: подъехала — взяла что дают. Кузов
 * ломает эту универсальность и этим создаёт главную трудность среза 4 —
 * ОБРАТНАЯ ЗАГРУЗКА ПЕРЕСТАЁТ БЫТЬ ЗАДАЧЕЙ ПРО МАРШРУТ. Раньше обратный груз
 * достаточно было найти по пути; теперь он обязан подойти ещё и по кузову, а
 * подходит далеко не всякий: цистерна возит два груза из шести, зерновоз —
 * один. Игрок вынужден специализировать парк и строить линии под то, что его
 * машины физически умеют везти.
 *
 * ИСТОЧНИК ИСТИНЫ ОДИН — CARGO_REQUIREMENTS в src/data/vehicles.ts. Здесь нет
 * ни одной собственной таблицы совместимости, только индексы по этой. Заведи
 * файл симуляции свою копию — и первая же правка данных («в тент тоже сыплют
 * зерно, если некуда деваться») применилась бы к погрузке, но не к интерфейсу
 * покупки прицепа, или наоборот. Такое расхождение не падает: игрок просто
 * видит в списке прицеп, с которым машина потом стоит порожней.
 *
 * ТЯГАЧ БЕЗ ПРИЦЕПА НЕ ВЕЗЁТ НИЧЕГО, а не «везёт что угодно». Это не
 * перестраховка от битого сейва, а правило игры: прицеп — отдельная покупка
 * (TRAILER_PRICE), и купленный без него тягач обязан стоять, пока игрок не
 * решит, ПОД ЧТО его специализировать. Ровно это решение срез и добавляет.
 *
 * НЕИЗВЕСТНЫЙ ГРУЗ НЕ ВЕЗЁТ НИКТО. Груз, которого нет в CARGO_REQUIREMENTS,
 * считается неперевозимым — запрет, а не разрешение. Обратный выбор («не знаем
 * требований, значит подойдёт любой кузов») означал бы, что забытая строчка в
 * данных делает новый груз всемогущим: он ездил бы в чём попало и обесценивал
 * бы специализацию всего парка. Забытая строчка при запрете тоже видна, но
 * иначе — груз просто не грузится, и тест ниже ловит это до игрока.
 *
 * Функции чистые и без состояния: индексы строятся один раз при загрузке
 * модуля из неизменяемых данных.
 */

import { CARGO_REQUIREMENTS } from '../../data/vehicles'
import type { CargoType, TrailerType } from '../types'

/**
 * Полный перечень кузовов.
 *
 * Не таблица фактов, а развёртка типа TrailerType в значения: union живёт
 * только в системе типов, а перебрать его нужно и тесту, и интерфейсу покупки.
 *
 * Записан через Record<TrailerType, true> нарочно. Массив литералов
 * компилятором не проверяется, и новый тип прицепа тихо выпал бы из списка
 * покупки — то есть появился бы в игре мёртвым. Record обязан быть полным,
 * поэтому та же забывчивость становится ошибкой КОМПИЛЯЦИИ.
 */
const TRAILER_INDEX: Record<TrailerType, true> = {
  тент: true,
  реф: true,
  цистерна: true,
  платформа: true,
  зерновоз: true,
  лесовоз: true,
}

export const TRAILER_TYPES: readonly TrailerType[] = Object.freeze(
  Object.keys(TRAILER_INDEX) as TrailerType[],
)

/**
 * Груз → кузова, в которых его можно везти.
 *
 * Порядок внутри списка сохраняется как в данных: первым стоит «родной» кузов
 * (зерно — зерновоз), дальше вынужденные варианты (зерно — тент). Интерфейс
 * покупки читает этот порядок как рекомендацию, поэтому терять его нельзя.
 *
 * Две строки на один груз — опечатка в данных, и списки таких строк
 * ОБЪЕДИНЯЮТСЯ, а не затирают друг друга. Молчаливая победа последней строки
 * отняла бы у груза половину кузовов, и искали бы причину в погрузке.
 */
const TRAILERS_BY_CARGO: ReadonlyMap<CargoType, readonly TrailerType[]> =
  (() => {
    const index = new Map<CargoType, TrailerType[]>()

    for (const requirement of CARGO_REQUIREMENTS) {
      let listed = index.get(requirement.cargo)
      if (listed === undefined) {
        listed = []
        index.set(requirement.cargo, listed)
      }
      for (const trailer of requirement.trailers) {
        if (!listed.includes(trailer)) listed.push(trailer)
      }
    }

    return index
  })()

/**
 * Кузов → грузы, которые в нём поедут. Обращение предыдущего индекса.
 *
 * Считается из него же, а не из данных заново: два независимых прохода по
 * CARGO_REQUIREMENTS — это два места, где можно ошибиться по-разному, и
 * несимметричность вылезла бы в игре как «прицеп груз берёт, а груз этот
 * прицеп не признаёт».
 *
 * Порядок грузов — порядок их появления в данных, то есть детерминированный:
 * список уходит в интерфейс, и он не должен переставляться от запуска к
 * запуску.
 */
const CARGO_BY_TRAILER: ReadonlyMap<TrailerType, readonly CargoType[]> =
  (() => {
    const index = new Map<TrailerType, CargoType[]>()

    for (const [cargo, trailers] of TRAILERS_BY_CARGO) {
      for (const trailer of trailers) {
        const listed = index.get(trailer)
        if (listed === undefined) index.set(trailer, [cargo])
        else if (!listed.includes(cargo)) listed.push(cargo)
      }
    }

    return index
  })()

/**
 * Влезет ли этот груз в этот кузов.
 *
 * Единственная проверка совместимости во всей игре: её зовёт погрузка
 * (logistics/loading.ts), её же обязан звать интерфейс, когда подсказывает
 * игроку, что линия не поедет. `null` — тягач без прицепа, ответ всегда «нет».
 */
export function canCarry(
  trailer: TrailerType | null,
  cargo: CargoType,
): boolean {
  if (trailer === null) return false

  const trailers = TRAILERS_BY_CARGO.get(cargo)
  return trailers !== undefined && trailers.includes(trailer)
}

/**
 * Кузова, в которых поедет этот груз. Пусто — груза нет в требованиях.
 *
 * Возвращается КОПИЯ. Индекс живёт всё время партии, и отданный наружу массив
 * рано или поздно кто-нибудь отсортирует под свою панель — справочник поедет
 * молча и навсегда, а разбираться будут с погрузкой.
 */
export function trailersFor(cargo: CargoType): TrailerType[] {
  return [...(TRAILERS_BY_CARGO.get(cargo) ?? [])]
}

/** Грузы, которые поедут в этом кузове. Копия по той же причине. */
export function cargoFor(trailer: TrailerType): CargoType[] {
  return [...(CARGO_BY_TRAILER.get(trailer) ?? [])]
}
