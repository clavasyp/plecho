/**
 * Движение машины по графу дорог.
 *
 * Машина знает только то, что видно из её положения: на каком ребре стоит и
 * какой город следующий по маршруту. Маршрут — готовая цепочка СОСЕДНИХ
 * городов, её строит поиск пути; здесь никакого поиска нет и быть не должно.
 * Если между текущим городом и следующим в маршруте нет прямого ребра, машина
 * просто стоит: это ошибка того, кто выдал маршрут, и прятать её подбором
 * объезда — значит сделать баг невидимым.
 *
 * Все функции чистые и возвращают новый объект машины. Состояние игры целиком
 * пересобирается на каждом тике, поэтому мутация одной машины «на месте» тихо
 * ломала бы сравнение снимков, откат и интерполяцию в рендере, где хранятся
 * позиции предыдущего тика.
 */

import type {
  CityId,
  Edge,
  GameState,
  Vehicle,
  VehiclePosition,
} from '../types'
import { speedKmh as roadSpeedKmh } from '../world/speed'

/**
 * Фактическая скорость машины на ребре, км/ч.
 *
 * Тонкая обёртка над единственной формулой скорости в проекте (world/speed).
 * Существует ради удобства вызова: здесь под рукой уже есть сама машина, а не
 * её крейсерская скорость отдельным числом.
 *
 * Формула намеренно НЕ дублируется. Раньше она была написана дважды — здесь и
 * в поиске пути — и версии разошлись: маршрут строился по одному расписанию, а
 * проезжался по другому. Подробный разбор последствий — в шапке pathfind.ts.
 */
export function speedKmh(vehicle: Vehicle, edge: Edge): number {
  return roadSpeedKmh(vehicle.cruiseKmh, edge)
}

/**
 * Ребро между двумя городами или undefined, если прямой дороги нет.
 *
 * Рёбра ненаправленные, поэтому пара проверяется в обе стороны. Линейный
 * перебор выбран сознательно: рёбер в мире меньше двух десятков, а отдельный
 * индекс «город → соседи» пришлось бы держать в состоянии и синхронизировать с
 * графом. Когда мир вырастет, индекс появится в world/graph.ts — здесь тогда
 * останется один вызов.
 */
export function findEdgeInState(
  state: GameState,
  a: CityId,
  b: CityId,
): Edge | undefined {
  for (const edge of Object.values(state.world.edges)) {
    if (
      (edge.from === a && edge.to === b) ||
      (edge.from === b && edge.to === a)
    ) {
      return edge
    }
  }
  return undefined
}

/** Дальний конец ребра относительно того, откуда выехали. */
function otherEnd(edge: Edge, fromId: CityId): CityId {
  return edge.from === fromId ? edge.to : edge.from
}

/**
 * Продвинуть машину по маршруту за интервал времени. Возвращает новую машину.
 *
 * Ключевая тонкость — цикл, а не единственный шаг. За один тик (15 минут)
 * машина обычно не успевает пройти и половины ребра, но при ускорении времени
 * или на коротких рёбрах она проходит несколько подряд. Наивная реализация
 * «доехал до узла — вышел» теряет остаток времени на каждом прибытии: машина
 * встаёт в городе до следующего тика, и чем короче плечи, тем сильнее она
 * отстаёт. Ошибка коварна тем, что выглядит как «ну, постояла в городе» и
 * никогда не всплывает как явный сбой — поэтому здесь честно доедаем
 * hoursLeft, сколько бы узлов ни встретилось по дороге.
 *
 * Обратная тонкость — остаток времени на пустом маршруте не переносится и не
 * копится: машина, доехавшая до конца, просто стоит.
 */
export function advanceVehicle(
  vehicle: Vehicle,
  state: GameState,
  deltaHours: number,
): Vehicle {
  let position: VehiclePosition = vehicle.position
  let route: CityId[] = vehicle.route
  let odometer = vehicle.odometer
  let hoursLeft = deltaHours

  /*
   * Предохранитель от вечного цикла. По построению цикл конечен: каждый проход
   * либо тратит время, либо укорачивает маршрут, а маршрут конечен. Но игровой
   * цикл не имеет права зависнуть даже на битых данных (ребро нулевой длины,
   * маршрут из повторов одного города), а зависший тик — это белый экран без
   * единого сообщения об ошибке. Запас взят с большим избытком: реально нужно
   * 2 × длина маршрута + 2 прохода.
   */
  let stepsLeft = route.length * 2 + 8

  while (hoursLeft > 0 && stepsLeft-- > 0) {
    if (position.kind === 'узел') {
      // Стоим без задания — время просто не расходуется.
      if (route.length === 0) break

      const target = route[0]

      // Поиск пути возвращает маршрут вместе с городом отправления, а ручной
      // маршрут — обычно без него. Снимаем текущий город здесь, чтобы
      // вызывающему не приходилось знать, где именно машина стоит.
      if (target === position.nodeId) {
        route = route.slice(1)
        continue
      }

      const edge = findEdgeInState(state, position.nodeId, target)
      // Прямой дороги нет — маршрут невалиден, машина остаётся в городе.
      if (edge === undefined) break

      position = {
        kind: 'ребро',
        edgeId: edge.id,
        fromId: position.nodeId,
        progress: 0,
      }
      continue
    }

    const edge = state.world.edges[position.edgeId]
    // Ребро исчезло из мира (перестройка графа под старым сохранением).
    if (edge === undefined) break

    const speed = speedKmh(vehicle, edge)
    // Нулевая скорость — не тупик, а причина стоять: иначе деление ниже дало
    // бы Infinity и машина «телепортировалась» бы в конец ребра.
    if (speed <= 0) break

    const remainingKm = Math.max(0, edge.km * (1 - position.progress))
    const hoursToEnd = remainingKm / speed

    // До конца ребра не дотягиваем — двигаемся и на этом тик кончается.
    if (hoursToEnd > hoursLeft) {
      const travelledKm = speed * hoursLeft
      odometer += travelledKm
      position = {
        ...position,
        progress: position.progress + travelledKm / edge.km,
      }
      break
    }

    // Доехали до узла. Остаток времени остаётся у машины и тратится дальше —
    // на следующей итерации она встанет на следующее ребро.
    odometer += remainingKm
    hoursLeft -= hoursToEnd

    const arrivedAt = otherEnd(edge, position.fromId)
    position = { kind: 'узел', nodeId: arrivedAt }

    // Пройденный город снимается с маршрута только если он там и стоял:
    // машина может проехать город транзитом, если его нет в списке остановок.
    if (route.length > 0 && route[0] === arrivedAt) {
      route = route.slice(1)
    }
  }

  // Ничего не произошло — возвращаем ту же машину. Это не микрооптимизация:
  // по совпадению ссылок рендер отличает стоящие машины от едущих и не
  // пересобирает для них геометрию каждый тик.
  if (
    position === vehicle.position &&
    route === vehicle.route &&
    odometer === vehicle.odometer
  ) {
    return vehicle
  }

  return { ...vehicle, position, route, odometer }
}

/**
 * Назначить машине маршрут. Возвращает новую машину.
 *
 * Массив копируется: маршрут приходит снаружи (из поиска пути, из линии, из
 * команды ИИ), и владелец исходного массива не должен иметь возможности
 * задним числом менять состояние игры, дописав в него город.
 *
 * Текущее положение не трогаем. Машина посреди ребра доедет до его конца и
 * только потом пойдёт по новому маршруту — развернуть её на месте нельзя, и
 * это правильно: разворот фуры на трассе тоже не бесплатный.
 */
export function setRoute(vehicle: Vehicle, route: readonly CityId[]): Vehicle {
  return { ...vehicle, route: [...route] }
}
