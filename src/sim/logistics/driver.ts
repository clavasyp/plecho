// ─── Режим труда и отдыха ──────────────────────────────────────────────────

/**
 * Часов управления подряд до обязательного отдыха.
 *
 * Девять — не подобранное число, а норма: и ЕСТР, и приказ Минтранса дают
 * водителю грузовика ровно девять часов управления в сутки (дважды в неделю
 * допускаются десять — этой поблажки в игре нет, она стоила бы отдельного
 * недельного счётчика, которому в types.ts места нет).
 *
 * Сорокапятиминутный перерыв после 4.5 часов за рулём отдельно не моделируется:
 * машина и так встаёт на каждой остановке кольца, а стоянка здесь — отдых (см.
 * atWheel). Заводить под перерыв ещё одно состояние значило бы удвоить число
 * способов стоять, не добавив игроку ни одного решения.
 */
export const MAX_SHIFT_HOURS = 9

/**
 * Часов отдыха, чтобы полностью восстановиться после полной смены.
 *
 * Одиннадцать — ежедневный отдых по тому же ЕСТР. Отсюда и берётся ПОТОЛОК
 * СУТОЧНОГО ПРОБЕГА, ради которого весь этот режим и написан: цикл «смена плюс
 * отдых» длится двадцать часов, то есть за рулём машина проводит 9/20 = 45%
 * времени вместо прежних ста процентов. ЗИЛ на М-2 (60.9 км/ч, минус потеря на
 * усталости) проходит около 590 км в сутки вместо полутора тысяч.
 *
 * Что это меняет в игре: один тягач больше не заменяет два. Плотное кольцо
 * упирается не в длину плеча, а в человека, и вторая машина со вторым водителем
 * становится единственным способом возить больше. Ровно этого от среза и ждут.
 *
 * ЧЕСТНАЯ НЕТОЧНОСТЬ. Цикл в 20 часов не привязан к календарным суткам, поэтому
 * в среднем за сутки выходит 10.8 часа управления вместо нормативных девяти.
 * Привязать смену к суткам можно было бы только отдельным полем «когда началась
 * смена», а Driver в types.ts — контракт. Ошибка в 20% от суточной нормы
 * дешевле, чем поле, которого нет.
 */
export const REST_HOURS = 11

/**
 * Прирост усталости за час за рулём и её спад за час на стоянке.
 *
 * Выводятся из режима, а не задаются отдельно, и это делает всю систему
 * согласованной по построению: полная смена ровно исчерпывает усталость до
 * единицы, полный отдых ровно сбрасывает её в ноль. Никакой третьей ручки, от
 * которой числа могли бы разъехаться, здесь нет.
 *
 * Из разных знаменателей следует главное свойство модели: час за рулём стоит
 * 11/9 ≈ 1.22 часа отдыха. Поэтому короткие стоянки под погрузкой — не
 * формальность: они списывают усталость пропорционально и отодвигают
 * обязательный отдых. Кольцо с частыми остановками физически выносливее
 * магистрального прогона в один конец.
 */
export const FATIGUE_PER_HOUR = 1 / MAX_SHIFT_HOURS
export const RECOVERY_PER_HOUR = 1 / REST_HOURS

/**
 * На сколько уставший водитель теряет в скорости при полной усталости.
 *
 * Двадцать процентов — около 12 км/ч у ЗИЛа. Величина намеренно скромная:
 * потолок суточного пробега ставит РЕЖИМ, а не эта потеря. Сделай её сильной —
 * и последние часы смены превратились бы в бессмысленное ползание, которое
 * игрок всё равно не может ни отменить, ни ускорить. Двадцать процентов видно в
 * расчётном времени прибытия, но выгоднее доработать смену, чем встать.
 */
export const FATIGUE_SPEED_PENALTY = 0.2

