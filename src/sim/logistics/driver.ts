/**
 * Какой допуск нужен, чтобы везти этот груз.
 *
 * Карта живёт здесь, а не в src/data, по одной причине: справочники данных в
 * этом срезе — контракт, который менять нельзя, а правило читает ровно один
 * потребитель — canDrive. Как только допусков станет больше трёх строк, место
 * им в data рядом с CARGO_REQUIREMENTS.
 *
 * Смысл ровно тот же, что у требований к прицепу, но с другой стороны: прицеп
 * ограничивает, ЧЕМ везти, допуск — КОМУ везти. Обратная загрузка от этого
 * становится ещё уже: обратный груз обязан подойти и по маршруту, и по кузову,
 * и по человеку за рулём.
 */
export const CARGO_LICENSE: Partial<Record<CargoType, DriverLicense>> = {
  // Класс опасности: наливное и горючее возят только с ДОПОГ.
  нефть: 'ДОПОГ',
  топливо: 'ДОПОГ',
  // Хлысты выходят за габарит — нужен допуск на длинномер.
  кругляк: 'длинномер',
}

/**
 * Может ли этот водитель везти этот груз.
 *
 * `null` — порожний рейс, его может выполнить кто угодно.
 *
 * СПРАШИВАТЬ ЭТО ОБЯЗАН ТОТ, КТО ГРУЗИТ, а не тот, кто выпускает в рейс.
 * Проверка на выезде выглядит надёжнее, но запирает уже гружёную машину: груз с
 * неё сам не денется, и она простоит трое суток до списания партии
 * (DEAD_CARGO_DAYS). Поэтому canDepart допуск не смотрит принципиально —
 * см. комментарий там.
 */
export function canDrive(driver: Driver, cargo: CargoType | null): boolean {
  if (cargo === null) return true

  const required = CARGO_LICENSE[cargo]
  if (required === undefined) return true

  return driver.licenses.includes(required)
}

// ─── Мелкая арифметика ─────────────────────────────────────────────────────

/**
 * Привести долю к 0..1.
 *
 * Битые входы дают ноль, а не NaN. NaN в усталости просачивается сквозь
 * сравнения (`NaN >= MAX` ложно), водитель никогда не уходит на отдых, а
 * множитель скорости отравляет движение — тот же довод, что в шапке
 * deliveryRevenue.
 */
function clamp01(value: number): number {
  if (!Number.isFinite(value)) return 0
  if (value < 0) return 0
  return value > 1 ? 1 : value
}

/**
 * Порог значимости усталости.
 *
 * Нужен ровно в одном месте — в проверке «отдохнул полностью». Усталость
 * набирается и снимается сложением дробей, которые в двоичной записи не
 * представимы: единица минус сорок четыре раза по 1/44 даёт не ноль, а
 * 1.1e-16. Без порога водитель просидел бы на стоянке лишние пятнадцать минут
 * из-за последнего бита мантиссы, а тик возвращения в рейс плавал бы от версии
 * к версии. Тот же приём и по той же причине — KM_EPSILON в line.ts.
 */
const FATIGUE_EPSILON = 1e-9

/** Привести счётчик смены к 0..MAX_SHIFT_HOURS. */
function clampDuty(hours: number): number {
  if (!Number.isFinite(hours) || hours < 0) return 0
  return hours > MAX_SHIFT_HOURS ? MAX_SHIFT_HOURS : hours
}

/**
 * Навык после km километров за рулём.
 *
 * Подтягивается к потолку долей оставшегося разрыва — см. SKILL_LEARNING_KM.
 * Функция выделена и экспортирована, потому что это единственное место, где
 * растёт навык, и проверять кривую удобнее прямо на ней, а не через сотню тиков
 * симуляции.
 */
export function grownSkill(skill: number, km: number): number {
  const current = clamp01(skill)
  if (!Number.isFinite(km) || km <= 0) return current

  const grown = current + ((SKILL_CAP - current) * km) / SKILL_LEARNING_KM
  return grown > SKILL_CAP ? SKILL_CAP : grown
}

/**
 * Зарплата за сутки, рубли.
 *
 * Базовая ставка из данных, надбавки за навык и за каждый допуск. Округляется до
 * рубля намеренно: зарплата видна игроку, а дробные копейки в панели — мусор.
 * Заодно это гасит дрожание — навык растёт непрерывно, и без округления объект
 * водителя пересоздавался бы каждый тик из-за пятнадцатого знака.
 */
export function wageFor(skill: number, licenses: readonly DriverLicense[]): number {
  const bonus =
    1 + SKILL_WAGE_BONUS * clamp01(skill) + LICENSE_WAGE_BONUS * licenses.length
  return Math.round(DRIVER_WAGE_PER_DAY * bonus)
}

// ─── Разрешения наружу ─────────────────────────────────────────────────────

/**
 * Водитель на обязательном отдыхе.
 *
 * ПРИЗНАК ОТДЫХА — САМ СЧЁТЧИК СМЕНЫ, отдельного поля под него нет и не будет:
 * Driver в types.ts — контракт. Счётчик работает так: за рулём растёт, на
 * стоянке ЗАМОРОЖЕН и обнуляется только полным восстановлением (усталость в
 * ноль). Значит «отработал смену» и «ещё не отдохнул» — это одно и то же
 * состояние hoursOnDuty >= MAX_SHIFT_HOURS, и различать их незачем.
 */
export function isResting(driver: Driver): boolean {
  return clampDuty(driver.hoursOnDuty) >= MAX_SHIFT_HOURS
}

/**
 * Водитель за рулём этой машины или null.
 *
 * Ищется в парке ВЛАДЕЛЬЦА машины: водители лежат в Company.drivers, и чужой
 * человек за рулём — это не наём, а рассинхрон данных, который лечится в сторе,
 * а не обходится здесь молча.
 */
export function driverOf(state: GameState, vehicle: Vehicle): Driver | null {
  const id = vehicle.driverId
  if (id === null) return null

  const company: Company | undefined = state.companies[vehicle.ownerId]
  if (company === undefined) return null

  // Сейв прошлой версии мог не знать про водителей вовсе — тогда за рулём никого.
  const drivers: Record<DriverId, Driver> | undefined = company.drivers
  return drivers?.[id] ?? null
}

/**
 * Разрешение на выезд: есть кому вести, он не на отдыхе, машина цела.
 *
 * ДОПУСК ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ, и это осознанно — разбор у canDrive: не пустить
 * в рейс уже гружёную машину значит запереть её на трое суток до списания
 * партии. Допуск обязан проверяться до погрузки.
 */
export function canDepart(state: GameState, vehicle: Vehicle): boolean {
  // Сломанная стоит до ремонта, кто бы за рулём ни сидел.
  if (vehicle.brokenDown) return false

  const driver = driverOf(state, vehicle)
  return driver !== null && !isResting(driver)
}

/**
 * Множитель скорости от усталости, 0.8…1.
 *
 * Отдельно от машины: интерфейсу и тестам нужно уметь спросить это про человека,
 * не собирая вокруг него мир.
 */
export function speedFactor(driver: Driver): number {
  return 1 - FATIGUE_SPEED_PENALTY * clamp01(driver.fatigue)
}

/**
 * Множитель скорости для машины целиком. НОЛЬ означает «не едет».
 *
 * Ноль здесь не заглушка, а способ не разъехаться с разрешением: фаза движения
 * умножает дорожную скорость на этот множитель и получает правильное поведение
 * во всех случаях сразу — нет водителя, водитель на отдыхе, машина сломана,
 * водитель устал. Верни функция единицу при отсутствии водителя — и забытая
 * проверка canDepart дала бы самоходную машину без человека, причём тихо.
 */
export function vehicleSpeedFactor(state: GameState, vehicle: Vehicle): number {
  if (!canDepart(state, vehicle)) return 0

  const driver = driverOf(state, vehicle)
  return driver === null ? 0 : speedFactor(driver)
}

/**
 * Множитель расхода топлива от навыка, 0.9…1.
 *
 * Применяет его фаза расходов: топливо считается по километрам и цене литра, а
 * не здесь. Водителя нет — множитель единичный: машина без водителя всё равно
 * не едет и километров не наматывает.
 */
export function fuelFactor(driver: Driver | null): number {
  if (driver === null) return 1
  return 1 - SKILL_FUEL_GAIN * clamp01(driver.skill)
}

/**
 * Множитель риска поломки, 0.5…2.
 *
 * Уставший ломает чаще, опытный — реже. Сам риск и его последствия считает
 * wear.ts: здесь нет ни базовой вероятности, ни износа, ни ремонта. Водителя
 * нет — множитель единичный по тому же доводу, что и у топлива.
 */
export function breakdownFactor(driver: Driver | null): number {
  if (driver === null) return 1

  const tired = 1 + FATIGUE_RISK_PENALTY * clamp01(driver.fatigue)
  const skilled = 1 - SKILL_RISK_RELIEF * clamp01(driver.skill)
  return tired * skilled
}

// ─── Фаза ──────────────────────────────────────────────────────────────────

/**
 * Машины, разложенные по водителям за рулём.
 *
 * Индекс строится один раз на фазу: иначе каждый водитель перебирал бы весь
 * парк, а при десятках машин и водителей это уже квадрат на каждом тике.
 *
 * Две машины с одним водителем — рассинхрон данных (стор не снял человека со
 * старой машины). Побеждает первая по порядку вставки ключей, то есть выбор
 * воспроизводим и не зависит от того, в каком порядке случилось поле. Разбор
 * того, почему на порядок вставки вообще можно опираться, — в шапке loading.ts.
 */
function vehiclesByDriver(state: GameState): Map<DriverId, Vehicle> {
  const wheels = new Map<DriverId, Vehicle>()

  for (const id of Object.keys(state.vehicles) as VehicleId[]) {
    const vehicle = state.vehicles[id]
    const driver = vehicle.driverId
    if (driver === null) continue
    if (!wheels.has(driver)) wheels.set(driver, vehicle)
  }

  return wheels
}

/**
 * Едет ли водитель прямо сейчас — и с какой дорожной скоростью.
 *
 * Ноль означает «стоит», и это ЕДИНСТВЕННОЕ определение стоянки в файле. За
 * рулём водитель ровно тогда, когда его машина находится на ребре и способна
 * ехать; всё остальное — стоянка, на которой усталость снимается: узел, поломка,
 * собственный обязательный отдых (фура ждёт на обочине), исчезнувшее из мира
 * ребро.
 *
 * Отдых на ребре — не натяжка, а необходимость: развернуть или телепортировать
 * машину в город нельзя, а смена кончается там, где кончается.
 */
function wheelSpeedKmh(
  edges: Record<EdgeId, Edge>,
  vehicle: Vehicle | null,
  resting: boolean,
): number {
  if (resting || vehicle === null || vehicle.brokenDown) return 0
  if (vehicle.position.kind !== 'ребро') return 0

  const edge: Edge | undefined = edges[vehicle.position.edgeId]
  if (edge === undefined) return 0

  return speedKmh(vehicle.cruiseKmh, edge)
}

/**
 * Один водитель за один тик. Возвращает НОВОГО, если что-то изменилось.
 *
 * Порядок вычислений важен ровно в одном месте: километры считаются по УСТАЛОСТИ
 * НА НАЧАЛО ТИКА, потому что именно с ней машина ехала прошлые пятнадцать минут
 * (см. про задержку в шапке файла). Возьми усталость после прироста — и пробег
 * разошёлся бы с тем, что насчитала фаза движения.
 */
function advanceDriver(
  driver: Driver,
  vehicle: Vehicle | null,
  edges: Record<EdgeId, Edge>,
): Driver {
  const wasFatigue = clamp01(driver.fatigue)
  const wasDuty = clampDuty(driver.hoursOnDuty)
  const resting = wasDuty >= MAX_SHIFT_HOURS

  const roadKmh = wheelSpeedKmh(edges, vehicle, resting)
  const atWheel = roadKmh > 0

  let fatigue: number
  let hoursOnDuty: number
  let skill = clamp01(driver.skill)

  if (atWheel) {
    fatigue = Math.min(1, wasFatigue + FATIGUE_PER_HOUR * HOURS_PER_TICK)
    // Смена обрезается потолком, а не переливается за него: тик может не лечь
    // в остаток смены ровно, и лишние минуты честнее потерять, чем разрешить.
    hoursOnDuty = Math.min(MAX_SHIFT_HOURS, wasDuty + HOURS_PER_TICK)
    skill = grownSkill(skill, roadKmh * speedFactor(driver) * HOURS_PER_TICK)
  } else {
    const rested = wasFatigue - RECOVERY_PER_HOUR * HOURS_PER_TICK
    fatigue = rested > FATIGUE_EPSILON ? rested : 0
    // Смена обнуляется ПОЛНЫМ восстановлением и только им. Иначе пятнадцать
    // минут под погрузкой сбрасывали бы режим, и потолка суточного пробега не
    // существовало бы вовсе — машина стояла бы тик и ехала следующие девять
    // часов, и так круглосуточно.
    hoursOnDuty = fatigue > 0 ? wasDuty : 0
  }

  // Переработка — работа на исходе смены, когда ехать по режиму ещё можно.
  const overworked = atWheel && wasFatigue >= OVERWORK_FATIGUE
  const loyalty = clamp01(
    driver.loyalty +
      LOYALTY_GAIN_PER_DAY * DAYS_PER_TICK -
      (overworked ? LOYALTY_LOSS_PER_DAY * DAYS_PER_TICK : 0),
  )

  // Вырос навык — выросла и цена человека. Это не побочный эффект, а часть
  // замысла: выращенный водитель ценен и стоит дороже, и в срезе 6 именно за
  // ним придёт конкурент.
  const wagePerDay = wageFor(skill, driver.licenses)

  // Ничего не изменилось — возвращаем того же водителя по ссылке. Как и в
  // остальных фазах, по совпадению ссылок интерфейс отличает изменившееся от
  // нетронутого и не пересобирает панель парка каждый тик.
  if (
    fatigue === driver.fatigue &&
    hoursOnDuty === driver.hoursOnDuty &&
    skill === driver.skill &&
    loyalty === driver.loyalty &&
    wagePerDay === driver.wagePerDay
  ) {
    return driver
  }

  return { ...driver, fatigue, hoursOnDuty, skill, loyalty, wagePerDay }
}

/**
 * Фаза водителей целиком. Возвращает НОВОЕ состояние.
 *
 * Обходятся все компании: водители конкурентов живут по тем же правилам, и
 * логика человека пишется один раз — ровно как линии и деньги.
 *
 * Порядок обхода не значим: водители не делят между собой ничего общего, каждый
 * считается от своей машины. Поэтому фаза читает ОДИН снимок состояния и не
 * зависит от порядка ключей — то же требование, что в фазе движения.
 */
export function runDrivers(state: GameState): GameState {
  const wheels = vehiclesByDriver(state)
  const edges = state.world.edges

  const companies: Record<CompanyId, Company> = { ...state.companies }
  let changed = false

  for (const companyKey of Object.keys(state.companies) as CompanyId[]) {
    const company = state.companies[companyKey]

    // Сейв прошлой версии мог не знать про водителей — тогда фазе здесь нечего
    // делать, а падать на пустом месте она не должна.
    const roster: Record<DriverId, Driver> | undefined = company.drivers
    if (roster === undefined) continue

    // Копия парка водителей заводится ЛЕНИВО: у компании, где за тик ничего не
    // изменилось (все в резерве, отдохнувшие), запись остаётся исходной по
    // ссылке и лишних объектов не появляется.
    let drivers: Record<DriverId, Driver> | null = null

    for (const key of Object.keys(roster) as DriverId[]) {
      const before = roster[key]
      const after = advanceDriver(before, wheels.get(key) ?? null, edges)
      if (after === before) continue

      if (drivers === null) drivers = { ...roster }
      drivers[key] = after
    }

    if (drivers !== null) {
      companies[companyKey] = { ...company, drivers }
      changed = true
    }
  }

  return changed ? { ...state, companies } : state
}

// ─── Найм ──────────────────────────────────────────────────────────────────

/**
 * Имена и фамилии кандидатов.
 *
 * Русские и неброские: водитель — не герой с генерируемым эпосом, а человек в
 * списке парка, которого игрок узнаёт по фамилии. Шестнадцать на шестнадцать
 * дают 256 сочетаний — на партию с десятком машин хватает с запасом, а редкий
 * повтор фамилии в жизни никого не удивляет.
 */
const FIRST_NAMES = [
  'Алексей', 'Анатолий', 'Андрей', 'Валерий',
  'Виктор', 'Владимир', 'Геннадий', 'Дмитрий',
  'Евгений', 'Игорь', 'Михаил', 'Николай',
  'Олег', 'Пётр', 'Сергей', 'Юрий',
] as const

const SURNAMES = [
  'Кузнецов', 'Соколов', 'Морозов', 'Волков',
  'Лебедев', 'Новиков', 'Фёдоров', 'Егоров',
  'Никитин', 'Захаров', 'Гуров', 'Панкратов',
  'Савельев', 'Ерохин', 'Кулагин', 'Тарасов',
] as const

/**
 * Разброс навыка на рынке труда.
 *
 * Верхняя граница НИЖЕ того, чего водитель достигает работой (см.
 * SKILL_LEARNING_KM: за два года выходит 0.89). Это главное решение про найм:
 * купить мастера на рынке нельзя, его можно только вырастить. Иначе найм стал бы
 * лотереей с перебором кандидатов, а выращенный водитель — бессмысленной
 * привязанностью.
 */
export const HIRE_SKILL_MIN = 0.15
export const HIRE_SKILL_MAX = 0.65

/**
 * Вероятность допуска у кандидата: базовая и надбавка за навык.
 *
 * Допуск приходит со стажем, поэтому он вероятнее у опытного — и получается
 * связная картина: человек с ДОПОГ обычно и умелее, и дороже вдвойне. ДОПОГ
 * реже длинномера: это отдельное обучение и переаттестация, а не отметка в
 * правах.
 */
const ADR_CHANCE_BASE = 0.1
const ADR_CHANCE_PER_SKILL = 0.3
const LONG_CHANCE_BASE = 0.2
const LONG_CHANCE_PER_SKILL = 0.4

/**
 * Свободный идентификатор водителя и его номер.
 *
 * Номер идёт от размера парка и дальше ищет первый незанятый — так найм после
 * увольнений не затирает работающего человека. Идентификатор говорящий и с
 * компанией внутри: в отладке видно, чей это водитель. Числовым он быть не
 * должен — числовые ключи движок сортирует по-своему и ломает порядок обхода,
 * на который опирается фаза прибытия (разбор — в шапке loading.ts).
 */
function freeDriverId(
  roster: Record<DriverId, Driver>,
  companyId: CompanyId,
): { id: DriverId; index: number } {
  let index = Object.keys(roster).length + 1

  for (;;) {
    const id = driverId(`${companyId}-drv-${index}`)
    if (roster[id] === undefined) return { id, index }
    index++
  }
}

/**
 * Нанять водителя. Возвращает НОВОЕ состояние.
 *
 * ОТКУДА БЕРЁТСЯ СЛУЧАЙНОСТЬ, и почему не из основного потока. Найм — команда
 * игрока, а не событие мира: она приходит в произвольный момент и произвольное
 * число раз. Дёрни она общий rngState — и вся дальнейшая история партии
 * (поломки, события, погода) сдвинулась бы от одного лишнего клика по кнопке
 * «нанять». Ровно от этого предостерегает шапка tick.ts, требуя единственного
 * потребителя случайности в тике. Поэтому кандидат выводится отдельным потоком
 * Rng.forKey от компании и номера найма, а rngState остаётся нетронутым.
 *
 * ПОВТОРНЫЙ НАЙМ ПРИ ТОМ ЖЕ СИДЕ ДАЁТ ТОГО ЖЕ ЧЕЛОВЕКА, и это не недосмотр:
 * рынок труда не обновляется от того, что кандидата подержали и уволили. Иначе
 * игрок перебирал бы кандидатов кликами, пока не выпадет ДОПОГ, — а перебор с
 * мгновенным откатом это не решение, а автомат в казино.
 *
 * ОТСЮДА ТРЕБОВАНИЕ К ВЫЗЫВАЮЩЕМУ: сид обязан меняться со временем (номер
 * тика — самый естественный выбор). Постоянный сид означал бы, что при
 * очередном номере найма компании всегда достаётся один и тот же человек.
 */
export function hireDriver(
  state: GameState,
  companyId: CompanyId,
  seed: number,
): GameState {
  const company: Company | undefined = state.companies[companyId]
  // Компании нет — нанимать некому. Молча, потому что это ошибка вызывающего,
  // а не игровая ситуация, и ронять на ней тик незачем.
  if (company === undefined) return state

  const existing: Record<DriverId, Driver> | undefined = company.drivers
  const roster = existing ?? {}

  const { id, index } = freeDriverId(roster, companyId)

  // Соль приводится к целому: Rng.forKey работает с 32-битным состоянием, и
  // дробный или битый сид дал бы NaN в хеше, то есть один и тот же поток на все
  // случаи жизни.
  const salt = Number.isFinite(seed) ? Math.trunc(seed) | 0 : 0
  const rng = Rng.forKey(`${companyId}/${index}`, salt)

  // ПОРЯДОК ОБРАЩЕНИЙ К ГПСЧ — ЧАСТЬ КОНТРАКТА. Переставь их местами, и все
  // сохранённые партии начнут выдавать других людей при том же сиде.
  const name = `${rng.pick(FIRST_NAMES)} ${rng.pick(SURNAMES)}`
  const skill = rng.range(HIRE_SKILL_MIN, HIRE_SKILL_MAX)

  const licenses: DriverLicense[] = []
  if (rng.chance(ADR_CHANCE_BASE + ADR_CHANCE_PER_SKILL * skill)) {
    licenses.push('ДОПОГ')
  }
  if (rng.chance(LONG_CHANCE_BASE + LONG_CHANCE_PER_SKILL * skill)) {
    licenses.push('длинномер')
  }

  const driver: Driver = {
    id,
    name,
    employerId: companyId,
    // В резерв, а не сразу за руль. Назначение на машину — отдельное решение
    // игрока, ровно как назначение машины на линию при покупке (см. createZil):
    // сделать его за него значило бы отобрать то самое решение, ради которого
    // водители в игре и появились.
    vehicleId: null,

    skill,
    licenses,

    // Пришёл отдохнувшим и со свежей сменой: рейс можно начать сегодня.
    fatigue: 0,
    hoursOnDuty: 0,

    wagePerDay: wageFor(skill, licenses),
    loyalty: HIRE_LOYALTY,
  }

  return {
    ...state,
    companies: {
      ...state.companies,
      [companyId]: { ...company, drivers: { ...roster, [id]: driver } },
    },
  }
}
