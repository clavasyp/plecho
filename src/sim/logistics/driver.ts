/**
 * Фаза водителей: усталость, режим труда и отдыха, навык, лояльность.
 *
 * До этого среза машина ехала круглосуточно и бесплатно устраивала это сама:
 * зарплата капала (DRIVER_WAGE_PER_DAY), но за рулём никого не было. Отсюда
 * следовала неприятная вещь — единственным ограничением на суточный пробег была
 * длина плеча. Один тягач, поставленный на плотное кольцо, работал 24 часа в
 * сутки, и покупка второй машины проигрывала более длинному кольцу почти всегда.
 * Здесь у машины появляется человек, и у суток появляется потолок.
 *
 * ЧТО ЭТА ФАЗА РЕШАЕТ И ЧЕГО НЕ РЕШАЕТ.
 *
 *   Решает: сколько часов подряд можно ехать, насколько водитель устал, как
 *   быстро он растёт и сколько стоит.
 *
 *   Не решает: едет ли машина (это движение), ломается ли она (это wear.ts),
 *   можно ли взять груз в этот прицеп (это trailer.ts). Наружу отдаются
 *   МНОЖИТЕЛИ и РАЗРЕШЕНИЯ — canDepart, vehicleSpeedFactor, fuelFactor,
 *   breakdownFactor, — а решение принимает тот, кому оно принадлежит. Считать
 *   риск поломки здесь означало бы держать формулу износа в двух файлах, и они
 *   разошлись бы ровно так же, как когда-то разошлись две формулы скорости
 *   (разбор — в шапке world/speed.ts).
 *
 * ПОЧЕМУ ФАЗА СТОИТ ДО ДИСПЕТЧЕРИЗАЦИИ. Водитель обязан уйти на отдых ДО того,
 * как ему выдадут маршрут: иначе машина получает задание, трогается и встаёт
 * посреди тика, а игрок видит выехавшую и тут же замершую фуру. Обратный
 * порядок ещё и подвесил бы линию — диспетчер считает, что плечо выполняется,
 * а оно не выполняется.
 *
 * ЗАДЕРЖКА В ОДИН ТИК, И ОНА НЕ ОШИБКА. Фаза видит положение машин, сложившееся
 * ПОСЛЕ движения прошлого тика: стоит машина на ребре — значит последние
 * пятнадцать минут она ехала, и эти пятнадцать минут сейчас и записываются
 * водителю в смену. Ровно та же усталость, по которой считался пробег прошлого
 * тика, лежит в driver.fatigue нетронутой, поэтому оценка километров ниже точна,
 * а не приблизительна.
 *
 * ИСТИНА О ТОМ, КТО ЗА РУЛЁМ, — ПОЛЕ МАШИНЫ (Vehicle.driverId), а не
 * Driver.vehicleId. Тот же довод, что и у принадлежности машины к линии
 * (logistics/line.ts): в рейс машину отправляет движение, а оно смотрит на
 * машину. Разойдись две записи — и водитель отдыхал бы, пока его тягач идёт по
 * трассе. Driver.vehicleId остаётся тем, чем он и объявлен в types.ts: отметкой
 * назначения для интерфейса, которую ведёт стор.
 *
 * Все функции чистые: входное состояние не меняется, включая вложенные объекты.
 */

