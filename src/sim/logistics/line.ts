/**
 * Фаза диспетчеризации: машина на линии получает маршрут к следующей остановке.
 *
 * До этого среза машина ехала туда, куда её однажды отправили, и вставала.
 * Линия снимает этот микроменеджмент: игрок задаёт КОЛЬЦО остановок, а здесь
 * каждый тик решается ровно один вопрос — «кому пора выезжать и куда». Больше
 * ничего: грузы и деньги живут в фазе прибытия (logistics/loading.ts),
 * километры — в фазе движения (logistics/vehicle.ts), поиск пути — в
 * world/pathfind.ts. Этот файл только диспетчер.
 *
 * ГЛАВНЫЙ ИНВАРИАНТ, И ОН ЖЕ КОНТРАКТ С ФАЗОЙ ПРИБЫТИЯ.
 *
 * `Vehicle.stopIndex` — это ЦЕЛЬ, а не пройденная остановка. Пока машина стоит
 * на остановке, индекс продолжает указывать на неё, и погрузка идёт по ЕЁ
 * инструкции; сдвигается индекс только в момент ОТПРАВЛЕНИЯ. Порядок фаз делает
 * это единственным работающим вариантом:
 *
 *   тик T:    движение довезло машину до узла остановки j
 *             прибытие  — стоим в stops[j].nodeId, stopIndex = j, грузимся по j
 *   тик T+1:  диспетчер — стоим на своей остановке, значит пора дальше:
 *             stopIndex := j+1, выдан маршрут; движение увозит машину
 *
 * Отсюда же берётся простой под погрузкой: машина стоит на остановке ровно один
 * тик, пятнадцать игровых минут. Сдвинь индекс в момент ПРИБЫТИЯ — и фаза
 * прибытия увидит машину, стоящую в городе остановки j, а инструкцию остановки
 * j+1, то есть будет грузить не то и не там. Такой дефект не падает, он просто
 * тихо возит не тот груз.
 *
 * ПОЧЕМУ ЛИНИЯ КОРОЧЕ ДВУХ ОСТАНОВОК НЕ РАБОТАЕТ. Кольцо из одной остановки не
 * имеет ни одного ПЛЕЧА: машине некуда ехать, она бесконечно «прибывает» туда,
 * где уже стоит. Перевозки в этом нет — а значит нет и линии. Терпеть такую
 * линию как рабочую означало бы гонять диспетчер вхолостую каждый тик и, что
 * хуже, показывать игроку работающую линию, которая ничего не везёт. Машина на
 * недостроенной линии стоит, и это честный сигнал: остановок мало.
 *
 * ЧТО ДЕЛАТЬ С НЕДОСТИЖИМОЙ ОСТАНОВКОЙ — ПРОПУСКАТЬ. Города, до которого нет
 * пути (размыло единственную дорогу, опечатка в остановке, город вне графа), в
 * этом круге просто нет: диспетчер берёт ближайшую следующую достижимую и везёт
 * машину туда. Причины две. Первая: одно порванное плечо не должно убивать всю
 * линию — остальные пять остановок обслуживаются, и сеть продолжает жить.
 * Вторая: встать «с признаком проблемы» физически негде — Vehicle описан в
 * types.ts и поля под флаг там нет, а заводить его ради диагностики значит
 * тащить в сохранение состояние, которое всегда выводится из карты заново.
 * Пропуск действует РОВНО НА ОДИН КРУГ: на следующем витке остановка проверяется
 * снова и, если дорогу починили, возвращается в работу сама.
 *
 * Если недостижимы все остановки разом (машина заперта в городе без дорог),
 * машина стоит и пробует снова каждый тик. Это дёшево: отрицательный ответ
 * поиска пути кэшируется, а мир может измениться в любой момент.
 *
 * РАССТАНОВКА ПО КОЛЬЦУ — см. ниже, у departureGapKm. Это самое содержательное
 * решение файла.
 *
 * СРЕЗ 5 ДОБАВИЛ ТРЕТЬЮ ПРИЧИНУ СТОЯТЬ — ПОСТ. Раньше машина, стоящая на своей
 * остановке, уезжала со следующим же тиком: погрузка была мгновенной. Теперь она
 * занимает часы, постов конечное число, и машина, которая стоит под погрузкой
 * или ждёт очереди на неё, диспетчером НЕ ТРОГАЕТСЯ. Разбор стыка с фазой
 * обслуживания — у самой проверки в advanceLineVehicles.
 *
 * Из очереди при этом машина не выпадает: её координата на кольце считается как
 * у всех, и соседи держат от неё интервал. Иначе стоящая под погрузкой машина
 * стала бы для остальных невидимой, и весь парк линии съезжался бы к занятому
 * посту — то самое сбивание в колонну, ради которого выдержка интервала и
 * написана, только теперь ещё и с очередью на въезде.
 *
 * Все функции чистые: входное состояние не меняется, включая вложенные объекты.
 */

import type { CityId, GameState, Line, Vehicle, VehicleId } from '../types'
import type { RoadGraph } from '../world/graph'
import { buildGraph } from '../world/graph'
import { findRoute, shortestKm } from '../world/pathfind'
import { setRoute } from './vehicle'

/**
 * Минимальное число остановок работающей линии.
 *
 * Две, а не одна: кольцо из одной точки не содержит ни одного плеча — разбор в
 * шапке файла. Константа экспортируется, чтобы интерфейс редактора линий и
 * тесты спрашивали это число здесь, а не переписывали двойку у себя.
 */
export const MIN_LINE_STOPS = 2

/**
 * Порог значимости расстояния, километры.
 *
 * Миллиметр. Нужен ровно в одном месте — в сравнении интервала с нормой:
 * идеально расставленные машины дают промежутки вида 161.66666666666669 при
 * норме 161.66666666666666, и строгое сравнение задержало бы машину на лишний
 * тик из-за последнего бита мантиссы. Ошибка была бы редкой, невоспроизводимой
 * на глаз и целиком выдуманной арифметикой.
 */
const KM_EPSILON = 1e-6

// ─── Кольцо остановок ──────────────────────────────────────────────────────

/**
 * Привести индекс остановки к диапазону линии.
 *
 * Индекс приходит из состояния и может оказаться каким угодно: игрок укоротил
 * линию через updateLine, сохранение сделано другой версией, машину назначили
 * руками. Отрицательный и вышедший за край индексы заворачиваются по кольцу, а
 * не обнуляются молча — машина остаётся примерно там, где была по смыслу.
 */
function normalizeStop(count: number, stopIndex: number): number {
  if (count <= 0 || !Number.isFinite(stopIndex)) return 0
  const index = Math.trunc(stopIndex) % count
  return index < 0 ? index + count : index
}

/**
 * Следующая остановка по кольцу. После последней — нулевая.
 *
 * Кольцо, а не отрезок, — это решение из docs/КОНЦЕПТ.md §3–4, и оно стоит
 * здесь одной строчкой `% count`. Отрезок «туда и обратно» подразумевал бы
 * возврат порожняком как норму; кольцо заставляет игрока с самого начала
 * думать, чем гружёной пойдёт обратная сторона.
 */
export function nextStop(line: Line, stopIndex: number): number {
  const count = line.stops.length
  if (count <= 0) return 0
  return (normalizeStop(count, stopIndex) + 1) % count
}

// ─── Откуда ехать ──────────────────────────────────────────────────────────

/**
 * Точка, из которой машине строится маршрут.
 *
 * Стоящая машина — это её узел. Едущая — ДАЛЬНИЙ конец ребра, а не ближний:
 * развернуть фуру посреди трассы нельзя, она в любом случае доедет до узла.
 * Маршрут из дальнего конца машина подхватит на ходу — фаза движения снимает
 * первый город маршрута, когда в него приезжает.
 *
 * null — ребро исчезло из мира (сохранение под перестроенным графом). Машина в
 * никуда маршрут не получает.
 */
function departurePoint(state: GameState, vehicle: Vehicle): CityId | null {
  const position = vehicle.position
  if (position.kind === 'узел') return position.nodeId

  const edge = state.world.edges[position.edgeId]
  if (edge === undefined) return null
  return edge.from === position.fromId ? edge.to : edge.from
}

/**
 * Маршрут от текущего положения машины до её ЦЕЛЕВОЙ остановки (stopIndex).
 *
 * null — пути нет, линия не работает или машина стоит на исчезнувшем ребре.
 *
 * Крейсерская скорость машины уходит в поиск пути обязательным аргументом, и
 * это не формальность: тихоходной машине выгоден другой маршрут, чем быстрой,
 * потому что потолок федеральной трассы ей всё равно не пригодится. Полный
 * разбор на реальных данных — в шапке world/pathfind.ts.
 */
export function routeToStop(
  state: GameState,
  vehicle: Vehicle,
  line: Line,
): CityId[] | null {
  if (line.stops.length < MIN_LINE_STOPS) return null

  const graph = buildGraph(state.world.edges)
  const target = normalizeStop(line.stops.length, vehicle.stopIndex)
  return routeToIndex(graph, state, vehicle, line, target)
}

/** То же, но по явному индексу и на готовом графе — рабочая лошадка фазы. */
function routeToIndex(
  graph: RoadGraph,
  state: GameState,
  vehicle: Vehicle,
  line: Line,
  index: number,
): CityId[] | null {
  const from = departurePoint(state, vehicle)
  if (from === null) return null

  const stop = line.stops[index]
  if (stop === undefined) return null

  return findRoute(graph, from, stop.nodeId, vehicle.cruiseKmh)
}

// ─── Система отсчёта кольца ────────────────────────────────────────────────

/**
 * Кольцо, развёрнутое в линейку километров.
 *
 * Нужна общая координата, по которой можно сказать «эта машина в ста
 * километрах позади той». Индекс остановки для этого не годится: плечи разной
 * длины, и «на одну остановку впереди» может означать и 110 км, и 328.
 *
 * Линейка в КИЛОМЕТРАХ, а не в часах, хотя маршруты строятся по времени.
 * Причина: часы зависят от машины (у ЗИЛа и тягача они разные), и разные машины
 * одной линии оказались бы в разных системах отсчёта — сравнивать их положение
 * стало бы нельзя. Километры одинаковы для всех, и ровно их видит игрок на
 * карте, когда говорит «машины идут вплотную».
 *
 * Берётся кратчайшее расстояние (shortestKm), то есть та же геометрия сети, по
 * которой считается тариф в фазе прибытия. Фактический маршрут машины может
 * быть чуть длиннее — линейке это безразлично, она измеряет взаимное
 * расположение, а не пробег.
 */
type RingFrame = {
  /** Длина плеча, ПРИВОДЯЩЕГО в остановку i, км. */
  inKm: number[]
  /** Расстояние от нулевой остановки до i-й по ходу кольца, км. */
  aheadKm: number[]
  /** Длина всего кольца, км. Ноль — кольцо вырождено (все остановки в одном
   * городе или до них вообще нет пути). */
  ringKm: number
}

/**
 * Линейка строится по кольцу, которое машины РЕАЛЬНО ЕДУТ, а не по списку
 * остановок буквально.
 *
 * Разница видна на линии с одной недостижимой остановкой. Диспетчер её
 * пропускает, машина идёт Калуга → Москва напрямую, 190 км. Наивная линейка
 * посчитала бы оба плеча через недостижимую остановку нулевыми — и все 190 км
 * пути схлопнулись бы в одну точку. Машины на этом участке оказались бы
 * «стоящими в одном месте», выдержка интервала не дала бы им разъехаться, и
 * линия задохнулась бы из-за одной битой остановки. Ровно это и случилось на
 * первом прогоне.
 *
 * Поэтому длина плеча — расстояние до ближайшей СЛЕДУЮЩЕЙ ДОСТИЖИМОЙ остановки,
 * то есть до той, куда машину и отправит диспетчер. Пропущенная остановка
 * получает нулевое входящее плечо и в кольце ничего не занимает.
 */
function ringFrame(graph: RoadGraph, line: Line): RingFrame {
  const count = line.stops.length
  const aheadKm = new Array<number>(count).fill(0)
  const inKm = new Array<number>(count).fill(0)
  let total = 0

  for (let i = 0; i < count; i++) {
    aheadKm[i] = total

    for (let step = 1; step < count; step++) {
      const next = (i + step) % count
      const km = shortestKm(graph, line.stops[i].nodeId, line.stops[next].nodeId)
      // Бесконечность — остановка в другой компоненте графа, её пропустят.
      if (!Number.isFinite(km)) continue

      const leg = Math.max(0, km)
      inKm[next] = leg
      total += leg
      break
    }
  }

  return { inKm, aheadKm, ringKm: total }
}

/** Привести координату к кольцу [0, ringKm). */
function wrapKm(km: number, ringKm: number): number {
  if (!(ringKm > 0) || !Number.isFinite(km)) return 0
  const wrapped = km % ringKm
  return wrapped < 0 ? wrapped + ringKm : wrapped
}

/**
 * Где машина находится на линейке кольца, километры от нулевой остановки.
 *
 * Считается «от цели назад»: машина едет к остановке target, до неё осталось
 * столько-то километров — значит она стоит на столько же позади этой остановки.
 * Так координата непрерывна и не требует знать, откуда машина выехала.
 *
 * Остаток обрезается длиной ВХОДЯЩЕГО плеча — того, по которому в эту остановку
 * приезжают. Это важно для машины, которая ТОЛЬКО ВЫХОДИТ на линию из
 * случайного города: без обрезки она уехала бы по линейке назад через всё
 * кольцо и оказалась бы «впереди» тех, кто уже работает. С обрезкой она стоит
 * ровно на предыдущей остановке — то есть в самом хвосте очереди на выезд, что
 * для новичка на линии и правильно.
 */
function ringPosition(
  graph: RoadGraph,
  state: GameState,
  frame: RingFrame,
  line: Line,
  vehicle: Vehicle,
  target: number,
): number {
  const inLegKm = frame.inKm[target]

  let remaining = 0

  // Машина на ребре обязана доехать до его конца — эти километры считаются
  // отдельно, потому что из середины ребра кратчайший путь не спросить.
  const position = vehicle.position
  if (position.kind === 'ребро') {
    const edge = state.world.edges[position.edgeId]
    if (edge !== undefined) {
      const left = Math.min(1, Math.max(0, 1 - position.progress))
      remaining += edge.km * left
    }
  }

  const from = departurePoint(state, vehicle)
  const toTarget =
    from === null
      ? Number.POSITIVE_INFINITY
      : shortestKm(graph, from, line.stops[target].nodeId)
  // Недостижимая цель — считаем машину стоящей на предыдущей остановке: это
  // худшее из возможных положений на кольце, и застрявшая машина не выглядит
  // обогнавшей остальных.
  remaining += Number.isFinite(toTarget) ? toTarget : inLegKm

  const behind = Math.min(inLegKm, Math.max(0, remaining))
  return wrapKm(frame.aheadKm[target] - behind, frame.ringKm)
}

// ─── Расстановка по кольцу ─────────────────────────────────────────────────

/** Машина линии на линейке кольца. */
type Member = {
  id: VehicleId
  /**
   * Место в списке линии. Нужен только для разрыва ничьих: машины, стоящие в
   * одной точке, обязаны разъезжаться в предсказуемом порядке, и порядок этот
   * взят у игрока — тот, в котором он назначал машины на линию.
   */
  rank: number
  /** Координата на кольце, км от нулевой остановки. */
  coord: number
}

/**
 * ВЫДЕРЖКА ИНТЕРВАЛА — то, ради чего в этом файле вообще есть арифметика.
 *
 * Задача звучит безобидно: три машины на линии не должны сбиваться в кучу. Но
 * без специального правила они собьются НЕИЗБЕЖНО, и вот почему. Машины
 * покупаются в одном городе, назначаются на линию в один клик и стартуют из
 * одной точки с одинаковой скоростью. Дальше они идут строго синхронно — ничто
 * в симуляции их не расталкивает. Получается колонна из трёх машин, которая
 * обслуживает линию РОВНО КАК ОДНА: приезжают втроём, первая забирает весь
 * готовый груз, две уходят порожняком, и следующие несколько часов на
 * остановках не стоит никто. Игрок заплатил за три машины, три зарплаты и три
 * бака топлива, а получил производительность одной — и не понимает, почему.
 *
 * Правило: машина уезжает с остановки, только если до ближайшей машины ВПЕРЕДИ
 * по кольцу не меньше нормы интервала — длина кольца, делённая на число машин
 * на нём. Не пускает — машина стоит на остановке и пробует на следующем тике.
 *
 * Почему именно так, а не «расставить по кольцу при назначении»:
 *
 *   1. Разовая расстановка держится ровно до первой помехи. Машины разной
 *      скорости, разное время под погрузкой, пустой склад на одной остановке —
 *      и колонна собирается заново, уже навсегда. Выдержка же работает
 *      постоянно и растаскивает парк САМА, сколько бы раз его ни сбило.
 *   2. Расставлять при назначении негде и нечем: момент «машина только что
 *      попала на линию» в чистой функции тика не отличим от «машина стоит на
 *      линии давно» — отдельного поля под это в types.ts нет и быть не должно.
 *
 * ЗАСТОЯ БЫТЬ НЕ МОЖЕТ, и это доказывается, а не проверяется на глаз. Промежутки
 * между соседями по кольцу в сумме дают ровно длину кольца, промежутков N штук,
 * значит хотя бы один не меньше среднего, то есть не меньше нормы L/N. Машина с
 * этим промежутком выезжает всегда. Ничья (все машины в одной точке) разводится
 * рангом: машина, назначенная на линию раньше, считается стоящей ВПЕРЕДИ —
 * поэтому колонну возглавляет первая по списку, а не случайная.
 *
 * Плата за выдержку — простой на остановке, и он честный: водителю в это время
 * платят (см. DRIVER_WAGE_PER_DAY в data/operating.ts). Так интервальное
 * движение и работает в жизни, и так же оно подсказывает игроку, что машин на
 * линии больше, чем ей нужно.
 */
function departureGapKm(
  sorted: readonly Member[],
  index: number,
  ringKm: number,
): number {
  // Единственная машина на линии сама себе и передняя, и задняя: ей принадлежит
  // всё кольцо, и ждать ей некого.
  if (sorted.length <= 1) return ringKm

  // Список отсортирован по ходу движения, поэтому впереди — следующий элемент,
  // а для последнего — первый через замыкание кольца. Разность считается именно
  // так, а не через остаток от деления: у машин, стоящих в одной точке, остаток
  // дал бы ноль и для замыкания тоже, то есть колонна встала бы намертво.
  if (index === sorted.length - 1) {
    return ringKm - (sorted[index].coord - sorted[0].coord)
  }
  return sorted[index + 1].coord - sorted[index].coord
}

// ─── Фаза целиком ──────────────────────────────────────────────────────────

/** Машины одной линии — линия и её парк, найденный по vehicle.lineId. */
type LineGroup = {
  line: Line
  ids: VehicleId[]
}

/**
 * Собрать парк по линиям.
 *
 * Истина о принадлежности машины — ПОЛЕ МАШИНЫ, а не список в линии. Список
 * ведёт стор, и он может отстать (машину продали, линию пересобрали); машина же
 * без своей линии просто не двигается, и такую ошибку видно сразу. Список
 * остаётся источником одного-единственного факта — порядка назначения, по
 * которому разводятся ничьи при выезде.
 *
 * Ключ группы включает владельца: линии разных компаний — разные объекты, и
 * совпадение идентификаторов у игрока и конкурента не должно склеивать их парки.
 */
function groupByLine(state: GameState): Map<string, LineGroup> {
  const groups = new Map<string, LineGroup>()

  for (const id of Object.keys(state.vehicles) as VehicleId[]) {
    const vehicle = state.vehicles[id]
    if (vehicle.lineId === null) continue

    const company = state.companies[vehicle.ownerId]
    if (company === undefined) continue

    const line = company.lines[vehicle.lineId]
    if (line === undefined) continue
    // Недостроенная линия не работает — машина стоит. См. шапку файла.
    if (line.stops.length < MIN_LINE_STOPS) continue

    // Косая черта в идентификаторах не встречается, а дефис склеил бы
    // пары «a» + «b-c» и «a-b» + «c» в один ключ.
    const key = `${vehicle.ownerId}/${vehicle.lineId}`
    const group = groups.get(key)
    if (group === undefined) groups.set(key, { line, ids: [id] })
    else group.ids.push(id)
  }

  return groups
}

/**
 * Фаза диспетчеризации целиком. Возвращает НОВОЕ состояние.
 *
 * Что делает с каждой машиной на линии:
 *
 *   • едет (маршрут не пуст) — не трогаем, плечо выполняется;
 *   • стоит под погрузкой или в очереди на пост — не трогаем, работа идёт;
 *   • стоит на своей остановке — отправляем к следующей по кольцу;
 *   • стоит где-то ещё без маршрута — отправляем к своей текущей остановке,
 *     то есть выводим на линию;
 *   • интервал до передней машины меньше нормы — держим на месте;
 *   • до остановки нет пути — берём ближайшую следующую достижимую.
 *
 * Машина БЕЗ ЛИНИИ не трогается вовсе — ни маршрут, ни индекс. Разовые рейсы
 * остаются рабочим инструментом: ими перегоняют машину на новую линию и пробуют
 * плечо до того, как строить под него сеть.
 *
 * РЕШЕНИЯ ПРИНИМАЮТСЯ ПО ОДНОМУ СНИМКУ состояния, как в фазе движения. Порядок
 * обхода машин на результат не влияет: выезд не меняет координату машины (она
 * остаётся там же, где стояла), поэтому «увидеть» соседа уже уехавшим нельзя ни
 * при каком порядке. Детерминизм тика не должен зависеть от порядка ключей
 * объекта — иначе он не держится ни на чём.
 */
export function advanceLineVehicles(state: GameState): GameState {
  const groups = groupByLine(state)
  // Ни одной машины на линиях — состояние возвращается по ссылке.
  if (groups.size === 0) return state

  // Граф строится один раз на фазу: сеть за тик не меняется, а спрашивают её
  // все машины сразу.
  const graph = buildGraph(state.world.edges)

  const vehicles: Record<VehicleId, Vehicle> = { ...state.vehicles }
  let changed = false

  for (const group of groups.values()) {
    const line = group.line
    const count = line.stops.length
    const frame = ringFrame(graph, line)

    const members: Member[] = group.ids.map((id, order) => {
      const vehicle = state.vehicles[id]
      const listed = line.assignedVehicles.indexOf(id)
      return {
        id,
        // Машины, которой нет в списке линии, ставим в хвост порядка — она на
        // линии работает, но очередь на выезд возглавить не может.
        rank: listed >= 0 ? listed : line.assignedVehicles.length + order,
        coord: ringPosition(
          graph,
          state,
          frame,
          line,
          vehicle,
          normalizeStop(count, vehicle.stopIndex),
        ),
      }
    })

    // По ходу движения. Ничья разводится рангом В ОБРАТНУЮ СТОРОНУ: при равных
    // координатах машина с меньшим рангом оказывается в конце массива, то есть
    // впереди всех по кольцу, и уезжает первой.
    const sorted = [...members].sort((a, b) =>
      a.coord === b.coord ? b.rank - a.rank : a.coord - b.coord,
    )
    const headwayKm = frame.ringKm / sorted.length

    for (let i = 0; i < sorted.length; i++) {
      const vehicle = state.vehicles[sorted[i].id]

      // Плечо выполняется — диспетчер в это не вмешивается. Сюда же попадает
      // машина с остатком разового маршрута: доедет и выйдет на линию сама.
      if (vehicle.route.length > 0) continue

      /*
       * ПОД ПОГРУЗКОЙ И В ОЧЕРЕДИ МАШИНА НЕ УЕЗЖАЕТ. Это треть стыка с фазой
       * обслуживания (logistics/service.ts); остальное живёт в фазе прибытия
       * (logistics/loading.ts). Договор между тремя фазами такой:
       *
       *   service   решает, КОГДА машина освободится: раздаёт посты, отсчитывает
       *             тики, копит очередь тем, кому поста не хватило.
       *   loading   решает, ЧТО машина погрузит, и делает это ровно в тот тик,
       *             когда обслуживание закончилось.
       *   line      (здесь) не выпускает машину с остановки, пока работа не
       *             закончена.
       *
       * Разъедься любые две из трёх — и получится либо машина, которая грузится
       * мгновенно (диспетчер увёз её раньше, чем пост отработал), либо машина,
       * которая стоит вечно. Обе поломки тихие: первая просто отменяет весь срез,
       * вторая выглядит как «линия почему-то не везёт».
       *
       * ДВУХ СЧЁТЧИКОВ ЗДЕСЬ МАЛО ПО ОТДЕЛЬНОСТИ, и это легко просмотреть.
       * serviceTicksLeft > 0 ловит только ту машину, которая уже стоит на посту.
       * У ждущей очереди он честный ноль — обслуживание ей ещё не начинали, — и
       * по одному этому полю диспетчер увёз бы её со СВОЕЙ ЖЕ остановки, ничего
       * не погрузив. Очередь превратилась бы в свою противоположность: вместо
       * простоя вторая машина получала бы разрешение проехать мимо завода
       * порожняком, то есть срез отменял бы сам себя. Условие то же, что в
       * прибытии (readyForWork в loading.ts), и обязано таким остаться.
       *
       * Проверка стоит ПОСЛЕ маршрута и ДО выдержки интервала намеренно. После
       * маршрута — потому что едущая машина под погрузкой стоять не может, и
       * спрашивать про неё нечего. До интервала — потому что простой под
       * погрузкой это не выдержка: считать его задержкой по интервалу значило бы
       * приписать очереди на посту вину за расстановку парка, и панель узких мест
       * показывала бы не ту причину.
       */
      if (vehicle.serviceTicksLeft > 0 || vehicle.queuedTicks > 0) continue

      const from = departurePoint(state, vehicle)
      if (from === null) continue

      if (departureGapKm(sorted, i, frame.ringKm) + KM_EPSILON < headwayKm) {
        continue
      }

      const target = normalizeStop(count, vehicle.stopIndex)
      // Стоим ровно на своей остановке — значит она обслужена и пора дальше.
      // Иначе машина только выходит на линию, и ехать ей к своей же цели.
      const arrived =
        vehicle.position.kind === 'узел' && line.stops[target].nodeId === from
      const first = arrived ? nextStop(line, target) : target

      // Обход не дальше одного круга: недостижимые остановки пропускаются, но
      // цикл обязан кончиться даже если недостижимы все.
      let picked: number | null = null
      let route: CityId[] | null = null
      for (let step = 0; step < count; step++) {
        const candidate = (first + step) % count
        const found = routeToIndex(graph, state, vehicle, line, candidate)
        if (found !== null) {
          picked = candidate
          route = found
          break
        }
      }

      // Ехать некуда: машина заперта или вся линия недостижима. Стоим и пробуем
      // на следующем тике — мир меняется, дороги чинят.
      if (picked === null || route === null) continue

      vehicles[vehicle.id] = { ...setRoute(vehicle, route), stopIndex: picked }
      changed = true
    }
  }

  return changed ? { ...state, vehicles } : state
}
