/**
 * Построить. Возвращает НОВОЕ состояние либо исходное по ссылке при отказе.
 *
 * ОДНА ПОСТРОЙКА КАЖДОГО ТИПА НА ГОРОД У ОДНОЙ КОМПАНИИ. Правило явное, и вот
 * почему оно именно такое.
 *
 *   Постройка — это ОТВЕТ НА ВОПРОС «расшивать ли это место», а не ползунок
 *   мощности. Разреши второй терминал — и пропускная способность снова
 *   покупается деньгами линейно, ровно как раньше покупался десятый грузовик.
 *   Срез затевался затем, чтобы у сети появился потолок; безлимитная застройка
 *   одного города возвращает всё ровно туда, откуда ушли.
 *
 *   Потолок при этом КОНЕЧЕН И ИЗВЕСТЕН: 1 базовый пост + 3 терминала + 1 склада
 *   + 6 хаба = 11 постов в городе, и больше не будет никогда. Игрок, упершийся в
 *   одиннадцать, обязан менять СЕТЬ — разносить погрузку по городам, перевешивать
 *   линии, брать машины большего класса, — а не докупать бетон. Это и есть
 *   содержание среза.
 *
 *   Правило держится НЕ ПРОВЕРКОЙ, А ФОРМОЙ КЛЮЧА: идентификатор выводится из
 *   тройки (компания, город, тип), поэтому вторая постройка того же типа — это
 *   тот же самый ключ, и занятый ключ означает отказ. Забыть такую проверку
 *   нельзя, потому что она и есть уникальность идентификатора.
 *
 *   РАЗНЫЕ ТИПЫ В ОДНОМ ГОРОДЕ РАЗРЕШЕНЫ НАМЕРЕННО. Терминал плюс склад — это
 *   осмысленная связка: четыре поста и 400 тонн за 160 000 против шести постов и
 *   1200 тонн за 260 000 у хаба. Дешевле, слабее и доступно раньше — то есть
 *   ступень, по которой игрок доходит до хаба, а не альтернатива ему.
 *
 * ДЕНЬГИ СПИСЫВАЮТСЯ, НО В dailyCosts НЕ ПОПАДАЮТ. Суточные потоки в панели
 * показывают ОПЕРАЦИОННУЮ работу сети; закинь в них разовую капитальную покупку —
 * и постройка терминала на день превратила бы прибыльную компанию в убыточную на
 * бумаге. Ровно так же устроена покупка машины в app/store.ts. В потоках
 * появляется не цена, а содержание — и появляется навсегда, что и правильно.
 */
export function buildBuilding(
  state: GameState,
  companyId: CompanyId,
  cityId: CityId,
  type: BuildingType,
): GameState {
  const company: Company | undefined = state.companies[companyId]
  if (company === undefined) return state
  // У банкрота партия окончена: ему не начисляют расходов, значит и строить он
  // не может — иначе постройка встала бы в мире, за которую никто не платит.
  if (company.bankrupt) return state

  // Постройка в несуществующем городе — не «невидимый терминал»: она добавляла
  // бы посты в узле, которого нет на карте, и содержание за него списывалось бы
  // до конца партии.
  if (state.world.cities[cityId] === undefined) return state

  const spec = BUILDING_SPEC[type]
  if (spec === undefined) return state

  // Сравнение написано отрицанием намеренно: NaN в цене или на счету обязан
  // означать отказ, а не «условие не выполнилось, значит строим».
  if (!(company.money >= spec.price)) return state

  const existing = buildingsOf(company)
  const id = buildingIdFor(companyId, cityId, type)
  // Место занято. См. разбор правила выше: отказ здесь — не проверка ради
  // проверки, а прямое следствие того, что ключ детерминирован.
  if (existing[id] !== undefined) return state

  const building: Building = {
    id,
    type,
    ownerId: companyId,
    cityId,
    // Посты и вместимость КОПИРУЮТСЯ в постройку, а не спрашиваются у
    // справочника каждый раз. Тот же довод, что у Vehicle.capacity: сохранение
    // обязано пережить перебалансировку данных.
    posts: spec.posts,
    storage: spec.storage,
    // Пустой. Всё, что окажется на складе, привезёт машина игрока.
    stock: {},
  }

  return {
    ...state,
    companies: {
      ...state.companies,
      [companyId]: {
        ...company,
        money: company.money - spec.price,
        buildings: { ...existing, [id]: building },
      },
    },
  }
}

/**
 * Снести. Возвращает НОВОЕ состояние либо исходное по ссылке, если такой
 * постройки нет.
 *
 * ГРУЗ НА СКЛАДЕ ПРОПАДАЕТ. Решение принято против двух более щедрых вариантов, и
 * оба они оказались дырами.
 *
 *   ВЫСЫПАТЬ ГРУЗ В ГОРОД значило бы, что снос — это способ ДОСТАВКИ. Городской
 *   склад кормит население и растит его (economy/consumption.ts); игрок свозил бы
 *   тонны в хранилище, сносил постройку и снабжал город даром, минуя и разгрузку,
 *   и её оплату, и вместимость города. То же самое с предприятием: у него в
 *   складе лежит сырьё производства, и бесплатная его подсыпка ломает всю цепочку.
 *
 *   ПРОДАТЬ ГРУЗ ЗА ДЕНЬГИ значило бы завести в игре второго покупателя, который
 *   платит без всякой перевозки. Вся экономика игры стоит на том, что деньги
 *   появляются РОВНО в момент доставки настоящему получателю; скупка на месте
 *   обесценивает и линии, и расстояния, и главный инвариант заодно.
 *
 * Так что содержимое списывается за счёт перевозчика — ровно как невостребованная
 * партия в фазе прибытия (DEAD_CARGO_ATTEMPTS в logistics/loading.ts). Правило
 * простое и предсказуемое: хочешь снести — вывези. Предупредить игрока об
 * остатке обязан интерфейс, а не симуляция.
 *
 * ДЕНЕГ СНОС НЕ ВОЗВРАЩАЕТ. Возврат хотя бы части цены превратил бы постройку в
 * бесплатную примерку: поставил, посмотрел на очередь, снёс. Решение обязано
 * стоить, иначе это не решение. Смысл сноса — перестать платить содержание, и
 * этого достаточно.
 *
 * Машину, УЖЕ СТОЯЩУЮ под погрузкой, снос не трогает: её serviceTicksLeft лежит
 * в самой машине и досчитается до нуля. Тонны, которые перегружают прямо сейчас,
 * не могут повиснуть в воздухе от того, что игрок нажал кнопку.
 */
export function demolishBuilding(state: GameState, id: BuildingId): GameState {
  // Владелец ищется перебором, а не выводится из идентификатора. Идентификатор
  // действительно содержит имя компании, но полагаться на разбор строки значит
  // сделать формат ключа частью логики: переименуй схему — и снос молча
  // перестанет находить постройки.
  for (const key of Object.keys(state.companies) as CompanyId[]) {
    const company = state.companies[key]
    const buildings = buildingsOf(company)
    if (buildings[id] === undefined) continue

    const next: Record<BuildingId, Building> = { ...buildings }
    delete next[id]

    return {
      ...state,
      companies: {
        ...state.companies,
        [key]: { ...company, buildings: next },
      },
    }
  }

  return state
}

