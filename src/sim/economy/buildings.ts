/**
 * Постройки игрока: терминалы, склады, хабы.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ПОЯВИЛСЯ. До среза 5 погрузка была мгновенной, а
 * значит бесплатной: десятая машина на линии стоила ровно столько же, сколько
 * первая, и правильным ответом на любую задачу было «купить ещё грузовик».
 * Теперь погрузка занимает часы, постов конечное число (BASE_POSTS в
 * data/infrastructure.ts — ровно один), и вторая машина на том же заводе встаёт
 * в очередь. У сети впервые появилась пропускная способность — а здесь
 * появляется то, чем игрок её расшивает, и то, чем эта расшивка ему обходится.
 *
 * ДВЕ ПОЛОВИНЫ ФАЙЛА.
 *
 *   РАСПОРЯЖЕНИЯ ИГРОКА — buildBuilding и demolishBuilding. Их зовёт стор
 *   (app/store.ts) в ответ на нажатие, а не тик. Обе возвращают исходное
 *   состояние по ссылке, если сделка не состоялась: молчаливый отказ здесь
 *   правильнее исключения ровно по тому же доводу, что и у покупки машины —
 *   кнопка в интерфейсе недоступна по тем же условиям, и до сюда доходит только
 *   гонка между кликом и уходящими на топливо деньгами.
 *
 *   ФАЗА ТИКА — runUpkeep. Содержание построек, статья, которой в игре раньше не
 *   было вовсе.
 *
 * СОДЕРЖАНИЕ — ГЛАВНОЕ, ЧТО ДЕЛАЕТ СТРОИТЕЛЬСТВО РЕШЕНИЕМ. Без него правильной
 * стратегией было бы застроить всю карту, как только появятся деньги, и никакого
 * выбора не осталось бы: постройка стала бы разовой покупкой, которая никогда не
 * бывает лишней. С содержанием терминал, поставленный там, где очереди нет, тихо
 * съедает прибыль, и игрок обязан отвечать не «где ещё построить», а «где узкое
 * место и стоит ли оно девятисот рублей в сутки».
 *
 * ЧЕГО В ЭТОМ ФАЙЛЕ НЕТ. Он не занимает посты, не считает время погрузки и не
 * держит очередь — это фаза обслуживания (logistics/service.ts). Он не грузит и
 * не выгружает тонны — это фаза прибытия (logistics/loading.ts). Наружу отсюда
 * отдаются ВМЕСТИМОСТИ И ОСТАТКИ, а решения принимает тот, кому они принадлежат:
 * тот же приём и по той же причине, что у водителей (logistics/driver.ts отдаёт
 * множители, а не решает за движение).
 *
 * Все функции чистые: входное состояние не меняется, включая вложенные объекты.
 */

import { BUILDING_SPEC } from '../../data/infrastructure'
import { TICKS_PER_DAY, buildingId } from '../types'
import type {
  Building,
  BuildingId,
  BuildingType,
  CargoType,
  CityId,
  Company,
  CompanyId,
  GameState,
  Tons,
} from '../types'
import { deliveryRevenue } from './finance'

/**
 * Порог значимости тоннажа.
 *
 * Тот же приём и по той же причине, что в logistics/loading.ts: тонны — числа с
 * плавающей точкой, и после нескольких частичных отгрузок на складе остаётся
 * что-нибудь вроде 4.4e-16. Без порога такой нанограмм считался бы грузом,
 * занимал бы вместимость и мешал бы принять честную партию.
 */
const TONS_EPSILON = 1e-9

// ─── Идентификатор ─────────────────────────────────────────────────────────

/**
 * Латинское сокращение типа для идентификатора.
 *
 * Типы построек в игре названы по-русски (BuildingType в types.ts), а
 * идентификаторы во всём проекте латинские: 'zil-1', 'elev-tula',
 * 'player-drv-1'. Разнобой в ключах сохранения читается хуже, а чинить его потом
 * пришлось бы миграцией сейвов.
 */
const TYPE_SLUG: Record<BuildingType, string> = {
  терминал: 'term',
  склад: 'depot',
  хаб: 'hub',
}

/**
 * Идентификатор постройки — ЧИСТАЯ ФУНКЦИЯ ОТ (компания, город, тип).
 *
 * Детерминированный, а не счётчик, и это не косметика: из него СЛЕДУЕТ главное
 * правило застройки (см. buildBuilding). Вторая постройка того же типа в том же
 * городе — это тот же самый ключ, и отказ получается не отдельной проверкой,
 * которую можно забыть, а самой невозможностью занять занятое место.
 *
 * Числовым идентификатор быть не должен: числовые ключи движок поднимает наверх
 * и сортирует по-своему, ломая порядок обхода, на который опирается фаза
 * прибытия (разбор — в шапке logistics/loading.ts).
 */
export function buildingIdFor(
  companyId: CompanyId,
  cityId: CityId,
  type: BuildingType,
): BuildingId {
  return buildingId(`${companyId}-${TYPE_SLUG[type] ?? type}-${cityId}`)
}

// ─── Чтение построек ───────────────────────────────────────────────────────

/**
 * Постройки компании.
 *
 * Сейв прошлой версии мог не знать про инфраструктуру вовсе — тогда здесь пусто,
 * а не падение. Тот же приём, что с Company.drivers в logistics/driver.ts.
 */
function buildingsOf(company: Company): Record<BuildingId, Building> {
  return company.buildings ?? {}
}

/** Постройки компании в этом городе, в порядке вставки ключей. */
export function buildingsIn(company: Company, cityId: CityId): Building[] {
  const found: Building[] = []
  for (const building of Object.values(buildingsOf(company))) {
    if (building.cityId === cityId) found.push(building)
  }
  return found
}

/**
 * Постов, добавленных постройками компании в этом городе.
 *
 * ТОЧКА СТЫКОВКИ С ФАЗОЙ ОБСЛУЖИВАНИЯ: postsAt (logistics/service.ts) — это
 * BASE_POSTS плюс вот это число. Сумма живёт здесь, а не там, затем, чтобы
 * правило «что даёт постройка» было ровно одно; разойдись эти две формулы, и
 * терминал добавлял бы посты в очереди, но не в панели узких мест.
 *
 * ПОСТЫ БЕРУТСЯ У САМОЙ ПОСТРОЙКИ, а не у BUILDING_SPEC по её типу. Тот же
 * довод, по которому Vehicle хранит копию грузоподъёмности своего класса:
 * сохранение обязано пережить перебалансировку справочника, иначе терминал,
 * построенный в прошлой версии, задним числом сменит число постов — и очередь,
 * которую игрок расшивал, соберётся заново без всякой причины.
 */
export function extraPosts(company: Company, cityId: CityId): number {
  let posts = 0
  for (const building of buildingsIn(company, cityId)) {
    const own = building.posts
    if (Number.isFinite(own) && own > 0) posts += own
  }
  return posts
}

// ─── Склад: вместимость и остатки ──────────────────────────────────────────

/**
 * Вместимость постройки, тонн. У чистого терминала — ноль.
 *
 * Битые значения дают ноль, а не NaN: NaN во вместимости просачивается сквозь
 * сравнения, и склад начал бы принимать бесконечно (тот же довод — в шапке
 * deliveryRevenue).
 */
export function storageCapacity(building: Building): Tons {
  const capacity = building.storage
  return Number.isFinite(capacity) && capacity > 0 ? capacity : 0
}

/** Сколько этого груза лежит на складе постройки. */
export function storedTons(building: Building, cargo: CargoType): Tons {
  const tons = building.stock?.[cargo] ?? 0
  return Number.isFinite(tons) && tons > 0 ? tons : 0
}

/** Сколько всего тонн лежит на складе постройки, по всем грузам разом. */
function usedStorage(building: Building): Tons {
  let used = 0
  for (const value of Object.values(building.stock ?? {})) {
    const tons = value ?? 0
    if (Number.isFinite(tons) && tons > 0) used += tons
  }
  return used
}

/**
 * Сколько ещё влезет в постройку, тонн.
 *
 * ВМЕСТИМОСТЬ ОБЩАЯ НА ВСЕ ГРУЗЫ, а не своя у каждого. Ровно так же устроен
 * склад предприятия, и по той же причине (Industry.stock в types.ts): общий
 * склад даёт ОДНО правило переполнения вместо шести. Заодно из этого растёт
 * настоящее решение: хаб, забитый зерном, не примет пиломатериалы, и игроку
 * приходится решать, подо что держать своё хранилище, а не считать его
 * бездонным по каждому грузу отдельно.
 */
export function freeStorage(building: Building): Tons {
  const free = storageCapacity(building) - usedStorage(building)
  return free > TONS_EPSILON ? free : 0
}

/** Сколько этого груза лежит у компании в городе, по всем её постройкам. */
export function storedIn(
  company: Company,
  cityId: CityId,
  cargo: CargoType,
): Tons {
  let tons = 0
  for (const building of buildingsIn(company, cityId)) {
    tons += storedTons(building, cargo)
  }
  return tons
}

/** Сколько ещё влезет компании в городе, по всем её постройкам. */
export function freeStorageIn(company: Company, cityId: CityId): Tons {
  let free = 0
  for (const building of buildingsIn(company, cityId)) {
    free += freeStorage(building)
  }
  return free
}

/**
 * Склад с изменённым остатком по одному грузу. Новый объект — вход не меняется.
 *
 * Одна функция и на приёмку, и на отгрузку: знак у delta. Ключ с нулём
 * УДАЛЯЕТСЯ, а не остаётся нулём: иначе сохранение копило бы мусорные записи по
 * каждому грузу, который когда-либо через склад проходил, а остаток в 4e-16
 * съедал бы вместимость.
 */
function stockWith(
  stock: Partial<Record<CargoType, Tons>>,
  cargo: CargoType,
  delta: Tons,
): Partial<Record<CargoType, Tons>> {
  const next: Partial<Record<CargoType, Tons>> = { ...stock }
  const tons = (next[cargo] ?? 0) + delta

  if (tons > TONS_EPSILON) {
    next[cargo] = tons
  } else {
    delete next[cargo]
  }

  return next
}

// ─── Склад в погрузке и выгрузке ───────────────────────────────────────────

/*
 * КАК СКЛАД УЧАСТВУЕТ В ПОГРУЗКЕ И ВЫГРУЗКЕ.
 *
 * Сама погрузка живёт в logistics/loading.ts, поэтому здесь описано ПРАВИЛО, а
 * наружу отданы функции, которыми фаза прибытия его исполняет: acceptToStorage
 * и releaseFromStorage. Правило состоит из пяти пунктов.
 *
 * 1. СКЛАД — ПОЛУЧАТЕЛЬ ПОСЛЕДНЕЙ ОЧЕРЕДИ. Сначала предприятие, потом город, и
 *    только потом своё хранилище. Иначе склад в городе с мукомольным перехватывал
 *    бы зерно у самого завода, цепочка вставала бы при полном хранилище игрока, и
 *    причину этого не нашёл бы никто. Постройка обязана принимать ИЗЛИШЕК, а не
 *    конкурировать с производством.
 *
 * 2. ПРИЁМ ОГРАНИЧЕН ВМЕСТИМОСТЬЮ, ОБЩЕЙ НА ВСЕ ГРУЗЫ. Не влезло — остаток едет
 *    дальше искать получателя, ровно как с предприятием.
 *
 * 3. ПОГРУЗКА СО СКЛАДА идёт так же, как погрузка готовой продукции у
 *    предприятия, и cargo.originId становится городом склада. Другого варианта
 *    контракт не оставляет: Building.stock — это тонны по типам, без памяти о
 *    том, откуда они приехали. Отсюда прямо следует пункт 4.
 *
 * 4. ЗА ПЕРЕВАЛКУ ПЛАТЯТ НЕ БОЛЬШЕ ПОЛОВИНЫ ТАРИФА — см. TRANSSHIPMENT_SHARE.
 *    Это единственное число в файле, которое нельзя двигать на глаз: выше
 *    половины в игре заводится вечный двигатель. Сколько именно платить внутри
 *    этой границы, решает фаза прибытия, и сейчас она платит НОЛЬ: своё добро,
 *    переложенное в собственный ангар, никто не покупал, а выручка придёт, когда
 *    груз доедет до настоящего получателя. Ноль лежит внутри границы, так что
 *    два файла друг другу не противоречат.
 *
 * 5. ГРУЗ, ВЗЯТЫЙ В ЭТОМ ЖЕ ГОРОДЕ, сдать на свой склад можно, и это не дыра:
 *    плечо нулевое, значит выручка нулевая (см. deliveryRevenue — нулевое плечо
 *    не оплачивается). Смысл такой перекладки в другом — снять продукцию с
 *    задыхающегося завода. Склад предприятия вмещает трое суток выпуска, и
 *    невывезенный завод сбрасывает выработку; своё хранилище на 400 тонн даёт
 *    игроку возможность держать цепочку живой, пока он собирает под неё парк.
 *    Платит он за это временем постов с обеих сторон и содержанием.
 *
 * ЧЕГО СКЛАД НЕ ДЕЛАЕТ: он не кормит город. Тонны в хранилище — товар
 * перевозчика, а не снабжение горожан, иначе постройка сама по себе растила бы
 * население, ни разу никуда не доехав.
 */

/**
 * ПОТОЛОК оплаты за сдачу груза на СВОЙ склад, доля тарифа.
 *
 * ПОЛОВИНА, И ЭТО ЧИСЛО ВЫВЕДЕНО, А НЕ ПОДОБРАНО. Разбор стоит того, чтобы его
 * прочитать целиком: без этой границы склад ломает главный инвариант игры.
 *
 * ОТКУДА БЕРЁТСЯ ОПАСНОСТЬ. Груз, сданный на склад, можно оттуда забрать. Значит
 * два склада в разных городах образуют кольцо, по которому одни и те же тонны
 * ездят туда-обратно вечно, ничего не потребляя. Плати мы за такое плечо полный
 * тариф — оба плеча кольца гружёные, оба оплачены, и по главному инварианту
 * («кольцо с двумя гружёными плечами прибыльно») это ВЕЧНЫЙ ДВИГАТЕЛЬ: сеть,
 * которая не возит ничего никому и приносит больше честной. Причём находится он
 * не игроком, а первым же оптимизатором.
 *
 * ПОЧЕМУ ИМЕННО ПОЛОВИНА. Пусть плечо L, машина везёт m тонн, переменные расходы
 * c руб/км, выручка за гружёное плечо R = m·(h + t·L)·p. Инвариант из
 * data/operating.ts утверждает про любое кольцо из двух плеч:
 *
 *       R  <  2·L·c        одно гружёное плечо кольцо не окупает
 *     2·R  >  2·L·c        два гружёных плеча окупают
 *
 * Перевалочное кольцо «склад → склад → склад» состоит из двух гружёных плеч,
 * каждое оплачено долей k:
 *
 *     выручка = 2·k·R      расходы = 2·L·c
 *
 * При k = 1/2 выручка равна ровно R — то есть в точности левой части инварианта,
 * которая СТРОГО меньше расходов. Кольцо из перевалок убыточно при любом плече,
 * любом грузе и любом классе машины, и проверяется это тем же самым неравенством,
 * которым проверяется вся экономика игры. Ни одной новой ручки баланса.
 *
 * При k > 1/2 на длинных плечах (где постоянная h растворяется, а m·t·p подходит
 * к 2c) вечный двигатель оживает. При k < 1/2 перевалка просто наказана сильнее,
 * чем требуется. Половина — верхняя граница безопасного, и брать меньше значит
 * отнимать у постройки смысл без всякой причины.
 *
 * ПОБОЧНОЕ СЛЕДСТВИЕ, И ОНО ЖЕЛАТЕЛЬНОЕ: перевалка НИКОГДА не приносит больше,
 * чем прямая доставка. Разница в пользу прямого рейса равна ½·m·p·(t·L₁ − h) и
 * положительна, пока плечо до склада длиннее h/t ≈ 21 км; самое короткое ребро
 * карты — 110 км, так что положительна всегда (на нём — 879 рублей с ходки ЗИЛа).
 * Значит склад покупают не ради выручки за тонно-километр, а ради того, ради чего
 * он и задуман: чтобы машины не стояли в очереди и не ходили порожняком.
 */
export const TRANSSHIPMENT_SHARE = 0.5

/**
 * Выручка за сдачу груза на свой склад, рубли.
 *
 * Обёртка над deliveryRevenue, а не своя формула. Тариф в игре обязан считаться
 * в одном месте (шапка economy/finance.ts): разойдись «выручка за доставку» и
 * «выручка за перевалку», и перебалансировка тарифа молча перекосила бы
 * экономику складов в неизвестную сторону.
 */
export function transshipmentRevenue(
  cargo: CargoType,
  tons: Tons,
  km: number,
  tariffPerTonKm: number,
  handlingPerTon: number,
): number {
  return (
    deliveryRevenue(cargo, tons, km, tariffPerTonKm, handlingPerTon) *
    TRANSSHIPMENT_SHARE
  )
}

/**
 * Изменить остаток на ОДНОЙ конкретной постройке. Знак у delta.
 *
 * САМЫЙ НИЗКИЙ УРОВЕНЬ И ЕДИНСТВЕННОЕ МЕСТО, ГДЕ МЕНЯЕТСЯ СКЛАД ПОСТРОЙКИ. Фаза
 * прибытия работает именно так: она уже выбрала, у КОГО берёт и КОМУ отдаёт (у
 * неё на руках идентификатор постройки), и ей нужна не «приёмка в городе», а
 * запись в конкретное хранилище. Держать эту запись у себя она не должна —
 * правило переполнения, порог значимости и удаление нулевых ключей разъехались
 * бы с этим файлом молча, и обнаружилось бы это тоннами, взявшимися из ниоткуда.
 *
 * ПЕРЕПОЛНИТЬ И УЙТИ В МИНУС НЕЛЬЗЯ НИ ПРИ КАКОЙ ОШИБКЕ ВЫЗЫВАЮЩЕГО: сверх
 * свободного места и сверх лежащего остатка функция просто не пойдёт. Тонны —
 * единственная величина в игре, которая обязана сходиться, и «доверять
 * вызывающему» здесь означало бы отдать сохранность баланса тому, кто про
 * вместимость знать не обязан.
 *
 * Ничего не изменилось — компания возвращается той же по ссылке.
 */
export function withStoredAt(
  company: Company,
  id: BuildingId,
  cargo: CargoType,
  delta: Tons,
): Company {
  if (!Number.isFinite(delta) || delta === 0) return company

  const stores = buildingsOf(company)
  const building = stores[id]
  if (building === undefined) return company

  const limit = delta > 0 ? freeStorage(building) : storedTons(building, cargo)
  const size = Math.min(Math.abs(delta), limit)
  if (size <= TONS_EPSILON) return company

  const change = delta > 0 ? size : -size

  return {
    ...company,
    buildings: {
      ...stores,
      [id]: { ...building, stock: stockWith(building.stock, cargo, change) },
    },
  }
}

/**
 * Принять тонны на склады компании в этом городе.
 *
 * Возвращает НОВУЮ компанию и сколько тонн влезло. Не влезло ничего — компания
 * возвращается той же по ссылке: по совпадению ссылок фаза прибытия отличает
 * изменившееся от нетронутого, как и все остальные фазы.
 *
 * Построек со вместимостью в городе может быть две (склад и хаб — разные типы,
 * см. правило застройки в buildBuilding), поэтому они наполняются по очереди, в
 * порядке вставки ключей. Порядок значим — от него зависит, где именно окажутся
 * тонны, — и потому обязан быть воспроизводимым; на порядок вставки здесь
 * опираться можно ровно по тому же разбору, что в шапке logistics/loading.ts.
 */
export function acceptToStorage(
  company: Company,
  cityId: CityId,
  cargo: CargoType,
  tons: Tons,
): { company: Company; accepted: Tons } {
  if (!Number.isFinite(tons) || tons <= TONS_EPSILON) {
    return { company, accepted: 0 }
  }

  const stores = buildingsOf(company)
  let current = company
  let left = tons
  let accepted = 0

  for (const key of Object.keys(stores) as BuildingId[]) {
    if (left <= TONS_EPSILON) break

    const building = stores[key]
    if (building.cityId !== cityId) continue

    const free = freeStorage(building)
    if (free <= TONS_EPSILON) continue

    // Каждая постройка трогается ровно один раз, поэтому свободное место
    // считается по исходному снимку и пересчитывать его незачем.
    const put = free < left ? free : left
    const next = withStoredAt(current, key, cargo, put)
    if (next === current) continue

    current = next
    left -= put
    accepted += put
  }

  return { company: current, accepted }
}

/**
 * Забрать тонны со складов компании в этом городе.
 *
 * Возвращает НОВУЮ компанию и сколько тонн удалось набрать — не больше, чем
 * просили, и не больше, чем лежит. Ничего не нашлось — компания та же по ссылке.
 *
 * Отдавать частями законно: машина берёт, сколько есть, и уезжает. Требование
 * «или полный кузов, или ничего» намертво заперло бы остаток на складе — ровно
 * тот же довод, по которому фаза прибытия принимает частичную разгрузку.
 */
export function releaseFromStorage(
  company: Company,
  cityId: CityId,
  cargo: CargoType,
  wanted: Tons,
): { company: Company; released: Tons } {
  if (!Number.isFinite(wanted) || wanted <= TONS_EPSILON) {
    return { company, released: 0 }
  }

  const stores = buildingsOf(company)
  let current = company
  let left = wanted
  let released = 0

  for (const key of Object.keys(stores) as BuildingId[]) {
    if (left <= TONS_EPSILON) break

    const building = stores[key]
    if (building.cityId !== cityId) continue

    const have = storedTons(building, cargo)
    if (have <= TONS_EPSILON) continue

    const take = have < left ? have : left
    const next = withStoredAt(current, key, cargo, -take)
    if (next === current) continue

    current = next
    left -= take
    released += take
  }

  return { company: current, released }
}

