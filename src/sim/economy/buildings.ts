/**
 * Содержание всех построек компании за тик, рубли.
 *
 * Ставка суточная (upkeepPerDay в data/infrastructure.ts) и делится на число
 * тиков в сутках — так же, как зарплата водителя в economy/operating.ts. Другого
 * способа нет: тик — единственные часы в игре, и «раз в сутки» означало бы
 * привязку к номеру тика, то есть скачок в счетах ровно в полночь.
 *
 * СТАВКА БЕРЁТСЯ У СПРАВОЧНИКА, А НЕ У ПОСТРОЙКИ, в отличие от постов и
 * вместимости, — и это не непоследовательность. Посты и вместимость постройка
 * ОБЕЩАЛА игроку в момент покупки, и менять их задним числом нечестно. Стоимость
 * содержания — это цена мира, а не свойство бетона: подорожало содержание — оно
 * подорожало у всех, и у старых терминалов тоже. Ровно так же цена литра топлива
 * не заморожена в машине по году её выпуска.
 */
export function upkeepPerTick(company: Company): number {
  let perDay = 0

  for (const building of Object.values(buildingsOf(company))) {
    const spec = BUILDING_SPEC[building.type]
    if (spec === undefined) continue

    const rate = spec.upkeepPerDay
    if (Number.isFinite(rate) && rate > 0) perDay += rate
  }

  return perDay / TICKS_PER_DAY
}

/**
 * Фаза содержания целиком. Возвращает НОВОЕ состояние.
 *
 * МЕСТО В ТИКЕ: внутри фазы расходов, ДО runOperatingCosts. Причина техническая
 * и жёсткая. Суточные потоки — это экспоненциальное окно (dayWindow в
 * economy/operating.ts), и затухание применяется РОВНО ОДИН РАЗ за тик, в
 * runOperatingCosts. Значит содержание обязано лечь в dailyCosts до затухания,
 * как выручка ложится туда через creditRevenue до него же. Встань эта фаза
 * после — окно показывало бы содержание завышенным на один шаг затухания
 * навсегда, а деньги на счету при этом были бы правильные: расхождение, которое
 * ищется по панели, а не по балансу.
 *
 * БАНКРОТ НЕ ПЛАТИТ. Партия для него окончена, расходы ему не начисляются вовсе
 * (freeze в economy/operating.ts), и содержание — не исключение: иначе счёт
 * разорившейся компании продолжал бы уходить в минус до конца игры.
 *
 * Проверку долга и банкротство эта фаза НЕ ДЕЛАЕТ. Их делает runOperatingCosts,
 * один раз и на все статьи разом: два места, решающих «разорился ли», разошлись
 * бы на первом же изменении отсрочки.
 *
 * Порядок обхода не значим: каждая компания платит за свои постройки, ничего
 * общего они не делят.
 */
export function runUpkeep(state: GameState): GameState {
  const companies: Record<CompanyId, Company> = { ...state.companies }
  let changed = false

  for (const id of Object.keys(companies) as CompanyId[]) {
    const company = companies[id]
    if (company.bankrupt) continue

    const bill = upkeepPerTick(company)
    // Компания без построек — это большинство компаний в начале партии. Ей эта
    // фаза не касается вовсе, и запись остаётся исходной по ссылке.
    if (!(bill > 0)) continue

    companies[id] = {
      ...company,
      money: company.money - bill,
      dailyCosts: company.dailyCosts + bill,
    }
    changed = true
  }

  return changed ? { ...state, companies } : state
}
