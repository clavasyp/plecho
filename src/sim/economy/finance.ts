/**
 * Деньги за перевозку.
 *
 * Единственное место, где километры и тонны превращаются в рубли. Формула одна
 * на всю игру: и для игрока, и для конкурентов, и для оценки рейса в интерфейсе.
 * Разные формулы «для расчёта» и «для показа» разошлись бы так же тихо, как
 * когда-то разошлись две формулы скорости (разбор — в шапке world/speed.ts).
 *
 * ЕДИНИЦЫ. Тонны и километры на входе, рубли на выходе. Ставки берутся из
 * CARGO_RATE (src/data/recipes.ts) и там же обоснованы.
 */

import { CARGO_PREMIUM } from '../../data/recipes'
import type { CargoType, Tons } from '../types'

/**
 * Опорное плечо, км — расстояние, на котором тариф равен ровно CARGO_RATE.
 *
 * 200 км выбраны не «для круглого числа»: средняя длина ребра в графе дорог —
 * 227 км, а самый частый радиус из Москвы вообще 185–200 (Тула 185, Владимир
 * 185, Калуга 190, Рязань 200). То есть типовой рейс в этом мире — это и есть
 * опорное плечо, и на нём слова из recipes.ts «базовая ставка за тонну» имеют
 * буквальный смысл: 1600 руб за тонну муки — это 1600 руб за тонну муки,
 * привезённую из Москвы в Тулу, без всяких поправочных множителей в уме.
 *
 * Отсюда же правило чтения любой цифры в CARGO_RATE: короче опорного — платят
 * меньше, длиннее — больше.
 */
export const DELIVERY_REFERENCE_KM = 200

/**
 * Доля тарифа, не зависящая от расстояния.
 *
 * Тариф двухсоставный, как в отрасли: часть за саму подачу машины под груз
 * (маневрирование, погрузка, оформление, разгрузка — всё это стоит одинаково
 * и на 100 км, и на 1000), часть за тонно-километры. Одной составляющей мало
 * в обе стороны: чистый тонно-километр обесценивает короткие плечи до
 * бессмысленности, а чистая ставка за тонну делает дальние рейсы глупостью —
 * зачем ехать 400 км за те же деньги.
 *
 * 0.4 — не на глаз. Реальная деградация ставки по расстоянию для двадцатитонной
 * фуры: около 150 руб/км на плече 100 км и около 65 руб/км на 1000 км. Двумя
 * точками однозначно определяется двухсоставный тариф: постоянная часть ≈ 9400
 * руб за рейс, переменная ≈ 56 руб/км. На опорных 200 км постоянная часть даёт
 * 46% выручки. Берём 0.4 — чуть в пользу дальних плеч, потому что простой под
 * погрузкой (то, чем короткие рейсы расплачиваются в жизни) в срезе 2 ещё не
 * смоделирован, и без этой поправки развозка по соседним городам была бы
 * доминирующей стратегией с первого дня.
 */
export const DELIVERY_FIXED_SHARE = 0.4

/** Доля тарифа за расстояние. Выводится, чтобы две доли не разъехались. */
export const DELIVERY_DISTANCE_SHARE = 1 - DELIVERY_FIXED_SHARE

/**
 * Выручка за доставленную партию, рубли.
 *
 *     руб = тонны × ставка × (0.4 + 0.6 × км / 200)
 *
 * ОБЕ составляющие пропорциональны ставке груза, а не только первая. Это
 * сознательно: у груза остаётся ровно одна ручка — CARGO_RATE, — и новый груз
 * добавляется одним числом в данных. Заодно это правдоподобно: тонно-километр
 * наливного топлива в цистерне и правда дороже тонно-километра кругляка на
 * лесовозе, потому что дороже сама техника под него.
 *
 * ПРОВЕРКА НА РЕАЛЬНЫХ ЧИСЛАХ (граф из data/roads.ts, ЗИЛ-130: 6 т, крейсерские
 * 70 км/ч, расход около 30 л/100 км). Считаем круговой рейс с ПОРОЖНИМ
 * возвратом — то есть худший случай, какой вообще бывает:
 *
 *   Москва → Тула, М-2 «Крым», 185 км, качество 0.87 → 60.9 км/ч, 3.04 ч.
 *     мука, 6 т: 6 × 1600 × (0.4 + 0.6 × 185/200) = 9168 руб
 *     круг 370 км ≈ 111 л, смена 6.1 ч → 1508 руб/ч выручки
 *     безубыточно по топливу до 82 руб/л
 *
 *   Тула → Калуга, Р-132, 110 км, качество 0.65 → 45.5 км/ч, 2.42 ч.
 *     зерно, 6 т: 6 × 900 × (0.4 + 0.6 × 110/200) = 3942 руб
 *     круг 220 км ≈ 66 л, смена 4.8 ч → 815 руб/ч
 *     безубыточно по топливу до 59 руб/л
 *
 *   Москва → Смоленск, М-1 «Беларусь», 395 км, качество 0.88 → 61.6 км/ч, 6.4 ч.
 *     мука, 6 т: 6 × 1600 × (0.4 + 0.6 × 395/200) = 15 216 руб
 *     круг 790 км ≈ 237 л, смена 12.8 ч → 1187 руб/ч
 *     безубыточно по топливу до 64 руб/л
 *
 * Топливо в игре появится в срезе 3 (economy/market.ts), поэтому проверка
 * сформулирована в виде порога: рейс остаётся прибыльным, пока солярка дешевле
 * 59 руб/л даже в самом худшем из трёх случаев. Любая правдоподобная цена ниже
 * этого порога, и запаса хватает ещё и на водителя, и на износ.
 *
 * Из тех же трёх строк видно, ЧТО игра поощряет. Выручка на километр КРУГА:
 * 24.8 руб на Туле, 19.3 руб на Смоленске, 17.9 руб на зерновом плече. Дальний
 * рейс окупается, но порожний возврат съедает его преимущество — ровно тот
 * конфликт, ради которого в игре есть обратная загрузка. А разрыв между 24.8 и
 * 17.9 говорит, что ВЫБОР ГРУЗА важнее выбора расстояния: возить дешёвое сырьё
 * по разбитой региональной трассе — работа на грани, и это правильно.
 *
 * НУЛЕВОЕ ПЛЕЧО НЕ ОПЛАЧИВАЕТСЯ. Тариф платят за перевозку, а не за факт
 * перекладывания тонн: если бы постоянная часть начислялась и при нулевом
 * пробеге, машина, стоящая в городе, где рядом стоят и производитель, и
 * потребитель, печатала бы деньги, гоняя груз между складами не сходя с места.
 * Разрыва в поведении это не создаёт — самое короткое ребро в графе 110 км.
 *
 * Битые входы (NaN, отрицательные тонны, неизвестный груз) дают ноль, а не NaN.
 * NaN, попавший в баланс компании, отравляет его навсегда и молча: все
 * последующие сравнения с ним ложны, и банкротство никогда не наступит.
 */
/**
 * Выручка за доставленную партию.
 *
 * ТАРИФ БЕРЁТСЯ У КЛАССА МАШИНЫ, и это не формальность. Ставка за
 * тонно-километр падает с размером партии (объёмная скидка), и ровно на этом
 * держится главный инвариант игры на тяжёлой технике: без скидки двадцать
 * тонн зарабатывали бы столько, что порожний возврат перестал бы пугать.
 *
 * Раньше здесь стояли ГЛОБАЛЬНЫЕ константы, а поля класса не читал никто —
 * весь расчёт по классам в src/data/vehicles.ts оказался декоративным.
 * Замеры ревизии на кратчайшем ребре карты (110 км): тягач с зерном давал
 * 8 660 руб за плечо против 7 766 руб расходов кольца, то есть инвариант был
 * нарушен, а тесты этого не видели — они считали по тем же глобальным числам.
 *
 * Поэтому тариф и плата за погрузку теперь ВХОДЯТ В СИГНАТУРУ: забыть их
 * нельзя, компилятор не даст.
 */
export function deliveryRevenue(
  cargo: CargoType,
  tons: Tons,
  km: number,
  tariffPerTonKm: number,
  handlingPerTon: number,
): number {
  const premium = CARGO_PREMIUM[cargo]

  if (
    !Number.isFinite(premium) ||
    !Number.isFinite(tons) ||
    !Number.isFinite(km) ||
    !Number.isFinite(tariffPerTonKm) ||
    !Number.isFinite(handlingPerTon)
  ) {
    return 0
  }
  if (tons <= 0 || km <= 0) return 0

  return tons * (handlingPerTon + tariffPerTonKm * km) * premium
}
