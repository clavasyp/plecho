/**
 * Фаза расходов: топливо, зарплата, обслуживание, суточный итог, банкротство.
 *
 * Вторая половина баланса. До среза 3 деньги в игре только приходили: любая
 * доставка была выгодна, порожнее плечо не стоило ничего, и метрика порожнего
 * пробега оставалась украшением отчёта. Здесь она становится деньгами — расход
 * топлива не зависит от груза (см. Vehicle.fuelPer100Km в sim/types.ts),
 * поэтому холостое плечо жжёт ровно столько же, сколько гружёное, и не приносит
 * ничего. Это и есть главный урок игры, выраженный в рублях.
 *
 * ─── ЧТО ИЗМЕНИЛ СРЕЗ 4: НИ ОДНОЙ ПЛОСКОЙ СТАВКИ НЕ ОСТАЛОСЬ ────────────────
 *
 * Раньше все три статьи были глобальными константами, одинаковыми для всего
 * парка. Теперь у каждой свой хозяин, и фаза только складывает:
 *
 *   топливо        расход берётся у МАШИНЫ (копия паспорта её класса), а
 *                  множитель за аккуратность — у ВОДИТЕЛЯ (fuelFactor);
 *   обслуживание   ставка берётся у logistics/wear.ts, который знает и класс
 *                  машины, и её износ. Плоского MAINTENANCE_PER_KM здесь
 *                  больше нет — изношенный грузовик обязан стоить дороже
 *                  нового, иначе решение «пора списывать» принимать не по чему;
 *   зарплата       берётся у ВОДИТЕЛЯ, а не у машины. Это не косметика:
 *                  водитель в резерве получает зарплату, не имея машины вовсе,
 *                  а машина без водителя не стоит ничего, кроме места на
 *                  площадке. Считай мы зарплату по парку — оба случая
 *                  посчитались бы наоборот.
 *
 * Ставки, которые всё-таки общие на весь мир (цена литра, отсрочка до
 * банкротства), по-прежнему живут в src/data/operating.ts и своих здесь не
 * заводится: баланс правится в одном файле, а не размазан по фазам.
 *
 * ─── ГЛАВНАЯ ТРУДНОСТЬ ФАЗЫ: СКОЛЬКО МАШИНА ПРОЕХАЛА ЗА ЭТОТ ТИК ───────────
 *
 * Топливо и обслуживание начисляются по пробегу ИМЕННО ЭТОГО тика, а не по
 * одометру: одометр — накопленный за партию, и списывать по нему каждый тик
 * значило бы разорить игрока за первый же час.
 *
 * Взять пробег тика вычитанием не из чего. Фаза получает ОДНО состояние — то,
 * что сложилось после движения, — а состояния на начало тика у неё нет и быть
 * не может: сигнатура фазы одна на все фазы конвейера. Хранить «одометр на
 * начало тика» тоже негде: types.ts — контракт, поля в Vehicle не добавить.
 *
 * Отдельно стоит закрыть заманчивый ложный ход. Разность
 * `odometer − loadedKm − emptyKm` могла бы служить отметкой непосчитанного
 * пробега, но logistics/vehicle.ts разносит километры по счетам В ТОТ ЖЕ
 * МОМЕНТ, когда наращивает одометр (и это правильно — только там машина знает,
 * гружена ли она), поэтому разность тождественно равна нулю. Инварианту
 * `loadedKm + emptyKm === odometer` посвящена проверка в tick.test.ts, то есть
 * он не случайность, а правило. Свободного счётчика в состоянии не осталось.
 *
 * Поэтому пробег тика здесь не ВОССТАНАВЛИВАЕТСЯ, а ИЗМЕРЯЕТСЯ по той же
 * модели движения, которой ехала машина, — см. tickKm.
 */

import {
  BANKRUPTCY_GRACE_DAYS,
  DRIVER_WAGE_PER_DAY,
  FUEL_PRICE_PER_LITER,
} from '../../data/operating'
import { driverOf, fuelFactor } from '../logistics/driver'
import { actualSpeedKmh, advanceVehicle } from '../logistics/vehicle'
import { maintenancePerKm } from '../logistics/wear'
import { TICKS_PER_DAY, TICKS_PER_HOUR } from '../types'
import type {
  Company,
  CompanyId,
  Driver,
  GameState,
  Vehicle,
} from '../types'

/**
 * Длительность тика в часах — 0.25.
 *
 * То же самое число, что HOURS_PER_TICK в sim/tick.ts, но выведенное здесь
 * заново, а не импортированное: tick.ts вызывает эту фазу, и обратный импорт
 * замкнул бы модули в цикл. Дублированием это не является — перевод единиц
 * `1 / TICKS_PER_HOUR` не содержит ни одного игрового решения и разъехаться с
 * собой не может; разъезжаются формулы (разбор — в шапке world/speed.ts), а не
 * определения единиц из контракта.
 */
const HOURS_PER_TICK = 1 / TICKS_PER_HOUR

/**
 * Базовая ставка зарплаты за тик, рубли.
 *
 * Суточная ставка СРЕДНЕГО водителя без допусков, размазанная по тикам.
 * Настоящая зарплата у каждого своя (Driver.wagePerDay), и считает её найм в
 * logistics/driver.ts; здесь константа осталась как точка отсчёта — по ней
 * читается любая ставка в панели и по ней же выведен стартовый капитал.
 */
export const WAGE_PER_TICK = DRIVER_WAGE_PER_DAY / TICKS_PER_DAY

/**
 * Доля суточного окна, которая сбрасывается каждый тик.
 *
 * Знаменатель на единицу больше числа тиков в сутках, и это не описка.
 * Слагаемое текущего тика попадает в окно ДО затухания (фаза видит уже
 * пополненный счётчик — почему так, объяснено у dayWindow), поэтому при
 * постоянном потоке x за тик установившееся значение окна равно
 * x·(1−d)/d. Чтобы оно совпало ровно с суточным итогом x·TICKS_PER_DAY,
 * требуется d = 1/(TICKS_PER_DAY + 1). Без поправки окно показывало бы
 * на процент меньше правды — мелочь, но мелочь необъяснимая.
 */
export const DAY_WINDOW_DECAY = 1 / (TICKS_PER_DAY + 1)

/**
 * Допуск при сравнении накопленных суток с отсрочкой.
 *
 * daysInDebt набирается сложением 1/96 две с половиной тысячи раз, и ровно
 * тридцати не получится никогда: в двоичной дроби 1/96 не представима. Без
 * допуска банкротство наступало бы то на 2880-м тике, то на 2881-м в
 * зависимости от того, в какую сторону накопилась ошибка, — то есть
 * недетерминированно с точки зрения игрока и невоспроизводимо в тесте.
 */
const DAY_EPSILON = 1e-9

/**
 * Стоимость топлива на пройденные километры, рубли.
 *
 * ТРИ СОМНОЖИТЕЛЯ, И У КАЖДОГО СВОЙ ХОЗЯИН. Расход на сто километров — у машины
 * (Vehicle.fuelPer100Km, копия паспорта её класса из справочника техники). Цена
 * литра — у данных: в срезе 6 она станет рыночной и замкнёт топливную петлю
 * нефть → НПЗ → АЗС → твой же парк, поэтому спрашивается, а не вписана
 * множителем. Аккуратность — у водителя (fuelFactor в logistics/driver.ts):
 * опытный жжёт меньше на той же машине, и это единственная статья расходов, на
 * которую человек за рулём влияет напрямую.
 *
 * Водителя может не быть — тогда множитель единичный. Спрашивать расход у
 * машины без водителя всё равно приходится: интерфейс оценивает плечо до того,
 * как игрок кого-то на машину посадил.
 *
 * Битые входы дают ноль, а не NaN. NaN, попавший в баланс компании, отравляет
 * его навсегда и молча: все сравнения с ним ложны, и банкротство не наступит
 * никогда (тот же довод — в шапке deliveryRevenue).
 */
export function fuelCost(
  vehicle: Vehicle,
  km: number,
  driver: Driver | null = null,
): number {
  const cost =
    ((km * vehicle.fuelPer100Km) / 100) *
    FUEL_PRICE_PER_LITER *
    fuelFactor(driver)

  return Number.isFinite(cost) && cost > 0 ? cost : 0
}

/**
 * Стоимость обслуживания на пройденные километры, рубли.
 *
 * Ставка спрашивается у logistics/wear.ts и НЕ вычисляется здесь. Там она
 * складывается из двух вещей, которых фаза расходов знать не обязана: паспортной
 * стоимости километра для класса машины и множителя за износ. Именно из-за
 * второго слагаемого статья и осталась отдельной от топлива, хотя обе считаются
 * по пробегу: у старой машины обслуживание ползёт вверх, а расход топлива —
 * нет. Сложи их в одно число, и разделять пришлось бы вместе с балансом.
 */
export function maintenanceCost(vehicle: Vehicle, km: number): number {
  const cost = km * maintenancePerKm(vehicle)
  return Number.isFinite(cost) && cost > 0 ? cost : 0
}

/**
 * Всё, что машина платит за километры: топливо плюс обслуживание.
 *
 * Водитель необязателен: интерфейс оценивает плечо, ещё не зная, кто поедет, и
 * получает расход по паспорту. В самой симуляции он передаётся всегда.
 */
export function distanceCost(
  vehicle: Vehicle,
  km: number,
  driver: Driver | null = null,
): number {
  return fuelCost(vehicle, km, driver) + maintenanceCost(vehicle, km)
}

/**
 * Зарплата одного водителя за тик, рубли.
 *
 * Ставка личная и начисляется КАЖДЫЙ тик: и в рейсе, и на стоянке, и на
 * обязательном отдыхе. Отсюда следует главное свойство штата — лишний человек
 * убыточен сам по себе, а не просто «не приносит пользы».
 */
export function wagePerTick(driver: Driver): number {
  const wage = driver.wagePerDay / TICKS_PER_DAY
  return Number.isFinite(wage) && wage > 0 ? wage : 0
}

/**
 * Фонд оплаты труда компании за тик, рубли.
 *
 * Считается ПО ШТАТУ, а не по парку, и это принципиально. Водитель в резерве
 * машины не имеет и в обходе парка не встретился бы ни разу — а получает он
 * полностью. Машина без водителя, наоборот, встретилась бы и потребовала
 * зарплату, которую платить некому. Оба случая — не редкость, а нормальный ход
 * игры: людей нанимают до покупки машины и оставляют после её продажи.
 */
export function payrollPerTick(company: Company): number {
  const roster = company.drivers
  if (roster === undefined) return 0

  let total = 0
  for (const driver of Object.values(roster)) {
    total += wagePerTick(driver)
  }
  return total
}

/**
 * Пробег машины за прошедший тик, километры.
 *
 * ИЗМЕРЕНИЕ, А НЕ РАЗНОСТЬ. Модель движения детерминирована и проста: машина
 * либо стоит в узле, либо едет по ребру со скоростью actualSpeedKmh, и фаза
 * движения всегда доедает тик целиком (см. цикл в advanceVehicle). Значит про
 * машину, которая на границе тика стоит НА РЕБРЕ, известно точно: весь тик она
 * ехала, и проехала `скорость × длительность тика`. Про машину, стоящую В УЗЛЕ,
 * известно, что дальше она не поехала.
 *
 * СКОРОСТЬ БЕРЁТСЯ ФАКТИЧЕСКАЯ, вместе с человеком за рулём. Это же закрывает
 * все четыре случая «машина не едет» одной строкой: нет водителя, водитель на
 * обязательном отдыхе, машина сломана — actualSpeedKmh даёт ноль, и брошенный
 * посреди ребра грузовик не жжёт солярку, стоя на обочине. Отдельной проверки
 * здесь нет намеренно: она была бы второй копией правил, живущих в driver.ts.
 *
 * ДОСЧЁТ ХВОСТА — вторая половина правила и обязательная. Плечо почти никогда
 * не укладывается в целое число тиков: последние несколько километров машина
 * проезжает в тике, на границе которого она уже стоит в узле, — и по первому
 * правилу этот остаток не оплатил бы никто. Потеря не косметическая: она равна
 * до одного тика хода НА КАЖДОЕ плечо (около 14 км для ЗИЛа на М-2, то есть
 * примерно 5% топлива в среднем) и тем больше в процентах, чем короче плечи.
 * Игра, где короткие плечи ездят дешевле длинных, учила бы ровно обратному
 * тому, ради чего затевалась. Поэтому, когда до конца плеча остаётся меньше
 * тика хода, остаток начисляется АВАНСОМ — в тике, когда машина ещё едет. В
 * следующем тике она встанет в узле и не заплатит ничего, а сумма за плечо
 * сойдётся ровно в его длину.
 *
 * «До конца плеча» — это именно остановка, а не любой узел: транзитный город
 * машина проезжает насквозь, не теряя ни минуты, и её пробег в таком тике
 * покрывается общим правилом. Отличает одно от другого сама фаза движения:
 * прогон advanceVehicle на тик вперёд показывает, встанет машина или поедет
 * дальше. Своей копии этого решения здесь нет намеренно — она разъехалась бы
 * с оригиналом, и разъезд был бы виден только в деньгах.
 *
 * ЧЕГО ЭТА МОДЕЛЬ НЕ ЛОВИТ, честно:
 *
 *   1. Тик, в котором машина пересекает транзитный узел, оплачивается по
 *      скорости НОВОГО ребра. Ошибка ограничена разностью скоростей за тик,
 *      знака не имеет (на обратном плече она обратная) и не накапливается.
 *   2. Плечо короче одного тика хода не оплачивается вовсе: машина уедет и
 *      приедет между двумя замерами. Самое короткое ребро в графе — 110 км,
 *      самый быстрый тик хода — 22.5 км, так что случай пока невозможен по
 *      данным. Если графу когда-нибудь понадобятся короткие рёбра, дешевле
 *      будет передать фазе предыдущее состояние, чем усложнять это правило.
 */
export function tickKm(vehicle: Vehicle, state: GameState): number {
  const position = vehicle.position

  // Стоит в узле — этот тик она не ехала. Хвост предыдущего плеча ей уже
  // начислен авансом, поэтому здесь именно ноль, а не «посмотрим, куда поедет».
  if (position.kind !== 'ребро') return 0

  const edge = state.world.edges[position.edgeId]
  // Ребро исчезло из мира (перестройка графа под старым сохранением) — платить
  // не за что. Движение в этом случае тоже стоит, см. advanceVehicle.
  if (edge === undefined) return 0

  const perTick = actualSpeedKmh(state, vehicle, edge) * HOURS_PER_TICK
  if (!Number.isFinite(perTick) || perTick <= 0) return 0

  const remaining = edge.km * (1 - position.progress)

  // До конца ребра больше тика хода — машина точно останется в пути, и хвоста
  // в этом тике не будет. Прогон движения незачем: он ничего не изменит.
  if (!(remaining <= perTick)) return perTick

  const ahead = advanceVehicle(vehicle, state, HOURS_PER_TICK)
  const stopping = ahead.position.kind === 'узел' && ahead.route.length === 0
  if (!stopping) return perTick

  const tail = ahead.odometer - vehicle.odometer
  return Number.isFinite(tail) && tail > 0 ? perTick + tail : perTick
}

/**
 * Расходы одной машины за тик, рубли: только километры.
 *
 * ЗАРПЛАТЫ ЗДЕСЬ НЕТ, и в этом всё отличие от среза 3. Пока водитель был
 * свойством машины, «расходы машины за тик» включали его ставку. Теперь водитель
 * — отдельная сущность со своим счётом (payrollPerTick), и прибавь мы зарплату
 * ещё и здесь, человек за рулём оплачивался бы дважды, а сидящий в резерве — ни
 * разу.
 *
 * Пробег берётся один раз и передаётся аргументом, а не спрашивается внутри:
 * интерфейсу и тестам нужно уметь спросить «сколько стоит вот столько
 * километров» без всякого состояния мира.
 */
export function vehicleTickCosts(
  vehicle: Vehicle,
  km: number,
  driver: Driver | null = null,
): number {
  return distanceCost(vehicle, km, driver)
}

/**
 * Скользящий суточный итог, рубли.
 *
 * ЗАЧЕМ ОКНО. dailyRevenue и dailyCosts обязаны показывать итог ПОСЛЕДНИХ
 * суток, а не сумму с начала партии: прибыль в тайкуне — это поток, и растущий
 * счёт при убыточной сети обычное дело, пока игрок проедает стартовый капитал.
 * Накопительный итог сообщил бы о беде в тот день, когда деньги кончились.
 *
 * ПОЧЕМУ ЭКСПОНЕНЦИАЛЬНОЕ, А НЕ ЧЕСТНАЯ СУММА ЗА 96 ТИКОВ. Честная сумма
 * требует хранить 96 отсчётов на компанию, а в Company есть ровно два числа —
 * types.ts контракт. Окно с затуханием даёт тот же ответ одним числом: при
 * постоянном потоке оно сходится ровно к суточному итогу (за это отвечает
 * поправка в DAY_WINDOW_DECAY), а на изменение потока реагирует плавно, что для
 * показателя даже лучше — метрика не прыгает от одной удачной разгрузки.
 *
 * ПОЧЕМУ СЛАГАЕМОЕ ЭТОГО ТИКА ЗАТУХАЕТ ВМЕСТЕ СО ВСЕМИ. Выручку в счётчик
 * кладёт фаза прибытия, расходы — эта; разделить «старое окно» и «поступление
 * этого тика» внутри одного числа невозможно. Значит, единственный способ
 * обойтись без второго поля — обращаться с обоими одинаково. Так и сделано, и
 * поэтому выручка с расходами считаются по одной формуле: перекос между ними
 * был бы виден в показанной прибыли, а он тут был бы ни на чём не основан.
 */
function dayWindow(total: number): number {
  const next = total * (1 - DAY_WINDOW_DECAY)
  return Number.isFinite(next) && next > 0 ? next : 0
}

/**
 * Начислить компании выручку так, чтобы она попала и в счёт, и в суточное окно.
 *
 * ТОЧКА СТЫКОВКИ С ФАЗОЙ ПРИБЫТИЯ. Расходы фаза считает сама, а выручку видит
 * только тот, кто разгружает машину (logistics/loading.ts): по состоянию ПОСЛЕ
 * разгрузки уже не восстановить, сколько тонн и за какое плечо было оплачено —
 * в GameState остаётся только новый остаток на счету. Значит, класть выручку в
 * окно обязан тот, кто её начисляет, а закрывать сутки — эта фаза.
 *
 * Функция существует затем, чтобы стык был ОДНОЙ строкой и не разъехался:
 * прибавить рубли к money, забыв про dailyRevenue, — ошибка бесшумная, она
 * ломает не деньги, а показанную игроку прибыль, и заметить её можно только по
 * тому, что панель врёт.
 */
export function creditRevenue(company: Company, amount: number): Company {
  if (!Number.isFinite(amount) || amount <= 0) return company

  return {
    ...company,
    money: company.money + amount,
    dailyRevenue: company.dailyRevenue + amount,
  }
}

/**
 * Итог тика для одной компании: списать расходы, обновить окно и счёт долга.
 *
 * ПОРЯДОК ЗДЕСЬ ЗНАЧИМ. Сначала деньги, потом проверка долга: компания должна
 * банкротиться по свежему остатку, а не по вчерашнему. Выручка этого тика уже
 * начислена — фаза расходов стоит в конвейере после прибытия именно затем,
 * чтобы никто не разорился утром того дня, за который ему вечером заплатят.
 */
function settle(company: Company, costs: number): Company {
  const money = company.money - costs

  // Ноль — это не долг. Уйти в минус можно только строго ниже нуля, и выход в
  // ноль обнуляет счётчик: отсрочка даётся за то, что не выбрался, а не за то,
  // что однажды оступился.
  const inDebt = money < 0
  const daysInDebt = inDebt ? company.daysInDebt + 1 / TICKS_PER_DAY : 0

  if (daysInDebt + DAY_EPSILON >= BANKRUPTCY_GRACE_DAYS) {
    // Партия окончена. Потоков больше нет, и показывать вчерашние — врать:
    // расходы этой компании со следующего тика не начисляются вовсе.
    return {
      ...company,
      money,
      daysInDebt,
      bankrupt: true,
      dailyRevenue: 0,
      dailyCosts: 0,
    }
  }

  const dailyRevenue = dayWindow(company.dailyRevenue)
  const dailyCosts = dayWindow(company.dailyCosts + costs)

  // Компании без парка, без долгов и без потоков этот тик не касается вовсе —
  // возвращаем ту же запись по ссылке. Как и в остальных фазах, по совпадению
  // ссылок интерфейс отличает изменившееся от нетронутого.
  if (
    money === company.money &&
    daysInDebt === company.daysInDebt &&
    dailyRevenue === company.dailyRevenue &&
    dailyCosts === company.dailyCosts
  ) {
    return company
  }

  return { ...company, money, daysInDebt, dailyRevenue, dailyCosts }
}

/**
 * Обанкротившаяся компания: ничего не начисляется, потоки обнулены.
 *
 * Возвращает ТОТ ЖЕ объект, если обнулять уже нечего. Это не микрооптимизация:
 * по совпадению ссылок интерфейс отличает изменившиеся записи от нетронутых.
 */
function freeze(company: Company): Company {
  if (company.dailyRevenue === 0 && company.dailyCosts === 0) return company
  return { ...company, dailyRevenue: 0, dailyCosts: 0 }
}

/**
 * Фаза расходов целиком. Возвращает НОВОЕ состояние.
 *
 * Порядок обхода здесь не значим, в отличие от фазы прибытия: машины не тянут
 * деньги из общего склада, каждая приносит своему владельцу свою сумму, а
 * сложение коммутативно. Поэтому всё считается от одного снимка состояния.
 *
 * Компании обходятся ВСЕ, а не только те, у кого есть машины: у компании без
 * парка остаётся штат, а он получает зарплату; и даже пустая компания может
 * сидеть в минусе — например, продав последнюю машину уже в долгах, — и
 * отсрочка ей отсчитывается на общих основаниях.
 */
export function runOperatingCosts(state: GameState): GameState {
  // Расходы собираются по машинам и по людям, а платит компания: один вычет из
  // счёта вместо десяти. Иначе порядок обхода парка начал бы влиять на то, в
  // какой именно момент внутри тика компания уходит в минус.
  const costs: Partial<Record<CompanyId, number>> = {}

  for (const vehicle of Object.values(state.vehicles)) {
    const owner = state.companies[vehicle.ownerId]
    // Машины без хозяина и машины банкрота не стоят ничего: у первых некому
    // выставить счёт, у вторых партия окончена.
    if (owner === undefined || owner.bankrupt) continue

    const driver = driverOf(state, vehicle)
    const cost = distanceCost(vehicle, tickKm(vehicle, state), driver)
    costs[owner.id] = (costs[owner.id] ?? 0) + cost
  }

  const companies: Record<CompanyId, Company> = { ...state.companies }
  let changed = false

  for (const id of Object.keys(companies) as CompanyId[]) {
    const before = companies[id]

    // Зарплата прибавляется здесь, а не в цикле по парку: она платится за
    // штат целиком, включая тех, кому машины не досталось.
    const bill = (costs[id] ?? 0) + payrollPerTick(before)
    const after = before.bankrupt ? freeze(before) : settle(before, bill)

    if (after !== before) {
      companies[id] = after
      changed = true
    }
  }

  // Все банкроты и всё уже обнулено — возвращаем то же состояние по ссылке.
  if (!changed) return state

  return { ...state, companies }
}
