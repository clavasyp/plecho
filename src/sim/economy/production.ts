import { RECIPE_BY_INDUSTRY } from '../../data/recipes'
import { TICKS_PER_DAY } from '../types'
import type {
  CargoType,
  GameState,
  Industry,
  IndustryId,
  Recipe,
  Tons,
} from '../types'

/**
 * Фаза производства: предприятия потребляют сырьё и кладут выпуск на склад.
 *
 * Здесь живёт главное утверждение всей игры: **мир зависит от игрока**. Завод не
 * выдаёт заказ и не ждёт вечно — он работает ровно настолько, насколько ему
 * подвозят сырьё и вывозят продукцию. Всё остальное в срезе (города, деньги,
 * погрузка) обслуживает этот факт.
 *
 * Выпуск за тик ограничен ТРЕМЯ независимыми потолками, и каждый из них — это
 * отдельная ошибка игрока, которую он должен уметь различить по интерфейсу:
 *
 *   1. СЫРЬЁ. Не подвёз — темп падает пропорционально дефициту. Именно
 *      пропорционально, а не в ноль: половина сырья должна давать половину
 *      выпуска, иначе цепочка ведёт себя как рубильник, и игрок не видит, что
 *      подходит к краю, — он видит только «работает» и «встало».
 *   2. МЕСТО НА СКЛАДЕ. Не вывез — завод задыхается собственной продукцией.
 *      Это ядро среза: без потолка склада предприятие производит в пустоту,
 *      вывоз перестаёт быть нужен, и карта превращается в доску объявлений.
 *   3. НАКОПЛЕННЫЙ ПРОСТОЙ. Забыл надолго — предприятие теряет мощность и не
 *      возвращается к паспортной сразу. Это цена бездействия: без неё
 *      брошенный завод бесконечно терпеливо ждёт игрока, и мир перестаёт быть
 *      живым.
 *
 * Фаза чистая и не зависит от порядка обхода: каждое предприятие считается от
 * снимка состояния и ни на кого не смотрит. Взаимное влияние (общий склад
 * города, очередь на терминале) появится в срезах 5–6 и должно будет прийти
 * явным общим состоянием, а не через порядок ключей объекта.
 */

/**
 * Вместимость склада — трое суток СОБСТВЕННОГО оборота предприятия.
 *
 * ПОЧЕМУ В СУТКАХ, А НЕ В ТОННАХ. Плоское число тонн одинаково давило бы
 * нефтебазу с её 80 т/сут и ЦБК с 30 т/сут: у первой запас кончался бы втрое
 * быстрее. Терпимость цепочки к опозданию не должна зависеть от размера завода —
 * она должна зависеть только от того, как часто ходят машины. Поэтому
 * вместимость измеряется в сутках оборота, и все шесть предприятий получают
 * одинаковый по СМЫСЛУ запас: «три дня без машин».
 *
 * ПОЧЕМУ ИМЕННО ТРИ. Сутки — это одна сорванная ходка: поломка, распутица, ночь
 * в дороге. Цепочка, которая рвётся от одной случайности, воспринимается не как
 * сложная, а как несправедливая. Неделя — противоположная беда: за сессию игрок
 * ни разу не увидит задохнувшийся завод, и главный урок среза просто не
 * произойдёт. Трое суток — это ещё прощение одной ошибки, но уже не прощение
 * привычки.
 *
 * ЧТО ЭТО ЗНАЧИТ НА СТАРТЕ. Мукомольный делает 40 т муки в сутки, склад держит
 * 120 т — двадцать ходок стартового ЗИЛа на 6 тонн. Одна машина такой завод не
 * вывезет никогда, и это правильный первый вывод игры: одна машина — это ещё не
 * транспортная компания.
 */
export const STOCK_DAYS = 3

/**
 * Ниже пяти процентов паспортной мощности предприятие считается стоящим.
 *
 * Порог не нулевой намеренно. Выпуск считается на дробях, и остаток места на
 * складе в тысячную тонны формально даёт работу, а фактически завод стоит и
 * обязан за это получать счётчик простоя. Ноль в качестве порога означал бы, что
 * забитый под завязку склад ИНОГДА, из-за ошибки округления, засчитывается как
 * рабочий тик — и деградация не наступала бы никогда.
 *
 * Пять процентов — заведомо меньше любой осмысленной поставки: даже один ЗИЛ на
 * 6 т, разгруженный в ЦБК, кормит его на двенадцать полноценных тиков.
 */
export const IDLE_UTILIZATION = 0.05

/**
 * Десять суток простоя — граница, за которой начинается потеря мощности.
 *
 * ЗАЧЕМ ВООБЩЕ. Без деградации невывезенный завод — это просто пауза: игрок
 * возвращается через игровой год и застаёт всё ровно там, где бросил. Мир,
 * который ничего не теряет от бездействия, не может и зависеть от действий, а
 * без этой зависимости срез бессмыслен.
 *
 * ПОЧЕМУ ДЕСЯТЬ. Меньше недели — наказание за случайность: одна поломка плюс
 * весеннее закрытие дороги съедают пять суток без всякой вины игрока. Больше
 * двух недель — игрок успевает забыть, что этот завод у него вообще есть, и
 * связь «я не ездил → мощность упала» перестаёт читаться. Десять суток
 * попадают между: это уже не невезение, но ещё в пределах памяти игрока.
 */
export const DEGRADE_AFTER_DAYS = 10

/** То же в тиках — с чем и сравнивается счётчик простоя. */
export const DEGRADE_AFTER_TICKS = DEGRADE_AFTER_DAYS * TICKS_PER_DAY

/**
 * Каждые сутки простоя сверх порога снимают 5% паспортной мощности.
 *
 * Темп намеренно медленный: деградация должна сначала читаться цифрой в
 * интерфейсе («мощность 85%») и только потом — последствиями. Игрок обязан
 * успеть увидеть проблему и среагировать; механика, которая наказывает раньше,
 * чем объясняет, воспринимается как поломка игры.
 */
export const DEGRADE_PER_DAY = 0.05

/**
 * Ниже 40% паспортной мощность не опускается.
 *
 * Пол нужен не для мягкости, а для читаемости. Предприятие с мощностью около
 * нуля формально живо, но неотличимо от мёртвого: выпуск не виден, восстановить
 * его нечем, а игрок видит на карте точку, которая ничего не делает и никак это
 * не объясняет. Закрытие предприятий — отдельная механика поздних срезов, и она
 * обязана быть ЯВНЫМ событием с уведомлением, а не побочным эффектом того, что
 * множитель тихо утёк в ноль.
 */
export const MIN_CAPACITY_FACTOR = 0.4

/**
 * Один тик работы отыгрывает четыре тика простоя.
 *
 * Восстанавливаться быстрее, чем деградировать, — правильно: снова запустить
 * линию проще, чем дать ей сгнить. Но не мгновенно: если множитель сбрасывается
 * первой же ходкой, наказание снимается одним визитом и перестаёт быть
 * наказанием — а вся деградация превращается в украшение интерфейса.
 *
 * В числах: месяц забвения (мощность на полу, 40%) стоит игроку пяти суток
 * ровной работы, две недели — примерно суток. Это ощутимо, но не безнадёжно.
 */
export const RECOVERY_TICKS_PER_TICK = 4

/**
 * Порог гашения вычислительного мусора, тонн.
 *
 * Тонна — крупная единица, и остаток в миллиардную долю тонны не значит ничего,
 * кроме накопленной ошибки деления. Но именно он отличает «склад пуст» от
 * «склад почти пуст» в сравнениях и оставляет в сейве числа вида 4.4e-16.
 */
const EPSILON = 1e-9

/**
 * Суточный оборот предприятия по конкретному грузу, тонн.
 *
 * Для выхода это паспортная мощность, для входа — сколько его съедает та же
 * мощность за сутки. Груз, которого нет в рецепте, даёт ноль: такому
 * предприятию его везти незачем.
 */
function dailyThroughput(recipe: Recipe, cargo: CargoType): Tons {
  if (cargo === recipe.output) {
    return recipe.dailyRate
  }
  const input = recipe.inputs.find((it) => it.type === cargo)
  return input ? recipe.dailyRate * input.perUnit : 0
}

/** Потолок склада по грузу. Одна формула на весь проект — см. STOCK_DAYS. */
function capacityOf(recipe: Recipe, cargo: CargoType): Tons {
  return dailyThroughput(recipe, cargo) * STOCK_DAYS
}

/**
 * Сколько тонн этого груза предприятие готово держать у себя.
 *
 * Экспортируется наружу нарочно: тот же потолок нужен погрузке, чтобы не
 * ссыпать в завод сырьё, которое туда физически не влезет, и интерфейсу, чтобы
 * рисовать шкалу заполнения. Правило переполнения в игре должно быть ровно
 * одно, и живёт оно здесь.
 *
 * Ноль означает «этот груз здесь не нужен» — ни как сырьё, ни как продукция.
 */
export function stockCapacity(industry: Industry, cargo: CargoType): Tons {
  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  // Тип предприятия без рецепта — дыра в данных, а не рабочее состояние. Но
  // ронять из-за неё весь тик незачем: такое предприятие просто ничего не
  // принимает и ничего не делает.
  if (!recipe) {
    return 0
  }
  return capacityOf(recipe, cargo)
}

/**
 * Доля паспортной мощности, доступная предприятию после простоя, 0..1.
 *
 * Функция от одного лишь счётчика простоя — и это осознанное ограничение.
 * Отдельного поля под накопленный износ в Industry нет, и заводить его не
 * нужно: две величины, которые всегда движутся вместе, рано или поздно
 * разъедутся в сейве, а состояние — контракт, который дороже удобства.
 */
export function capacityFactor(idleTicks: number): number {
  // Условие вывернуто намеренно: битый счётчик (NaN после кривого сейва) не
  // проходит проверку и даёт полную мощность, а не NaN. NaN просачивается
  // сквозь сравнения и тихо заражает и склад, и утилизацию — как и в
  // world/speed.ts, предохранитель стоит на входе в формулу.
  if (!(idleTicks > DEGRADE_AFTER_TICKS)) {
    return 1
  }
  const idleDays = (idleTicks - DEGRADE_AFTER_TICKS) / TICKS_PER_DAY
  return Math.max(MIN_CAPACITY_FACTOR, 1 - idleDays * DEGRADE_PER_DAY)
}

/**
 * Счётчик простоя на следующий тик.
 *
 * Считать его нужно не как «сколько тиков подряд стоим», а как ГЛУБИНУ ЯМЫ, в
 * которую предприятие себя загнало:
 *
 *   - Яма мельче порога деградации — первый же рабочий тик обнуляет счётчик.
 *     Это то поведение, которое игрок видит в игре постоянно: подвёз сырьё —
 *     завод работает, и никакого хвоста от вчерашнего простоя нет.
 *   - Яма глубже порога — из неё выбираются постепенно, по
 *     RECOVERY_TICKS_PER_TICK за рабочий тик. Иначе мощность возвращалась бы
 *     ровно на один тик позже остановки, и деградация ничего бы не стоила.
 *
 * Частичная загрузка считается работой без скидок: завод, работающий на 20%,
 * всё равно топят, освещают и обслуживают. Так счётчик остаётся целым числом —
 * его читает интерфейс и пишет сейв.
 */
function nextIdleTicks(idleTicks: number, utilization: number): number {
  if (utilization <= IDLE_UTILIZATION) {
    return idleTicks + 1
  }
  if (idleTicks <= DEGRADE_AFTER_TICKS) {
    return 0
  }
  return Math.max(0, idleTicks - RECOVERY_TICKS_PER_TICK)
}

/** Гасит остатки деления, чтобы «пусто» было ровно нулём. */
function snap(tons: Tons): Tons {
  return Math.abs(tons) < EPSILON ? 0 : tons
}

/**
 * Один шаг одного предприятия.
 *
 * Порядок внутри важен: выпуск считается по счётчику простоя НА НАЧАЛО тика, и
 * только потом счётчик обновляется. Иначе завод, остановленный переполнением,
 * успевал бы деградировать в том же тике, в котором его ещё оценивали как
 * рабочий, и деградация опережала бы причину на один шаг.
 */
function stepIndustry(industry: Industry): Industry {
  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  if (!recipe) {
    return industry
  }

  // Паспортная мощность за тик. Пересчёт из суток идёт через TICKS_PER_DAY, а
  // не через зашитое число: длительность тика — параметр времени, и если она
  // когда-нибудь изменится, экономика обязана поехать за ней сама.
  const nameplate = recipe.dailyRate / TICKS_PER_DAY

  // Потолок 1: мощность, доступная после простоя.
  let output = nameplate * capacityFactor(industry.idleTicks)

  // Потолок 2: место на складе продукции. Не хватает на полный тик — работаем
  // ровно на остаток места, а не встаём целиком: завод перед остановкой должен
  // тормозить, а не выключаться, иначе последняя тонна продукции никогда не
  // производится.
  const stored = industry.stock[recipe.output] ?? 0
  const room = Math.max(0, capacityOf(recipe, recipe.output) - stored)
  output = Math.min(output, room)

  // Потолок 3: сырьё. Каждый вход режет темп пропорционально своему дефициту,
  // а связывает самый дефицитный из них: половина зерна даёт ровно половину
  // муки. У источников список пуст, и цикл не делает ничего — связь с миром за
  // краем карты сырья не требует.
  for (const input of recipe.inputs) {
    const available = industry.stock[input.type] ?? 0
    output = Math.min(output, available / input.perUnit)
  }

  if (!(output > EPSILON)) {
    output = 0
  }

  // Доля именно от ПАСПОРТНОЙ мощности, а не от доступной после деградации:
  // игрок должен видеть, что завод работает на 60% из-за собственного простоя,
  // а не рапорт «100%» от изувеченного производства.
  const utilization = nameplate > 0 ? Math.min(1, output / nameplate) : 0

  const stock = { ...industry.stock }
  if (output > 0) {
    for (const input of recipe.inputs) {
      const available = stock[input.type] ?? 0
      // Расход считается от факта выпуска, а не от плана: сколько сделали,
      // столько сырья и ушло, ни тонной больше. Отрицательный остаток здесь
      // невозможен по построению, и Math.max стоит только против ошибки
      // деления на последней тонне.
      stock[input.type] = snap(Math.max(0, available - output * input.perUnit))
    }
    stock[recipe.output] = snap(stored + output)
  }

  return {
    ...industry,
    stock,
    utilization,
    idleTicks: nextIdleTicks(industry.idleTicks, utilization),
  }
}

/**
 * Фаза производства целиком. Входное состояние не изменяется.
 *
 * Мир без предприятий возвращается той же ссылкой: до появления промышленности
 * (и в сейвах среза 1) фазе просто нечего делать, и подменять запись мира ради
 * пустого цикла незачем.
 */
export function runProduction(state: GameState): GameState {
  const industries: Record<IndustryId, Industry> = {}
  let changed = false

  for (const id of Object.keys(state.world.industries) as IndustryId[]) {
    const before = state.world.industries[id]
    const after = stepIndustry(before)
    if (after !== before) {
      changed = true
    }
    industries[id] = after
  }

  return changed ? { ...state, world: { ...state.world, industries } } : state
}
