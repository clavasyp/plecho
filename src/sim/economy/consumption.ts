/**
 * Потребление городов и демография.
 *
 * Здесь замыкается главная петля игры. Город ест со своего склада; ест он
 * пропорционально населению; население растёт от устойчивого снабжения. То
 * есть НАЛАЖЕННАЯ СЕТЬ САМА СОЗДАЁТ СЕБЕ НАГРУЗКУ: наладил поставки — город
 * вырос — спрос вырос — прежних машин уже не хватает. Игрок не получает
 * заданий, он получает последствия своих же успехов, и это единственная
 * причина, по которой мир вообще должен меняться.
 *
 * Отсюда три требования, из которых выведены все числа ниже.
 *
 * 1. РОСТ НЕЛЬЗЯ КУПИТЬ ОДНОЙ ХОДКОЙ. Иначе оптимальная стратегия — завалить
 *    город разово и уехать. Поэтому рост включает не факт поставки, а счётчик
 *    непрерывного снабжения `suppliedDays`, и порог у него — недели.
 * 2. ПОТЕРЯ МЕДЛЕННЕЕ ПРИОБРЕТЕНИЯ. Сеть строится часами реального времени, и
 *    одна пропущенная поставка не имеет права стереть эту работу. Сжатие
 *    втрое медленнее роста и вдобавок масштабируется дефицитом.
 * 3. МИР ОСТАЁТСЯ УЗНАВАЕМЫМ. Город не превращается ни в мегаполис вдесятеро,
 *    ни в пустое место: и то и другое ломает карту, к которой игрок привык, и
 *    обесценивает знание реальной географии — а оно здесь часть удовольствия.
 *
 * ПРО МАСШТАБ ЦИФР. На стартовых данных спрос заведомо больше выпуска: Тула с
 * её 457 тысячами жителей просит 59 тонн в сутки, а Москва с 13.3 миллиона —
 * 1726, то есть двадцать мукомольных комбинатов только на муку. Это не
 * ошибка баланса, а прямое следствие честного населения: столица в принципе не
 * снабжаема одной компанией, и правильная реакция игры на это — медленное
 * сжатие с полом, а не осыпание карты. Числа сжатия подобраны в том числе под
 * этот случай.
 *
 * Функция чистая: вход не меняется ни на одном уровне вложенности.
 */

import { CITIES_BY_ID } from '../../data/cities'
import { CONSUMER_CARGO, CONSUMPTION_PER_1K } from '../../data/recipes'
import { TICKS_PER_DAY } from '../types'
import type { CargoType, City, CityId, GameState, Tons } from '../types'

/**
 * Расчётная длина месяца для темпов роста, суток.
 *
 * Тридцать, а не настоящая длина календарного месяца. Темп — конструкторская
 * константа, а не астрономический факт: привяжи его к календарю, и город в
 * феврале будет расти на десятую часть медленнее, чем в январе, без единой
 * игровой причины. Такое расхождение невозможно ни объяснить игроку, ни
 * поймать в тесте.
 */
export const DAYS_PER_GROWTH_MONTH = 30

/** Тиков в расчётном месяце: 96 × 30 = 2880. */
export const TICKS_PER_GROWTH_MONTH = TICKS_PER_DAY * DAYS_PER_GROWTH_MONTH

/**
 * Сколько суток подряд нужно снабжать город, прежде чем он начнёт расти.
 *
 * Три недели. Снизу порог держит правило «рост нельзя купить одной ходкой»:
 * 2016 тиков подряд без единого срыва невозможно закрыть удачным рейсом, это
 * закрывается только РАБОТАЮЩЕЙ ЛИНИЕЙ с запасом по частоте. Сверху — терпение
 * игрока: игровые сутки идут двадцать реальных секунд, значит три недели — это
 * семь минут наблюдения на скорости ×1 и полторы на ×5. Месяц и больше уже
 * читались бы как «ничего не происходит».
 *
 * Порог сравнивается строго (`>`): «превысил», а не «достиг». Счётчик суток
 * накапливается по 1/96 за тик и приходит к 21.0 с ошибкой в последнем знаке,
 * поэтому рост может начаться на тик раньше или позже расчётного. Это
 * пятнадцать игровых минут из трёх недель — величина ниже любого игрового
 * смысла, и подпирать её эпсилонами значит усложнять код ради нуля.
 */
export const GROWTH_THRESHOLD_DAYS = 21

/**
 * Прирост населения за расчётный месяц при устойчивом снабжении, доля.
 *
 * Один процент в месяц — это 12.7% в год, темп нефтяного города, а не
 * среднерусского. Взят он не из демографии, а из заметности: игровой месяц
 * проходит за десять реальных минут, и рост, невидимый за час игры, обратной
 * связью не является — его для игрока просто нет.
 *
 * Проверка масштаба на Туле: за игровой год (два часа на ×1) устойчиво
 * снабжаемый город прибавляет 58 тысяч жителей, а с ними 7.5 тонны суточного
 * спроса — примерно один дополнительный рейс шеститонного ЗИЛа в сутки. Ровно
 * то, что игрок замечает по метрике порожнего пробега, но что не обрушивает
 * линию за один вечер. Удвоение города требует 70 месяцев непрерывного
 * снабжения — почти шесть игровых лет, и это осмысленная долгая цель.
 */
export const GROWTH_PER_MONTH = 0.01

/**
 * Убыль населения за расчётный месяц при ПОЛНОМ отсутствии снабжения, доля.
 *
 * Втрое медленнее роста, и это соотношение важнее самого числа. Построенное
 * стоит игроку часов реального времени, а рвётся оно мгновенно — поломка,
 * весенние ограничения, перехваченная конкурентом линия. Если бы город терял
 * жителей с той же скоростью, с какой набирает, любой сбой обнулял бы вечер
 * игры, и единственной разумной стратегией стала бы игра на паузе.
 *
 * 0.3% в месяц — это 3.5% в год: до нижней границы брошенный город идёт
 * четырнадцать игровых лет. Достаточно медленно, чтобы всегда успеть вернуться,
 * и достаточно заметно, чтобы за пару лет увидеть разницу в цифре.
 */
export const SHRINK_PER_MONTH = 0.003

/**
 * Потолок населения — доля от стартового.
 *
 * Удвоение. За тридцать лет кампании ни один город ЦФО в реальности не
 * удваивался, так что предел заведомо щедрый; смысл его не в исторической
 * точности, а в том, что вдвое больший город — это вдвое больший спрос, то
 * есть предел, который сеть игрока ещё способна догнать. Дальше рост перестал
 * бы быть наградой и стал бы наказанием.
 */
export const MAX_POPULATION_FACTOR = 2

/**
 * Пол населения — доля от стартового.
 *
 * Минус сорок процентов, дальше город не сжимается. Причин две. Игровая:
 * исчезнувший город убил бы узел графа, вокруг которого построена вся сеть
 * игрока, и лишил бы его возможности вернуться — а возвращаться должно быть
 * всегда можно. Смысловая: Ярославль, потерявший половину жителей, — всё ещё
 * Ярославль, а Ярославль с населением посёлка — это уже другая карта.
 */
export const MIN_POPULATION_FACTOR = 0.6

/**
 * Допуск при сравнении тонн, тонны.
 *
 * Один грамм. При полном снабжении списанное равно нужному бит в бит — оба
 * числа приходят из одного `Math.min`, — так что допуск нужен не для этого
 * случая, а для остатков после доставок и деления: склад, на котором осталось
 * 1e-13 тонны, обязан считаться пустым, иначе он вечно висит в сохранении и
 * бесконечно мешает пометить город снабжённым.
 */
const SUPPLY_EPS_TONS = 1e-6

/**
 * Множитель населения за тик при росте.
 *
 * Считается один раз: корень степени 2880 из 1.01. Экспоненциальная форма, а
 * не «прибавить 1/2880 месячного прироста», потому что рост процентный по
 * определению — выросший город растёт от нового населения, а не от стартового.
 */
const GROWTH_TICK_FACTOR =
  (1 + GROWTH_PER_MONTH) ** (1 / TICKS_PER_GROWTH_MONTH)

/** Доля населения, теряемая за тик при полном отсутствии снабжения. */
const SHRINK_TICK_STEP =
  1 - (1 - SHRINK_PER_MONTH) ** (1 / TICKS_PER_GROWTH_MONTH)

/**
 * Суточная потребность города в грузе, тонн.
 *
 * Нормы заданы на тысячу жителей — отсюда деление. Неизвестный груз даёт ноль,
 * а не NaN: списки CONSUMER_CARGO и CONSUMPTION_PER_1K лежат в данных рядом, но
 * порознь, и рассинхрон между ними обязан оставить город без спроса, а не
 * превратить его население в NaN — NaN отсюда расползётся по всей экономике и
 * переживёт сохранение.
 */
export function demandPerDay(population: number, cargo: CargoType): Tons {
  const rate = CONSUMPTION_PER_1K[cargo] ?? 0
  const demand = (rate * population) / 1000
  return demand > 0 ? demand : 0
}

/** Потребность за один тик — суточная, делённая на число тиков в сутках. */
export function demandPerTick(population: number, cargo: CargoType): Tons {
  return demandPerDay(population, cargo) / TICKS_PER_DAY
}

/**
 * Границы населения города.
 *
 * Отсчитываются от ПАСПОРТНОГО населения из справочника мира, а не от текущего:
 * коридор должен стоять на месте, иначе он ездит вместе с городом и не
 * ограничивает ничего. Хранить стартовое значение в City нельзя — тип это
 * контракт и в нём такого поля нет, — а справочник неизменяем и доступен
 * симуляции: из него же собирается начальное состояние партии.
 *
 * Города, которого в справочнике нет (сценарий, мод, сейв другой версии),
 * ограничены только темпом: коридор для него неизвестен, и выдумывать его,
 * оттолкнувшись от текущего населения, значит молча запретить рост.
 */
export function populationLimits(city: City): { min: number; max: number } {
  const known = CITIES_BY_ID[city.id]
  const base = known ? known.population : city.population
  return {
    min: base * MIN_POPULATION_FACTOR,
    max: base * MAX_POPULATION_FACTOR,
  }
}

/**
 * Один город за один тик: поел, пересчитал счётчик снабжения, подвинул
 * население. Возвращает НОВЫЙ город либо тот же объект, если не изменилось
 * ничего.
 */
function consumeCity(city: City): City {
  const population = city.population

  /** Сколько всего тонн нужно за тик — по всем потребительским грузам. */
  let demand = 0
  /** Сколько из этого удалось снять со склада. */
  let taken = 0

  let stock = city.stock
  let stockChanged = false

  for (const cargo of CONSUMER_CARGO) {
    const need = demandPerTick(population, cargo)
    if (need <= 0) continue
    demand += need

    const available = stock[cargo] ?? 0
    if (available <= 0) continue

    // Съедаем не больше, чем есть: нехватка — это недобор, а не долг. Склад в
    // минусе означал бы, что город занял тонны у будущего, и первая же машина
    // ушла бы на погашение этого долга вместо реального спроса.
    const eaten = Math.min(available, need)
    taken += eaten

    if (!stockChanged) {
      // Копия делается лениво — только когда действительно есть что списывать.
      // Голодающий город не порождает мусора и возвращается по той же ссылке.
      stock = { ...city.stock }
      stockChanged = true
    }

    const left = available - eaten
    if (left <= SUPPLY_EPS_TONS) {
      // Опустевшая позиция уходит со склада целиком. Отсутствие ключа и ноль
      // для всех потребителей значат одно и то же (`?? 0`), зато сохранение не
      // зарастает нулями и остатками в тринадцатом знаке.
      delete stock[cargo]
    } else {
      stock[cargo] = left
    }
  }

  // Спроса нет вовсе — население ноль или нормы пусты. Это не голод и не
  // снабжение: трогать счётчик и население здесь не за что.
  if (demand <= 0) return city

  /** Доля закрытой потребности, 0..1. */
  const satisfaction = taken / demand
  const supplied = demand - taken <= SUPPLY_EPS_TONS

  /*
   * Счётчик снабжения ведётся ДРОБНЫМ, по 1/96 суток за тик.
   *
   * Целый счётчик потребовал бы второго поля — «сколько тиков идёт текущий
   * день», — то есть двух фактов об одном и том же, которые разъедутся при
   * первой же загрузке сохранения. Дробная форма хранит ровно то же самое
   * одним числом и заодно честнее: «снабжается вторые сутки» — это состояние,
   * которое игроку полезно видеть, а не ноль до полуночи.
   *
   * Обнуление жёсткое и без прощения: одна недостача рвёт серию. В этом весь
   * смысл счётчика — он мерит УСТОЙЧИВОСТЬ, а не сумму привезённого.
   */
  const suppliedDays = supplied ? city.suppliedDays + 1 / TICKS_PER_DAY : 0

  let nextPopulation = population
  const limits = populationLimits(city)

  if (suppliedDays > GROWTH_THRESHOLD_DAYS) {
    // Порог пройден — город растёт. Проверка на потолок стоит до умножения:
    // город, уже стоящий на границе, не должен каждый тик пересобирать объект
    // ради возврата к тому же числу.
    if (population < limits.max) {
      nextPopulation = Math.min(population * GROWTH_TICK_FACTOR, limits.max)
    }
  } else if (!supplied) {
    /*
     * Сжатие пропорционально ДЕФИЦИТУ, а не факту недостачи.
     *
     * Иначе город, которому не хватило тонны пиломатериалов, терял бы жителей
     * ровно так же быстро, как полностью брошенный, и игрок не видел бы
     * разницы между «почти справляюсь» и «бросил» — то есть лишился бы
     * единственного сигнала о том, куда добавлять машины.
     *
     * Дефицит масштабирует ШАГ, а не показатель степени: на шаге порядка 1e-6
     * разница между этими формулами уходит в тринадцатый знак, а линейная
     * форма читается однозначно и не требует возведения в степень на каждый
     * город каждый тик.
     */
    const deficit = 1 - satisfaction
    if (population > limits.min) {
      nextPopulation = Math.max(
        population * (1 - SHRINK_TICK_STEP * deficit),
        limits.min,
      )
    }
  }

  /*
   * Границы ограничивают ИЗМЕНЕНИЕ, а не значение.
   *
   * Обычный clamp вместо двух проверок выше телепортировал бы к границе город,
   * оказавшийся вне коридора — после правки данных, загрузки старого сейва или
   * сценария с намеренно вымершим городом. Население обязано меняться только
   * по игровой причине, поэтому коридор умеет лишь останавливать движение, но
   * не толкать.
   */

  if (
    !stockChanged &&
    nextPopulation === population &&
    suppliedDays === city.suppliedDays
  ) {
    return city
  }

  return { ...city, stock, population: nextPopulation, suppliedDays }
}

/**
 * Фаза потребления: города съедают привезённое, растут или сжимаются.
 *
 * Все города считаются от ОДНОГО снимка состояния и друг друга не видят —
 * склад у каждого свой, перетока между городами нет. Значит результат не
 * зависит от порядка обхода ключей, и детерминизм не держится на порядке
 * свойств объекта.
 *
 * Население хранится ДРОБНЫМ и здесь не округляется. Округление на каждом тике
 * убило бы рост совсем: прирост Калуги за пятнадцать минут — половина
 * человека, и после округления она превращалась бы в ноль вечно. Округляет
 * интерфейс, при выводе, один раз.
 */
export function runConsumption(state: GameState): GameState {
  const cities: Record<CityId, City> = {}
  let changed = false

  for (const id of Object.keys(state.world.cities) as CityId[]) {
    const before = state.world.cities[id]
    const after = consumeCity(before)
    if (after !== before) {
      changed = true
    }
    cities[id] = after
  }

  // Ничего не изменилось (пустой мир, или все города давно на полу и с пустыми
  // складами) — отдаём то же состояние по ссылке, как и остальные фазы тика.
  return changed ? { ...state, world: { ...state.world, cities } } : state
}
