/**
 * Игровое время: календарная дата, выведенная из номера тика.
 *
 * В состоянии хранится только `tick` — целое число шагов с начала партии. Дата
 * не хранится нигде: два источника правды о времени неизбежно разъезжаются,
 * стоит один раз загрузить сохранение или перемотать состояние назад.
 *
 * ПОЧЕМУ КАЛЕНДАРЬ СВОЙ, А НЕ ЧЕРЕЗ Date. Date — это не арифметика, это
 * арифметика плюс часовой пояс машины. `new Date(1994, 0, 1)` даёт полночь по
 * местному времени, `getMonth()` читает тоже по местному, и одно и то же
 * сохранение, открытое в Москве и в Лиссабоне, покажет разные сутки. Вместе с
 * сутками разъедутся сезон, ночные события и всё, что от них считается, —
 * то есть детерминизм, ради которого sim и держат чистым. Date.UTC от этого
 * лечит, но лечит только там, где о нём вспомнили: одного `getHours()` вместо
 * `getUTCHours()` достаточно, чтобы зависимость от пояса вернулась молча.
 * Ручная целочисленная арифметика такого режима отказа не имеет в принципе и
 * даёт одинаковый результат в Node, в браузере и в тесте.
 *
 * Заодно снимается ловушка нумерации: в Date месяцы считаются с нуля, а в
 * GameDate — с единицы, как их пишет человек. Смешение двух нумераций в одном
 * коде — классическая ошибка ровно на месяц.
 *
 * Соглашения GameDate: month 1..12, day 1..31, hour 0..23, minute 0..59.
 * Партия начинается 1 января startYear в 00:00 — тик 0 это ровно эта минута.
 */

import { MINUTES_PER_TICK, TICKS_PER_DAY } from './types'
import type { GameDate, Season } from './types'

/** Минут в сутках. Выводится из шага тика, а не пишется как 1440 руками. */
const MINUTES_PER_DAY = TICKS_PER_DAY * MINUTES_PER_TICK

/** Длины месяцев невисокосного года, индекс 0 — январь. */
const DAYS_IN_MONTH = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31] as const

/**
 * Названия месяцев в родительном падеже — «12 марта», а не «12 март».
 * Отдельного именительного нет: дата в интерфейсе всегда с числом.
 */
const MONTHS_GENITIVE = [
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
] as const

/**
 * Високосный ли год по григорианскому правилу.
 *
 * Полное правило, а не упрощённое «кратен четырём»: партия идёт с 1994 года
 * далеко в будущее, и 2100-й — первый год, на котором упрощение врёт. Стоит
 * оно одну лишнюю проверку, а найти потом сдвиг календаря на сутки в поздней
 * партии стоило бы несравнимо дороже.
 */
export function isLeapYear(year: number): boolean {
  return year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0)
}

/** Дней в месяце (month 1..12) с поправкой на високосный февраль. */
export function daysInMonth(year: number, month: number): number {
  return month === 2 && isLeapYear(year) ? 29 : DAYS_IN_MONTH[month - 1]
}

/** Дней в году: 365 или 366. */
export function daysInYear(year: number): number {
  return isLeapYear(year) ? 366 : 365
}

/**
 * Сезон по номеру месяца.
 *
 * Метеорологические границы (зима — декабрь-февраль), а не астрономические по
 * солнцестояниям: сезон здесь нужен как переключатель погоды, скорости, ставок
 * и осевых ограничений, а они меняются по месяцам, а не по 21-м числам.
 *
 * Бросает на месяце вне 1..12: единственный способ сюда попасть — испорченная
 * дата, а молча вернуть «осень» значит спрятать баг.
 */
export function season(month: number): Season {
  if (!Number.isInteger(month) || month < 1 || month > 12) {
    throw new Error(`season: месяц вне диапазона 1..12: ${month}`)
  }
  if (month === 12 || month <= 2) return 'зима'
  if (month <= 5) return 'весна'
  if (month <= 8) return 'лето'
  return 'осень'
}

/**
 * Дата и время из номера тика.
 *
 * Годы и месяцы отматываются циклом, а не формулой по 400-летнему циклу.
 * Цикл здесь дешевле во всех смыслах: партия живёт десятки лет, то есть речь о
 * паре десятков итераций на вызов при одном вызове за тик, зато код читается
 * глазами и проверяется на переходах через февраль без бумаги. Формула с
 * эпохами выиграла бы наносекунды и проиграла бы всё остальное.
 */
export function dateFromTick(tick: number, startYear: number): GameDate {
  if (!Number.isFinite(tick) || tick < 0) {
    throw new Error(`dateFromTick: недопустимый тик ${tick}`)
  }

  // Дробный тик приходит из рендера, который интерполирует между шагами
  // симуляции. Для календаря он бессмыслен: минута внутри тика одна.
  const minutes = Math.floor(tick) * MINUTES_PER_TICK

  let dayIndex = Math.floor(minutes / MINUTES_PER_DAY)
  const minuteOfDay = minutes - dayIndex * MINUTES_PER_DAY

  let year = startYear
  while (dayIndex >= daysInYear(year)) {
    dayIndex -= daysInYear(year)
    year += 1
  }

  let month = 1
  while (dayIndex >= daysInMonth(year, month)) {
    dayIndex -= daysInMonth(year, month)
    month += 1
  }

  return {
    year,
    month,
    day: dayIndex + 1,
    hour: Math.floor(minuteOfDay / 60),
    minute: minuteOfDay % 60,
    season: season(month),
  }
}

/**
 * Доля суток: 0 — полночь, 0.5 — полдень, 1 не достигается никогда.
 *
 * Считается прямо из тика, минуя разбор даты: освещению не нужны ни год, ни
 * месяц, а разворачивать ради угла солнца весь календарь — лишняя работа
 * каждый кадр.
 *
 * Дробный тик допустим и осмыслен: рендер интерполирует положение между
 * тиками, и свет обязан ехать вместе с ним, иначе рассвет пойдёт ступеньками
 * по пятнадцать минут.
 */
export function dayProgress(tick: number): number {
  const withinDay = tick % TICKS_PER_DAY
  // Отрицательный тик календарём запрещён, но остаток от деления в JS
  // сохраняет знак — приводим к [0, 1), чтобы функция не отдавала минус.
  return (withinDay < 0 ? withinDay + TICKS_PER_DAY : withinDay) / TICKS_PER_DAY
}

/** Дата для интерфейса: «12 марта 1994». */
export function formatDate(date: GameDate): string {
  return `${date.day} ${MONTHS_GENITIVE[date.month - 1]} ${date.year}`
}

/**
 * Время для интерфейса: «08:15».
 *
 * Двадцать четыре часа и ведущий ноль — не только потому, что так пишут в
 * России. Строка получается постоянной ширины, и панель времени перестаёт
 * дёргаться на каждом тике, когда «9:45» сменяется на «10:00».
 */
export function formatTime(date: GameDate): string {
  const pad = (value: number) => String(value).padStart(2, '0')
  return `${pad(date.hour)}:${pad(date.minute)}`
}
