/**
 * Длина ленты рассуждений одной компании.
 *
 * Двадцать четыре записи — это около трёх недель ежедневных решений (см.
 * isDecisionTick: решение одно в игровые сутки). Столько и нужно: игрок должен
 * видеть не последнюю реплику, а ПОВОРОТ — как осторожный, разорившись на
 * длинном плече, ушёл на короткие. Одной-двух записей для этого мало, а сотня
 * превращает панель в бесконечную ленту и раздувает сохранение на ровном месте:
 * лента входит в JSON состояния целиком.
 *
 * Вытесняется старое, а не новое: свежая мысль объясняет то, что происходит на
 * карте прямо сейчас, и терять её ради истории нельзя.
 */
export const THINKING_LIMIT = 24

/**
 * Добавить мысль в ленту компании. Возвращает НОВУЮ компанию.
 *
 * ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЛЕНТА РАСТЁТ, и это не удобство, а требование. Мысли
 * приходят из ДВУХ источников — от скриптового конкурента (фаза ниже) и от
 * модели (deliverPlan в app/store.ts) — и обрезать ленту каждый по-своему они не
 * должны: разъедься два правила, и одна из веток однажды перестала бы вытеснять
 * старое вовсе, а обнаружилось бы это по распухшему сохранению через месяц.
 *
 * Пустой текст не записывается: пустая строка в ленте — это не «конкурент
 * промолчал», а мусор, который игрок листает.
 */
export function rememberThought(company: Company, thought: Thought): Company {
  if (thought.text.trim() === '') return company

  const feed = [...(company.thinking ?? []), thought]
  return {
    ...company,
    thinking:
      feed.length > THINKING_LIMIT ? feed.slice(feed.length - THINKING_LIMIT) : feed,
  }
}

/**
 * Тик, в котором конкуренты думают. Один на игровые сутки.
 *
 * ПОЧЕМУ РАЗ В СУТКИ, А НЕ КАЖДЫЙ ТИК. Тик — это пятнадцать игровых минут.
 * Перевозчик не перестраивает сеть каждые пятнадцать минут, а на ускорении ×5
 * это было бы около двадцати решений в секунду реального времени: лента
 * рассуждений превратилась бы в шум, в котором не виден ни один мотив, а на пути
 * модели — в сотни сетевых запросов за игровой месяц.
 *
 * ПОЧЕМУ НЕ РЕЖЕ. Всё, на что конкурент смотрит, измеряется СУТКАМИ: суточные
 * потоки компании — это скользящее суточное окно (dayWindow в
 * economy/operating.ts), зарплата суточная, устойчивое снабжение города считается
 * в сутках, отсрочка до банкротства — тридцать суток. Решение, принимаемое чаще
 * своей метрики, принимается по шуму; принимаемое реже — опаздывает: конкурент,
 * думающий раз в игровой месяц, за прогон в шестьдесят суток успел бы ответить
 * игроку дважды и разориться между двумя мыслями, ни разу не попытавшись
 * выправиться.
 *
 * ПОЧЕМУ ИМЕННО ПОСЛЕДНИЙ ТИК СУТОК. Фаза решений идёт в КОНЦЕ тика, а фаза
 * команд — в НАЧАЛЕ следующего. Значит решение, принятое на последнем тике суток,
 * применяется первым тиком следующих — то есть ровно «в начале дня», как того и
 * требует порядок фаз. Считай мы от полуночи, команды применялись бы в 00:15,
 * и объяснить эту четверть часа было бы нечем.
 *
 * ВСЕ КОНКУРЕНТЫ ДУМАЮТ В ОДИН И ТОТ ЖЕ ТИК. Развести их по разным часам суток
 * заманчиво (на пути модели это размазало бы запросы), но тогда они смотрят на
 * РАЗНЫЕ состояния мира, и «кто кого опередил» начинает зависеть от того, чей
 * час раньше, — то есть от расстановки в файле данных. Раз решения принимаются по
 * одному снимку, никакого преимущества по очереди хода не возникает.
 */
function isDecisionTick(tick: number): boolean {
  if (!Number.isFinite(tick)) return false
  return tick % TICKS_PER_DAY === TICKS_PER_DAY - 1
}

/**
 * Конкуренты принимают решения.
 *
 * ПРЕДПОСЛЕДНЯЯ ФАЗА НЕ СЛУЧАЙНО: решение принимается по миру, который уже
 * досчитан — с итогами дня, свежими складами и обновлёнными ценами. Реши
 * конкурент раньше, он смотрел бы на наполовину обновлённое состояние, а игрок
 * читал бы в ленте объяснения к тому, чего ещё не произошло.
 *
 * СЕТЕВОГО ВЫЗОВА ЗДЕСЬ НЕТ И НЕ БУДЕТ. Эта фаза кладёт в очередь то, что
 * предложила ЭВРИСТИКА (sim/ai/scripted.ts) — чистая функция состояния. Ответ
 * модели попадает в ту же очередь, но снаружи и асинхронно (deliverPlan в
 * app/store.ts), поэтому тик остаётся детерминированным при любом состоянии сети.
 *
 * КОГО ФАЗА ВЕДЁТ:
 *
 *   'человек'  — никого и никогда. За игрока решает игрок; подставить ему
 *                команду отсюда значило бы играть за него.
 *   'скрипт'   — ведёт. Это состояние по умолчанию (см. createInitialState) и
 *                оно же запасной путь: без ключа и без сети мир полон.
 *   'модель'   — НЕ ведёт. Компанию взял на себя слой приложения, и он же
 *                отвечает за запасной вариант: не дозвонился — кладёт в очередь
 *                предложение того же скрипта (askGemini вернул null →
 *                вызывающий берёт scriptedCommands). Продублируй мы это здесь, у
 *                компании было бы два хозяина и два решения в сутки.
 *
 * БАНКРОТ НЕ ДУМАЕТ: партия для него окончена, ему не начисляют даже расходов
 * (freeze в economy/operating.ts). Компания с НЕПУСТОЙ очередью тоже
 * пропускается — значит её решение уже лежит и ещё не разобрано, а перебивать
 * чужое решение своим фаза права не имеет.
 */
function runAi(state: GameState): GameState {
  if (!isDecisionTick(state.tick)) return state

  const companies: Record<CompanyId, Company> = { ...state.companies }
  let changed = false

  for (const id of Object.keys(state.companies) as CompanyId[]) {
    const company = state.companies[id]
    if (company.controller !== 'скрипт') continue
    if (company.bankrupt) continue
    if ((company.pendingCommands ?? []).length > 0) continue

    // Эвристика зовётся от ОДНОГО снимка состояния — того, что сложился к концу
    // тика, — а не от рабочей копии. Иначе решение второго конкурента зависело
    // бы от решения первого, то есть от порядка ключей объекта, и «кто кого
    // опередил» держалось бы ни на чём. Команды всё равно применяются по очереди
    // в следующем тике, и там незаконное отбрасывается.
    const commands: Command[] = [...scriptedCommands(state, id)]
    const text = scriptedThought(state, id)

    const next = rememberThought(
      commands.length > 0 ? { ...company, pendingCommands: commands } : company,
      // fromModel: ложь — рассуждение подставлено скриптовым вариантом. Игрок
      // обязан отличать одно от другого: невидимая подмена модели скриптом
      // превратила бы всю ленту в недостоверную.
      { tick: state.tick, text, fromModel: false },
    )

    if (next === company) continue
    companies[id] = next
    changed = true
  }

  return changed ? { ...state, companies } : state
}

