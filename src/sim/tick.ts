/**
 * Главный тик симуляции: один шаг мира длиной в 15 игровых минут.
 *
 * Тик — чистая функция состояния. Ни времени по часам, ни случайности из
 * Math.random, ни сети: всё, что влияет на результат, лежит в GameState, вплоть
 * до состояния ГПСЧ. Отсюда следует всё, ради чего симуляция отделена от
 * рендера: сохранение воспроизводится тик в тик, баг чинится прогоном из
 * сейва, а ускорение времени — это просто больше вызовов tick за кадр, без
 * единой строчки особой логики.
 *
 * ПОРЯДОК ФАЗ ЗАФИКСИРОВАН ЗДЕСЬ И СЕЙЧАС, хотя часть фаз ещё пустая. Это не
 * преждевременное обобщение, а обратное ему: порядок — самое дорогое решение в
 * тике, и менять его потом больно. Он определяет, видит ли машина груз,
 * произведённый в этот же тик, и успевает ли компания заплатить за топливо до
 * проверки банкротства. Порядок взят из docs/АРХИТЕКТУРА.md §4, заглушки стоят
 * на своих местах и подписаны срезом, в котором оживут.
 *
 * Смысл выбранного порядка в двух словах: сначала мир делает то, что от
 * решений не зависит (время, производство), потом отрабатывает транспорт
 * (диспетчеризация, движение, прибытие), потом фиксируются последствия
 * (потребление, деньги), и только в конце принимаются новые решения (рынок,
 * ИИ, события). Так решение всегда принимается по состоянию, которое уже
 * сложилось, а не по наполовину обновлённому.
 *
 * Две фазы среза 3 встали не в конец списка, а внутрь него, и обе — по
 * содержательной причине. Диспетчеризация обязана идти ДО движения: иначе
 * машина, вставшая на остановке, теряет тик впустую на каждой остановке
 * кольца. Расходы обязаны идти ПОСЛЕ прибытия: иначе компания разоряется
 * утром того дня, за который ей вечером заплатят. Развёрнуто — в шапках
 * соответствующих фаз ниже.
 *
 * Две фазы среза 4 встали так же плотно и по такой же логике. Водители идут
 * ПЕРЕД диспетчеризацией: усталость и режим труда решают, кто вообще способен
 * сегодня выехать, а решать это после того, как машине выдали маршрут, значит
 * выдавать маршруты спящим. Износ идёт СРАЗУ ПОСЛЕ движения: ресурс стирается
 * теми же километрами, которые только что проехали, и любой другой порядок
 * означал бы, что машина изнашивается за вчерашний пробег.
 *
 * СРЕЗ 5 ДОБАВИЛ ОДНУ НАСТОЯЩУЮ ФАЗУ И ОДНУ СТАТЬЮ РАСХОДОВ, и обе встали
 * вплотную к соседям. Обслуживание идёт МЕЖДУ ДВИЖЕНИЕМ И ПРИБЫТИЕМ: машина,
 * доехавшая до узла в этом тике, в этом же тике встаёт под погрузку, а тонны
 * переходят в кузов только когда пост отработал. Содержание построек идёт
 * ВНУТРИ фазы расходов и ДО подведения итога, чтобы попасть в суточное окно до
 * его затухания. Развёрнуто — в шапках фаз 8 и 11 ниже.
 *
 * СРЕЗ 6 ВСТАВИЛ ФАЗУ В САМОЕ НАЧАЛО, и это самое дорогое изменение порядка за
 * все шесть срезов. Команды разбираются СРАЗУ ПОСЛЕ ВРЕМЕНИ, до всего остального:
 * решения принимаются в начале дня, а не посреди рейса. Отсюда же следует и
 * главное свойство всей затеи с языковой моделью — МОДЕЛЬ НЕ НАХОДИТСЯ ВНУТРИ
 * ТИКА. Её ответ приходит асинхронно, ложится в состояние (Company.pendingCommands)
 * и разбирается этой фазой как обычные данные, поэтому тик остаётся синхронным и
 * детерминированным: без него рассыпались бы разом тесты экономики, прогоны
 * баланса на сотни игровых лет и воспроизведение багов по сохранению. Парная ей
 * фаза решений стоит на другом конце тика (фаза 13) и по такой же причине:
 * решать надо по досчитанному миру. Развёрнуто — в шапках фаз 2 и 13.
 */

