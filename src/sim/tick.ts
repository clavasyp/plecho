/** Длительность одного тика в часах — 0.25. Скорости везде в км/ч. */
export const HOURS_PER_TICK = 1 / TICKS_PER_HOUR

/**
 * Один шаг симуляции. Входное состояние не изменяется.
 *
 * Фазы применяются конвейером: каждая получает результат предыдущей. Фаза,
 * которой нечего делать, возвращает то же состояние по ссылке — лишних копий
 * не появляется, а на детерминизм это не влияет никак.
 */
export function tick(state: GameState): GameState {
  let next = state

  next = advanceClock(next)
  next = runCommands(next)
  next = runProduction(next)
  next = runDrivers(next)
  next = advanceLineVehicles(next)
  next = moveVehicles(next)
  next = runWear(next)
  next = runService(next)
  next = runArrivals(next)
  next = runConsumption(next)
  next = runUpkeep(next)
  next = runOperatingCosts(next)
  next = updateMarket(next)
  next = runAi(next)
  next = rollEvents(next)

  return next
}

/**
 * Прогнать несколько тиков подряд.
 *
 * Нужно и игровому циклу (при ускорении за кадр проходит несколько тиков), и
 * прогонам баланса, где счёт идёт на игровые годы. Отрицательное n — не откат,
 * а ноль шагов: время в игре назад не идёт, а тихо принять такой аргумент
 * значит спрятать ошибку вызывающего.
 */
export function tickMany(state: GameState, n: number): GameState {
  let next = state
  for (let i = 0; i < n; i++) {
    next = tick(next)
  }
  return next
}

// ─── Фаза 1: время ─────────────────────────────────────────────────────────

/**
 * Счётчик тиков — единственные часы в игре.
 *
 * Дата, время суток и сезон здесь не хранятся: они однозначно выводятся из
 * номера тика и стартового года. Хранить их отдельно означало бы завести две
 * копии одного факта, которые рано или поздно разъедутся — например, после
 * загрузки сейва, записанного другой версией календаря.
 */
function advanceClock(state: GameState): GameState {
  return { ...state, tick: state.tick + 1 }
}

// ─── Фаза 2: команды ───────────────────────────────────────────────────────
//
// runCommands (sim/ai/commands.ts). Очереди Company.pendingCommands всех компаний
// разбираются, законные команды применяются, незаконные отбрасываются, очереди
// очищаются.
//
// ЗДЕСЬ ПРОХОДИТ ГРАНИЦА МЕЖДУ СЕТЬЮ И СИМУЛЯЦИЕЙ, и ради неё фаза и заведена.
// Ответ языковой модели приходит АСИНХРОННО и попадает не сюда, а в состояние —
// в Company.pendingCommands (app/store.ts, deliverPlan). Тик разбирает очередь
// синхронно, как обычные данные, и остаётся ровно тем, чем был: чистой функцией
// без сети, без часов и без Math.random. Сохранение с записанными командами
// воспроизводится один в один, а прогон баланса на сотни игровых лет не зависит
// от интернета вовсе.
//
// ВТОРАЯ ПОЛОВИНА ФАЗЫ — ЧЕСТНОСТЬ. Конкурент не исполняет код и не трогает
// состояние: он возвращает список команд из перечисления Command, и каждая
// проверяется теми же функциями, что и действия игрока (isLegal). Модель
// предлагает — симуляция решает.
//
// САМАЯ ПЕРВАЯ ПОСЛЕ ВРЕМЕНИ, И ЭТО НЕ ПЕРЕСТАВЛЯЕТСЯ. Решения принимаются в
// начале дня, а не посреди рейса: команда, применённая после диспетчеризации,
// застала бы машину с уже выданным маршрутом — купленный грузовик простоял бы
// сутки, снятая линия успела бы отправить парк ещё на круг, а проданный прицеп
// уехал бы с грузом. Хуже того, часть команд применялась бы к состоянию,
// которого конкурент не видел: снимок ему собирали по КОНЦУ прошлого тика, и
// применять его решения надо к тому же самому состоянию, а не к наполовину
// обновлённому.

// ─── Фаза 3: производство ──────────────────────────────────────────────────
//
// runProduction (sim/economy/production.ts). Предприятия потребляют вход и
// кладут выход на склад.
//
// Стоит ДО движения намеренно: произведённое в этот тик доступно машине,
// которая в этот же тик приедет под погрузку. Иначе каждая партия груза ждала
// бы лишний тик без всякой игровой причины, а на ускорении времени это ещё и
// зависело бы от того, сколько тиков успел прокрутить кадр.

// ─── Фаза 4: водители ──────────────────────────────────────────────────────
//
// runDrivers (sim/logistics/driver.ts). Усталость, режим труда и отдыха, рост
// навыка с пробегом, лояльность.
//
// СТОИТ ДО ДИСПЕТЧЕРИЗАЦИИ, И ЭТО ГЛАВНОЕ ПРО ЕЁ МЕСТО. Водитель решает, кто
// сегодня вообще способен выехать: отработавший смену уходит на обязательный
// отдых, и машина под ним стоит, сколько бы маршрутов ей ни выдали. Посчитай
// эту фазу после диспетчеризации — и линия выдавала бы маршруты спящим, а
// выдержка интервала (см. departureGapKm в line.ts) считала бы их уехавшими:
// парк на кольце расставлялся бы по машинам, которые никуда не поехали.
//
// И ДО ДВИЖЕНИЯ — по той же причине, по которой производство стоит до движения:
// усталость, набранная в этом тике, обязана действовать в этом же тике, иначе
// каждое изменение состояния водителя опаздывало бы ровно на пятнадцать минут,
// а на ускорении времени опоздание зависело бы от числа тиков за кадр.

// ─── Фаза 5: диспетчеризация ───────────────────────────────────────────────
//
// advanceLineVehicles (sim/logistics/line.ts). Машины, назначенные на линии,
// получают маршрут к своей следующей остановке; дойдя до конца кольца, идут к
// его началу.
//
// СТОИТ ДО ДВИЖЕНИЯ, И ЭТО НЕ ПЕРЕСТАВЛЯЕТСЯ. Машина, доехавшая до остановки в
// прошлом тике, разгрузилась там же (фаза прибытия) и осталась стоять с пустым
// маршрутом. Диспетчеризация после движения означала бы, что этот тик она
// простояла в городе ни за чем — и так на каждой остановке кольца. При четырёх
// остановках и рейсе в сутки набегает четыре потерянных тика в сутки: не
// катастрофа, но простой, которого игрок не заказывал и в отчёте не увидит.
// Хуже другое — величина потери зависела бы от длины кольца, то есть от того,
// что игрок как раз и оптимизирует, и его метрики врали бы тем сильнее, чем
// плотнее сеть.
//
// Обратный порядок «сначала подвинули, потом выдали маршрут» лишён и второго
// смысла: маршрут строится от ТЕКУЩЕГО положения машины, и выдавать его сразу
// после того, как она сдвинулась, — значит считать путь от точки, из которой
// она уже уехала.

// ─── Фаза 6: движение ──────────────────────────────────────────────────────

/**
 * Каждая машина продвигается по своему маршруту на длительность тика.
 *
 * Все машины считаются от ОДНОГО снимка состояния, а не от результата
 * предыдущей. Это делает фазу независимой от порядка обхода: пока машины не
 * мешают друг другу, результат один и тот же при любом порядке ключей. Когда в
 * срезе 5 появятся очереди на терминалах и загрузка дорог, взаимное влияние
 * придётся вносить явным общим состоянием, а не через порядок цикла — иначе
 * детерминизм держится на порядке ключей объекта, то есть ни на чём.
 *
 * ПРОБЕГ РАСКЛАДЫВАЕТСЯ НА ГРУЖЁНЫЙ И ПОРОЖНИЙ ЗДЕСЬ ЖЕ, внутри advanceVehicle,
 * и в срезе 3 это перестало быть деталью учёта. Пока расходов не было, порожний
 * пробег оставался числом в отчёте; теперь каждый километр из emptyKm — это
 * сожжённая солярка и стёртая резина, за которые никто не заплатил. Считать эти
 * километры где-то ещё, кроме места, где машина знает, гружена ли она, нельзя:
 * разбор конкретного дефекта, из-за которого счета когда-то закрывались на
 * остановках и теряли 99.5% одометра, — в шапке logistics/vehicle.ts.
 */
function moveVehicles(state: GameState): GameState {
  const vehicles: Record<VehicleId, Vehicle> = {}
  let changed = false

  for (const id of Object.keys(state.vehicles) as VehicleId[]) {
    const before = state.vehicles[id]
    const after = advanceVehicle(before, state, HOURS_PER_TICK)
    if (after !== before) {
      changed = true
    }
    vehicles[id] = after
  }

  // Ни одна машина не сдвинулась (весь парк стоит без заданий) — незачем
  // подменять запись целиком.
  return changed ? { ...state, vehicles } : state
}

// ─── Фаза 7: износ ─────────────────────────────────────────────────────────
//
// runWear (sim/logistics/wear.ts). Ресурс стирается пробегом, счётчик до ТО
// растёт, разыгрывается поломка.
//
// СРАЗУ ПОСЛЕ ДВИЖЕНИЯ, И ЭТО НЕ ПЕРЕСТАВЛЯЕТСЯ. Износ считается по километрам
// ЭТОГО тика, а взять их можно только пока машина стоит там, куда её привело
// движение: фаза меряет пробег той же моделью, что и фаза расходов (tickKm), а
// модель читает положение машины. Отодвинь износ на тик — и ресурс стирался бы
// за вчерашний пробег, а сломаться машина могла бы уже на стоянке, доехав.
//
// ДО ПРИБЫТИЯ, а не после: машина, сломавшаяся на подъезде, не должна успеть
// разгрузиться в этом же тике. Поломка обязана срывать доставку — в этом весь
// её смысл, иначе она сводится к строчке расхода.
//
// Здесь же живёт единственное в тике обращение к ГПСЧ (розыгрыш поломки).
// Требование одного потребителя случайности расписано у фазы событий ниже.

// ─── Фаза 8: обслуживание ──────────────────────────────────────────────────
//
// runService (sim/logistics/service.ts). Машина, которой в узле есть что
// переваливать, занимает пост; постов у компании в городе конечное число
// (BASE_POSTS плюс постройки), и тем, кому не хватило, растёт очередь.
//
// ЭТО ГЛАВНАЯ ФАЗА СРЕЗА 5, и стоит она ДО ПРИБЫТИЯ не по вкусу, а потому, что
// иначе её нельзя написать вовсе. Прибытие перекладывает тонны; обслуживание
// решает, РАЗРЕШЕНО ли их перекладывать в этом тике. Разрешение обязано быть
// готово к моменту, когда прибытие смотрит на машину, — то есть посчитано
// раньше. Переставь фазы местами, и погрузка шла бы по вчерашнему решению: в
// тик прибытия машина грузилась бы мгновенно, а пост занимала бы уже пустой.
//
// И ПОСЛЕ ДВИЖЕНИЯ, а не до: машина, доехавшая до узла в этом тике, обязана
// встать под погрузку в этом же тике. Иначе каждая остановка стоила бы лишний
// тик ожидания неизвестно за что, и потеря росла бы с числом остановок кольца —
// то есть с тем, что игрок как раз оптимизирует.
//
// Сама фаза не трогает ни складов, ни грузов, ни денег: две фазы, перекладывающие
// тонны, — это две формулы переполнения, которые однажды разойдутся.

// ─── Фаза 9: прибытие ──────────────────────────────────────────────────────
//
// runArrivals (sim/logistics/loading.ts). Машина, стоящая в узле и отстоявшая
// своё под погрузкой, разгружается и грузится — на линии строго по инструкции
// остановки, без линии по-прежнему автоматически, — и получает деньги за
// доставленное.
//
// Отдельная фаза после движения, а не часть advanceVehicle: перевозка — это
// событие экономики, и ей нужны склады, ставки и деньги, которых в логистике
// машины нет и не должно быть.

// ─── Фаза 10: потребление ───────────────────────────────────────────────────
//
// runConsumption (sim/economy/consumption.ts). Города съедают привезённое,
// растут или сжимаются.
//
// После прибытия: груз, доставленный в этот тик, обязан покрыть спрос этого же
// тика — иначе город голодал бы при машине, стоящей у него под разгрузкой.

// ─── Фаза 11: расходы ──────────────────────────────────────────────────────
//
// runUpkeep (sim/economy/buildings.ts) плюс runOperatingCosts
// (sim/economy/operating.ts). Содержание построек, топливо по пройденным за тик
// километрам, зарплата и обслуживание; в конце подводится суточный итог
// (dailyRevenue/dailyCosts) и проверяется банкротство.
//
// СОДЕРЖАНИЕ ИДЁТ ПЕРВЫМ, И ЭТО НЕ ВКУСОВЩИНА. Суточные потоки — это
// экспоненциальное окно, и затухание применяется РОВНО ОДИН РАЗ за тик, внутри
// runOperatingCosts. Значит всё, что обязано попасть в окно этого тика, должно
// лечь в dailyCosts до него — ровно так же выручка ложится туда через
