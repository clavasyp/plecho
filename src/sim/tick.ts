/**
 * Главный тик симуляции: один шаг мира длиной в 15 игровых минут.
 *
 * Тик — чистая функция состояния. Ни времени по часам, ни случайности из
 * Math.random, ни сети: всё, что влияет на результат, лежит в GameState, вплоть
 * до состояния ГПСЧ. Отсюда следует всё, ради чего симуляция отделена от
 * рендера: сохранение воспроизводится тик в тик, баг чинится прогоном из
 * сейва, а ускорение времени — это просто больше вызовов tick за кадр, без
 * единой строчки особой логики.
 *
 * ПОРЯДОК ФАЗ ЗАФИКСИРОВАН ЗДЕСЬ И СЕЙЧАС, хотя большинство фаз ещё пустые.
 * Это не преждевременное обобщение, а обратное ему: порядок — самое дорогое
 * решение в тике, и менять его потом больно. Он определяет, видит ли машина
 * груз, произведённый в этот же тик, и успевает ли компания заплатить за
 * топливо до проверки банкротства. Порядок взят из docs/АРХИТЕКТУРА.md §4,
 * заглушки стоят на своих местах и подписаны срезом, в котором оживут.
 *
 * Смысл выбранного порядка в двух словах: сначала мир делает то, что от
 * решений не зависит (время, производство, движение), потом фиксируются
 * последствия (прибытие, потребление, деньги), и только в конце принимаются
 * новые решения (рынок, ИИ, события). Так решение всегда принимается по
 * состоянию, которое уже сложилось, а не по наполовину обновлённому.
 */

import { advanceVehicle } from './logistics/vehicle'
import { TICKS_PER_HOUR } from './types'
import type { GameState, Vehicle, VehicleId } from './types'

/** Длительность одного тика в часах — 0.25. Скорости везде в км/ч. */
export const HOURS_PER_TICK = 1 / TICKS_PER_HOUR

/**
 * Один шаг симуляции. Входное состояние не изменяется.
 *
 * Фазы применяются конвейером: каждая получает результат предыдущей. Фаза,
 * которой нечего делать, возвращает то же состояние по ссылке — лишних копий
 * не появляется, а на детерминизм это не влияет никак.
 */
export function tick(state: GameState): GameState {
  let next = state

  next = advanceClock(next)
  next = runProduction(next)
  next = moveVehicles(next)
  next = handleArrivals(next)
  next = runConsumption(next)
  next = settleFinances(next)
  next = updateMarket(next)
  next = runAi(next)
  next = rollEvents(next)

  return next
}

/**
 * Прогнать несколько тиков подряд.
 *
 * Нужно и игровому циклу (при ускорении за кадр проходит несколько тиков), и
 * прогонам баланса, где счёт идёт на игровые годы. Отрицательное n — не откат,
 * а ноль шагов: время в игре назад не идёт, а тихо принять такой аргумент
 * значит спрятать ошибку вызывающего.
 */
export function tickMany(state: GameState, n: number): GameState {
  let next = state
  for (let i = 0; i < n; i++) {
    next = tick(next)
  }
  return next
}

// ─── Фаза 1: время ─────────────────────────────────────────────────────────

/**
 * Счётчик тиков — единственные часы в игре.
 *
 * Дата, время суток и сезон здесь не хранятся: они однозначно выводятся из
 * номера тика и стартового года. Хранить их отдельно означало бы завести две
 * копии одного факта, которые рано или поздно разъедутся — например, после
 * загрузки сейва, записанного другой версией календаря.
 */
function advanceClock(state: GameState): GameState {
  return { ...state, tick: state.tick + 1 }
}

// ─── Фаза 2: производство ──────────────────────────────────────────────────

/**
 * Предприятия потребляют входы и кладут выход на склад.
 *
 * Заглушка до среза 2, где появятся industries и recipes. Стоит ДО движения
 * намеренно: произведённое в этот тик должно быть доступно машине, которая в
 * этот же тик приедет под погрузку, иначе каждая партия груза будет ждать
 * лишний тик без всякой игровой причины.
 */
function runProduction(state: GameState): GameState {
  return state
}

// ─── Фаза 3: движение ──────────────────────────────────────────────────────

/**
 * Каждая машина продвигается по своему маршруту на длительность тика.
 *
 * Все машины считаются от ОДНОГО снимка состояния, а не от результата
 * предыдущей. Это делает фазу независимой от порядка обхода: пока машины не
 * мешают друг другу, результат один и тот же при любом порядке ключей. Когда в
 * срезе 5 появятся очереди на терминалах и загрузка дорог, взаимное влияние
 * придётся вносить явным общим состоянием, а не через порядок цикла — иначе
 * детерминизм держится на порядке ключей объекта, то есть ни на чём.
 */
function moveVehicles(state: GameState): GameState {
  const vehicles: Record<VehicleId, Vehicle> = {}
  let changed = false

  for (const id of Object.keys(state.vehicles) as VehicleId[]) {
    const before = state.vehicles[id]
    const after = advanceVehicle(before, state, HOURS_PER_TICK)
    if (after !== before) {
      changed = true
    }
    vehicles[id] = after
  }

  // Ни одна машина не сдвинулась (весь парк стоит без заданий) — незачем
  // подменять запись целиком.
  return changed ? { ...state, vehicles } : state
}

// ─── Фаза 4: прибытие ──────────────────────────────────────────────────────

/**
 * Машина доехала до остановки: выгрузка, погрузка, расчёт за рейс.
 *
 * Заглушка до среза 2 (деньги за груз) и среза 3 (правила линий). Отдельная
 * фаза после движения, а не часть advanceVehicle: перевозка — это событие
 * экономики, и ей нужны склады, ставки и деньги, которых в логистике машины
 * нет и не должно быть.
 */
function handleArrivals(state: GameState): GameState {
  return state
}

// ─── Фаза 5: потребление ───────────────────────────────────────────────────

/**
 * Города съедают привезённое, растут или сжимаются.
 *
 * Заглушка до среза 2. После прибытия: груз, доставленный в этот тик, должен
 * успеть покрыть спрос этого же тика, иначе город будет голодать при машине,
 * стоящей у него под разгрузкой.
 */
function runConsumption(state: GameState): GameState {
  return state
}

// ─── Фаза 6: финансы ───────────────────────────────────────────────────────

/**
 * Зарплаты, ТО, платежи по кредитам, налоги, проверка банкротства.
 *
 * Заглушка до среза 3. Идёт после того, как посчитана вся выручка тика: иначе
 * компания банкротилась бы утром того дня, за который ей вечером заплатят.
 */
function settleFinances(state: GameState): GameState {
  return state
}

// ─── Фаза 7: рынок ─────────────────────────────────────────────────────────

/**
 * Пересчёт цен на топливо и ставок за перевозку.
 *
 * Заглушка до среза 2. После финансов: цены следующего тика формируются по
 * итогам этого, и никто в текущем тике не платит по ещё не объявленной цене.
 */
function updateMarket(state: GameState): GameState {
  return state
}

// ─── Фаза 8: решения ИИ ────────────────────────────────────────────────────

/**
 * Конкуренты принимают решения.
 *
 * Заглушка до среза 6. Предпоследняя фаза не случайно: ИИ должен видеть мир
 * уже посчитанным — с новыми ценами и итогами дня. Сетевого вызова здесь не
 * будет никогда: LLM отвечает асинхронно, а её ответ попадает в состояние как
 * очередь команд и применяется этой фазой на следующем тике.
 */
function runAi(state: GameState): GameState {
  return state
}

// ─── Фаза 9: события ───────────────────────────────────────────────────────

/**
 * Поломки, штрафы, аварии, происшествия в городах.
 *
 * Заглушка до среза 4. Последняя фаза и единственный потребитель случайности в
 * тике: ГПСЧ дёргается в одном месте, поэтому добавление события не сдвигает
 * последовательность для всех остальных систем и старые сейвы продолжают
 * воспроизводиться. Отсюда же требование записывать rngState обратно в
 * состояние.
 */
