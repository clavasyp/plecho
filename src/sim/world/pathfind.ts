/**
 * Поиск маршрута по графу дорог — Дейкстра по ВРЕМЕНИ В ПУТИ.
 *
 * Вес ребра — часы, а не километры, и в этом весь смысл файла. Километровый
 * маршрут в игре про грузоперевозки — неправильный ответ: водитель оплачивается
 * по времени, машина за смену успевает столько рейсов, сколько успевает, а
 * разбитая двухполоска съедает больше, чем экономит на расстоянии.
 *
 * И ВТОРОЕ, НЕ МЕНЕЕ ВАЖНОЕ: маршрут зависит от машины. Поэтому крейсерская
 * скорость входит в сигнатуру каждой функции здесь, и обойти это нельзя.
 *
 * Живой пример прямо из данных — Калуга → Орёл. Есть два варианта:
 *
 *   напрямую  Р-92, 210 км, региональная, качество 0.55
 *   через Тулу  Р-132, 110 км, региональная 0.65  +  М-2, 183 км, федеральная 0.78
 *
 * Магистральный тягач (крейсерские 90):
 *   напрямую  210/38.5                      = 5.455 ч
 *   объезд    110/45.5 + 183/70.2           = 5.025 ч   ← быстрее на 26 мин
 *
 * Стартовый ЗИЛ (крейсерские 70):
 *   напрямую  210/38.5                      = 5.455 ч   ← быстрее на 19 мин
 *   объезд    110/45.5 + 183/54.6           = 5.769 ч
 *
 * Один и тот же объезд для тягача выигрывает, а для ЗИЛа проигрывает — и
 * причина ровно одна: ЗИЛ не может воспользоваться федеральной трассой, его
 * потолок 70 ниже, чем её 90. Он платит за лишние 83 километра, не получая
 * взамен скорости.
 *
 * Именно поэтому нельзя считать вес ребра «вообще», без машины. Раньше здесь
 * была своя таблица скоростей по классам дорог, не смотревшая на транспорт, —
 * и поиск честно отправлял ЗИЛ по маршруту, который для него медленнее.
 * Формула скорости теперь ровно одна на весь проект и живёт в ./speed.
 */

import type { CityId } from '../types'
import type { RoadGraph } from './graph'
import { findEdge, hasCity, neighbors } from './graph'
import { edgeTravelHours } from './speed'

// ─── Кэш маршрутов ─────────────────────────────────────────────────────────

/** Найденный маршрут либо null, если пути нет. */
type Route = CityId[] | null

/**
 * Кэш маршрутов, ключ — «откуда->куда».
 *
 * Зачем: Дейкстра запускается на каждый вопрос «как ехать», а вопросов много —
 * назначение линии, перестроение парка, каждый прикидочный расчёт конкурента.
 * При этом ответ меняется редко: граф дорог статичен, а качество и класс
 * ползут медленно (сезон, ремонт, загрузка). Считать одно и то же заново —
 * чистая трата тика.
 *
 * Кэш привязан к графу через WeakMap, и это делает половину сброса
 * автоматической: новый граф (после загрузки сохранения или пересборки мира) —
 * это новый ключ и, значит, пустой кэш, а старый уезжает в сборщик мусора
 * вместе с графом.
 *
 * КОГДА СБРАСЫВАТЬ РУКАМИ. Ровно один случай: веса изменились НА МЕСТЕ, то
 * есть кто-то поправил поля существующего Edge — сезонное падение качества,
 * закрытие дороги на ремонт, будущая загрузка ребра. Граф при этом остался тем
 * же объектом, WeakMap ничего не заметит, и маршруты останутся посчитанными по
 * старой карте. Правило простое: изменил Edge — позови clearRouteCache().
 *
 * Размер не ограничиваем: пар городов не больше квадрата их числа (для ЦФО это
 * сотня записей), вытеснение здесь стоило бы дороже, чем экономило.
 */
let routeCache = new WeakMap<RoadGraph, Map<string, Route>>()

/** Сбросить кэш целиком. См. рассуждение выше о том, когда это нужно. */
export function clearRouteCache(): void {
  routeCache = new WeakMap()
}

// ─── Поиск ─────────────────────────────────────────────────────────────────

/**
 * Кратчайший по времени маршрут: последовательность городов от `from` до `to`
 * включительно. null — если пути нет.
 *
 * Маршрут из города в себя — это `[from]`, поездка нулевой длины: так вызов
 * не требует особой ветки у каждого потребителя. Но только для города,
 * который граф знает: на опечатку в идентификаторе честнее ответить null, чем
 * выдать правдоподобный маршрут в несуществующий город.
 *
 * `cruiseKmh` — крейсерская скорость машины, для которой строится маршрут.
 * Не деталь и не необязательный параметр: тихоходная машина не может
 * воспользоваться преимуществом федеральной трассы, и оптимальный путь для
 * неё другой. См. разбор Калуга → Орёл в шапке файла.
 */
export function findRoute(
  graph: RoadGraph,
  from: CityId,
  to: CityId,
  cruiseKmh: number,
): CityId[] | null {
  let cache = routeCache.get(graph)
  if (cache === undefined) {
    cache = new Map<string, Route>()
    routeCache.set(graph, cache)
  }

  // Крейсерская скорость входит в ключ: для разных машин ответы разные, и
  // общий кэш без неё раздавал бы чужой маршрут.
  const key = `${from}->${to}@${cruiseKmh}`
  const hit = cache.get(key)
  // undefined значит «не считали», null — «посчитали, пути нет». Различать
  // обязательно: иначе недостижимые пары пересчитываются при каждом вопросе,
  // а это самый дорогой случай — обход всей достижимой части графа.
  if (hit !== undefined) return copyRoute(hit)

  const route = searchRoute(graph, from, to, cruiseKmh)
  cache.set(key, route)
  return copyRoute(route)
}

/**
 * Копия маршрута наружу.
 *
 * Отдавать сам массив нельзя: Vehicle.route — это «что осталось проехать», и
 * машина выкусывает из него города по мере движения. Первая же машина, которой
 * достался бы массив из кэша, объела бы его до пустого — а следующий
 * спросивший получил бы этот огрызок как готовый маршрут.
 */
function copyRoute(route: Route): CityId[] | null {
  return route === null ? null : route.slice()
}

/**
 * Собственно Дейкстра, без кэша.
 *
 * Минимум ищется линейным перебором открытых узлов, без кучи. Для десятков
 * (и даже сотен) городов O(V²) быстрее и понятнее двоичной кучи: на таких
 * размерах вся структура умещается в кэш процессора, а кода вдвое меньше.
 * Понадобится тысяча узлов — здесь появится куча, и снаружи это никак не
 * будет видно.
 *
 * Порядок обхода детерминирован: узлы перебираются в порядке их открытия, то
 * есть при равных весах побеждает тот, до кого добрались раньше. Для игры, где
 * баг обязан воспроизводиться по сохранению, это не мелочь.
 */
function searchRoute(
  graph: RoadGraph,
  from: CityId,
  to: CityId,
  cruiseKmh: number,
): Route {
  if (!hasCity(graph, from) || !hasCity(graph, to)) return null
  if (from === to) return [from]

  /**
   * Лучшее известное время до города, часы. Оно же множество открытых узлов:
   * город появляется здесь в тот момент, когда до него впервые дотянулись.
   */
  const best = new Map<CityId, number>([[from, 0]])
  /** Откуда пришли — по этим ссылкам маршрут собирается обратным ходом. */
  const previous = new Map<CityId, CityId>()
  const settled = new Set<CityId>()

  for (;;) {
    let current: CityId | undefined
    let currentHours = Number.POSITIVE_INFINITY
    for (const [city, hours] of best) {
      if (!settled.has(city) && hours < currentHours) {
        current = city
        currentHours = hours
      }
    }

    // Открытых узлов не осталось — цель в другой компоненте графа.
    if (current === undefined) break
    // До цели дошли. Вес неотрицательный, поэтому её оценка уже окончательная
    // и продолжать обход незачем.
    if (current === to) break

    settled.add(current)

    for (const neighbor of neighbors(graph, current)) {
      if (settled.has(neighbor.cityId)) continue

      const hours = edgeTravelHours(neighbor.edge, cruiseKmh)
      // Непроезжее ребро (качество ноль) — как будто его нет.
      if (!Number.isFinite(hours)) continue

      const candidate = currentHours + hours
      const known = best.get(neighbor.cityId)
      if (known === undefined || candidate < known) {
        best.set(neighbor.cityId, candidate)
        previous.set(neighbor.cityId, current)
      }
    }
  }

  if (!best.has(to)) return null

  const route: CityId[] = [to]
  let step = to
  while (step !== from) {
    const back = previous.get(step)
    // Цепочка обязана дойти до начала: до `to` добрались, значит ссылка есть
    // у каждого узла на пути. Если её вдруг нет — маршрут порван, и лучше
    // честно сказать «пути нет», чем вернуть обрубок.
    if (back === undefined) return null
    route.push(back)
    step = back
  }

  return route.reverse()
}

/**
 * Суммарное время маршрута в часах.
 *
 * Маршрут из одного города (или пустой) стоит ноль — ехать некуда.
 *
 * Разрыв в маршруте — соседние города, между которыми нет дороги — даёт
 * бесконечность, а не исключение. Функция нужна прежде всего для сравнения
 * вариантов (кто из конкурентов возьмёт заказ, какой из двух маршрутов
 * выгоднее), и битый вариант должен проигрывать любому целому автоматически,
 * а не ронять тик.
 */
export function routeCost(
  graph: RoadGraph,
  route: readonly CityId[],
  cruiseKmh: number,
): number {
  let hours = 0

  for (let i = 1; i < route.length; i++) {
    const edge = findEdge(graph, route[i - 1], route[i])
    if (edge === undefined) return Number.POSITIVE_INFINITY
    hours += edgeTravelHours(edge, cruiseKmh)
  }

  return hours
}
