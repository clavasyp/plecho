import type { Edge, RoadClass } from '../types'

/**
 * Единственный источник правды о скорости на дороге.
 *
 * Модуль существует ровно затем, чтобы формула была ОДНА. Раньше её считали в
 * двух местах — поиск пути и движение машины, — и формулы разошлись: маршрут
 * строился по одному расписанию, а проезжался по другому. Дефект тихий и
 * крайне неприятный: машина едет «просто медленнее, чем думали», и никакой
 * ошибки при этом не возникает.
 *
 * Как это выглядело на реальных данных: для стартового ЗИЛа с крейсерскими
 * 70 км/ч поиск пути выбирал объезд Калуга → Тула → Орёл вместо прямой Р-92,
 * потому что считал скорость по классу дороги, не глядя на машину. Фактически
 * ЗИЛ проезжал этот объезд на 19 минут МЕДЛЕННЕЕ прямого пути: разницу классов
 * он всё равно не использует — его потолок ниже, чем у любой федеральной
 * трассы.
 *
 * Отсюда главный вывод, зафиксированный в сигнатурах: **скорость и время в
 * пути нельзя посчитать, не зная машину**. Любая функция здесь требует
 * крейсерскую скорость аргументом, и обойти это невозможно по типам.
 */

/**
 * Потолок скорости по классу дороги, км/ч.
 *
 * Числа грузовые и упираются в закон, а не в двигатель: тяжёлому грузовику
 * разрешено 90 км/ч по автомагистрали и 70 вне населённых пунктов на обычной
 * дороге. Ограничитель на седельном тягаче всё равно не даст больше 90.
 *
 * Местная дорога получает 50, а не разрешённые 60, потому что она из
 * населённых пунктов практически не выходит и разгоняться на ней негде.
 *
 * Это именно потолок: он ограничивает машину сверху, но не ускоряет
 * тихоходную.
 */
export const ROAD_CLASS_LIMIT_KMH: Record<RoadClass, number> = {
  // М-трассы: разделённые потоки, обгон не нужен, поток идёт ровно.
  'федеральная': 90,
  // Две встречные полосы вне населённых пунктов: обгон возможен не везде.
  'региональная': 70,
  // Посёлки со знаком 60, повороты, техника на проезжей части.
  'местная': 50,
}

/**
 * Фактическая скорость на ребре, км/ч.
 *
 *     v = min(крейсерская, потолок класса) × качество
 *
 * Два сомножителя отвечают за разное, и в этом весь смысл формулы. Минимум —
 * жёсткое ограничение сверху: быстрее потолка нельзя, но и медленнее своей
 * крейсерской машина не поедет по чужой вине. Качество — множитель, а не
 * второе ограничение, потому что описывает не предел, а долю потерянного
 * времени: обгоны на двухполоске, светофоры в посёлках вдоль трассы, ямы.
 * Такие потери пропорциональны времени в пути, поэтому и входят множителем.
 *
 * Проверка на данных: М-2 «Крым» (федеральная, 0.87) даёт тягачу с
 * крейсерскими 90 ровно 78.3 км/ч, и Москва — Тула (185 км) занимает 2 ч 22
 * мин — столько эта дорога и занимает.
 *
 * Битые данные (NaN, отрицательное качество) дают ноль, а не NaN. Ноль
 * означает «машина стоит» и корректно обрабатывается всеми потребителями;
 * NaN же просачивается сквозь сравнения (`NaN <= 0` ложно!) и подвешивает
 * циклы движения. Проверка на конечность здесь — предохранитель ровно от этого.
 */
export function speedKmh(cruiseKmh: number, edge: Edge): number {
  const limited = Math.min(cruiseKmh, ROAD_CLASS_LIMIT_KMH[edge.class])
  const speed = limited * edge.quality
  return Number.isFinite(speed) && speed > 0 ? speed : 0
}

/**
 * Время проезда по ребру для конкретной машины, часы.
 *
 * Непроезжее ребро — нулевое качество, весенний размыв, обвал моста — даёт
 * бесконечность. Так оно само выпадает из поиска пути, не требуя отдельного
 * флага в данных, и автоматически проигрывает любому целому маршруту при
 * сравнении вариантов.
 */
export function edgeTravelHours(edge: Edge, cruiseKmh: number): number {
  const speed = speedKmh(cruiseKmh, edge)
  return speed > 0 ? edge.km / speed : Number.POSITIVE_INFINITY
}
