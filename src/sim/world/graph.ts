/**
 * Граф дорог: смежность городов и доступ к рёбрам.
 *
 * В состоянии игры дороги лежат плоской таблицей `Record<EdgeId, Edge>` — так
 * их удобно сериализовать и так их проще всего набивать в данных. Но ни одному
 * потребителю эта форма не подходит: поиск пути, движение машины и подсветка
 * вариантов в интерфейсе спрашивают одно и то же — «какие дороги выходят из
 * этого города». По таблице ответ стоит перебора всех рёбер, а спрашивают
 * сотни раз за тик. Здесь таблица один раз разворачивается в списки смежности.
 *
 * ПОЧЕМУ RoadGraph — ПРОИЗВОДНЫЙ КЭШ, А НЕ ЧАСТЬ СОСТОЯНИЯ.
 *
 * Смежность полностью выводится из `world.edges` и не несёт ни бита
 * собственной информации. По общему правилу проекта производные значения не
 * хранятся — иначе рано или поздно они разъедутся с источником, и разъедутся
 * тихо: маршруты будут строиться по дороге, которой в состоянии уже нет.
 * Построение стоит один проход по рёбрам, то есть дешевле любой попытки
 * поддерживать копию в актуальном состоянии. Граф строится после загрузки
 * сохранения и пересобирается, если множество рёбер изменилось.
 *
 * Отсюда же выбор `Map` вместо простых объектов. Сериализовать граф не нужно,
 * а `Map` вдобавок физически не переживает `JSON.stringify` — превращается в
 * `{}`. Если кто-то попробует положить граф в GameState, ближайший вызов
 * `neighbors` после загрузки упадёт на отсутствующем `.get`, вместо того чтобы
 * молча работать с пустой смежностью. Ошибка такого рода должна быть громкой.
 */

import type { CityId, Edge, EdgeId } from '../types'

/** Сосед города: куда ведёт дорога и какая именно. */
export type Neighbor = {
  /** Город на другом конце ребра. */
  cityId: CityId
  edge: Edge
}

/**
 * Структура смежности. Производный кэш — см. шапку файла, в GameState не
 * хранится и не сериализуется.
 */
export type RoadGraph = {
  /**
   * Для каждого города — рёбра, из него выходящие. Ребро попадает в списки
   * обоих концов: дорога ненаправленная, а направление движения живёт в
   * VehiclePosition, а не в графе.
   */
  readonly adjacency: ReadonlyMap<CityId, readonly Neighbor[]>
}

/**
 * Общий пустой список для городов, которых в графе нет.
 *
 * Возвращать его, а не создавать `[]` на каждый промах: `neighbors` зовётся из
 * внутреннего цикла Дейкстры, и мусор там не нужен.
 */
const NO_NEIGHBORS: readonly Neighbor[] = []

/**
 * Развернуть таблицу рёбер в структуру смежности.
 *
 * Граф знает только те города, у которых есть хотя бы одна дорога. Город без
 * рёбер в графе дорог не представлен вообще — это не потеря данных, а ровно то,
 * что означает «до него нельзя доехать».
 */
export function buildGraph(edges: Record<EdgeId, Edge>): RoadGraph {
  const adjacency = new Map<CityId, Neighbor[]>()

  const link = (from: CityId, to: CityId, edge: Edge): void => {
    const list = adjacency.get(from)
    if (list === undefined) {
      adjacency.set(from, [{ cityId: to, edge }])
    } else {
      list.push({ cityId: to, edge })
    }
  }

  for (const edge of Object.values(edges)) {
    // Петля (ребро из города в себя) — всегда ошибка в данных, её ловит
    // roads.test.ts. Но если она сюда всё-таки доедет, пусть лучше исчезнет:
    // город, ставший собственным соседом, потом всплывает машиной, которая
    // «едет» из Тулы в Тулу, и искать причину придётся уже в логистике.
    if (edge.from === edge.to) continue

    link(edge.from, edge.to, edge)
    link(edge.to, edge.from, edge)
  }

  return { adjacency }
}

/** Есть ли у города хоть одна дорога, то есть знает ли о нём граф. */
export function hasCity(graph: RoadGraph, city: CityId): boolean {
  return graph.adjacency.has(city)
}

/**
 * Соседние города и ведущие к ним рёбра.
 *
 * Для неизвестного города — пустой список, а не исключение: «никуда не ведёт»
 * — законный ответ для поиска пути, он сам решит, что делать.
 */
export function neighbors(
  graph: RoadGraph,
  city: CityId,
): readonly Neighbor[] {
  return graph.adjacency.get(city) ?? NO_NEIGHBORS
}

/**
 * Ребро между двумя городами или undefined, если прямой дороги нет.
 *
 * Порядок аргументов не важен: ребро ненаправленное и лежит в списках обоих
 * концов, поэтому перебор соседей любого из городов даёт один и тот же ответ.
 *
 * Отдельного индекса по паре городов здесь намеренно нет. Степень узла — это
 * единицы рёбер (у Москвы, самой связной, их семь), так что перебор соседей
 * уже фактически константа, а второй индекс был бы второй структурой, которую
 * нужно держать согласованной с первой.
 *
 * Пар с двумя рёбрами данные не допускают (проверяется в roads.test.ts),
 * поэтому «первое совпадение» — оно же единственное. Если когда-нибудь
 * появятся параллельные дороги (платный объезд рядом с бесплатной), этой
 * функции понадобится критерий выбора, а `routeCost` придётся считать по тем
 * же рёбрам, которые выбрал поиск пути, а не искать их заново.
 */
export function findEdge(
  graph: RoadGraph,
  a: CityId,
  b: CityId,
): Edge | undefined {
  for (const neighbor of neighbors(graph, a)) {
    if (neighbor.cityId === b) return neighbor.edge
  }
  return undefined
}
