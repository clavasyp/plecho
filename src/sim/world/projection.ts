/**
 * Проекция широты и долготы на игровую плоскость.
 *
 * Мир хранится в градусах (так приходят реальные данные о городах), а вся
 * игровая логика и рендер работают в километрах на плоскости. Здесь стык.
 *
 * Проекция — равнопромежуточная (equirectangular) с постоянным масштабом по
 * долготе, взятым на широте точки отсчёта. Формально это грубо: настоящая
 * длина градуса долготы сжимается к полюсу, а мы её замораживаем. Но игровой
 * регион — ЦФО, полоса примерно ±3° по широте вокруг 55-й параллели, и на
 * таком куске ошибка масштаба не превышает процента-полутора (проверяется
 * тестом на паре Смоленск—Владимир, самой широкой по долготе). Взамен формула
 * умещается в две строки и, главное, остаётся ЛИНЕЙНОЙ.
 *
 * Линейность здесь ценнее точности. Постоянный масштаб означает, что проекция
 * — это аффинное преобразование: прямая на сфере остаётся прямой на плоскости,
 * середина ребра остаётся серединой, а машина, интерполируемая по progress,
 * едет ровно там, где нарисована дорога. Если бы масштаб зависел от широты
 * каждой точки, всё это пришлось бы пересчитывать, и на длинных меридиональных
 * рёбрах геометрия поехала бы.
 *
 * Оси: X на восток, Y на север — как на бумажной карте.
 *
 * ВАЖНО ПРО РЕНДЕР. В Three.js вверх смотрит Y, а горизонтальная плоскость —
 * это XZ. Поэтому наш север (Point2.y) уходит в Z, и уходить обязан СО СМЕНОЙ
 * ЗНАКА: position = [p.x, height, -p.y]. Проверка на пальцах: восток × север =
 * вверх; в осях Three.js X × (−Z) = +Y, сходится. Если же взять z = +y, то
 * X × Z = −Y, «вверх» окажется внизу и карта выйдет зеркальной — Смоленск
 * встанет восточнее Владимира. Ошибка тихая: сцена выглядит правдоподобно,
 * пока не прочитаешь подписи городов.
 */

import type { LatLon, Point2 } from '../types'

/** Средний радиус Земли, км. Сферу вместо эллипсоида берём осознанно. */
export const EARTH_RADIUS_KM = 6371

/**
 * Километров в одном градусе широты — примерно 111.19.
 *
 * Одинаково на любой широте: меридианы это большие круги. Масштаб по долготе
 * получается из этого же числа умножением на косинус широты.
 */
const KM_PER_DEGREE = (Math.PI / 180) * EARTH_RADIUS_KM

const toRadians = (degrees: number): number => (degrees * Math.PI) / 180

/**
 * Точка отсчёта для карты ЦФО.
 *
 * Центроид десяти игровых городов лежит около 55.07° с.ш., 36.99° в.д., так
 * что круглые 55 и 37 — это он с точностью до километров. Круглые числа взяты
 * намеренно: в отладке координаты города считаются в уме (Москва — это чуть
 * меньше градуса на север от отсчёта, то есть примерно +84 км по Y).
 *
 * Заодно 55° — та широта, на которой замораживается масштаб по долготе, и
 * искажение размазывается симметрично: Ярославль на севере и Орёл на юге
 * ошибаются в разные стороны, а не копят ошибку в одну.
 */
export const CFO_ORIGIN: LatLon = { lat: 55, lon: 37 }

/**
 * Перевести географическую точку в километры на игровой плоскости.
 *
 * Точка отсчёта даёт (0, 0). Севернее — положительный y, восточнее —
 * положительный x.
 */
export function project(coord: LatLon, origin: LatLon): Point2 {
  // Масштаб по долготе берётся на широте ОТСЧЁТА, а не самой точки — см.
  // рассуждение про линейность в шапке файла.
  const lonScale = Math.cos(toRadians(origin.lat))

  return {
    x: (coord.lon - origin.lon) * KM_PER_DEGREE * lonScale,
    y: (coord.lat - origin.lat) * KM_PER_DEGREE,
  }
}

/**
 * Спроецировать список точек одним вызовом, сохраняя порядок.
 *
 * Нужен ровно для того, как проекция используется на деле: города и точки
 * рёбер проецируются пачкой один раз при сборке мира, а дальше живут в
 * километрах.
 */
export function projectAll(
  coords: readonly LatLon[],
  origin: LatLon,
): Point2[] {
  return coords.map((coord) => project(coord, origin))
}

/**
 * Расстояние по большому кругу (гаверсинус), км.
 *
 * Считается по сфере, а НЕ по спроецированной плоскости, и это важно: функция
 * нужна как независимая линейка для проверки данных о дорогах — дорога обязана
 * быть длиннее прямой. Меряй мы плоскостью, проверка сравнивала бы проекцию
 * сама с собой и молча проглотила бы ошибку масштаба.
 */
export function distanceKm(a: LatLon, b: LatLon): number {
  const lat1 = toRadians(a.lat)
  const lat2 = toRadians(b.lat)
  const dLat = lat2 - lat1
  const dLon = toRadians(b.lon - a.lon)

  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2

  // Зажим до 1 — против арифметики с плавающей точкой: на почти
  // противоположных точках h вылезает за единицу на единицы ULP, и asin
  // возвращает NaN вместо половины окружности.
  return 2 * EARTH_RADIUS_KM * Math.asin(Math.min(1, Math.sqrt(h)))
}
