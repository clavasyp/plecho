/**
 * Модель состояния игры.
 *
 * Всё состояние — одна сериализуемая структура. Никакого игрового состояния за
 * её пределами: сохранение это JSON.stringify(state), загрузка — JSON.parse.
 *
 * Здесь описан срез 1 (мир, время, движение). Экономика, линии, водители и
 * инфраструктура добавляются в срезах 2–5, их формы — в docs/АРХИТЕКТУРА.md.
 * Типы намеренно не заводятся заранее: неиспользуемые определения устаревают
 * быстрее, чем становятся нужны.
 */

// ─── Идентификаторы ────────────────────────────────────────────────────────
// Строковые литеральные типы вместо number: в отладке и в сохранении сразу
// видно, что за сущность, а перепутать CityId с EdgeId не даёт компилятор.

export type CityId = string & { readonly __brand: 'CityId' }
export type EdgeId = string & { readonly __brand: 'EdgeId' }
export type VehicleId = string & { readonly __brand: 'VehicleId' }
export type CompanyId = string & { readonly __brand: 'CompanyId' }
export type IndustryId = string & { readonly __brand: 'IndustryId' }
export type LineId = string & { readonly __brand: 'LineId' }

export const cityId = (id: string) => id as CityId
export const edgeId = (id: string) => id as EdgeId
export const vehicleId = (id: string) => id as VehicleId
export const companyId = (id: string) => id as CompanyId
export const industryId = (id: string) => id as IndustryId
export const lineId = (id: string) => id as LineId

// ─── География ─────────────────────────────────────────────────────────────

/** Точка на сфере — как в исходных данных. */
export type LatLon = {
  lat: number
  lon: number
}

/** Точка на игровой плоскости в километрах после проекции. */
export type Point2 = {
  x: number
  y: number
}

/** Профиль города определяет, какие предприятия у него в окрестностях. */
export type CityProfile =
  | 'столица'
  | 'промышленный'
  | 'аграрный'
  | 'транзитный'
  | 'ресурсный'

/**
 * Статическое описание города — то, что задано данными и не меняется.
 *
 * Отделено от City намеренно: src/data описывает мир, а не его состояние.
 * Складывать в файл данных пустой склад и нулевой счётчик снабжения — значит
 * смешивать «какая Тула есть» с «что с Тулой происходит прямо сейчас».
 */
export type CityStatic = {
  id: CityId
  name: string
  coord: LatLon
  /** Жителей на начало партии. Дальше величина живёт в City и меняется. */
  population: number
  profile: CityProfile
}

export type City = CityStatic & {
  /**
   * Жителей сейчас. Величина ДИНАМИЧЕСКАЯ: снабжаемый город растёт,
   * брошенный сжимается.
   *
   * Это главная обратная связь игры — наладил поставки, город вырос, спрос
   * вырос, и твоя сеть перестала справляться.
   */
  population: number

  /** Склад потребительских товаров, доставленных в город. */
  stock: Partial<Record<CargoType, Tons>>

  /**
   * Сколько подряд суток город получал всё, что ему нужно.
   *
   * Рост требует УСТОЙЧИВОГО снабжения, а не одной удачной поставки: иначе
   * выгоднее было бы завалить город разово и уехать.
   */
  suppliedDays: number
}

/** Класс дороги задаёт базовую скорость и пропускную способность. */
export type RoadClass = 'федеральная' | 'региональная' | 'местная'

export type Edge = {
  id: EdgeId
  from: CityId
  to: CityId
  /** Длина по дороге, не по прямой. */
  km: number
  class: RoadClass
  /** Обозначение трассы для интерфейса: «М-4», «Р-132». */
  route: string
  /** 0..1 — качество покрытия. Влияет на скорость и износ. */
  quality: number
}

// ─── Время ─────────────────────────────────────────────────────────────────

/** Один тик симуляции. Всё игровое время выражается в тиках. */
export const MINUTES_PER_TICK = 15
export const TICKS_PER_HOUR = 60 / MINUTES_PER_TICK
export const TICKS_PER_DAY = TICKS_PER_HOUR * 24

export type Season = 'зима' | 'весна' | 'лето' | 'осень'

/** Производное от tick представление — удобно для интерфейса, не хранится. */
export type GameDate = {
  year: number
  month: number
  day: number
  hour: number
  minute: number
  season: Season
}

export type GameSpeed = 0 | 1 | 2 | 5

// ─── Грузы и производство ──────────────────────────────────────────────────

/**
 * Всё в игре считается в ТОННАХ.
 *
 * Единица взята у самой отрасли, а не придумана. Это даёт бесплатную интуицию:
 * «ЗИЛ берёт 6 тонн» игрок понимает без объяснений, а «ЗИЛ берёт 6 условных
 * единиц» — нет. Тонны же связывают между собой грузоподъёмность, выпуск
 * завода, ставку за перевозку и вместимость склада — все эти числа
 * оказываются в одной системе и сравнимы напрямую.
 */
export type Tons = number

export type CargoType =
  // Сырьё — производится источниками, потребляется переработкой
  | 'зерно'
  | 'кругляк'
  | 'нефть'
  // Продукция — производится переработкой, потребляется городами
  | 'мука'
  | 'пиломатериалы'
  | 'топливо'

export type IndustryType =
  // Источники: производят без входного сырья. Так смоделирована связь с миром
  // за пределами карты — зерно растёт в поле, нефть приходит по трубе.
  | 'элеватор'
  | 'лесозаготовка'
  | 'нефтебаза'
  // Переработка: вход → выход. Здесь и живёт вся логистическая головоломка.
  | 'мукомольный'
  | 'ЦБК'
  | 'НПЗ'

/**
 * Рецепт производства.
 *
 * Данные, а не код: добавление цепочки не должно требовать правки симуляции.
 */
export type Recipe = {
  industryType: IndustryType
  /** Пусто у источников. */
  inputs: { type: CargoType; perUnit: number }[]
  output: CargoType
  /** Тонн выхода за сутки при полном снабжении и свободном складе. */
  dailyRate: Tons
}

export type Industry = {
  id: IndustryId
  type: IndustryType
  cityId: CityId
  /**
   * Склад: и входное сырьё, и готовая продукция в одном месте.
   *
   * Разделять их незачем — тип груза уже говорит, чем он здесь является, а
   * общий склад даёт ровно одно правило переполнения вместо двух.
   */
  stock: Partial<Record<CargoType, Tons>>
  /**
   * Доля от паспортной мощности в последнем тике, 0..1.
   *
   * Производное значение, но хранится: игроку нужно видеть, что завод стоит,
   * а не вычислять это самому. Ноль — предприятие остановлено.
   */
  utilization: number
  /**
   * Сколько тиков подряд предприятие простаивает.
   *
   * Долгий простой ведёт к деградации: мир должен наказывать бездействие, иначе
   * невывезенный завод просто ждёт игрока бесконечно.
   */
  idleTicks: number
}

// ─── Транспорт ─────────────────────────────────────────────────────────────

/**
 * Положение машины на карте.
 *
 * Машина либо стоит в узле, либо едет по ребру. Третьего не дано — это
 * упрощает и движение, и отрисовку, и сериализацию.
 */
export type VehiclePosition =
  | { kind: 'узел'; nodeId: CityId }
  | {
      kind: 'ребро'
      edgeId: EdgeId
      /** Откуда выехали — ребро само по себе ненаправленное. */
      fromId: CityId
      /** 0..1 — доля пройденного пути от fromId. */
      progress: number
    }

export type Vehicle = {
  id: VehicleId
  ownerId: CompanyId
  position: VehiclePosition
  /**
   * Оставшийся маршрут — города, которые предстоит посетить по порядку.
   * Пустой массив означает, что машина стоит без задания.
   */
  route: CityId[]

  /**
   * Линия, на которую назначена машина. null — работает разовыми рейсами.
   *
   * Назначенная машина сама достраивает себе маршрут до следующей остановки и
   * никогда не останавливается: дойдя до конца кольца, идёт на его начало.
   * Разовые рейсы остаются — ими удобно перегнать машину на новую линию и
   * попробовать плечо до того, как строить под него сеть.
   */
  lineId: LineId | null
  /** Индекс остановки линии, к которой машина сейчас едет. */
  stopIndex: number

  /**
   * Сколько тиков подряд машина стоит с грузом, который некому принять.
   *
   * Ждать при переполненном складе получателя — правильное поведение и честная
   * обратная связь: сеть везёт больше, чем потребляют. Ждать ВЕЧНО и молча —
   * нет. Без этого счётчика машина с грузом, которого никто на кольце не ждёт,
   * до конца партии возила бы его по кругу, исправно жгла зарплату и топливо и
   * показывала при этом идеальную метрику гружёного пробега.
   *
   * По достижении порога груз списывается за счёт перевозчика — так в отрасли
   * и поступают с невостребованной партией. Игрок видит убыток и причину.
   */
  blockedTicks: number
  /** Крейсерская скорость по идеальной дороге, км/ч. */
  cruiseKmh: number
  /**
   * Расход топлива, литров на 100 км.
   *
   * Главная статья переменных расходов и единственная, которая жжётся
   * одинаково что с грузом, что порожняком. Именно она превращает порожний
   * пробег из абстрактной метрики в деньги: холостое плечо стоит ровно
   * столько же топлива, сколько гружёное, а приносит ноль.
   */
  fuelPer100Km: number
  /** Накопленный пробег, км. */
  odometer: number

  /** Грузоподъёмность, тонн. */
  capacity: Tons
  /**
   * Что везёт. null — идёт порожняком.
   *
   * `originId` — город погрузки, и он обязателен. Тариф в перевозках считается
   * по кратчайшему маршруту между точками, а НЕ по фактическому пробегу
   * водителя: иначе кружение по карте становится способом заработка, а
   * доставка груза обратно в город, где его же и взяли, оплачивается как
   * настоящий рейс. Оба эксплойта закрываются одним этим полем.
   */
  cargo: { type: CargoType; tons: Tons; originId: CityId } | null

  /**
   * Разделение пробега на гружёный и порожний.
   *
   * Главная метрика мастерства во всей игре: процент километров, пройденных
   * пустым. Хороший игрок держит его ниже 15%. Хранится в двух счётчиках, а не
   * одним процентом, чтобы не терять точность при усреднении.
   */
  loadedKm: number
  emptyKm: number
}

// ─── Линии ─────────────────────────────────────────────────────────────────

/**
 * Остановка линии: где встать и что там сделать.
 *
 * Здесь и живёт единственное настоящее решение игрока. До линий погрузка была
 * автоматической — машина брала что дают и сдавала где примут, — и оптимизации
 * в этом не было никакой. Указав на каждой остановке, ЧТО грузить и ЧТО
 * выгружать, игрок проектирует поток груза по своей сети, а не отправляет
 * отдельные рейсы.
 *
 * Пустые списки — законное состояние: остановка может быть только для выгрузки,
 * только для погрузки или транзитной вовсе без работы.
 */
export type Stop = {
  nodeId: CityId
  /** Что выгрузить здесь, если это едет в кузове. */
  unload: CargoType[]
  /** Что взять здесь, если есть у кого. Порядок задаёт приоритет. */
  load: CargoType[]
}

/**
 * Линия — замкнутый маршрут с назначенным на него парком.
 *
 * После последней остановки машина идёт к первой: линия всегда кольцо, а не
 * отрезок. Это не упрощение, а прямое следствие главной механики игры. Отрезок
 * «туда» подразумевает возврат порожняком, и такая линия обязана выглядеть
 * плохо; кольцо же заставляет игрока с самого начала думать, чем гружёной
 * пойдёт обратная сторона. Обратная загрузка встроена в саму форму объекта.
 */
export type Line = {
  id: LineId
  name: string
  /** Замкнутая последовательность. Меньше двух остановок — линия не работает. */
  stops: Stop[]
  assignedVehicles: VehicleId[]
}

// ─── Компании ──────────────────────────────────────────────────────────────

/**
 * Игрок и конкуренты — одна и та же структура.
 * Логика компании пишется один раз, различие только в том, кто решает.
 */
export type Company = {
  id: CompanyId
  name: string
  money: number
  controller: 'человек' | 'скрипт' | 'модель'

  /** Линии компании. У конкурентов такие же — логика сети пишется один раз. */
  lines: Record<LineId, Line>

  /**
   * Итог последних игровых суток, рубли. Только для показа.
   *
   * Прибыль в тайкуне обязана быть видна как ПОТОК, а не как остаток на счету.
   * Растущие деньги при убыточной сети — обычное дело в начале партии: игрок
   * проедает стартовый капитал и узнаёт об этом, когда он кончился. Суточный
   * итог показывает беду сразу.
   */
  dailyRevenue: number
  dailyCosts: number

  /**
   * Компания разорена. Партия для неё окончена.
   *
   * Отдельный флаг, а не проверка «деньги меньше нуля»: уйти в минус на день —
   * нормально, а вот не выбраться из него — это конец, и момент наступления
   * конца должен быть зафиксирован явно.
   */
  bankrupt: boolean
  /** Сколько подряд суток компания сидит в минусе. */
  daysInDebt: number
}

// ─── Состояние игры ────────────────────────────────────────────────────────

export type GameState = {
  /** Состояние ГПСЧ. Записывается обратно после каждого использования. */
  rngState: number

  /** Сколько тиков прошло с начала партии. Дата выводится отсюда. */
  tick: number

  /** Год, с которого начинается партия. */
  startYear: number

  world: {
    cities: Record<CityId, City>
    edges: Record<EdgeId, Edge>
    industries: Record<IndustryId, Industry>
  }

  companies: Record<CompanyId, Company>
  playerId: CompanyId

  vehicles: Record<VehicleId, Vehicle>
}
