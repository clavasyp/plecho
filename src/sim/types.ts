/** Профиль города определяет, какие предприятия у него в окрестностях. */
export type CityProfile =
  | 'столица'
  | 'промышленный'
  | 'аграрный'
  | 'транзитный'
  | 'ресурсный'

/**
 * Статическое описание города — то, что задано данными и не меняется.
 *
 * Отделено от City намеренно: src/data описывает мир, а не его состояние.
 * Складывать в файл данных пустой склад и нулевой счётчик снабжения — значит
 * смешивать «какая Тула есть» с «что с Тулой происходит прямо сейчас».
 */
export type CityStatic = {
  id: CityId
  name: string
  coord: LatLon
  /** Жителей на начало партии. Дальше величина живёт в City и меняется. */
  population: number
  profile: CityProfile
}

export type City = CityStatic & {
  /**
   * Жителей сейчас. Величина ДИНАМИЧЕСКАЯ: снабжаемый город растёт,
   * брошенный сжимается.
   *
   * Это главная обратная связь игры — наладил поставки, город вырос, спрос
   * вырос, и твоя сеть перестала справляться.
   */
  population: number

  /** Склад потребительских товаров, доставленных в город. */
  stock: Partial<Record<CargoType, Tons>>

  /**
   * Сколько подряд суток город получал всё, что ему нужно.
   *
   * Рост требует УСТОЙЧИВОГО снабжения, а не одной удачной поставки: иначе
   * выгоднее было бы завалить город разово и уехать.
   */
  suppliedDays: number
}

/** Класс дороги задаёт базовую скорость и пропускную способность. */
export type RoadClass = 'федеральная' | 'региональная' | 'местная'

export type Edge = {
  id: EdgeId
  from: CityId
  to: CityId
  /** Длина по дороге, не по прямой. */
  km: number
  class: RoadClass
  /** Обозначение трассы для интерфейса: «М-4», «Р-132». */
  route: string
  /** 0..1 — качество покрытия. Влияет на скорость и износ. */
  quality: number
}

