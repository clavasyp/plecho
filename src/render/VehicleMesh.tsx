function flushColors(mesh: InstancedMesh): void {
  const colors = mesh.instanceColor
  if (colors === null) return
  if (colors.usage !== DynamicDrawUsage) colors.setUsage(DynamicDrawUsage)
  colors.needsUpdate = true
}

