/**
 * Машины на карте.
 *
 * Здесь стык двух разных частот. Симуляция шагает редко — один тик это 15
 * игровых минут, и на ×1 их проходит несколько в секунду. Экран обновляется 60
 * раз в секунду. Если рисовать машину там, где её оставил последний тик, она
 * будет прыгать заметными скачками: на федеральной трассе за тик проезжается
 * около двадцати километров, то есть десятки пикселей.
 *
 * Поэтому позиция каждый кадр интерполируется между двумя снимками состояния —
 * `prev` и `state` из стора — по доле `clock.alpha`, которую крутит игровой
 * цикл. Симуляция при этом остаётся дискретной и детерминированной:
 * интерполяция живёт только в рендере и ни на что не влияет.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: `alpha` читается напрямую из мутируемого объекта
 * `clock` внутри `useFrame`, а состояние — через `useGameStore.getState()`.
 * Ни то, ни другое не подписано на React. Подписка на величину, меняющуюся
 * каждый кадр, означала бы перерисовку дерева компонентов 60 раз в секунду —
 * это дороже, чем вся отрисовка сцены вместе взятая. Компонент рендерится
 * ровно тогда, когда меняется ёмкость буфера инстансов, то есть почти никогда.
 *
 * Инстансинг: машин со временем сотни, и все они одинаковой формы. Три
 * `InstancedMesh` — это три вызова отрисовки на весь парк вместо трёх на
 * машину. Почему именно три, а не два, разобрано ниже, у признака остановки.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * ЧТО СРЕЗ 4 ИЗМЕНИЛ ЗДЕСЬ. До него машина была одна и безликая, и метка ей
 * годилась любая. Теперь у парка есть три различия, которые игрок принимает как
 * РЕШЕНИЯ, и все три обязаны быть видны с высоты, не наводя мышь:
 *
 *   ЧТО ЭТО ЗА МАШИНА — размер кузова (класс и грузоподъёмность);
 *   ГОТОВА ЛИ ОНА РАБОТАТЬ — есть ли кузов вообще (прицеп) и горит ли кабина;
 *   ЕСТЬ ЛИ В НЕЙ ГРУЗ — температура кузова, как и раньше.
 *
 * Ни одно из трёх не добавляет в сцену нового цвета: стилевой замок остаётся
 * прежним — тёплое одно, светится только оно.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * ЧТО СРЕЗ 6 ИЗМЕНИЛ ЗДЕСЬ: НА КАРТЕ ПОЯВИЛИСЬ ЧУЖИЕ МАШИНЫ.
 *
 * До этого среза владелец не спрашивался ни разу, и это было честно: парк на
 * карте был только один. Теперь конкурентов трое, у каждого свой грузовик с
 * первого тика, и без различения владельца игрок видел бы вчетверо больший
 * собственный парк — то есть карта врала бы про главное.
 *
 * ЧЕМ РАЗЛИЧАТЬ. Цветом нельзя: тёплый тон в палитре ровно один, он означает
 * «сюда смотри» и принадлежит игроку (palette.ts). Раздай конкурентам синий и
 * зелёный — и замок, на котором держится вся картинка, ломается ради вещи,
 * которая на общем плане занимает три пикселя. Значит канал должен быть не
 * тональный, и он взят ГЕОМЕТРИЧЕСКИЙ — тот же приём, которым в LineMesh
 * различаются линии:
 *
 *   СВОЯ МАШИНА — ОБЪЁМ. Две коробки на дороге: кабина и кузов, у работающей
 *   кабина светится и уходит в блум.
 *
 *   ЧУЖАЯ МАШИНА — ПЛОСКОСТЬ. Одна плита в длину сцепа, лежащая на полотне:
 *   без деления на кабину и кузов, без свечения, без тени, в приглушённом
 *   ХОЛОДНОМ тоне интерфейса.
 *
 * ПОЧЕМУ ЭТО РАБОТАЕТ В ОБЕ СТОРОНЫ, а именно этого требует срез — «чужое не
 * должно спорить за внимание со своим, но должно быть видно».
 *
 *   НЕ СПОРИТ. Внимание в этой сцене выигрывают три вещи разом: тепло, свечение
 *   и высота. У чужой машины нет ни одной из трёх — она холодная, матовая и
 *   плоская, то есть проигрывает своей по всем каналам сразу, а не «немножко
 *   темнее».
 *
 *   ВИДНО. Плита светлее любой дороги (textDim против roadFederal — вдвое с
 *   лишним по относительной яркости) и заметно светлее рельефа, поэтому силуэт
 *   читается на любом фоне, по которому машина может ехать. А главное — она
 *   ДВИЖЕТСЯ, и движение глаз ловит без всякой яркости.
 *
 * ПОЧЕМУ ПЛОСКОЕ НЕ ПУТАЕТСЯ НИ С ОДНИМ СОСТОЯНИЕМ СВОЕЙ МАШИНЫ. Своя машина
 * бывает погашенной (сломана, без водителя) — но она при этом остаётся ДВУМЯ
 * КОРОБКАМИ С ВЫСОТОЙ. Различие «объём против плоскости» ортогонально всем трём
 * признакам среза 4 и потому не отнимает ни одного из них.
 *
 * ЧЕГО ЧУЖАЯ МАШИНА НЕ ПОКАЗЫВАЕТ — ГРУЖЕНА ЛИ ОНА. Это не экономия на мешах, а
 * то же правило, по которому в LineMesh чужая сеть рисуется следом, а не схемой:
 * с обочины видно, ЧТО за машина и КУДА она едет, но не что у неё в кузове.
 * Класс (длина плиты) и курс остаются — их видно и в жизни.
 *
 * ─────────────────────────────────────────────────────────────────────────
 * НОЧЬЮ У МАШИН ГОРЯТ ФАРЫ.
 *
 * Партия начинается 1 января в полночь (sim/state.ts), то есть ПЕРВЫЙ ЖЕ КАДР
 * игры — ночной, и до сих пор ночь на карте не значила ничего: свет, тон и
 * машины выглядели одинаково в любой час. Теперь у едущей машины впереди лежит
 * луч.
 *
 * ЭТО ТОТ САМЫЙ СЛУЧАЙ, РАДИ КОТОРОГО В ПАЛИТРЕ ЗАВЕДЁН СВЕТЯЩИЙСЯ АКЦЕНТ.
 * Замок «светится только акцент» не нарушается ни на волос: луч — того же
 * оранжевого, что и кабина, и никакого нового цвета в сцену не приходит. Он
 * кладётся СЛОЖЕНИЕМ поверх кадра (единственный физически верный способ рисовать
 * свет: свет не закрашивает поверхность, а добавляется к ней) и гаснет к
 * дальнему концу через вершинный цвет, поэтому у него нет ни границы, ни
 * силуэта — есть только пятно света на асфальте.
 *
 * КОГДА ЛУЧ ГОРИТ — три условия сразу, и каждое отсекает состояние, которое иначе
 * соврало бы: темно, машина НА ПЕРЕГОНЕ и машина НА ХОДУ. Разбор всех трёх, а
 * заодно и того, почему у конкурентов фар нет, — в шапке vehicleLights.ts. Там же
 * живёт вся арифметика ночи: она чистая и проверяется юнит-тестом, здесь остаются
 * только матрицы.
 *
 * ОТКУДА БЕРЁТСЯ НОЧЬ. Из общего буфера атмосферы (`atmosphere` в sky.ts) — того
 * же, из которого Scene берёт свет, туман и цвет неба. Своей кривой суток у фар
 * НЕТ и быть не должно: две синусоиды, посчитанные в разных файлах, однажды
 * разойдутся на четверть часа, и получится кадр, где небо ещё дневное, а фары
 * уже горят. Буфер читается так же, как `clock.alpha`: без подписки, прямо в
 * кадре, ровно тем слоем, которому он нужен.
 */

