/**
 * Пиксельный пол для лент: дорог и линий.
 *
 * ЗАЧЕМ. Ширина ленты живёт в километрах — так и должно быть, иначе масштаб
 * карты перестаёт ощущаться (разбор в шапке RoadMesh.tsx). Но у километров есть
 * граница снизу, за которой они перестают быть видимыми вообще. Замер на
 * «стране целиком»: при 4 км на пиксель федеральная трасса шириной 3.4 км даёт
 * 0.85 пикселя, региональная 0.58, местная 0.35, своя линия 0.42, чужая 0.21.
 *
 * Полоса тоньше пикселя не становится тусклее — она становится ПУНКТИРНОЙ.
 * Растеризатор берёт фрагмент, только если центр пикселя попал внутрь
 * треугольника, поэтому такая лента то попадает, то нет, и дорога рассыпается в
 * рваную цепочку точек, которая ещё и мерцает при панораме. Сглаживание здесь не
 * помогает: SMAA работает по готовому кадру и восстановить не взятую выборку не
 * может. Именно в этом виде игрок и увидел карту страны — «дорог нет».
 *
 * ЧТО ДЕЛАЕТСЯ. Лента, оказавшаяся тоньше своего пола, раздвигается ровно до
 * него — и ни на пиксель больше. На рабочем зуме множитель равен единице, то
 * есть в игре, где игрок проводит почти всё время, не меняется ничего: правка
 * работает только там, где без неё объекта на экране просто нет.
 *
 * ─── ПОЧЕМУ В ШЕЙДЕРЕ, А НЕ ПЕРЕСБОРКОЙ БУФЕРА ─────────────────────────────
 *
 * Ширина зависит от зума, зум меняется каждым колесом мыши. Пересборка вершин
 * означала бы перезаливку всей дорожной сети страны на каждый кадр зума — ровно
 * та беда, которую в этом проекте уже ловили прибором: 294 буфера вершин за
 * десять секунд при полностью неизменной геометрии (tests/e2e/perf.spec.ts).
 * В шейдере это стоит двух умножений матрицы на вершину и НУЛЯ буферов.
 *
 * ─── ПОЧЕМУ СЧЁТ ИДЁТ В ОТСЕЧЕНИИ, А НЕ «КИЛОМЕТРОВ НА ПИКСЕЛЬ» ────────────
 *
 * Соблазнительно посчитать на процессоре одно число — сколько километров в
 * пикселе — и раздать его шейдеру. Для этой камеры так НЕЛЬЗЯ, и это не
 * придирка. Проекция изометрическая: точка мира ложится на экран как
 * ((x − z)/√2, (x + z)/√6). Значит километр вдоль одной диагонали занимает на
 * экране в √3 раз больше пикселей, чем километр вдоль другой, и одного числа на
 * все направления не существует. Дорога Москва — Тула и дорога Москва — Тверь
 * получили бы разный пол при одинаковой ширине.
 *
 * Поэтому каждая вершина считает СВОЙ размер сама: проецирует и себя, и точку на
 * оси ленты, и меряет расстояние между ними в пикселях кадрового буфера. Это
 * точно при любой ориентации ребра, при любом угле поворота камеры и при
 * перспективе тоже — хотя камера здесь ортографическая.
 *
 * ─── ЧТО ЭТИМ ЛЕЧИТЬ НЕЛЬЗЯ ────────────────────────────────────────────────
 *
 * ОКНА И ОГРАДЫ — НЕТ, и это записано здесь, чтобы следующий раз не пришлось
 * выяснять заново. Окно в силуэте города — квадрат порядка 0.2 пикселя; пол в
 * полтора пикселя увеличил бы его площадь в пятьдесят раз, и застройка на общем
 * плане превратилась бы в сплошное свечение. Стилевой замок §15 говорит, что
 * светится ровно один тёплый акцент; раздутые окна отменяют его целиком.
 * Пиксельный пол осмыслен только для ЛЕНТ — объектов, у которых одна размерность
 * (длина) остаётся крупной, а вторая (ширина) уходит под пиксель. Точка, у
 * которой мелки обе размерности, должна не толстеть, а ИСЧЕЗАТЬ — этим и
 * занимается отбор подписей и уровней детализации.
 */

import { Vector2 } from 'three'
import type { Material, WebGLProgramParametersWithUniforms } from 'three'
import { useThree, useFrame } from '@react-three/fiber'

/**
 * Полы, пиксели полной ширины ленты.
 *
 * ПОРЯДОК ВЕЛИЧИН СОХРАНЁН, ПРОПОРЦИИ — НЕТ, и это осознанный размен. Настоящие
 * ширины относятся как 3.4 : 2.3 : 1.4, то есть 2.43 : 1.64 : 1. Удержать эту
 * пропорцию на полу значило бы поставить местную дорогу на 0.9 пикселя, то есть
 * оставить её ровно в том состоянии, ради выхода из которого всё и делается.
 * Ниже пикселя пропорцию показать НЕЧЕМ — там уже нет места, где ей проявиться.
 * Поэтому на полу классы отказываются от точного отношения ради того, чтобы
 * остаться различимыми вообще, и лестница «федеральная толще региональной толще
 * местной» цела.
 *
 * Числа выведены из одного требования: полтора пикселя — минимум, при котором
 * растеризатор берёт полосу на КАЖДОМ шаге вдоль неё, при любом наклоне. При
 * 1.0 полоса под углом 45° начинает пропускать пиксели через один. Единица
 * оставлена только чужому следу — он и по замыслу на грани видимости, это
 * «след на обочине», а не объект внимания (разбор в шапке LineMesh.tsx).
 */
export const PIXEL_FLOOR = {
  roadFederal: 2.2,
  roadRegional: 1.7,
  roadLocal: 1.3,
  /** Своя невыбранная линия: тоньше федеральной трассы, толще чужого следа. */
  lineOwn: 1.6,
  /** Выбранная линия забирает акцент и обязана читаться первой. */
  lineSelected: 2.6,
  /** Чужой след: единственный, кому позволено остаться на грани. */
  lineRival: 1.0,
} as const

/**
 * Имя атрибута со СМЕЩЕНИЕМ ВЕРШИНЫ ОТ ОСИ ЛЕНТЫ, в километрах сцены.
 *
 * Именно смещение, а не нормаль и не полуширина по отдельности: шейдеру нужно
 * знать и направление, и величину, а хранить их двумя атрибутами значит завести
 * два факта об одном и том же и однажды их рассинхронизировать. Из смещения
 * восстанавливается ось (`position − aWiden`), и это всё, что нужно.
 *
 * Вершина, лежащая ровно на оси, имеет нулевое смещение и не двигается никогда —
 * поэтому продлённые концы ленты и стыки сами собой остаются на месте.
 */
export const WIDEN_ATTRIBUTE = 'aWiden'

/**
 * Половина размера кадрового буфера в пикселях — общий уникум на все ленты.
 *
 * Половина, а не полный размер, потому что отсечённые координаты приходят в
 * диапазоне −1…1: перевод в пиксели это умножение ровно на половину стороны.
 * Считать это в шейдере на каждую вершину незачем.
 *
 * Объект ОДИН на все материалы: three кладёт его по ссылке в карту униформов
 * каждой программы, и обновление в одном месте доезжает до всех лент разом.
 * Размер именно КАДРОВОГО БУФЕРА, а не окна: плотность пикселей здесь считает
 * renderScale (App.tsx) и она может быть меньше плотности экрана — растеризация
 * идёт в буфере, и «пиксель» в этом файле означает пиксель буфера.
 */
export const pixelFloorResolution = { value: new Vector2(1, 1) }

/** Многоразовый приёмник размера буфера: в кадре аллокаций нет. */
const bufferSize = new Vector2()

/**
 * Объявления, которые дописываются в начало вершинной программы.
 *
 * `attribute` и `varying` здесь корректны и на WebGL2: three компилирует
 * встроенные материалы с приставкой, в которой стоят `#define attribute in` и
 * `#define varying out`, — то есть исходник остаётся на диалекте 1.00, а
 * преобразованием занимается сам движок.
 */
const DECLARATIONS = `
attribute vec3 ${WIDEN_ATTRIBUTE};
uniform vec2 uPixelFloorHalfRes;
uniform float uPixelFloorMinHalfPx;
`

/** Куда вставляется тело: вслед за объявлением `transformed`. */
const ANCHOR = '#include <begin_vertex>'

/**
 * Тело пола.
 *
 * Считается ДО всех остальных преобразований вершины, сразу за begin_vertex:
 * дальше по цепочке идут скиннинг, морфинг и смещения, и вмешиваться в их
 * результат значило бы мерить пиксели уже сдвинутой геометрии.
 *
 * Порог `1e-4` отсекает вершины на оси: у них смещение нулевое, делить на их
 * экранный размер нельзя, а двигать их и не требуется.
 */
const BODY = `
{
  vec3 axisPoint = transformed - ${WIDEN_ATTRIBUTE};
  vec4 clipAxis = projectionMatrix * modelViewMatrix * vec4(axisPoint, 1.0);
  vec4 clipEdge = projectionMatrix * modelViewMatrix * vec4(transformed, 1.0);
  vec2 pxAxis = clipAxis.xy / max(abs(clipAxis.w), 1e-6) * uPixelFloorHalfRes;
  vec2 pxEdge = clipEdge.xy / max(abs(clipEdge.w), 1e-6) * uPixelFloorHalfRes;
  float halfPx = length(pxEdge - pxAxis);
  if (halfPx > 1e-4 && halfPx < uPixelFloorMinHalfPx) {
    transformed += ${WIDEN_ATTRIBUTE} * (uPixelFloorMinHalfPx / halfPx - 1.0);
  }
}
`

/**
 * Ключ кэша программ.
 *
 * Нужен обязательно. Three кэширует скомпилированные программы, и по умолчанию
 * ключ материала — исходный текст его `onBeforeCompile`. Функция ниже одна на
 * все ленты, поэтому все они честно делят ОДНУ программу; а вот от материалов
 * того же класса БЕЗ пола (силуэты, площадки, техника) ключ их отличает, и
 * подмены не будет.
 *
 * Пол приходит униформом, а не текстом программы, — поэтому лента с полом 2.2 и
 * лента с полом 1.0 остаются одной программой. Это и есть причина, по которой
 * число не зашивается в исходник.
 */
const CACHE_KEY = 'plecho-pixel-floor-v1'

/**
 * Повесить пиксельный пол на материал ленты.
 *
 * Материал после этого ОБЯЗАН получать геометрию с атрибутом `aWiden` — без
 * него драйвер подставит нули, смещение окажется нулевым, и пол просто не
 * сработает ни на одной вершине. Молча: ошибки компиляции не будет. Поэтому
 * сборщики буферов (RoadMesh, LineMesh) складывают позиции и смещения в одном
 * цикле, а не в двух — чтобы забыть одно из двух было физически неудобно.
 */
export function attachPixelFloor(material: Material, minWidthPx: number): void {
  const minHalfPx = { value: minWidthPx / 2 }

  material.onBeforeCompile = (
    shader: WebGLProgramParametersWithUniforms,
  ): void => {
    shader.uniforms.uPixelFloorHalfRes = pixelFloorResolution
    shader.uniforms.uPixelFloorMinHalfPx = minHalfPx
    shader.vertexShader =
      DECLARATIONS + shader.vertexShader.replace(ANCHOR, ANCHOR + BODY)
  }

  material.customProgramCacheKey = (): string => CACHE_KEY

  // Материал мог быть уже собран к моменту, когда до него дошла эта строка:
  // ref у mesh срабатывает после создания материала, а первый кадр может
  // случиться раньше следующей перерисовки.
  material.needsUpdate = true
}

/**
 * Держать размер кадрового буфера в актуальном состоянии.
 *
 * Вызывается ОДИН раз, из Scene: это общий на всю сцену уникум, и обновлять его
 * из каждой ленты значило бы делать одну и ту же работу трижды за кадр.
 *
 * Спрашивается именно `getDrawingBufferSize`, а не `state.size`: между ними
 * лежит плотность пикселей из renderScale, и на мониторе с ретиной они
 * отличаются вдвое. Пол, посчитанный по размеру окна, промахнулся бы ровно во
 * столько же раз.
 */
export function usePixelFloor(): void {
  const gl = useThree((state) => state.gl)

  useFrame(() => {
    gl.getDrawingBufferSize(bufferSize)
    pixelFloorResolution.value.set(bufferSize.x / 2, bufferSize.y / 2)
  })
}
