/**
 * Пустой обработчик перекрытия. Один на модуль: новая функция на каждый рендер
 * заставляла бы drei переподписываться на каждом кадре.
 */
const noHiding = (): void => {}

export function Cities(): JSX.Element {
  /*
   * ПОДПИСКА НА РЕЕСТР, А НЕ НА ОБЪЕКТЫ ГОРОДОВ.
   *
   * Здесь стоял useShallow по самим объектам City с пояснением «сами объекты не
   * меняются». Это перестало быть правдой: население дрейфует КАЖДЫЙ ТИК у всех
   * пятидесяти трёх городов (рост и сжатие в economy/consumption.ts), поэтому
   * поверхностное сравнение не отсекало ничего, и вся застройка страны
   * пересобиралась по несколько раз в секунду — впустую, потому что силуэт
   * выходил бит в бит тот же.
   *
   * Ключ — идентификаторы плюс население, ОКРУГЛЁННОЕ до процента. Округление
   * здесь и есть решение: силуэт считается от населения, но десятая доля
   * процента его не двигает, а сравнение без округления меняется каждый тик.
   * Тот же приём уже применён в BuildingMesh и IndustryMesh.
   */
  const roster = useGameStore((store) =>
    Object.values(store.state.world.cities)
      .map((city) => `${city.id}:${Math.round(city.population / 1000)}`)
      .join('|'),
  )
  const cities = useGameStore.getState().state.world.cities

  /*
   * СТУПЕНЬ ПЛОТНОСТИ ПОДПИСЕЙ — от текущего зума камеры.
   *
   * Считается в кадре, а в состояние попадает только при СМЕНЕ ступени: зум
   * меняется непрерывно, и перерисовывать дерево на каждый его пиксель нельзя.
   */
  const camera = useThree((state) => state.camera)
  const viewport = useThree((state) => state.size)
  const [tier, setTier] = useState(LABEL_TIERS - 1)

  useFrame(() => {
    const zoom = (camera as THREE.OrthographicCamera).zoom
    if (!Number.isFinite(zoom) || zoom <= 0) return

    /*
     * Ортографическая камера кладёт на пиксель ровно 1/zoom единиц мира, а
     * единица мира здесь — километр (см. projection.ts). Значит ширина кадра в
     * километрах считается точно, без всяких наблюдений за поведением камеры.
     */
    const visibleKm = viewport.width / zoom

    const share =
      (FULL_MAP_KM - visibleKm) / (FULL_MAP_KM - CLOSE_UP_KM)
    const clamped = Math.min(1, Math.max(0, share))
    const next = Math.round(clamped * (LABEL_TIERS - 1))

    if (next !== tier) setTier(next)
  })

  const layout = useMemo(() => {
    const items = Object.values(cities).map((city) => {
      const form = cityForm(city)
      const at = cityPoint(city)

      return { city, at, form, blocks: blocksOf(form) }
    })

    return {
      items,
      buildings: items.flatMap((item) =>
        item.blocks.buildings.map((building) => ({
          x: item.at.x + building.x,
          z: item.at.z + building.z,
          width: building.width,
          depth: building.depth,
          height: building.height,
          yaw: building.yaw,
          // Тон по высоте: высокое — светлее. Один и тот же признак кодируется
          // дважды, силуэтом и тоном, поэтому иерархия читается даже там, где
          // силуэт съеден перспективой или туманом.
          tone: building.tone,
        })),
      ),
      windows: items.flatMap((item) =>
        item.blocks.windows.map((light) => ({
          x: item.at.x + light.x,
          y: light.y,
          z: item.at.z + light.z,
          yaw: light.yaw,
          size: light.size,
        })),
      ),
      pads: items.map((item) => ({
        x: item.at.x,
        z: item.at.z,
        radiusX: item.form.radiusX,
        radiusZ: item.form.radiusZ,
        yaw: item.form.grid,
      })),
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [roster])

  const pads = useMemo(() => buildPads(layout.pads), [layout.pads])

  const mesh = useRef<THREE.InstancedMesh>(null)
  const windowMesh = useRef<THREE.InstancedMesh>(null)
  const windowMaterial = useRef<THREE.MeshBasicMaterial>(null)

  useLayoutEffect(() => {
    const target = mesh.current
    if (!target) return

    const matrix = new THREE.Matrix4()
    const quaternion = new THREE.Quaternion()
    const position = new THREE.Vector3()
    const scale = new THREE.Vector3()
    const axis = new THREE.Vector3(0, 1, 0)

    const low = new THREE.Color(palette.buildingLow)
    const high = new THREE.Color(palette.buildingHigh)
    const color = new THREE.Color()

    layout.buildings.forEach((building, index) => {
      // Коробка BoxGeometry центрирована, а здание стоит на земле — отсюда
      // подъём на половину высоты.
      position.set(building.x, layers.buildingBase + building.height / 2, building.z)
      quaternion.setFromAxisAngle(axis, building.yaw)
      scale.set(building.width, building.height, building.depth)

      target.setMatrixAt(index, matrix.compose(position, quaternion, scale))
      target.setColorAt(index, color.lerpColors(low, high, building.tone))
    })

    target.instanceMatrix.needsUpdate = true
    if (target.instanceColor) target.instanceColor.needsUpdate = true

    // Без этого отсечение по пирамиде видимости считает габариты по исходной
    // коробке 1×1×1 в начале координат, и вся застройка исчезает, стоит увести
    // камеру от нуля.
    target.computeBoundingSphere()

    const lights = windowMesh.current
    if (!lights) return

    layout.windows.forEach((light, index) => {
      position.set(light.x, light.y, light.z)
      quaternion.setFromAxisAngle(axis, light.yaw)
      scale.set(light.size, light.size, light.size)
      lights.setMatrixAt(index, matrix.compose(position, quaternion, scale))
    })

    lights.instanceMatrix.needsUpdate = true
    lights.computeBoundingSphere()
    // Днём окон нет, и меш обязан стартовать погашенным: иначе первый кадр
    // партии, которая начинается в полночь 1 января, вспыхнет полным светом
    // раньше, чем useFrame успеет посчитать час.
    lights.visible = false
  }, [layout])

  /**
   * Единственная работа этого файла в кадре — одно число.
   *
   * Ни одного объекта не создаётся и ни одной подписки не заводится: доля
   * дневного света уже посчитана Scene и лежит в общем буфере, отсюда её
   * остаётся только прочитать. Гасить меш целиком важнее, чем кажется: днём это
   * снимает со сцены сотни прозрачных инстансов вместе с их сортировкой и целым
   * вызовом отрисовки.
   */
  useFrame(() => {
    const material = windowMaterial.current
    const lights = windowMesh.current
    if (material === null || lights === null) return

    const opacity = windowGlow(atmosphere.daylight)

    material.opacity = opacity
    lights.visible = opacity > GLOW_EPSILON
  })

  /**
   * Дев-хук: что НА САМОМ ДЕЛЕ нарисовано, а не что посчитано.
   *
   * Числа берутся с живых InstancedMesh, а формы — из разложенного макета. Тот
   * же довод, что у __plechoBuildings: посчитать матрицы и не смонтировать меш —
   * ровно тот отказ, которого юнит-тест не видит по устройству. В
   * продакшен-сборке ветка вырезается целиком: import.meta.env.DEV — константа
   * этапа сборки.
   */
  useEffect(() => {
    if (!import.meta.env.DEV) return

    const dev = globalThis as unknown as { __plechoCities?: unknown }

    dev.__plechoCities = () => ({
      cities: layout.items.map((item) => ({
        id: item.city.id,
        profile: item.city.profile,
        population: item.city.population,
        radiusX: item.form.radiusX,
        radiusZ: item.form.radiusZ,
        peak: item.form.peak,
        top: item.blocks.top,
        buildings: item.blocks.buildings.length,
        windows: item.blocks.windows.length,
      })),
      boxes: mesh.current?.count ?? 0,
      windows: windowMesh.current?.count ?? 0,
      glow: windowMaterial.current?.opacity ?? 0,
      lit: windowMesh.current?.visible ?? false,
    })

    return () => {
      delete dev.__plechoCities
    }
  }, [layout])

  /*
   * КОГО ПОДПИСЫВАЕМ НА ЭТОЙ СТУПЕНИ.
   *
   * Крупные города получают имя всегда, мелкие — по мере приближения. Порядок
   * отбора строго по населению, поэтому на любом масштабе подписаны САМЫЕ
   * ЗНАЧИМЫЕ из видимых, а не случайные: карта, на которой подписан Тобольск, но
   * не Москва, читалась бы как ошибка.
   */
  const named = useMemo(() => {
    const share = tier / (LABEL_TIERS - 1)
    const budget = Math.round(
      LABELS_AT_FULL_MAP + (LABELS_AT_CLOSE_UP - LABELS_AT_FULL_MAP) * share,
    )

    return [...layout.items]
      .sort((a, b) => b.city.population - a.city.population)
      .slice(0, Math.max(1, budget))
  }, [layout, tier])

  return (
    <group>
      <mesh receiveShadow>
        <bufferGeometry>
          <bufferAttribute
            attach="attributes-position"
            args={[pads.positions, 3]}
          />
          <bufferAttribute
            attach="attributes-normal"
            args={[pads.normals, 3]}
          />
        </bufferGeometry>
        <meshStandardMaterial
          color={palette.terrainEdge}
          roughness={1}
          metalness={0}
        />
      </mesh>

      {layout.buildings.length > 0 && (
        <instancedMesh
          ref={mesh}
          // null! — идиома R3F: геометрия и материал приходят детьми, здесь
          // важно только третье значение, число экземпляров.
          args={[null!, null!, layout.buildings.length]}
          castShadow
          receiveShadow
        >
          <boxGeometry args={[1, 1, 1]} />
          {/* Цвет материала белый специально: instanceColor не заменяет цвет
              материала, а умножается на него, и любой другой оттенок здесь
              притушил бы всю палитру зданий разом. */}
          <meshStandardMaterial color="#ffffff" roughness={0.82} metalness={0} />
        </instancedMesh>
      )}

      {layout.windows.length > 0 && (
        <instancedMesh
          ref={windowMesh}
          args={[null!, null!, layout.windows.length]}
          // Тени выключены намеренно, обе. Окно — источник света, а не
          // препятствие ему; кубик в четверть метра всё равно не попал бы в
          // карту теней, где тексель покрывает около четырёхсот метров, зато
          // тысяча лишних объектов в проходе тени стоила бы вполне реальных
          // миллисекунд.
          castShadow={false}
          receiveShadow={false}
        >
          <boxGeometry args={[1, 1, 1]} />
          {/*
            Материал БЕЗ ОСВЕЩЕНИЯ и ровно один на все окна округа. Basic, а не
            standard с emissive, по двум причинам сразу: свет из окна не должен
            гаснуть вместе с ночным ключевым светом, и unlit-материал не считает
            ни одного источника на тысяче инстансов.

            Цвет — акцент палитры, единственный тёплый и единственный, которому
            позволено светиться. Тот же довод, что у ограды в IndustryMesh: замок
            ломается не цветом, а ПЛОЩАДЬЮ, и суммарная площадь окон ничтожна,
            поэтому самым ярким объектом ночной карты остаётся машина.
          */}
          <meshBasicMaterial
            ref={windowMaterial}
            color={palette.accent}
            transparent
            opacity={0}
          />
        </instancedMesh>
      )}

      {named.map((item) => (
        <Html
          key={item.city.id}
          center
          position={[item.at.x, item.blocks.top + LABEL_CLEARANCE, item.at.z]}
          // Подпись не должна перехватывать курсор: под ней панорамирование
          // карты, и «мёртвые» пятна вокруг городов ощущаются как поломка.
          pointerEvents="none"
          /*
           * ПУСТОЙ ОБРАБОТЧИК ПЕРЕКРЫТИЯ — И ЭТО НЕ ЗАГЛУШКА, А ЛЕЧЕНИЕ.
           *
           * drei решает, показывать ли подпись, по функции isObjectBehindCamera:
           * берёт вектор «камера → объект» и сравнивает его угол с направлением
           * взгляда; больше девяноста градусов — прячет. Для перспективной
           * камеры это верно, для ОРТОГРАФИЧЕСКОЙ — бессмысленно: у неё нет
           * точки схода, а ближняя плоскость у нас вообще отрицательная
           * (CAMERA_NEAR = −3500 в Scene.tsx), потому что карта тянется «за
           * спину» камере и обязана рисоваться.
           *
           * Пока карта была округом в 600 км, все города укладывались в переднюю
           * полусферу и это не проявлялось. На карте страны в 3700 км за
           * плоскость уходит половина: двадцать подписей не показывались на
           * первом же кадре, а после панорамирования исчезали Урал, Сибирь и юг
           * целиком — двадцать пять имён.
           *
           * Передав onOcclude, мы забираем у drei право трогать display (см. его
           * Html.js: `if (onOcclude) onOcclude(...) else el.style.display = ...`).
           * Прятать подписи по перекрытию нам не нужно вовсе — их видимость
           * решает ступень масштаба выше.
           */
          onOcclude={noHiding}
          zIndexRange={[20, 0]}
          style={{
            color:
              item.city.population >= MAJOR_POPULATION
                ? palette.text
                : palette.textDim,
            font: '600 10px/1 ui-sans-serif, system-ui, "Segoe UI", sans-serif',
            letterSpacing: '0.16em',
            textTransform: 'uppercase',
            whiteSpace: 'nowrap',
            userSelect: 'none',
            // Обводка цветом фона: подпись пересекает и тёмный рельеф, и
            // светлую застройку, и читаться должна на обоих.
            textShadow: `0 0 6px ${palette.background}, 0 0 3px ${palette.background}`,
          }}
        >
          {item.city.name}
        </Html>
      ))}
    </group>
  )
}
