  // не поднимается выше 1.57 (при 0.8). То есть «транзитный вытянут сильнее
  // любого оседлого» — не удача конкретных сидов, а свойство таблицы, и сквозной
  // тест силуэтов проверяет именно его.
  'транзитный': {
    radius: 1.12,
    peak: 0.7,
    count: 0.84,
    coreBias: 0.6,
    falloff: 1.15,
    aspectMin: 0.6,
    aspectMax: 0.74,
    landmarkChance: 0.03,
    landmarkFactor: 1.35,
    coreShare: 0,
    towerFactor: 1,
    slab: 1.8,
    yawJitter: 0.06,
  },

  // Компактное плотное пятно средней высоты. В ЦФО таких городов нет — профиль
  // заведён под расширение на Урал и Поволжье (об этом прямо сказано в
