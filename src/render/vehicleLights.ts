/**
 * Фары: единственное, что светится на карте по причине, а не по назначению.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ — та же причина, что и у roadSurface.ts: VehicleMesh
 * тянет Three, а vitest здесь ходит по чистому Node. Всё, что можно посчитать
 * числом — горят ли фары, насколько ярок луч, какой формы он лежит на асфальте,
 * — считается тут и проверяется тестом; в компоненте остаются матрицы.
 *
 * ─── ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА: НОЧЬ ЗДЕСЬ НЕ СЧИТАЕТСЯ ─────────────────────────
 *
 * Соблазн был ровно один и очень сильный: завести свою кривую суток от
 * `dayProgress(tick)` — десять строк, ни от кого не зависит, проверяется
 * мгновенно. Он отвергнут, и это самое важное, что записано в этом файле.
 *
 * Высоту солнца в проекте считает `sky.ts` — одной функцией на всю сцену, из
 * которой выведены свет, туман, цвет неба и подложки. Заведи фары вторую кривую
 * — и рано или поздно появится кадр, в котором небо ещё дневное, а фары уже
 * горят; разойтись двум синусоидам достаточно на пятнадцать минут, а искать
 * причину придётся в двух файлах сразу, ни один из которых не выглядит
 * неправильным. Ровно об этом предупреждает шапка sky.ts, и «ночные окна городов
 * и фары» названы там читателями буфера поимённо.
 *
 * Поэтому здесь есть ровно один перевод — `nightFrom`, и он берёт готовую долю
 * дневного света. Ни тика, ни календаря, ни сезона этот файл не видит вовсе.
 *
 * ПОЧЕМУ ОТ ЭТОГО СРАЗУ РАБОТАЕТ СЕЗОН. Доля дневного света в sky.ts выведена из
 * высоты солнца, а та поднята косинусом времени года. Значит зимой фары горят
 * почти всю смену водителя, а летом — считаные часы, и никакой отдельной
 * «зимней» ветки для этого писать не нужно: она уже написана один раз, в
 * астрономии сцены.
 *
 * ─── ПОЧЕМУ ФАРЫ ГОРЯТ НЕ У ВСЕХ ────────────────────────────────────────────
 *
 * Фара — не украшение ночи, а сообщение: ЭТА МАШИНА СЕЙЧАС ЕДЕТ. Отсюда три
 * условия сразу (см. beamsBurn), и каждое отсекает состояние, которое иначе
 * соврало бы:
 *
 *   ТЕМНО. Днём луч на асфальте не виден и в жизни — а на карте он был бы просто
 *   вторым оранжевым пятном рядом с машиной, то есть шумом поверх акцента.
 *
 *   МАШИНА НА ПЕРЕГОНЕ. Стоящая в городе машина фарами не светит: иначе ночная
 *   Москва, где на площадке стоит половина парка, превратилась бы в оранжевое
 *   зарево, из которого не выделить ни одной едущей фуры. А едущая фура — это и
 *   есть главный объект карты.
 *
 *   МАШИНА НА ХОДУ. Сломанная и брошенная без водителя не светят ничем — у них
 *   уже погашена кабина (CAB_BROKEN в VehicleMesh), и фары обязаны молчать
 *   вместе с ней. Тёмный сцеп на ночной трассе — самое тревожное, что может
 *   показать эта карта, и он обязан быть тёмным.
 *
 * ЧУЖИЕ МАШИНЫ НОЧЬЮ НЕ СВЕТЯТ, и это не забывчивость. Свечение в этой сцене
 * принадлежит акценту, акцент принадлежит игроку (palette.ts); раздай фары
 * конкурентам — и ночная карта станет ровно тем, чем не должна: россыпью
 * одинаковых огней, на которой своё уже не найти. Чужая плита видна и без фар:
 * материал у неё неосвещаемый, то есть темнота её не гасит (разбор — в
 * VehicleMesh, у RIVAL_TONE).
 */

// ─── Единственный перевод времени в свет ───────────────────────────────────

/**
 * Насколько темно: 0 — полный день, 1 — глухая ночь.
 *
 * На входе — `atmosphere.daylight` из sky.ts, и ничего другого сюда подставлять
 * нельзя. Перевод намеренно тривиален: вся форма суток — длина сумерек, разница
 * зимы и лета, склейка полуночи — уже заложена в самой доле дневного света, и
 * любое «уточнение» здесь означало бы вторую кривую суток рядом с первой.
 *
 * ГДЕ ФАРЫ ЗАГОРАЮТСЯ. Доля дневного света растёт от нуля, когда солнце ещё под
 * горизонтом, до единицы, когда оно поднялось заметно выше, — то есть в момент,
 * когда солнце касается горизонта, темнота уже около 0.85. Это и есть привычное
 * «фары включают в сумерках, а не когда стемнело», полученное без единого
 * отдельного правила.
 */
export function nightFrom(daylight: number): number {
  if (!Number.isFinite(daylight)) return 0
  return daylight < 0 ? 1 : daylight > 1 ? 0 : 1 - daylight
}

// ─── Когда фары горят ──────────────────────────────────────────────────────

/**
 * Ниже этой темноты фары не рисуются вовсе.
 *
 * Не косметический порог, а экономия целого прохода отрисовки: при нуле
 * инстансов меш не попадает на видеокарту (count = 0 отсекает до вершинного
 * шейдера), и днём вся эта машинерия стоит ровно ничего. Два процента — это
 * первые минуты сумерек, когда луч всё равно неотличим от нуля.
 */
export const BEAM_MIN_NIGHT = 0.02

/** Горят ли фары у машины. Разбор трёх условий — в шапке файла. */
export function beamsBurn(night: number, onRoad: boolean, stalled: boolean): boolean {
  return night >= BEAM_MIN_NIGHT && onRoad && !stalled
}

// ─── Форма луча ────────────────────────────────────────────────────────────

/**
 * Длина луча перед машиной, км.
 *
 * Соразмерна сцепу (9 км у базового класса) и заметно короче самого короткого
 * плеча карты (110 км, Тула — Калуга): луч читается как принадлежность машины, а
 * не как самостоятельный объект на дороге. На полностью отдалённой камере
 * (примерно 0.75 км на пиксель) это семнадцать пикселей — то есть ровно та
 * величина, из-за которой едущую ночью фуру видно там, где сама она занимает
 * три пикселя.
 */
export const BEAM_LENGTH_KM = 13

/** Полуширина луча у капота: чуть уже кабины — свет выходит из фар, а не из бортов. */
export const BEAM_NEAR_HALF_KM = 0.9

/**
 * Полуширина луча на дальнем конце.
 *
 * Полторы ширины федерального полотна (3.4 км) намеренно: свет не считается с
 * границей асфальта и захватывает обочину — именно по этому расхождению луч
 * читается как свет, а не как ещё одна лента разметки поверх дороги.
 */
export const BEAM_FAR_HALF_KM = 2.5

/**
 * Яркость луча в глухую ночь.
 *
 * Меньше единицы, и это принципиально. Луч кладётся СЛОЖЕНИЕМ поверх готового
 * кадра, то есть он всегда светлее того, на что лёг; при полной яркости он
 * перебивал бы саму кабину — единственное тело сцены, которому положено быть
 * ярчайшим. Восемь десятых оставляют кабину впереди и при этом заводят луч на
 * порог свечения (0.55 в postFx), так что в блум он попадает и мягкое гало
 * вокруг фуры появляется.
 */
export const BEAM_PEAK = 0.8

/** Насколько ярок луч при такой темноте. */
export function beamStrength(night: number): number {
  const t = clampUnit(night)
  return BEAM_PEAK * t
}

/**
 * Свечение кабины днём и ночью.
 *
 * Дневное значение — ровно то, что стояло в VehicleMesh до появления фар:
 * машина остаётся такой же, какой была, и ничего не «чинится» задним числом.
 * Ночью кабина разгорается — не ради красоты, а потому, что ночью падает
 * освещённость всей сцены (sky.ts гасит ключ до лунного), и постоянное свечение
 * на потемневшем фоне читалось бы СЛАБЕЕ, чем днём, хотя должно наоборот.
 */
export const CAB_GLOW_DAY = 1.15
export const CAB_GLOW_NIGHT = 1.8

/** Свечение кабины при такой темноте. */
export function cabGlow(night: number): number {
  return CAB_GLOW_DAY + (CAB_GLOW_NIGHT - CAB_GLOW_DAY) * clampUnit(night)
}

function clampUnit(value: number): number {
  if (!Number.isFinite(value)) return 0
  return value < 0 ? 0 : value > 1 ? 1 : value
}
