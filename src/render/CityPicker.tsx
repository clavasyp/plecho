import { useMemo, useState } from 'react'
import type { JSX } from 'react'
import { useGameStore } from '../app/store'
import type { CityId } from '../sim/types'
import { useLineSelection } from '../ui/lineSelection'
import { useSelection } from '../ui/selection'
import { cityPoint } from './CityMesh'
import { layers } from './layers'
import { palette } from './palette'

/**
 * Кликабельные цели по городам.
 *
 * Отдельный слой невидимых сфер, а не обработчик на самой застройке. Причина
 * простая: застройка рисуется одним InstancedMesh на все города сразу, и по
 * попаданию пришлось бы вычислять, какому городу принадлежит инстанс, — а сфера
 * ещё и попадает по промежутку между зданиями, тогда как в силуэт нужно ещё
 * прицелиться.
 *
 * КЛИК ВЫБИРАЕТ ГОРОД, А НЕ ОТПРАВЛЯЕТ МАШИНУ. Раньше было наоборот, и это
 * оказалось прямой ошибкой: указание на объект и команда транспорту — разные
 * действия, а разделял их один и тот же жест. Промахнулся мимо города —
 * потерял рейс; захотел просто посмотреть, что там с заводом, — тоже потерял
 * рейс. Теперь клик открывает панель города (ui/CityPanel.tsx), а отправка
 * стала кнопкой внутри неё: необратимое действие требует отдельного нажатия.
 *
 * ─── РЕЖИМ ДОБАВЛЕНИЯ ОСТАНОВОК (срез 3) ─────────────────────────────────────
 *
 * Пока редактор линий не в режиме добавления, всё как было: клик выбирает
 * город. В режиме добавления тот же клик ДОПИСЫВАЕТ ОСТАНОВКУ в открытое кольцо,
 * и панель города при этом не открывается.
 *
 * Именно клик по карте, а не отдельный жест и не выпадающий список городов.
 * Кольцо прокладывается по карте: расстояния между остановками и есть предмет
 * решения, и отбирать их у игрока в тот момент, когда он решает, — значит
 * отбирать всё. Модальность здесь безопасна, потому что она ЯВНАЯ И ВИДНАЯ:
 * режим включает сам игрок, полоса режима висит в редакторе, а города на карте
 * в этом режиме подсвечены все разом — этот слой за то и отвечает.
 *
 * ГДЕ ЖИВЁТ САМО ДОБАВЛЕНИЕ. Не здесь. Этот слой знает ровно одно действие —
 * «указать город», — и это правильно: указание на объект не должно зависеть от
 * того, что открыто в панелях. Смысл жеста доопределяет у себя редактор
 * (ui/LineEditor.tsx подписан на выбор города, пока включён режим), он же и
 * гасит выбор, поэтому карточка города не успевает появиться. Копии правила
 * «остановка дописывается в конец кольца» здесь нет намеренно: два места,
 * знающих одно правило, разъезжаются молча.
 *
 * ЕДИНСТВЕННОЕ, ЧТО МЕНЯЕТ РЕЖИМ В ЭТОМ ФАЙЛЕ, — переключение выбора. Обычный
 * клик по уже выбранному городу СНИМАЕТ выбор (это про открыть-закрыть
 * карточку), а в режиме добавления снимать нечего: там клик означает «вот этот
 * город», и второй клик по тому же городу обязан поставить его в кольцо второй
 * раз — узловая база, куда заезжают и по дороге туда, и по дороге обратно,
 * законна. Поэтому в режиме добавления выбор сначала сбрасывается, а потом
 * ставится заново: получается указание, а не переключение.
 */

/** Радиус цели, км. Заметно больше застройки: целиться нужно в город, не в дом. */
const PICK_RADIUS = 16

/**
 * Прозрачность подсветки цели.
 *
 * Три состояния, и порядок между ними значим: наведение всегда заметнее
 * выбранного, иначе курсор «теряется» на уже выбранном городе. Отдельная
 * величина для режима добавления — самая слабая: она горит СРАЗУ НА ВСЕХ
 * городах и обязана читаться как ровный фон возможных остановок, а не как
 * десять одновременных выделений.
 */
const HIGHLIGHT = {
  hovered: 0.18,
  selected: 0.12,
  adding: 0.07,
  none: 0,
} as const

/**
 * Что происходит по клику в город. Целиком.
 *
 * Вынесено из обработчика по одной причине: дев-хук в конце файла обязан
 * дёргать ЭТОТ код, а не свою копию. Хук, повторяющий поведение своими словами,
 * проверяет сам себя — ровно та ловушка, ради которой этот слой вообще
 * тестируется сквозным тестом.
 *
 * Режим читается через getState, а не берётся из подписки компонента: действию
 * нужно значение на момент клика, а подписка нужна только подсветке.
 */
function pickCity(cityId: CityId): void {
  // В режиме добавления клик УКАЗЫВАЕТ город, а не переключает выбор — разбор в
  // шапке файла. Сброс безопасен и когда выбора не было.
  if (useLineSelection.getState().adding) useSelection.getState().clear()

  // Повторный клик по выбранному городу снимает выбор — переключение живёт в
  // самом store, см. ui/selection.ts.
  useSelection.getState().select(cityId)
}

export function CityPicker(): JSX.Element {
  /*
   * Подписка на СПИСОК ИДЕНТИФИКАТОРОВ: реестр городов пересобирается каждый
   * тик вместе с состоянием, а мишеням для клика нужны только координаты, и те
   * не меняются никогда. Голая подписка на объект заставляла пересобирать все
   * пятьдесят три сферы по несколько раз в секунду.
   */
  const roster = useGameStore((s) => Object.keys(s.state.world.cities).join('|'))
  const cities = useGameStore.getState().state.world.cities
  const selected = useSelection((s) => s.city)

  /*
   * Подписка на режим — по одному полю, как везде. Стор режима отдельный от
   * игрового состояния (разбор — в шапке ui/selection.ts), поэтому включение
   * режима не будит подписчиков мира: перерисовывается этот слой, а не дороги с
   * машинами. Проверять ещё и `line !== null` не нужно: setAdding не даёт
   * включить режим без открытой линии, и вторая копия этого условия здесь
   * означала бы вторую копию правила.
   */
  const adding = useLineSelection((s) => s.adding)

  const [hovered, setHovered] = useState<string | null>(null)

  const points = useMemo(
    () =>
      Object.values(cities).map((city) => ({
        id: city.id,
        name: city.name,
        ...cityPoint(city),
      })),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [roster],
  )

  return (
    <group>
      {points.map((point) => (
        <mesh
          key={point.id}
          position={[point.x, layers.vehicle, point.z]}
          onClick={(event) => {
            // Иначе один клик пройдёт насквозь и попадёт ещё и в город за ним.
            event.stopPropagation()
            pickCity(point.id)
          }}
          onPointerOver={(event) => {
            event.stopPropagation()
            setHovered(point.id)
            document.body.style.cursor = 'pointer'
          }}
          onPointerOut={() => {
            setHovered(null)
            document.body.style.cursor = 'auto'
          }}
        >
          <sphereGeometry args={[PICK_RADIUS, 12, 8]} />
          {/*
            Невидимая, но кликабельная: depthWrite отключён, чтобы сфера не
            прятала за собой застройку и подписи. Под курсором проступает
            акцентом — единственная подсветка на карте, и она же подсказывает,
            что по городу вообще можно кликать.

            Выбранный город светится и без курсора, чуть слабее наведения.
            Панель показывает название, но не место: без отметки на карте игрок
            читает данные про «Тулу», не видя, где она, — а вся ценность
            диагностики в том, чтобы соотнести цифры с расстояниями.

            В режиме добавления слабо горят ВСЕ города разом. Это единственная
            индикация модальности прямо на карте: она отвечает на вопрос «куда
            можно ткнуть» до того, как игрок ткнул, и заодно не даёт перепутать
            режимы — ровный фон из десяти огоньков ни на что другое в игре не
            похож.
          */}
          <meshBasicMaterial
            transparent
            depthWrite={false}
            color={palette.accent}
            opacity={
              hovered === point.id
                ? HIGHLIGHT.hovered
                : adding
                  ? HIGHLIGHT.adding
                  : selected === point.id
                    ? HIGHLIGHT.selected
                    : HIGHLIGHT.none
            }
          />
        </mesh>
      ))}
    </group>
  )
}

/**
 * Клик по городу из e2e — только в разработке.
 *
 * Тот же довод, что у __plechoSelect в ui/selection.ts: попасть в город на
 * трёхмерной сцене можно лишь экранными координатами, а они зависят от камеры,
 * зума и разрешения — такой тест ломается от любой правки кадрирования и не
 * проверяет ничего по существу. Но __plechoSelect дёргает store напрямую и
 * потому проходит МИМО этого слоя, а у слоя теперь есть собственное правило
 * (в режиме добавления клик указывает, а не переключает). Проверять правило
 * нужно на нём самом — отсюда вторая дверь, ведущая ровно в обработчик клика.
 *
 * В продакшен-сборке ветка вырезается целиком: import.meta.env.DEV — константа
 * этапа сборки.
 */
if (import.meta.env.DEV) {
  ;(globalThis as unknown as { __plechoPick?: unknown }).__plechoPick = (
    id: string,
  ) => pickCity(id as CityId)
}
