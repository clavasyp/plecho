/**
 * Машина, на которой запустили игру, и что из этого следует.
 *
 * ─── ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ПОЯВИЛСЯ ───────────────────────────────────────
 *
 * Жалоба «два кадра в секунду» разбиралась тридцатью одним замером, и все они
 * сошлись на одном: 76–77% периода кадра ЛИНЕЙНО зависит от числа пикселей
 * буфера, а геометрия не стоит ничего — выброс девяноста процентов
 * треугольников сцены не изменил кадр в пределах цены деления. Но замеры шли на
 * программном растеризаторе, и оставался вопрос, на чём же играет сам игрок.
 *
 * Ответ пришёл строкой из его браузера:
 *
 *   ANGLE (Microsoft, Microsoft Basic Render Driver (0x0000008C) Direct3D11)
 *   буфер 1650×1271 (2.1 Мпикс) · кадр 90.3 мс (11.1 к/с)
 *
 * «Microsoft Basic Render Driver» — это ЗАПАСНОЙ адаптер Windows. Видеокарты у
 * браузера нет вовсе: нет драйвера, или GPU отключён, или это виртуальная
 * машина. Всё рисует процессор.
 *
 * И это не редкий случай, ради которого не стоит стараться. Портфолио открывают
 * с чужих машин, с рабочих ноутбуков, из виртуалок и удалённых сеансов, и на
 * всех них игра обязана хотя бы двигаться. Поэтому режим включается САМ, без
 * настройки: человеку, у которого нет драйвера, не поможет ползунок качества —
 * он его не найдёт.
 *
 * ─── ЧТО МЕНЯЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО ──────────────────────────────────────
 *
 * Раз кадр упирается в пиксели, режим режет ПИКСЕЛИ, и ничего кроме. Ни одна
 * правка здесь не трогает ни палитру, ни свечение акцента, ни состав эффектов:
 * стилевой замок §15 остаётся целым, картинка становится мягче, но не другой.
 *
 * ЧТО СОЗНАТЕЛЬНО НЕ ДЕЛАЕТСЯ. Не снимается блум — свечение единственного
 * тёплого акцента живёт целиком в нём, и без него карта перестаёт быть этой
 * картой. Не упрощается геометрия — замер показал, что она бесплатна, и
 * потратить на неё день значило бы потратить его зря.
 */

/**
 * Незамаскированное имя того, что рисует.
 *
 * Спрашивается у ОТДЕЛЬНОГО одноразового контекста, а не у контекста игры, и
 * это принципиально: ответ нужен ДО того, как смонтирован холст, — от него
 * зависит плотность пикселей, с которой холст создаётся. Контекст сразу же
 * теряется явно: браузеры держат ограниченное их число, и забытый пробный
 * контекст однажды отнял бы у игры настоящий.
 *
 * Без расширения WEBGL_debug_renderer_info браузер отдаёт обезличенное
 * «WebKit WebGL», по которому ничего не понять; тогда возвращается пустая
 * строка и режим не включается. Ошибиться в сторону ПОЛНОГО качества здесь
 * правильнее: лишняя мягкость картинки у того, у кого всё в порядке, — беда
 * заметнее, чем недополученные кадры у того, у кого и так всё плохо.
 */
function probeRenderer(): string {
  if (typeof document === 'undefined') return ''

  const canvas = document.createElement('canvas')
  const gl =
    canvas.getContext('webgl2') ??
    (canvas.getContext('webgl') as WebGLRenderingContext | null)
  if (gl === null) return ''

  const info = gl.getExtension('WEBGL_debug_renderer_info')
  const name =
    info === null
      ? gl.getParameter(gl.RENDERER)
      : gl.getParameter(info.UNMASKED_RENDERER_WEBGL)

  gl.getExtension('WEBGL_lose_context')?.loseContext()

  return typeof name === 'string' ? name : ''
}

/**
 * Признаки того, что видеокарты нет.
 *
 * Перечислены ИМЕНА, а не отсутствие чего-либо: программный путь всегда
 * называет себя, и это надёжнее любой косвенной проверки.
 *
 *   swiftshader — растеризатор Google, куда Chrome уходит сам, когда драйвер
 *                 не годится;
 *   llvmpipe    — то же самое в Linux через Mesa;
 *   basic render, microsoft basic — запасной адаптер Windows: драйвера нет,
 *                 GPU отключён, либо это виртуальная машина;
 *   software    — общий признак на случай имени, которого мы не знаем.
 */
const SOFTWARE = /swiftshader|llvmpipe|software|basic render|microsoft basic/i

/** Имя того, что рисует. Пустая строка — браузер не сказал. */
export const rendererName = probeRenderer()

/** Правда ли, что кадр считает процессор. Решается один раз при загрузке. */
export const softwareRendering = SOFTWARE.test(rendererName)

/**
 * Бюджет пикселей кадрового буфера.
 *
 * 4.5 миллиона на настоящей карте — это примерно 2560×1760, разбор у
 * renderScale в App.tsx.
 *
 * 0.9 миллиона на процессоре выведены из замера игрока: у него буфер 2.1 Мпикс
 * и кадр 90.3 мс. Зависимость линейная (89.3 мс + 317 мс на мегапиксель по
 * подгонке прямой), значит 0.9 Мпикс дают около 37 мс — двадцать семь кадров в
 * секунду вместо одиннадцати. Ниже опускаться нет смысла: постоянная часть в
 * 89 мс уже не режется числом пикселей и упирается в карту теней и обход сцены.
 */
export const pixelBudget = softwareRendering ? 900_000 : 4_500_000

/**
 * Пол плотности пикселей.
 *
 * На настоящей карте 0.72 — ниже него лента федеральной дороги на предельном
 * отдалении уходит под полтора пикселя буфера, а этот проект дважды терял
 * дорожную сеть визуально.
 *
 * На процессоре пол опущен до 0.5 сознательно: там выбор не между чёткой и
 * мягкой картинкой, а между игрой и слайд-шоу. Пиксельный пол в вершинном
 * шейдере (pixelFloor.ts) при этом продолжает держать ленту видимой — он
 * считает в пикселях БУФЕРА и потому едет вместе с плотностью.
 */
export const minDensity = softwareRendering ? 0.5 : 0.72

/**
 * Сторона карты теней.
 *
 * Тени — второй по величине потребитель пикселей после постпроцессинга: при
 * 2048 это проход глубины в 4.19 мегапикселя, то есть ВДВОЕ больше самого
 * кадра на машине игрока. Половинная сторона режет его вчетверо.
 *
 * Цена честная: тексель растёт с 410 до 820 метров. На общем плане, где
 * километр занимает четверть пикселя, разницы нет вовсе; на крупном плане тень
 * от коробки завода становится мягче и грубее по краю. Для машины без
 * видеокарты это несравнимо дешевле, чем потерять две трети кадров.
 */
export const shadowMapSide = softwareRendering ? 1024 : 2048

/**
 * Сколько выборок берёт цель постпроцессинга.
 *
 * Ноль на процессоре. Четырёхкратное сглаживание означает вчетверо больше
 * работы растеризатора и полноэкранный резолв каждый кадр — на видеокарте это
 * заложено в железо и почти бесплатно, на процессоре это буквально вчетверо
 * больше вычислений на каждую грань.
 *
 * Замерянная цена: контраст ленты дороги на предельном отдалении падает с 0.081
 * до 0.061, то есть на четверть. Порог видимости при этом не пробивается —
 * ленту держит пиксельный пол шейдера, а не сглаживание.
 */
export const multisampling = softwareRendering ? 0 : 4

/**
 * Сколько уровней в мип-пирамиде блума.
 *
 * Восемь по умолчанию, из них три последних (20×12, 10×6, 5×3 пикселя)
 * добавляют шесть проходов ради 0.04% закраски кадра. На видеокарте это
 * незаметно в обе стороны, на процессоре шесть смен цели рендера — уже цена.
 *
 * Замер разницы в картинке на ночной Москве, где светятся только окна: 0.219
 * из 255 при собственном шуме прибора 0.231. То есть неразличимо.
 */
export const bloomLevels = softwareRendering ? 5 : 8
