/**
 * Линии игрока на карте.
 *
 * Линия — замкнутое кольцо остановок, но игрок задаёт только ГОРОДА, а едет
 * машина по ДОРОГАМ. Между «Москва → Смоленск» в списке остановок и реальным
 * ходом по М-1 лежит поиск пути, и разница видна не всегда: кольцо, которое на
 * бумаге выглядит компактным, может идти через полкарты. Поэтому линия рисуется
 * по фактическому маршруту, ребро за ребром, тем же findRoute, каким её ведёт
 * диспетчер (src/sim/logistics/line.ts). Иначе карта показывала бы замысел, а
 * счёт за топливо приходил бы за исполнение.
 *
 * ─── ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА: ЧЕМ ЛИНИИ ОТЛИЧАЮТСЯ ДРУГ ОТ ДРУГА ──────────────
 *
 * Обычный ответ — цвет: метро всего мира так и устроено. Здесь он запрещён, и
 * запрет не каприз: в palette.ts тёплый цвет ровно один и означает он «сюда
 * смотри». Раздай линиям красный, синий и зелёный — и карта, где до сих пор
 * светилась только техника, превратится в схему из методички. Значит, различать
 * надо чем-то, кроме тона.
 *
 * Взяты ДВА независимых канала, оба геометрические:
 *
 *   ПОЛОСА. Линия идёт не по оси дороги, а со смещением вбок на свою полосу —
 *   как параллельные маршруты на транспортной схеме. Это не украшение, а
 *   единственный способ увидеть, что по М-2 идут ТРИ кольца, а не одно: лежащие
 *   в одной точке ленты неразличимы в принципе, сколько их ни раскрашивай.
 *   Полоса у линии одна на всю карту, поэтому кольцо опознаётся по положению в
 *   пучке, а не только по форме.
 *
 *   ФАЗА ШТРИХА. Линия штриховая, и штрихи разных линий сдвинуты по фазе. Канал
 *   работает там, где кончаются полосы: при четвёртой линии полосы идут по
 *   второму кругу, и совпавшие по полосе кольца расходятся штрихом. Полос три и
 *   фаз три — девять различимых видов, дальше рисунок повторяется. Это предел
 *   честности приёма, и он записан здесь, а не выясняется на карте.
 *
 * Штрих несёт и второй смысл: он КЛИНОВИДНЫЙ, широким концом вперёд по ходу
 * кольца. Направление обхода — не мелочь (кольцо «Москва → Тула → Калуга» и то
 * же кольцо наоборот грузятся совершенно по-разному), а стрелок на карте нет и
 * заводить их незачем: сужающийся хвост читается как стрелка на любом зуме и
 * при этом остаётся штрихом, когда карта отдалена.
 *
 * ВЫБРАННАЯ ЛИНИЯ забирает акцент — единственный тёплый цвет палитры — и
 * становится СПЛОШНОЙ и вдвое шире. Три признака сразу, потому что один здесь не
 * работает: на общем плане кольцо занимает считаные пиксели, и «чуть ярче» на
 * нём не читается. Тёплый цвет линии не спорит с машинами: у машин он ещё и
 * светящийся (emissiveIntensity в VehicleMesh), они остаются самыми яркими
 * телами сцены. Замок цел — тёплое по-прежнему означает «сюда смотри», и теперь
 * это работает для линии, с которой игрок прямо сейчас работает.
 *
 * ─── ЧТО ИЗМЕНИЛ СРЕЗ 6: ЧУЖИЕ КОЛЬЦА ПОЯВИЛИСЬ НА КАРТЕ ────────────────────
 *
 * До этого среза здесь было записано обратное: «чужие линии не рисуются вовсе,
 * сеть конкурента — его коммерческая тайна». Решение отменено сознательно, и вот
 * чем.
 *
 * ПЕРВОЕ — ИГРОВОЕ. Пока конкурентов не было, скрывать было нечего. Теперь их
 * трое, и у каждого свой характер: агрессивный ЛЕЗЕТ В ТВОИ НАПРАВЛЕНИЯ,
 * осторожный сидит на своих, нишевый забирает один груз (types.ts,
 * CompetitorPersonality). Против разных характеров нужны разные ответы — в этом
 * весь замысел, — но ответить нельзя на то, чего не видно. Невидимый соперник
 * читается не как соперник, а как необъяснимый шум в экономике: груз со склада
 * кто-то забрал, ставка просела, а причины на карте нет.
 *
 * ВТОРОЕ — ЧЕСТНОСТЬ ФИКЦИИ. Регулярный маршрут по дорогам общего пользования
 * тайной не является: чужая фура, каждый день идущая через тот же перекрёсток,
 * видна любому, кто там стоит. Тайна — это ЧТО она везёт и сколько на этом
 * зарабатывает, и вот как раз этого чужое кольцо не показывает: ни груза
 * остановок, ни направления обхода, ни выделения. Только след — где он ездит.
 *
 * ЧЕМ ЧУЖОЕ ОТЛИЧАЕТСЯ ОТ СВОЕГО. Опять не цветом (акцент один и он у игрока), а
 * ТРЕМЯ независимыми геометрическими признаками сразу — по той же причине, по
 * которой у выбранной линии их три: на общем плане кольцо занимает считаные
 * пиксели, и одного признака там не хватает.
 *
 *   МЕСТО. Свои линии идут ПО дороге, в пучке вокруг её оси. Чужие вынесены ЗА
 *   пучок, на обочину, и на полотно не заезжают. «Своё в середине, чужое сбоку» —
 *   это читается мгновенно и не требует ни легенды, ни сравнения.
 *
 *   ВЕС. Чужая лента вдвое тоньше своей.
 *
 *   РИТМ И ТОН. Чужой штрих короткий, частый и БЕЗ КЛИНА — то есть без указания
 *   направления, которого игрок и не должен получать даром, — а тон взят
 *   тусклее: самая тёмная застройка вместо светлой. Своё ярче чужого вдвое с
 *   половиной по относительной яркости, чужое ярче рельефа втрое. Порядок
 *   внимания получается ровно тот, что нужен: акцент → своё → полотно → чужое →
 *   фон, и он записан не только здесь, но и проверкой в roadSurface.test.ts.
 *
 * ─── ЧТО ИСПРАВЛЕНО ПОСЛЕ РАЗБОРА КАДРОВ: СВОЯ ЛИНИЯ БЫЛА СЛИШКОМ ГРОМКОЙ ────
 *
 * Невыбранные свои кольца рисовались приглушённым тоном ИНТЕРФЕЙСА (textDim) и
 * без тональной компрессии материала. Довод был верный — линия обязана читаться
 * поверх полотна, — а следствие оказалось хуже причины: компрессия в этом
 * проекте живёт не в материале, а в цепочке постпроцессинга (ToneMapping в
 * Scene.tsx) и накрывает кадр целиком, поэтому «неприводимый» тон вылезал ярче
 * всего, что вокруг него приведено. На ближнем плане штрихи читались почти
 * белыми и становились вторым по яркости телом кадра после акцента: на снимке
 * терминала белые полосы спорили с оранжевой рампой — то есть невыбранная линия
 * перебивала то, ради чего игрок в этот кадр и смотрел.
 *
 * Тон опущен до СВЕТЛОЙ ЗАСТРОЙКИ. Он по-прежнему светлее любого дорожного
 * полотна — то есть линия видна на трассе, ради чего всё и делалось, — и
 * по-прежнему вдвое с половиной ярче чужого следа, который остался на тёмной
 * застройке и не двигался. Изменилось одно: линия перестала спорить с акцентом.
 * Между невыбранной линией и выбранной теперь разница в два с половиной раза
 * вместо полутора, и глаз наконец находит в кадре сначала оранжевое, а потом всё
 * остальное.
 *
 * ГЕОМЕТРИЯ. Все невыбранные свои линии сливаются в ОДИН буфер вершин, выбранная
 * — во второй, все чужие — в третий: три вызова отрисовки на любое число линий и
 * любое число контор. Инстансинг здесь не подходит — у штрихов разная длина и
 * разная ширина концов, то есть разная форма, а не разное положение одной формы.
 */

