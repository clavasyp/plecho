const ROAD_CLEARANCE = 1.5

/**
 * На сколько отодвигается двор, когда слоты на одной дороге кончились.
 *
 * Случай редкий (нужен город с одной-единственной трассой и больше двух
 * построек), но обработать его надо: без яруса третья постройка встала бы
 * ровно на вторую.
 */
const TIER_STEP = 13

/** Единичный вектор направления и нормали к нему на плоскости карты. */
type Frame = {
  /** Начало отсчёта — центр города в координатах сцены. */
  cx: number
  cz: number
  /** Азимут дороги в плоскости XZ. */
  angle: number
  /** Вдоль дороги, от города наружу. */
  fx: number
  fz: number
  /** Поперёк дороги, в сторону выбранной обочины. */
  lx: number
  lz: number
  /** Радиус городской площадки, км. */
  padRadius: number
}

/**
 * Слот вокруг города: какая трасса, какая обочина, какой ярус.
 *
 * Слоты нумеруются подряд, а раздаются по НЕИЗМЕННОМУ правилу: сначала все
 * дороги по одной обочине, потом те же дороги по другой, потом следующий ярус.
 * Поэтому у города с двумя и более трассами (а такие все, кроме вырожденных
 * данных) рампа и три постройки расходятся по разным лучам, и ни один слот не
 * зависит от того, что игрок построил раньше.
 */
function frameForSlot(
  cx: number,
  cz: number,
  padRadius: number,
  roads: readonly number[],
  slot: number,
): Frame {
  // Города без дорог в данных быть не может (граф связный), но рендер не должен
  // падать на битом сохранении: без лучей двор просто смотрит на восток.
  const count = roads.length
  const angle = count === 0 ? 0 : roads[slot % count]
  const lap = count === 0 ? slot : Math.floor(slot / count)
  const side = lap % 2 === 0 ? 1 : -1
  const tier = Math.floor(lap / 2)

  const fx = Math.cos(angle)
  const fz = Math.sin(angle)

  return {
    cx,
    cz,
    angle,
    fx,
    fz,
    // Нормаль к направлению, развёрнутая на нужную обочину.
    lx: -fz * side,
    lz: fx * side,
    padRadius: padRadius + tier * TIER_STEP,
  }
}

const Y_AXIS = new Vector3(0, 1, 0)
const scratchPosition = new Vector3()
const scratchScale = new Vector3()
const scratchRotation = new Quaternion()

/**
 * Матрица тела: локальные оси двора → сцена.
 *
 * Поворот вокруг вертикали на −angle, и знак не произволен. Вращение вокруг +Y
 * переводит локальную ось X в (cos yaw, −sin yaw), а направление на карте задано
 * парой (cos a, sin a) — то есть чтобы локальная X легла ВДОЛЬ дороги, нужен
 * yaw = −a. Тот же перевёрнутый знак, что у Z в cityPoint, и по той же причине
 * (разбор — в шапке projection.ts). При этом локальная Z ложится ровно на
 * нормаль к дороге, поэтому позиция собирается теми же двумя векторами кадра.
 */
function bodyMatrix(
  frame: Frame,
  /** Вдоль дороги от центра города, км. */
  along: number,
  /** Поперёк дороги, км: знак уже учтён в кадре. */
  across: number,
  y: number,
  scaleX: number,
  scaleY: number,
  scaleZ: number,
  out: Matrix4,
): Matrix4 {
  scratchPosition.set(
    frame.cx + frame.fx * along + frame.lx * across,
    y,
    frame.cz + frame.fz * along + frame.lz * across,
  )
  scratchRotation.setFromAxisAngle(Y_AXIS, -frame.angle)
  scratchScale.set(scaleX, scaleY, scaleZ)
  return out.compose(scratchPosition, scratchRotation, scratchScale)
}

/**
 * Азимуты трасс, выходящих из каждого города, отсортированные по возрастанию.
 *
 * Сортировка обязательна: слот выбирается индексом в этом списке, а порядок
 * обхода рёбер в объекте состояния — не то, на чём можно строить положение
 * здания на карте. С сортировкой луч у слота один и тот же в любой сессии.
 */
function roadAngles(world: GameState['world']): Map<CityId, number[]> {
  const angles = new Map<CityId, number[]>()

  for (const edge of Object.values(world.edges)) {
    const from = world.cities[edge.from]
    const to = world.cities[edge.to]
    if (from === undefined || to === undefined) continue

    const a = cityPoint(from)
    const b = cityPoint(to)
    const forward = Math.atan2(b.z - a.z, b.x - a.x)

    const outbound = angles.get(edge.from) ?? []
    outbound.push(forward)
    angles.set(edge.from, outbound)

    const inbound = angles.get(edge.to) ?? []
    inbound.push(forward + Math.PI)
    angles.set(edge.to, inbound)
  }

  for (const list of angles.values()) list.sort((x, y) => x - y)
  return angles
}

// ─── Разложенные постройки ─────────────────────────────────────────────────

type Group = {
  matrices: Matrix4[]
  /** Доля высоты тела от самого высокого во дворе, 0..1 — из неё берётся тон. */
  tones: number[]
}

type Layout = {
  /** Сколько построек разложено. Ноль — рисовать нечего. */
  sites: number
  boxes: Group
  towers: Group
}

const EMPTY_LAYOUT: Layout = {
  sites: 0,
  boxes: { matrices: [], tones: [] },
  towers: { matrices: [], tones: [] },
}

/**
 * Расстановка построек и сборка всех матриц.
 *
 * СОСТАВ приходит отдельным аргументом `roster` — это то, на что подписан
 * компонент, — а ГЕОГРАФИЯ читается из снимка мира. Разделение не формальность:
 * список построек обязан быть ровно тем, изменение которого разбудило пересчёт,
 * иначе геометрия окажется собранной по одному состоянию, а признак её свежести
 * — по другому. Тот же приём, что в IndustryMesh.
 */
function buildLayout(
  roster: Record<string, string>,
  world: GameState['world'],
): Layout {
  const ids = Object.keys(roster)
  if (ids.length === 0) return EMPTY_LAYOUT

  const boxes: Group = { matrices: [], tones: [] }
  const towers: Group = { matrices: [], tones: [] }
  const roads = roadAngles(world)
  let sites = 0

  for (const id of ids) {
    // Значение реестра — это «тип@город», собранное селектором. Разбирать
    // строку приходится потому, что подписка обязана быть на ЗНАЧЕНИЯ (useShallow
    // сравнивает их поверхностно), а объект постройки пересобирается вместе с
    // компанией на каждом тике.
    const at = roster[id].indexOf('@')
    if (at <= 0) continue

    const type = roster[id].slice(0, at) as BuildingType
    const cityId = roster[id].slice(at + 1) as CityId

    const site = SITES[type]
    const city = world.cities[cityId]
    // Неизвестный тип постройки — не повод ронять карту: расширение BuildingType
    // не должно требовать одновременной правки рендера, иначе новые типы будут
    // добавляться со страхом. Города, которого нет в мире, симуляция не даст
    // застроить вовсе (buildBuilding), но сейв прошлой версии — может.
    if (site === undefined || city === undefined) continue

    const slotIndex = SLOT_ORDER.indexOf(type)
    const point = cityPoint(city)
    const frame = frameForSlot(
      point.x,
      point.z,
      cityPadRadius(city.population),
      roads.get(cityId) ?? [],
      // Слот 0 занят рампой, поэтому постройки начинаются с первого. Тип, не
      // попавший в SLOT_ORDER (расширение контракта), встаёт в конец очереди
      // слотов, а не поверх терминала.
      RAMP_SLOT + 1 + (slotIndex < 0 ? SLOT_ORDER.length : slotIndex),
    )

    // Двор целиком выходит за пятно застройки: центр — радиус пятна плюс
    // половина длины плюс просвет.
    const along = frame.padRadius + site.length / 2 + PAD_CLEARANCE
    const across = ROAD_CLEARANCE + site.width / 2

    sites++

    // Плита двора заполняет всю толщу от рельефа до уровня построек: повисшая
    // над землёй плита дала бы щель, а вкопанная — z-fighting с подложкой.
    boxes.matrices.push(
      bodyMatrix(
        frame,
        along,
        across,
        layers.yard / 2,
        site.length,
        layers.yard,
        site.width,
        new Matrix4(),
      ),
    )
    // Земля не участвует в шкале тона: это подложка, а не корпус.
    boxes.tones.push(-1)

    let peak = 0
    for (const part of site.parts) peak = Math.max(peak, part.height)
    for (const tower of site.towers) peak = Math.max(peak, tower.height)
    const tone = (height: number): number => (peak > 0 ? height / peak : 1)

    for (const part of site.parts) {
      boxes.matrices.push(
        bodyMatrix(
          frame,
          along + part.x,
          across + part.z,
          layers.yard + part.height / 2,
          part.width,
          part.height,
          part.depth,
          new Matrix4(),
        ),
      )
      boxes.tones.push(tone(part.height))
    }

    for (const tower of site.towers) {
      towers.matrices.push(
        bodyMatrix(
          frame,
          along + tower.x,
          across + tower.z,
          layers.yard + tower.height / 2,
          tower.radius,
          tower.height,
          tower.radius,
          new Matrix4(),
        ),
      )
      towers.tones.push(tone(tower.height))
    }
  }

  return { sites, boxes, towers }
}

// ─── Цвет ──────────────────────────────────────────────────────────────────

/**
 * Постройки игрока ХОЛОДНЫЕ, и это распределение акцента, а не забывчивость.
 *
 * Соблазн покрасить своё имущество в тёплый велик — «вот что я построил», — но
 * акцент в этой сцене занят и означает «дело транспорта»: работающая машина,
 * город под курсором, задохнувшийся завод. Постройка сама по себе не работа, а
 * актив; тёплой в её дворе бывает только машина на рампе. Заодно площадь: три
 * двора по десятку километров, залитые оранжевым, перекричали бы на общем плане
 * и машины, и очередь — то есть ровно то, ради чего постройка и ставилась.
 *
 * Тона — те же, что у городской застройки и промышленности: высокое светлее,
 * низкое темнее. Один признак закодирован дважды, формой и тоном, поэтому силуэт
 * читается и там, где его съел туман.
 */
const BODY_DARK = new Color(palette.buildingLow)
const BODY_LIT = new Color(palette.buildingHigh)
const YARD_COLOR = new Color(palette.terrainEdge)
const scratchColor = new Color()

/** Цвет тела по его доле высоты. Отрицательный тон — это двор, а не корпус. */
function toneColor(tone: number): Color {
  if (tone < 0) return YARD_COLOR
  return scratchColor.lerpColors(BODY_DARK, BODY_LIT, tone)
}

function paintGroup(mesh: InstancedMesh, group: Group): void {
  for (let i = 0; i < group.tones.length; i++) {
    mesh.setColorAt(i, toneColor(group.tones[i]))
  }
  if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true
}

// ─── Постройки ─────────────────────────────────────────────────────────────

/**
 * Подписка на СОСТАВ построек игрока, а не на состояние компании.
 *
 * Компания пересобирается каждый тик — содержание построек списывает деньги, —
 * и подписка на неё перестраивала бы всю геометрию по нескольку раз в секунду.
 * Селектор сводит её к тому, от чего геометрия действительно зависит: какие
 * постройки есть, какого они типа и в каком городе. Значения — строки, поэтому
 * useShallow сравнивает их ПО ЗНАЧЕНИЮ, и компонент перерисовывается только при
 * постройке или сносе.
 *
 * ТОЛЬКО ПОСТРОЙКИ ИГРОКА. Конкуренты в срезе 5 не строят ничего (см. runAi в
 * sim/tick.ts), а когда начнут — их терминалы обязаны отличаться от своих, и
 * решать это придётся отдельно. Показать чужое имущество тем же силуэтом и тем
 * же цветом значило бы соврать игроку про его собственную пропускную способность:
 * посты чужой постройки ему не достаются (postsAt считает по владельцу).
 */
function selectRoster(store: GameStore): Record<string, string> {
  const roster: Record<string, string> = {}
  const state = store.state
  const player = state.companies[state.playerId]

  for (const building of Object.values(player?.buildings ?? {})) {
    roster[building.id] = `${building.type}@${building.cityId}`
  }

  return roster
}

export function Buildings(): JSX.Element {
  const roster = useGameStore(useShallow(selectRoster))

  // Города читаются разовым снимком, а не подпиской: их геометрия за партию не
  // меняется, а население — меняется, и подписка на него пересобирала бы всю
  // расстановку за каждым выросшим горожанином. Постройка, ползающая по карте
  // вслед за ростом города, — дефект хуже любого пересечения; про запас, который
  // это оплачивает, сказано у cityPadRadius.
  const layout = useMemo(
    () => buildLayout(roster, useGameStore.getState().state.world),
    [roster],
  )

  const boxRef = useRef<InstancedMesh>(null)
  const towerRef = useRef<InstancedMesh>(null)

  useLayoutEffect(() => {
    const meshes = [boxRef.current, towerRef.current]
    const groups = [layout.boxes, layout.towers]

    for (let m = 0; m < meshes.length; m++) {
      const mesh = meshes[m]
      const group = groups[m]
      if (mesh === null || group.matrices.length === 0) continue

      for (let i = 0; i < group.matrices.length; i++) {
        mesh.setMatrixAt(i, group.matrices[i])
      }
      mesh.instanceMatrix.needsUpdate = true
      paintGroup(mesh, group)

      // Без пересчёта габаритов отсечение по пирамиде видимости считает их по
      // исходной коробке в начале координат, и все постройки исчезают, стоит
      // увести камеру от нуля.
      mesh.computeBoundingSphere()
    }
  }, [layout])

  /**
   * Дев-хук: что НА САМОМ ДЕЛЕ нарисовано, а не что посчитано.
   *
   * Числа читаются с живых InstancedMesh, а не из layout, и это принципиально.
   * Роль этого файла в срезе появилась потому, что дважды подряд крупные куски
   * оказывались мёртвым кодом при зелёных тестах: посчитать матрицы и не
   * смонтировать меш — ровно такой случай, и хук, отвечающий из layout, его бы
   * не заметил. Здесь ответ даёт объект сцены: нет меша — нет и числа.
   *
   * В продакшен-сборке ветка вырезается целиком: import.meta.env.DEV — константа
   * этапа сборки.
   */
  useEffect(() => {
    if (!import.meta.env.DEV) return

    const dev = globalThis as unknown as { __plechoBuildings?: unknown }

    dev.__plechoBuildings = () => ({
      sites: layout.sites,
      boxes: boxRef.current?.count ?? 0,
      towers: towerRef.current?.count ?? 0,
    })

    return () => {
      delete dev.__plechoBuildings
    }
  }, [layout])

  return (
    <group>
      {/*
        Цвет материала белый специально, как у застройки и промышленности:
        instanceColor не заменяет цвет материала, а УМНОЖАЕТСЯ на него, и любой
        оттенок здесь притушил бы всю шкалу тона разом. Emissive нет — светятся в
        этой сцене только машины и рампы под погрузкой.

        Тени включены: постройка обязана стоять на земле так же, как застройка, а
        не лежать на ней наклейкой. Отбрасывают их корпуса, принимает плита двора,
        и разводить эти роли по двум мешам ради двух флагов не стоит ни одного
        лишнего вызова отрисовки.
      */}
      {layout.boxes.matrices.length > 0 && (
        <instancedMesh
          ref={boxRef}
          // null! — идиома R3F: геометрия и материал приходят детьми, здесь
          // значимо только третье значение, число экземпляров.
          args={[null!, null!, layout.boxes.matrices.length]}
          castShadow
          receiveShadow
        >
          <boxGeometry args={[1, 1, 1]} />
          <meshStandardMaterial color="#ffffff" roughness={0.85} metalness={0} />
        </instancedMesh>
      )}

      {layout.towers.matrices.length > 0 && (
        <instancedMesh
          ref={towerRef}
          args={[null!, null!, layout.towers.matrices.length]}
          castShadow
          receiveShadow
        >
          <cylinderGeometry args={[TAPER_RATIO, 1, 1, ROUND_SEGMENTS]} />
          <meshStandardMaterial color="#ffffff" roughness={0.9} metalness={0} />
        </instancedMesh>
      )}
    </group>
  )
}

