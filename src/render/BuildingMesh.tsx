/**
 * Деталь двора в его собственных осях, километры.
 *
 * Ось X — вдоль подъездной дороги (от города наружу), Z — поперёк неё, начало
 * координат в центре двора. Тел два вида: коробка (навес, корпус, будка) и
 * сужающееся кверху тело вращения (башня хаба). Больше не понадобилось: у
 * транспортной постройки нет ни резервуаров, ни градирен, а лишний вид тела —
 * это лишний вызов отрисовки на всю карту.
 */
type Part = {
  x: number
  z: number
  /** Габарит вдоль дороги. */
  width: number
  /** Габарит поперёк дороги. */
  depth: number
  height: number
}

type Tower = { x: number; z: number; radius: number; height: number }

type Site = {
  /** Габарит двора вдоль дороги, км. */
  length: number
  /** Габарит двора поперёк дороги, км. */
  width: number
  parts: readonly Part[]
  towers: readonly Tower[]
}

const box = (
  x: number,
  z: number,
  width: number,
  depth: number,
  height: number,
): Part => ({ x, z, width, depth, height })

