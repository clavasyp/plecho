/** Что случилось с машинами компании в одном городе прямо сейчас. */
type Load = { busy: number; queued: number }

/** Машина держит пост: тот же счётчик, по которому её не выпускает диспетчер. */
function isLoading(vehicle: Vehicle): boolean {
  return vehicle.serviceTicksLeft > 0
}

/** Машина ждёт поста. Счётчик обнуляется в тот момент, когда пост достался. */
function isQueued(vehicle: Vehicle): boolean {
  return !(vehicle.serviceTicksLeft > 0) && vehicle.queuedTicks > 0
}

/** Ёмкость буферов под текущий размер парка и число городов. */
const selectCapacity = (store: GameStore): number => {
  const cities = Object.keys(store.state.world.cities).length
  const vehicles = Object.keys(store.state.vehicles).length
  const needed = cities * MAX_DOCKS + vehicles
  return Math.max(1, Math.ceil(needed / CAPACITY_STEP)) * CAPACITY_STEP
}

/** Опора рампы: у какого города она стоит и в какую сторону растёт. */
type Anchor = { id: CityId; frame: Frame }

/**
 * Подписка на СОСТАВ городов, и значением взят сам идентификатор.
 *
 * Соблазн положить в значение ещё и население велик — от него зависит радиус
 * пятна, то есть место рампы, — и он ошибочен. Население растёт каждые сутки, и
 * рампы поехали бы вслед за ним по всей карте: игрок увидел бы, что двор
 * переезжает сам собой. Место считается один раз, а рост города оплачен запасом
 * (см. cityPadRadius).
 */
function selectCityRoster(store: GameStore): Record<string, string> {
  const roster: Record<string, string> = {}
  for (const city of Object.values(store.state.world.cities)) {
    roster[city.id] = city.id
  }
  return roster
}

function buildAnchors(
  roster: Record<string, string>,
  world: GameState['world'],
): Anchor[] {
  const roads = roadAngles(world)
  const anchors: Anchor[] = []

  // Обход идёт по РЕЕСТРУ, а не по миру напрямую, — по тому же доводу, что и в
  // постройках: список городов обязан быть ровно тем, изменение которого
  // разбудило пересчёт. Порядок ключей он же и задаёт, а значит буфер инстансов
  // между кадрами не переставляется.
  for (const key of Object.keys(roster) as CityId[]) {
    const city = world.cities[key]
    if (city === undefined) continue

    const point = cityPoint(city)
    anchors.push({
      id: city.id,
      frame: frameForSlot(
        point.x,
        point.z,
        cityPadRadius(city.population),
        roads.get(city.id) ?? [],
        RAMP_SLOT,
      ),
    })
  }

  return anchors
}

const dockMatrix = new Matrix4()

/**
 * Буфер матриц обновляется каждый кадр — драйверу об этом лучше сказать явно,
 * иначе он разместит его в памяти, оптимизированной под статику. Тот же приём и
 * по той же причине, что markDynamic в VehicleMesh.
 */
function markDynamic(mesh: InstancedMesh): void {
  mesh.instanceMatrix.setUsage(DynamicDrawUsage)
}

export function ServicePosts(): JSX.Element {
  const capacity = useGameStore(selectCapacity)
  const cityRoster = useGameStore(useShallow(selectCityRoster))

  // Состав городов приходит подпиской, география — разовым снимком: население
  // растёт каждые сутки, и подписка на него переставляла бы рампы вслед за
  // каждым выросшим горожанином. Тот же приём и тот же довод, что у построек.
  const anchors = useMemo(
    () => buildAnchors(cityRoster, useGameStore.getState().state.world),
    [cityRoster],
  )

  const hotRef = useRef<InstancedMesh>(null)
  const coldRef = useRef<InstancedMesh>(null)

  /** Загрузка узлов, переиспользуемая между кадрами: в кадре нет аллокаций. */
  const loadRef = useRef<Load[]>([])
  if (loadRef.current.length !== anchors.length) {
    loadRef.current = anchors.map(() => ({ busy: 0, queued: 0 }))
  }

  /** Что нарисовано в последнем кадре — только для дев-хука. */
  const drawnRef = useRef({ docks: 0, busy: 0, queued: 0 })

  useFrame(() => {
    const hot = hotRef.current
    const cold = coldRef.current
    if (hot === null || cold === null) return

    // Прямое чтение стора вместо хука: подписка на состояние означала бы
    // перерисовку дерева на каждом тике, то есть по нескольку раз в секунду.
    const state = useGameStore.getState().state
    const load = loadRef.current

    for (const entry of load) {
      entry.busy = 0
      entry.queued = 0
    }

    // Обход идёт по ПАРКУ, а не по городам: узлов десяток, а машин со временем
    // сотни, и вложенный поиск дал бы квадрат на каждом кадре.
    for (const vehicle of Object.values(state.vehicles)) {
      // ТОЛЬКО СВОИ МАШИНЫ. Очередь считается по компаниям (postsAt), и чужой
      // хвост у того же завода к пропускной способности игрока отношения не
      // имеет: показать его здесь значило бы обвинить игрока в чужой пробке.
      if (vehicle.ownerId !== state.playerId) continue
      if (vehicle.position.kind !== 'узел') continue

      const index = anchorIndex(anchors, vehicle.position.nodeId)
      if (index < 0) continue

      if (isLoading(vehicle)) load[index].busy++
      else if (isQueued(vehicle)) load[index].queued++
    }

    const limit = Math.min(hot.instanceMatrix.count, cold.instanceMatrix.count)
    let hotCount = 0
    let coldCount = 0
    /** Сколько холодных тел — рампы, а сколько — хвост. Только для дев-хука. */
    let dockCount = 0
    let queuedCount = 0

    for (let i = 0; i < anchors.length; i++) {
      const anchor = anchors[i]
      const entry = load[i]

      // Постов спрашиваем у симуляции, а не считаем здесь: правило «базовый пост
      // плюс постройки» живёт в одном месте, и вторая его копия разошлась бы с
      // первой — терминал добавлял бы рампы на карте и не добавлял в очереди.
      const posts = Math.min(
        MAX_DOCKS,
        Math.max(0, postsAt(state, anchor.id, state.playerId)),
      )

      const start = anchor.frame.padRadius + PAD_CLEARANCE + DOCK.length / 2
      const across = ROAD_CLEARANCE + DOCK.width / 2

      for (let post = 0; post < posts; post++) {
        if (coldCount >= limit) break

        const along = start + post * DOCK_PITCH

        // Платформа растёт от РЕЛЬЕФА, а не от уровня двора: повисшая над землёй
        // плита дала бы щель, вкопанная — z-fighting с подложкой. Поэтому её
        // толщина складывается из зазора двора и собственной высоты.
        const deck = layers.yard + DOCK.height
        cold.setMatrixAt(
          coldCount,
          bodyMatrix(
            anchor.frame,
            along,
            across,
            deck / 2,
            DOCK.length,
            deck,
            DOCK.width,
            dockMatrix,
          ),
        )
        cold.setColorAt(coldCount, DOCK_COLOR)
        coldCount++
        dockCount++

        // Машина на рампе. Тело тёплое и светящееся, поэтому лежит в другом меше
        // — emissive это свойство материала, одно на все инстансы. Стоит она НА
        // платформе, то есть выше ждущих: ещё одно различие сверх цвета.
        if (post < entry.busy && hotCount < limit) {
          hot.setMatrixAt(
            hotCount,
            bodyMatrix(
              anchor.frame,
              along,
              across,
              deck + CHIP.height / 2,
              CHIP.length,
              CHIP.height,
              CHIP.width,
              dockMatrix,
            ),
          )
          hotCount++
        }
      }

      // Хвост очереди — за последней рампой, вдоль трассы, прочь от города. Это
      // и есть узкое место, увиденное глазами: чем длиннее хвост, тем дороже
      // обходится узел. Считаем от той же точки, что и рампы, чтобы хвост рос
      // именно за ними, а не поверх.
      const tail = start + Math.max(0, posts - 1) * DOCK_PITCH + QUEUE_GAP

      for (let waiting = 0; waiting < entry.queued; waiting++) {
        if (coldCount >= limit) break

        cold.setMatrixAt(
          coldCount,
          bodyMatrix(
            anchor.frame,
            tail + waiting * DOCK_PITCH,
            across,
            layers.yard + CHIP.height / 2,
            CHIP.length,
            CHIP.height,
            CHIP.width,
            dockMatrix,
          ),
        )
        cold.setColorAt(coldCount, QUEUED_COLOR)
        coldCount++
        queuedCount++
      }
    }

    // Лишние инстансы не прячутся нулевым масштабом, а отсекаются счётчиком: он
    // работает до вершинного шейдера.
    hot.count = hotCount
    cold.count = coldCount
    hot.instanceMatrix.needsUpdate = true
    cold.instanceMatrix.needsUpdate = true
    if (cold.instanceColor !== null) {
      if (cold.instanceColor.usage !== DynamicDrawUsage) {
        cold.instanceColor.setUsage(DynamicDrawUsage)
      }
      cold.instanceColor.needsUpdate = true
    }

    const drawn = drawnRef.current
    drawn.docks = dockCount
    drawn.busy = hotCount
    drawn.queued = queuedCount
  })

  /**
   * Дев-хук: сколько машин НА САМОМ ДЕЛЕ нарисовано на рампах и в хвосте.
   *
   * Считается по итогам кадра, с живых мешей, и отвечает ровно на тот вопрос,
   * ради которого роль этого файла в срезе существует: «видно ли это в игре».
   * Собственного пересчёта состояния здесь нет намеренно — хук, повторяющий
   * логику своими словами, проверяет сам себя.
   */
  useEffect(() => {
    if (!import.meta.env.DEV) return

    const dev = globalThis as unknown as { __plechoDocks?: unknown }

    dev.__plechoDocks = () => ({
      // Тёплых тел на сцене ровно столько, сколько машин стоит под погрузкой.
      busy: hotRef.current?.count ?? 0,
      // Холодных — рампы плюс хвост очереди, и это тоже число со сцены.
      cold: coldRef.current?.count ?? 0,
      // Из чего сложились холодные — по счётчикам последнего кадра.
      docks: drawnRef.current.docks,
      queued: drawnRef.current.queued,
    })

    return () => {
      delete dev.__plechoDocks
    }
  }, [])

  return (
    <>
      {/*
        Машина под погрузкой — единственное тёплое тело этого файла и второе во
        всей сцене после кабины едущей машины. Свечение выше порога блума (0.55 в
        postFx), поэтому работающая рампа видна искрой даже там, где сама коробка
        занимает несколько пикселей.

        frustumCulled выключен по той же причине, что у машин: отсечение по
        пирамиде видимости считается по геометрии инстанса, а не по разбросу
        инстансов, и все рампы карты исчезали бы разом, стоит камере отвести
        взгляд от начала координат.

        Тени рампы не отбрасывают: карта теней растянута на весь округ, тексель
        покрывает около четырёхсот метров, и от двухкилометровой коробки в ней
        осталось бы дрожащее пятно. Своё место в кадре она держит свечением.
      */}
      <instancedMesh
        ref={hotRef}
        args={[undefined, undefined, capacity]}
        frustumCulled={false}
        onUpdate={markDynamic}
      >
        <boxGeometry args={[1, 1, 1]} />
        <meshStandardMaterial
          color={palette.accent}
          emissive={palette.accent}
          emissiveIntensity={1.15}
          roughness={0.45}
          metalness={0.05}
        />
      </instancedMesh>

      {/*
        Рампы и хвост очереди. Цвет материала белый, настоящий приходит
        по-инстансно (DOCK_COLOR и QUEUED_COLOR выше): задай мы здесь оттенок, он
        домножился бы на инстансный и увёл бы из палитры оба цвета сразу.

        Тени и отбрасывает, и принимает — в отличие от машин. Разница в том, что
        машина на карте держит своё место СВЕЧЕНИЕМ, а ждущая коробка не светится
        вовсе: без тени она читалась бы наклейкой на рельефе, а не телом,
        стоящим у обочины. Тексель карты теней покрывает здесь около четырёхсот
        метров, поэтому тень выходит грубой — но именно она и сажает хвост
        очереди на землю.
      */}
      <instancedMesh
        ref={coldRef}
        args={[undefined, undefined, capacity]}
        frustumCulled={false}
        castShadow
        receiveShadow
        onUpdate={markDynamic}
      >
        <boxGeometry args={[1, 1, 1]} />
        <meshStandardMaterial roughness={0.8} metalness={0} />
      </instancedMesh>
    </>
  )
}

/**
 * Номер города в списке опорных точек.
 *
 * Линейный поиск по десятку узлов дешевле, чем Map, которую пришлось бы держать
 * рядом с массивом и синхронизировать с ним. Когда карта вырастет за пределы
 * ЦФО, это место придётся заменить индексом — и оно для того и вынесено в
 * отдельную функцию, а не размазано по циклу кадра.
 */
function anchorIndex(anchors: readonly Anchor[], id: CityId): number {
  for (let i = 0; i < anchors.length; i++) {
    if (anchors[i].id === id) return i
  }
  return -1
}
