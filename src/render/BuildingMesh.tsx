/**
 * ПОВТОР КОНСТАНТ ЗАСТРОЙКИ, И ЭТО ТОТ ЖЕ ИЗВЕСТНЫЙ ДОЛГ, ЧТО В IndustryMesh.
 *
 * Радиус пятна города считается в CityMesh и наружу не отдаётся — оттуда
 * экспортируется только cityPoint. Постройке радиус нужен ровно затем, чтобы
 * встать ЗА застройкой, поэтому формула повторена и здесь. Честное решение —
 * экспорт силуэта из CityMesh, и его стоит сделать при первой же правке того
 * файла; пока копий три, и они обязаны совпадать с REFERENCE_POPULATION,
 * REFERENCE_RADIUS, RADIUS_EXPONENT и PAD_MARGIN.
 *
 * Долг закрыт запасом, как и там: двор отодвигается на радиус пятна ПЛЮС
 * половину собственной длины плюс просвет, и расхождение формул на десяток
 * процентов не даёт видимого дефекта. Рост города тоже покрыт запасом —
 * расстановка считается один раз (см. подписку компонента) и за партию не
 * двигается, а пятно растёт как pop^0.42, то есть просвет съедается только
 * примерно двукратным ростом населения.
 */
const CITY_REFERENCE_POPULATION = 300_000
const CITY_REFERENCE_RADIUS = 6
const CITY_RADIUS_EXPONENT = 0.42
const CITY_PAD_MARGIN = 1.3

/** Радиус городской площадки — то, за что постройка обязана выйти. */
function cityPadRadius(population: number): number {
  const scale = population / CITY_REFERENCE_POPULATION
  return (
    CITY_REFERENCE_RADIUS * scale ** CITY_RADIUS_EXPONENT * CITY_PAD_MARGIN
  )
}

