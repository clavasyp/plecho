/**
 * Рампа: невысокая платформа у обочины, к которой машина подаётся под погрузку.
 *
 * ВЫСОТА У НЕЁ НЕ НУЛЕВАЯ, И ЭТО НЕ УКРАШЕНИЕ. Плоское пятно двора на изометрии
 * не читается вовсе — цвет площадки почти совпадает с рельефом, а тени у плиты
 * нет по определению. Платформа в семьсот метров ловит ключевой свет боком,
 * получает собственную тень и потому видна как ОБЪЕКТ; заодно машина на ней
 * стоит выше ждущих, и это ещё один канал различия сверх цвета.
 */
