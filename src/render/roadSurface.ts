/**
 * Покрытие дороги: чем лента полотна отличается от нарисованной по линейке
 * полоски.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. RoadMesh.tsx — компонент: он импортирует React и
 * Three, а vitest в этом проекте гоняется в чистом Node (vitest.config.ts,
 * environment: 'node'). Всё, что здесь лежит, — арифметика без единого объекта
 * сцены, и потому проверяется юнит-тестом, а не разглядыванием снимка. Сам
 * RoadMesh остаётся тем, чем должен: сборкой буферов из этих чисел.
 *
 * ─── ПОЧЕМУ ОСЬ ДОРОГИ ОСТАЁТСЯ ПРЯМОЙ, А ПОКРЫТИЕ — НЕТ ────────────────────
 *
 * В шапке RoadMesh записан запрет: гнуть дорогу нельзя, потому что машина
 * интерполируется по progress ЛИНЕЙНО между концами ребра, и любой декоративный
 * изгиб увёл бы полотно из-под фур. Запрет верен и снимать его нечем: в графе у
 * ребра по-прежнему нет промежуточных точек.
 *
 * Но требование «дорога не должна быть идеально прямой линией между точками»
 * относится не к ОСИ, а к ПОКРЫТИЮ, и эти две вещи разделяются полностью:
 *
 *   ОСЬ — прямая до последнего знака. По ней едет машина, по ней же считается
 *   километраж, и трогать её нельзя.
 *
 *   КРОМКИ — гуляют. Полоса набирает ширину влево и вправо НЕЗАВИСИМО, и обе
 *   величины медленно дышат вдоль трассы. Асфальт перестаёт быть прямоугольником
 *   и становится положенным: где-то шире, где-то уже, обочина то подходит к
 *   полотну, то отходит.
 *
 * Машина при этом не съезжает с дороги никогда: разброс кромки ограничен долей
 * полуширины (SHOULDER_WOBBLE_*), а сцеп уже полотна и стоит на оси.
 *
 * ─── ВТОРОЕ: КАЧЕСТВО ПОКРЫТИЯ НАКОНЕЦ ВИДНО ────────────────────────────────
 *
 * У ребра есть `quality` 0..1 — он решает скорость (world/speed.ts) и износ
 * (logistics/wear.ts), то есть половину экономики рейса. На карте он не был
 * показан ничем: разбитая Р-92 (0.55) и свежая М-1 (0.88) выглядели одинаково, и
 * игрок узнавал разницу только из счёта за ремонт.
 *
 * Качество говорит ДВУМЯ каналами сразу, и оба геометрические либо тональные,
 * но ни один не вводит нового цвета:
 *
 *   ТОН. Убитое покрытие подмешивает к цвету класса цвет РЕЛЬЕФА — дорога
 *   буквально начинает растворяться в поле, по которому идёт. Направление
 *   выбрано не на вкус: у классов уже есть тональная лестница «чем выше класс,
 *   тем светлее» (palette.ts), и качество обязано двигать тон в ту же сторону,
 *   что и класс, иначе разбитая федеральная стала бы светлее хорошей
 *   региональной и лестница классов сломалась бы об качество.
 *
 *   КРОМКА. Чем хуже покрытие, тем сильнее гуляет ширина: у М-1 края почти
 *   ровные, у Р-92 полотно рвано расширяется и сужается. Это тот же сигнал,
 *   прочитанный формой, — и он работает там, где тон уже неразличим: на общем
 *   плане, где вся дорога занимает два пикселя по толщине.
 */

import { Rng } from '../sim/rng'
import { palette } from './palette'

// ─── Разбиение ленты на участки ────────────────────────────────────────────

/**
 * Целевая длина участка ленты, км.
 *
 * Ориентир — не дорога, а ЭКРАН. При полностью отдалённой камере карта в 600 км
 * ложится примерно в 800 пикселей, то есть километр — это чуть больше пикселя.
 * Одиннадцать километров дают участок в десяток пикселей: кромка успевает
 * заметно сместиться от узла к узлу и при этом не превращается в пилу с зубом в
 * пиксель, которую сглаживание всё равно замажет в грязь.
 *
 * Сверху величину держит цена: самое длинное ребро карты (410 км) даёт 37
 * участков, вся сеть из восемнадцати рёбер — около четырёхсот четырёхугольников
 * на всю дорожную сеть. Это по-прежнему три вызова отрисовки и меньше тысячи
 * треугольников.
 */
export const SURFACE_STEP_KM = 11

/**
 * Меньше трёх участков не бывает даже у самого короткого ребра.
 *
 * Один участок — это ровно прежняя прямая лента; два дают единственный узел
 * посередине и читаются как излом, а не как дыхание кромки. С трёх начинается
 * рисунок.
 */
export const MIN_SURFACE_STEPS = 3

/** На сколько участков резать ленту длиной km. */
export function surfaceSteps(km: number): number {
  if (!Number.isFinite(km) || km <= 0) return MIN_SURFACE_STEPS
  return Math.max(MIN_SURFACE_STEPS, Math.round(km / SURFACE_STEP_KM))
}

// ─── Дыхание кромки ────────────────────────────────────────────────────────

/**
 * Разброс полуширины у идеального покрытия (quality = 1), доля от полуширины.
 *
 * Ноль сюда ставить нельзя. Новая дорога тоже не отчерчена по линейке — у неё
 * есть уширения на подъёмах, карманы, съезды, — и полностью ровная кромка
 * читается как чертёж, а не как асфальт. Пять процентов — это на федеральной
 * трассе (полуширина 1.7 км) восемь десятых километра на всю ленту, то есть
 * около пикселя на общем плане: видно как лёгкую неровность и не видно как
 * дефект.
 */
export const SHOULDER_WOBBLE_NEW = 0.05

/**
 * Сколько разброса добавляет полностью убитое покрытие (quality = 0).
 *
 * Двадцать процентов сверху — предел, за которым лента перестаёт быть дорогой.
 * Проверялось об самое узкое полотно: у региональной дороги полуширина 1.15 км,
 * при quality = 0.5 разброс выходит 0.16, то есть кромка гуляет на 0.18 км в
 * каждую сторону. Сцеп машины (полуширина 1.2 км) при этом местами выступает за
 * кромку на считаные сотни метров — на изометрии это доли пикселя, и это честно:
 * на разбитой двухполоске фура и правда идёт по всей ширине.
 */
export const SHOULDER_WOBBLE_WORN = 0.2

/** Насколько сильно гуляет кромка у покрытия такого качества. */
export function shoulderWobble(quality: number): number {
  return SHOULDER_WOBBLE_NEW + SHOULDER_WOBBLE_WORN * (1 - clamp01(quality))
}

/**
 * Насколько узел кромки помнит предыдущий.
 *
 * ГЛАВНОЕ ЧИСЛО ЭТОГО ФАЙЛА, и оно про то, чем дорога отличается от помех.
 * Независимая случайная ширина в каждом узле даёт ленту, дребезжащую каждые
 * десять пикселей, — глаз читает такое как шум растеризации, а не как рельеф
 * дороги. Память в 0.85 растягивает волну примерно на семь узлов, то есть на
 * восемьдесят километров: полотно широко раскрывается перед развязкой и медленно
 * поджимается на перегоне, ровно как на трассе, снятой с высоты.
 *
 * Наверх величину держит то же соображение: при 0.95 лента перестаёт меняться
 * вовсе на длине ребра и превращается в прежний прямоугольник, только чуть
 * другой ширины.
 */
export const SHOULDER_MEMORY = 0.85

/**
 * Множители полуширины по узлам ленты — отдельно для левой и правой кромки.
 *
 * ДВЕ НЕЗАВИСИМЫЕ ПОСЛЕДОВАТЕЛЬНОСТИ, А НЕ ОДНА СИММЕТРИЧНАЯ. Симметричное
 * дыхание даёт «сосиску» — тело, у которого ось видна глазом по самой форме, и
 * такая лента снова читается как проведённая по линейке, только с утолщениями.
 * Независимые кромки убирают ось из картинки совсем: видно полосу асфальта, у
 * которой обе стороны живут своей жизнью, — а настоящая ось при этом остаётся
 * ровно там, где была, и по ней по-прежнему едет машина.
 *
 * СЛУЧАЙНОСТЬ ПРИВЯЗАНА К КЛЮЧУ РЕБРА (Rng.forKey — тот же приём, которым
 * CityMesh раскладывает застройку). Дорога Москва — Тула обязана выглядеть
 * одинаково в этой партии, в следующей и на снимке в тесте: рисунок кромки —
 * такая же характеристика места, как её длина.
 *
 * Соль разводит левую и правую кромки в разные потоки: возьми мы один поток на
 * обе, они получили бы сдвинутую на шаг, но ту же самую последовательность — и
 * лента поехала бы вбок вместо того, чтобы дышать.
 *
 * Ход — авторегрессия первого порядка с приведением к [-1, 1]. Коэффициент при
 * новом слагаемом взят как sqrt(1 − memory²) не для красоты: при нём разброс
 * ряда не зависит от памяти, и SHOULDER_MEMORY можно крутить, не пересчитывая
 * заново SHOULDER_WOBBLE_*.
 */
export function shoulderProfile(
  seed: string,
  nodes: number,
  quality: number,
): { left: number[]; right: number[] } {
  const count = Math.max(2, Math.floor(nodes))
  const amplitude = shoulderWobble(quality)

  return {
    left: walk(Rng.forKey(seed, 1), count, amplitude),
    right: walk(Rng.forKey(seed, 2), count, amplitude),
  }
}

function walk(rng: Rng, count: number, amplitude: number): number[] {
  const out: number[] = new Array<number>(count)
  const fresh = Math.sqrt(1 - SHOULDER_MEMORY * SHOULDER_MEMORY)

  let value = rng.range(-1, 1)
  for (let i = 0; i < count; i++) {
    out[i] = 1 + amplitude * value
    value = clampUnit(value * SHOULDER_MEMORY + rng.range(-1, 1) * fresh)
  }

  return out
}

// ─── Тон покрытия ──────────────────────────────────────────────────────────

/**
 * Какую долю пути до цвета рельефа проходит совсем убитое покрытие.
 *
 * Не единицу намеренно: дорога качеством в ноль всё ещё дорога, и слиться с
 * полем она не имеет права — по ней ездят и её видно. Семь десятых оставляют
 * худшему покрытию карты (Р-132 Ярославль — Тверь, 0.5) заметный отрыв от
 * рельефа и при этом разводят его с лучшим (М-1, 0.88) на четверть расстояния до
 * земли — а это уже видно, когда две такие дороги сходятся в одном городе.
 */
export const QUALITY_FADE = 0.7

/** Цвет полотна: цвет класса, приглушённый качеством покрытия. */
export function surfaceTone(base: string, quality: number): string {
  return mixHex(base, palette.terrain, (1 - clamp01(quality)) * QUALITY_FADE)
}

// ─── Цветовая арифметика ───────────────────────────────────────────────────
//
// Работы с цветом здесь ровно столько, сколько нужно дорогам, и живёт она тут по
// той же причине, что и всё остальное в этом файле: её надо проверять в Node,
// где нет Three с его Color. Нового цвета арифметика не заводит — она умеет
// только смешать два уже существующих значения палитры и измерить их яркость.

/** Разобрать '#rrggbb' в три составляющих 0..255. Мусор даёт чёрный. */
function parseHex(hex: string): [number, number, number] {
  const value = hex.trim().replace('#', '')
  if (value.length !== 6) return [0, 0, 0]
  const n = Number.parseInt(value, 16)
  if (!Number.isFinite(n)) return [0, 0, 0]
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

/**
 * Смешать два цвета палитры.
 *
 * Смешение идёт в тех же координатах, в которых цвета записаны, — то есть в
 * sRGB. Физически честнее было бы мешать в линейном пространстве, но здесь
 * решается задача не физическая, а тональная: нужно, чтобы половина пути от
 * дороги к рельефу выглядела серединой ГЛАЗУ. Линейное смешение даёт середину
 * заметно темнее воспринимаемой, и лестница качества съехала бы в тёмный конец.
 */
export function mixHex(from: string, to: string, t: number): string {
  const share = clamp01(t)
  const a = parseHex(from)
  const b = parseHex(to)

  let out = '#'
  for (let i = 0; i < 3; i++) {
    const mixed = Math.round(a[i] + (b[i] - a[i]) * share)
    out += mixed.toString(16).padStart(2, '0')
  }
  return out
}

/**
 * Относительная яркость цвета по WCAG.
 *
 * Нужна не для красоты, а как ЛИНЕЙКА ПОРЯДКА ВНИМАНИЯ. Вся карта построена на
 * утверждениях вида «своё ярче чужого, чужое ярче фона»; пока они живут только в
 * комментариях, любая правка палитры может их молча перевернуть. С линейкой
 * порядок проверяется тестом.
 */
export function relativeLuminance(hex: string): number {
  const [r, g, b] = parseHex(hex)
  return (
    0.2126 * toLinear(r / 255) + 0.7152 * toLinear(g / 255) + 0.0722 * toLinear(b / 255)
  )
}

function toLinear(channel: number): number {
  return channel <= 0.04045
    ? channel / 12.92
    : Math.pow((channel + 0.055) / 1.055, 2.4)
}

export function clamp01(value: number): number {
  if (!Number.isFinite(value)) return 0
  return value < 0 ? 0 : value > 1 ? 1 : value
}

function clampUnit(value: number): number {
  return value < -1 ? -1 : value > 1 ? 1 : value
}
