/**
 * Высоты слоёв сцены по оси Y, километры.
 *
 * Единственный источник правды о том, что над чем лежит. Раньше эти числа были
 * рассыпаны по трём файлам, каждый выбирал их для себя — и они разошлись:
 * площадки городов оказались на километре, дороги под ними, здания росли от
 * нуля и уходили нижним километром внутрь собственной площадки, а машины
 * ездили ниже любой дороги. Каждое число по отдельности выглядело разумно.
 *
 * Правило: слой добавляется ТОЛЬКО сюда, и порядок задаётся здесь же. Ни один
 * компонент не имеет права придумать себе высоту сам.
 *
 * Зазоры маленькие и неравномерные намеренно. Карта разглядывается сверху под
 * изометрией, поэтому вертикаль почти не читается — зазор нужен ровно затем,
 * чтобы соседние плоскости не мерцали от z-fighting, и ни на километр больше:
 * приподнятая на видимую высоту дорога начала бы отбрасывать тень и висеть
 * над землёй.
 */

export const layers = {
  /** Подложка. Основание всей сцены. */
  ground: 0,

  /** Площадка города — пятно застройки под зданиями. */
  cityPad: 0.08,

  /**
   * Дорожное полотно по классам.
   *
   * Порядок совпадает со значимостью: федеральная лежит поверх региональной на
   * пересечениях, и на развязке видно, какая из дорог главная.
   */
  roadLocal: 0.14,
  roadRegional: 0.18,
  roadFederal: 0.22,

  /**
   * Основание зданий — ровно уровень площадки.
   *
   * Здание должно стоять НА площадке, а не быть в неё вкопанным: непрозрачный
   * диск площадки срезает всё, что ниже него.
   */
  buildingBase: 0.08,

  /**
   * Линии игрока — поверх любой дороги, под машинами.
   *
   * Линия не объект мира, а замысел игрока, наложенный на карту: она обязана
   * лежать поверх полотна, иначе кольцо теряется ровно на федеральных трассах,
   * по которым и идёт. Но под машинами — на карте едут они, а линия только
   * показывает, где.
   *
   * Выбранная линия поднята ещё на ступень. Причина не в красоте: две ленты на
   * одной высоте пересекаются копланарно и мерцают Z-конфликтом на пересечениях,
   * а выбранная линия обязана быть видна целиком и всегда. Разница в сотые доли
   * километра на изометрии не читается вовсе — она нужна только глубине.
   */
  lineRoute: 0.25,
  lineSelected: 0.27,

  /**
   * Машины — выше самой высокой дороги.
   *
   * Иначе фура на федеральной трассе уходит под полотно и исчезает именно там,
   * где на неё чаще всего смотрят.
   */
  vehicle: 0.3,
} as const

/** Высота полотна для класса дороги. */
export function roadElevation(roadClass: string): number {
  switch (roadClass) {
    case 'федеральная':
      return layers.roadFederal
    case 'региональная':
      return layers.roadRegional
    default:
      return layers.roadLocal
  }
}
