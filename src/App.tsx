/**
 * Корень приложения — только композиция.
 *
 * Здесь нет и не должно быть игровой логики: App заводит игровой цикл, ставит
 * холст со сценой и кладёт поверх слой интерфейса. Всё остальное решают
 * симуляция (src/sim), сцена (src/render) и панели (src/ui).
 *
 * ЭТОТ ФАЙЛ — СПИСОК ТОГО, ЧТО ИГРОК ВИДИТ ПОВЕРХ КАРТЫ, и относиться к нему
 * надо соответственно. В срезе 2 три панели на две с лишним тысячи строк были
 * написаны, покрыты тестами и не смонтированы ни в одно дерево: они
 * компилировались, их юнит-тесты были зелёными, а в игре их не существовало.
 * Юнит-тест проверяет модуль, но не может проверить, что модуль кто-то вызвал.
 * Отсюда два правила, которые здесь и живут:
 *
 *   1. НОВАЯ ПАНЕЛЬ ПОЯВЛЯЕТСЯ В ЭТОМ ФАЙЛЕ В ТОМ ЖЕ КОММИТЕ, ЧТО И ЕЁ ФАЙЛ.
 *   2. Её присутствие в DOM доказывает сквозной тест в tests/e2e, а не вера.
 */

import { Canvas } from '@react-three/fiber'
import { useRivalRunner } from './app/ai/runner'
import { useGameLoop } from './app/loop'
import { useSound } from './app/sound'
import { Scene } from './render/Scene'
import { BottleneckPanel } from './ui/BottleneckPanel'
import { CityPanel } from './ui/CityPanel'
import { CompanyPanel } from './ui/CompanyPanel'
import { FleetPanel } from './ui/FleetPanel'
import { LineEditor } from './ui/LineEditor'
import { RivalPanel } from './ui/RivalPanel'
import { TimeControls } from './ui/TimeControls'
import './App.css'

/**
 * Сколько пикселей отдавать на пиксель разметки.
 *
 * СЧИТАЕТСЯ ОТ ПЛОЩАДИ ЭКРАНА, А НЕ БЕРЁТСЯ ЧИСЛОМ, и вот почему. Прежде здесь
 * стояло `dpr={[1, 2]}` — «не больше двойки». На ноутбуке это честные два, и
 * ничего страшного; на мониторе 2560×1440 с ретиной те же два дают буфер
 * 5120×2880, то есть 14.7 миллиона пикселей. Дальше это число умножается на всю
 * цепочку постпроцессинга: четырёхкратное сглаживание, мип-пирамида блума,
 * буферы тональной компрессии, виньетки и зерна. Оперативной памяти на такой
 * кадр уходит в разы больше самой игры, чей замер — 65 МБ кучи, стабильных.
 *
 * Поэтому ограничение стоит не на КРАТНОСТИ, а на итоговом числе пикселей.
 * Бюджет в 4.5 миллиона — это примерно 2560×1760: на таком разрешении тёмная
 * низкополигональная сцена с блумом и зерном уже не выигрывает от добавочной
 * плотности, зато мелкий монитор по-прежнему получает свою честную двойку.
 *
 * Пол в единицу обязателен: на очень широком экране формула ушла бы ниже, и
 * картинка стала бы мыльной ради памяти, которой и так хватает.
 */
function renderScale(): number {
  const PIXEL_BUDGET = 4_500_000

  const width = globalThis.innerWidth || 1920
  const height = globalThis.innerHeight || 1080
  const density = globalThis.devicePixelRatio || 1

  const fit = Math.sqrt(PIXEL_BUDGET / (width * height))
  return Math.min(density, Math.max(1, fit))
}

export default function App() {
  // Единственное место, где заводится цикл: он живёт ровно столько же, сколько
  // приложение, и не должен перезапускаться от перерисовок.
  useGameLoop()

  /*
   * ВТОРОЙ ЦИКЛ СРЕЗА 6 — И ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ИГРА ВООБЩЕ ДОХОДИТ ДО
   * СЕТИ.
   *
   * Отсюда и только отсюда достижимы app/ai/runner.ts, app/ai/prompt.ts и
   * app/ai/gemini.ts: до этой строчки весь путь языковой модели — три файла с
   * зелёными юнит-тестами — не был импортирован НИ ОТКУДА и в собранную игру не
   * попадал вовсе. Ровно тот случай, ради которого в шапке этого файла записаны
   * оба правила: юнит-тест проверяет модуль, но не может проверить, что модуль
   * кто-то вызвал.
   *
   * Хук, а не компонент, потому что рисовать ему нечего: он подписывается на
   * стор, раз в игровые сутки принимает решение за каждого конкурента и раз в
   * игровой месяц спрашивает модель. Ответ кладётся не в тик, а в СОСТОЯНИЕ
   * (deliverPlan в app/store.ts) — граница между сетью и симуляцией проходит
   * там, и здесь она не нарушается ничем.
   *
   * БЕЗ КЛЮЧА ВЫЗОВ ОСТАЁТСЯ. Раннер сам проверяет наличие ключа и, не найдя
   * его, возвращает конкурентов скрипту — то есть их ведёт фаза решений тика, а
   * лента рассуждений наполняется скриптовыми мыслями с честной пометкой. Игра
   * без ключа обязана быть полной игрой, а не игрой без конкурентов; условие
   * вокруг этой строки означало бы ровно обратное.
   */
  useRivalRunner()

  /*
   * ТРЕТИЙ ЦИКЛ — ЗВУК, И ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ИГРА ВООБЩЕ ЗВУЧИТ.
   *
   * Хук, а не компонент, по той же причине, что и раннер конкурентов: рисовать
   * ему нечего. Он подписывается на стор, сравнивает соседние снимки и на
   * разнице между ними синтезирует отклик — симуляция про звук не знает и знать
   * не должна, граница src/sim здесь не пересекается ни разу.
   *
   * ПО УМОЛЧАНИЮ ЗВУКА НЕТ, и выключенный он не стоит ничего: подписка выходит
   * до разбора состояния. Включает его кнопка в панели времени — единственная,
   * и это требование браузера, а не вкус: Web Audio не запускается без жеста
   * пользователя.
   */
  useSound()

  return (
    <>
      <div className="scene">
        {/*
          На холсте — только то, что относится к контексту рендера целиком.
          Камеру, свет, туман и постпроцессинг настраивает Scene: там им место,
          и там их видно все сразу.

          Плотность пикселей считает renderScale — разбор у неё же.
        */}
        <Canvas shadows dpr={renderScale()}>
          <Scene />
        </Canvas>
      </div>

      <div className="ui-layer">
        <TimeControls />
        <CompanyPanel />
        <CityPanel />

        {/*
          Точка монтирования редактора линий — и одновременно то место, за
          которое сквозной тест берётся, чтобы доказать, что редактор в игре
          есть. Обёртка не рисует ничего своего: `display: contents` не создаёт
          бокса вовсе, поэтому раскладка панели остаётся её собственным делом, а
          правило `.ui-layer > *` из App.css продолжает работать — pointer-events
          свойство наследуемое, и `auto` с обёртки достаётся самой панели.

          Тест ищет непустой ТЕКСТ внутри этого узла. Пустая обёртка текста не
          даёт, значит проверка не может пройти при невставленном редакторе — и
          при этом не привязывается ни к одному слову из чужого файла.
        */}
        <div data-testid="line-editor" style={{ display: 'contents' }}>
          <LineEditor />
        </div>

        {/*
          Панель парка среза 4: классы техники, прицепы, водители, износ, ТО и
          поломки. Обёртка та же и по той же причине, что у редактора линий, —
          это не копипаста, а сознательно ОДИНАКОВАЯ точка крепления: у каждой
          панели, чьё присутствие доказывает сквозной тест, должен быть один и
          тот же вид якоря, иначе следующий такой тест придумает третий способ.

          ПАНЕЛЬ МОНТИРУЕТСЯ БЕЗУСЛОВНО, а свёрнута она или развёрнута — её
          собственное дело: открытость лежит в ui/fleetSelection.ts, потому что
          дверей в парк две (своя кнопка и строка «столько-то машин стоит» в
          панели компании). App про эти двери не знает и знать не должен — он
          отвечает на вопрос «что вообще есть на экране», а не «что сейчас
          раскрыто». Ровно поэтому и обёртка не пуста никогда: у закрытой панели
          внутри лежит её кнопка вызова, и сквозной тест отличает «панель есть,
          но свёрнута» от «панель забыли смонтировать».

          ПАНЕЛЬ СМОНТИРОВАНА ЗДЕСЬ, А НЕ ВНУТРИ ПАНЕЛИ КОМПАНИИ, хотя парк —
          часть компании и открывается в том числе оттуда. Причина в том, как
          ими пользуются. Панель компании отвечает на вопрос «как идут дела» и
          читается мельком; панель парка отвечает на «что делать с этой машиной»
          и требует, чтобы в ней копались: списать, отправить на ТО, пересадить
          водителя. Вложенная, она закрывалась бы вместе с чужим заголовком и
          наследовала бы его ширину — то есть решение о машине зависело бы от
          того, развёрнут ли отчёт о деньгах.
        */}
        <div data-testid="fleet-panel" style={{ display: 'contents' }}>
          <FleetPanel />
        </div>

        {/*
          Панель узких мест среза 5 — главный экран того, что этот срез добавил
          в игру. Якорь тот же и по той же причине, что у редактора линий и у
          панели парка: у каждой панели, чьё присутствие доказывает сквозной
          тест, должен быть ОДИН И ТОТ ЖЕ вид точки крепления, иначе следующий
          такой тест придумает четвёртый способ до неё дотянуться.

          ПАНЕЛЬ МОНТИРУЕТСЯ БЕЗУСЛОВНО. Свёрнута она или развёрнута — её
          собственное дело (открытость лежит в useState внутри неё, дверь сюда
          одна); App отвечает на вопрос «что вообще есть на экране», а не «что
          сейчас раскрыто». Свёрнутая панель не пуста никогда — внутри лежит её
          кнопка вызова, и сквозной тест отличает «панель есть, но свёрнута» от
          «панель забыли смонтировать».

          СТОИТ ПОСЛЕДНЕЙ В СПИСКЕ, И ЭТО НЕ ПОРЯДОК ВАЖНОСТИ. Панели раскладывает
          App.css, а не порядок узлов; здесь порядок означает лишь очерёдность
          появления в срезах, и нарушать её значило бы потерять единственную
          подсказку о том, откуда каждая панель взялась.
        */}
        <div data-testid="bottleneck-panel" style={{ display: 'contents' }}>
          <BottleneckPanel />
        </div>

        {/*
          Панель соперников среза 6 — главный экран того, что этот срез добавил в
          игру, и половина ценности всей затеи с конкурентами. Соперник, чьи
          мотивы видны, читается как соперник; невидимый — как необъяснимый шум в
          экономике: груз со склада кто-то забрал, а причины на экране нет.

          Якорь тот же и по той же причине, что у редактора линий, панели парка и
          панели узких мест: у каждой панели, чьё присутствие доказывает сквозной
          тест, должен быть ОДИН И ТОТ ЖЕ вид точки крепления, иначе следующий
          такой тест придумает пятый способ до неё дотянуться.

          ПАНЕЛЬ МОНТИРУЕТСЯ БЕЗУСЛОВНО, а свёрнута она или развёрнута — её
          собственное дело (открытость живёт в useState внутри неё, дверь сюда
          одна). App отвечает на вопрос «что вообще есть на экране», а не «что
          сейчас раскрыто»; свёрнутая панель не пуста никогда — внутри лежит её
          кнопка вызова, и сквозной тест отличает «панель есть, но свёрнута» от
          «панель забыли смонтировать».

          СТОИТ ПОСЛЕДНЕЙ, И ЭТО НЕ ПОРЯДОК ВАЖНОСТИ: панели раскладывает
          App.css, а порядок узлов здесь означает лишь очерёдность появления в
          срезах — единственную оставшуюся подсказку о том, откуда каждая панель
          взялась.
        */}
        <div data-testid="rival-panel" style={{ display: 'contents' }}>
          <RivalPanel />
        </div>
      </div>
    </>
  )
}
