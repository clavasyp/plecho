/**
 * Корень приложения — только композиция.
 *
 * Здесь нет и не должно быть игровой логики: App заводит игровой цикл, ставит
 * холст со сценой и кладёт поверх слой интерфейса. Всё остальное решают
 * симуляция (src/sim), сцена (src/render) и панели (src/ui).
 *
 * ЭТОТ ФАЙЛ — СПИСОК ТОГО, ЧТО ИГРОК ВИДИТ ПОВЕРХ КАРТЫ, и относиться к нему
 * надо соответственно. В срезе 2 три панели на две с лишним тысячи строк были
 * написаны, покрыты тестами и не смонтированы ни в одно дерево: они
 * компилировались, их юнит-тесты были зелёными, а в игре их не существовало.
 * Юнит-тест проверяет модуль, но не может проверить, что модуль кто-то вызвал.
 * Отсюда два правила, которые здесь и живут:
 *
 *   1. НОВАЯ ПАНЕЛЬ ПОЯВЛЯЕТСЯ В ЭТОМ ФАЙЛЕ В ТОМ ЖЕ КОММИТЕ, ЧТО И ЕЁ ФАЙЛ.
 *   2. Её присутствие в DOM доказывает сквозной тест в tests/e2e, а не вера.
 */

import { Canvas } from '@react-three/fiber'
import { useGameLoop } from './app/loop'
import { Scene } from './render/Scene'
import { CityPanel } from './ui/CityPanel'
import { CompanyPanel } from './ui/CompanyPanel'
import { FleetPanel } from './ui/FleetPanel'
import { LineEditor } from './ui/LineEditor'
import { TimeControls } from './ui/TimeControls'
import './App.css'

export default function App() {
  // Единственное место, где заводится цикл: он живёт ровно столько же, сколько
  // приложение, и не должен перезапускаться от перерисовок.
  useGameLoop()

  return (
    <>
      <div className="scene">
        {/*
          На холсте — только то, что относится к контексту рендера целиком.
          Камеру, свет, туман и постпроцессинг настраивает Scene: там им место,
          и там их видно все сразу.

          dpr ограничен двойкой: на ретине честный devicePixelRatio означает
          вчетверо больше пикселей ради разницы, которую на тёмной сцене
          с блумом не разглядеть, — а тиков за кадр нужно успевать до десяти.
        */}
        <Canvas shadows dpr={[1, 2]}>
          <Scene />
        </Canvas>
      </div>

      <div className="ui-layer">
        <TimeControls />
        <CompanyPanel />
        <CityPanel />

        {/*
          Точка монтирования редактора линий — и одновременно то место, за
          которое сквозной тест берётся, чтобы доказать, что редактор в игре
          есть. Обёртка не рисует ничего своего: `display: contents` не создаёт
          бокса вовсе, поэтому раскладка панели остаётся её собственным делом, а
          правило `.ui-layer > *` из App.css продолжает работать — pointer-events
          свойство наследуемое, и `auto` с обёртки достаётся самой панели.

          Тест ищет непустой ТЕКСТ внутри этого узла. Пустая обёртка текста не
          даёт, значит проверка не может пройти при невставленном редакторе — и
          при этом не привязывается ни к одному слову из чужого файла.
        */}
        <div data-testid="line-editor" style={{ display: 'contents' }}>
          <LineEditor />
        </div>

        {/*
          Панель парка среза 4: классы техники, прицепы, водители, износ, ТО и
          поломки. Обёртка та же и по той же причине, что у редактора линий, —
          это не копипаста, а сознательно ОДИНАКОВАЯ точка крепления: у каждой
          панели, чьё присутствие доказывает сквозной тест, должен быть один и
          тот же вид якоря, иначе следующий такой тест придумает третий способ.

          ПАНЕЛЬ МОНТИРУЕТСЯ БЕЗУСЛОВНО, а свёрнута она или развёрнута — её
          собственное дело: открытость лежит в ui/fleetSelection.ts, потому что
          дверей в парк две (своя кнопка и строка «столько-то машин стоит» в
          панели компании). App про эти двери не знает и знать не должен — он
          отвечает на вопрос «что вообще есть на экране», а не «что сейчас
          раскрыто». Ровно поэтому и обёртка не пуста никогда: у закрытой панели
          внутри лежит её кнопка вызова, и сквозной тест отличает «панель есть,
          но свёрнута» от «панель забыли смонтировать».

          ПАНЕЛЬ СМОНТИРОВАНА ЗДЕСЬ, А НЕ ВНУТРИ ПАНЕЛИ КОМПАНИИ, хотя парк —
          часть компании и открывается в том числе оттуда. Причина в том, как
          ими пользуются. Панель компании отвечает на вопрос «как идут дела» и
          читается мельком; панель парка отвечает на «что делать с этой машиной»
          и требует, чтобы в ней копались: списать, отправить на ТО, пересадить
          водителя. Вложенная, она закрывалась бы вместе с чужим заголовком и
          наследовала бы его ширину — то есть решение о машине зависело бы от
          того, развёрнут ли отчёт о деньгах.
        */}
        <div data-testid="fleet-panel" style={{ display: 'contents' }}>
          <FleetPanel />
        </div>
      </div>
    </>
  )
}
