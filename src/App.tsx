/**
 * Сколько пикселей отдавать на пиксель разметки.
 *
 * СЧИТАЕТСЯ ОТ ПЛОЩАДИ ЭКРАНА, А НЕ БЕРЁТСЯ ЧИСЛОМ, и вот почему. Прежде здесь
 * стояло `dpr={[1, 2]}` — «не больше двойки». На ноутбуке это честные два, и
 * ничего страшного; на мониторе 2560×1440 с ретиной те же два дают буфер
 * 5120×2880, то есть 14.7 миллиона пикселей. Дальше это число умножается на всю
 * цепочку постпроцессинга: четырёхкратное сглаживание, мип-пирамида блума,
 * буферы тональной компрессии, виньетки и зерна. Оперативной памяти на такой
 * кадр уходит в разы больше самой игры, чей замер — 65 МБ кучи, стабильных.
 *
 * Поэтому ограничение стоит не на КРАТНОСТИ, а на итоговом числе пикселей.
 * Бюджет в 4.5 миллиона — это примерно 2560×1760: на таком разрешении тёмная
 * низкополигональная сцена с блумом и зерном уже не выигрывает от добавочной
 * плотности, зато мелкий монитор по-прежнему получает свою честную двойку.
 *
 * ─── ПОЛ В ЕДИНИЦУ БЫЛ ОШИБКОЙ, И ОН ОТМЕНЯЛ ВЕСЬ БЮДЖЕТ ───────────────────
 *
 * Здесь стояло `Math.min(density, Math.max(1, fit))` с пояснением «пол в
 * единицу обязателен, иначе картинка станет мыльной». Довод верен для экрана с
 * ретиной и неверен для всех остальных, а именно они и страдают.
 *
 * Разбор на числах. Монитор 4K БЕЗ ретины: плотность 1, площадь 8.29 Мпикс,
 * fit = 0.74. Пол поднимает 0.74 до единицы, минимум с плотностью даёт единицу
 * — и буфер выходит 8.29 Мпикс при бюджете 4.5, то есть превышение в 1.84
 * раза. Бюджет не действовал ВООБЩЕ ни на одном экране с плотностью единица,
 * а это большинство настольных мониторов.
 *
 * Цена превышения замерена прямо: период кадра на 8.29 Мпикс — 2230 мс против
 * 1411 мс на бюджетных 4.50, то есть в 1.58 раза. Для кадра, у которого
 * 76–77% времени линейно зависит от числа пикселей, это самый сильный рычаг из
 * существующих: снятие ВСЕЙ арифметики пяти эффектов постпроцессинга даёт
 * максимум 17%, а один этот пол — 37%.
 *
 * Пол оставлен, но опущен до 0.72 и получил другой смысл: он защищает не от
 * мыла, а от вырождения. Ниже него лента федеральной дороги на предельном
 * отдалении уходит под пиксель даже с пиксельным полом шейдера (pixelFloor.ts),
 * а этот проект дважды терял дорожную сеть визуально и третьего раза не хочет.
 *
 * ПЕРЕСЧЁТ НА ИЗМЕНЕНИЕ ОКНА обязателен и его тоже не было: функция звалась
 * один раз при монтировании, поэтому перенос окна на другой монитор оставлял
 * старую плотность. Замер: после 1920×1080 при плотности 2 и последующего
 * сжатия до 1280×720 плотность оставалась 1.4731 вместо 2.0000.
 */
const PIXEL_BUDGET = 4_500_000

/**
 * Ниже этого плотность не опускается ни при каком экране.
 *
 * 0.72 — не круглое число и взято не на глаз: при нём буфер на мониторе 4K
 * выходит ровно в бюджет (8.29 × 0.72² = 4.30 Мпикс), а лента федеральной
 * дороги на предельном отдалении остаётся выше полутора пикселей буфера, ниже
 * которых растеризатор начинает пропускать её через одну.
 */
const MIN_DENSITY = 0.72

function renderScale(): number {
  const width = globalThis.innerWidth || 1920
  const height = globalThis.innerHeight || 1080
  const density = globalThis.devicePixelRatio || 1

  const fit = Math.sqrt(PIXEL_BUDGET / (width * height))
  return Math.max(MIN_DENSITY, Math.min(density, fit))
}

/**
 * Плотность, которая пересчитывается при изменении окна.
 *
 * Слушать надо И resize, И медиазапрос по плотности: перенос окна между
 * мониторами с разной плотностью НЕ ВСЕГДА меняет размер окна, и на одном лишь
 * resize такой перенос остался бы незамеченным. Медиазапрос строится на текущее
 * значение и пересоздаётся после каждого срабатывания — иначе он сработает
 * ровно один раз и замолчит.
 */
function useRenderScale(): number {
  const [scale, setScale] = useState(renderScale)

  useEffect(() => {
    let query: MediaQueryList | null = null

    const update = (): void => {
      setScale(renderScale())
      listen()
    }

    const listen = (): void => {
      query?.removeEventListener('change', update)
      query = globalThis.matchMedia?.(
        `(resolution: ${globalThis.devicePixelRatio || 1}dppx)`,
      )
      query?.addEventListener('change', update)
    }

    globalThis.addEventListener('resize', update)
    listen()

    return () => {
      globalThis.removeEventListener('resize', update)
      query?.removeEventListener('change', update)
    }
  }, [])

  return scale
}

/**
 * Просил ли кто-нибудь возможность ЧИТАТЬ нарисованный кадр.
 *
 * Отдельная функция, а не выражение в разметке, ровно затем, чтобы условие
 * было видно целиком и в одном месте: собранная игра НИКОГДА не платит за эту
 * возможность (import.meta.env.DEV — константа этапа сборки, ветка вырезается),
 * а отладочная — только если её попросили адресом.
 */
function readbackWanted(): boolean {
  if (!import.meta.env.DEV) return false
  return new URLSearchParams(globalThis.location?.search ?? '').has('pixels')
}

