/**
 * Что игрок делает с линиями прямо сейчас: какая открыта и включён ли режим
 * добавления остановок.
 *
 * Отдельный store по той же причине, что и ui/selection.ts, и разбор там полный.
 * Коротко: GameState — это сейв («сохранение это JSON.stringify(state)», прямая
 * цитата из types.ts), а «открыт редактор линии line-2 и включён режим
 * добавления» к миру отношения не имеет. Положи это в GameState — и оно
 * немедленно окажется в сохранении, в сравнении снимков для интерполяции и в
 * тестах симуляции, которым до курсора игрока дела нет.
 *
 * Второй store, а не поле в selection.ts, — потому что подписки разные. Выбор
 * города меняется от каждого клика по карте, и панель редактора не обязана
 * перерисовываться от этого; режим добавления, наоборот, живёт весь сеанс
 * проектирования и не должен будить карточку города.
 *
 * ГЛАВНОЕ ПРАВИЛО ФАЙЛА: РЕЖИМ ДОБАВЛЕНИЯ ГАСНЕТ САМ ПРИ ЛЮБОЙ СМЕНЕ КОНТЕКСТА.
 * Клик по карте в этом режиме означает «добавить остановку», а вне его — «открыть
 * город». Это самый неприятный вид интерфейса из возможных: один и тот же жест
 * делает разное, и игрок узнаёт об этом по последствиям. Поэтому режим не
 * переживает ни закрытия панели, ни переключения на другую линию, ни удаления
 * той, которую редактировали, — и живёт ровно там, где виден переключатель.
 */

import { create } from 'zustand'
import type { LineId } from '../sim/types'

export type LineSelectionStore = {
  /** Открыт ли редактор линий. false — на экране только кнопка вызова. */
  open: boolean

  /** Линия, которую правят. null — показан список линий компании. */
  line: LineId | null

  /**
   * Режим добавления остановок: клик по городу на карте дописывает остановку
   * в конец кольца.
   *
   * Включается только при открытой линии — добавлять остановки в список линий
   * бессмысленно, а состояние, которое ничего не значит, рано или поздно
   * что-нибудь да сломает.
   */
  adding: boolean

  /** Показать редактор. Линия и режим при этом не меняются. */
  openEditor: () => void

  /** Убрать редактор с экрана. Режим добавления гаснет вместе с ним. */
  closeEditor: () => void

  /** Кнопка вызова: открыть, если закрыт, и наоборот. */
  toggleEditor: () => void

  /**
   * Открыть линию на правку. null — вернуться к списку линий.
   *
   * Панель при этом открывается: выбрать линию можно и снаружи (кликом по ней
   * на карте, когда появится отрисовка линий), и такой выбор обязан показать
   * то, что выбрали.
   */
  selectLine: (line: LineId | null) => void

  /** Включить или выключить режим добавления остановок. */
  setAdding: (adding: boolean) => void

  /** Переключатель режима — то самое единственное место, где он виден. */
  toggleAdding: () => void
}

export const useLineSelection = create<LineSelectionStore>((set) => ({
  open: false,
  line: null,
  adding: false,

  openEditor: () => set({ open: true }),

  closeEditor: () => set({ open: false, adding: false }),

  toggleEditor: () =>
    set((store) =>
      store.open ? { open: false, adding: false } : { open: true },
    ),

  selectLine: (line) =>
    set((store) => ({
      open: true,
      line,
      // Смена линии гасит режим ВСЕГДА, даже если игрок вернулся к той же самой:
      // проверка «а линия-то прежняя» сэкономила бы один клик и взамен оставила
      // бы состояние, в котором клик по карте дописывает остановку в линию, на
      // которую игрок уже не смотрит.
      adding: store.line === line ? store.adding : false,
    })),

  setAdding: (adding) =>
    set((store) => ({
      // Режим без открытой линии не значит ничего — включать его нечему.
      adding: adding && store.line !== null,
    })),

  toggleAdding: () =>
    set((store) => ({ adding: !store.adding && store.line !== null })),
}))

/**
 * Управление редактором из консоли и из e2e — только в разработке.
 *
 * Кликнуть по трёхмерной сцене из теста можно лишь по экранным координатам,
 * которые зависят от камеры и разрешения (тот же довод, что в ui/selection.ts).
 * Здесь это важнее вдвойне: сценарий среза — «открыть редактор, включить режим,
 * накликать кольцо», и без такой двери он не проверяется вовсе. В
 * продакшен-сборке ветка вырезается целиком: import.meta.env.DEV — константа
 * этапа сборки.
 */
if (import.meta.env.DEV) {
  ;(globalThis as unknown as { __plechoLines?: unknown }).__plechoLines =
    useLineSelection
}
