/**
 * Что происходит с населением и почему.
 *
 * Вторая по важности вещь в панели после остановленного завода. Рост города —
 * отложенная награда за УСТОЙЧИВОЕ снабжение (порог в три недели обоснован в
 * economy/consumption.ts), и без счётчика на экране игрок видит только
 * результат через семь минут наблюдения, но не видит, сколько до него осталось.
 * Прерванная серия при этом обнуляется молча — вот её и надо сказать вслух.
 *
 * ЭТА СТРОКА НИКОГДА НЕ ТРЕВОЖНАЯ, хотя соблазн подсветить «город сжимается»
 * велик. Проверено на живой партии: в срезе 2 у игрока одна машина, снабжать
 * она не успевает никого, и обнулённый счётчик — состояние ВСЕХ десяти городов
 * почти всё время. Акцент, который горит всегда и везде, перестаёт что-либо
 * значить — ровно по той причине, по которой в панели нет вечной строки
 * «мощность 100%». Тёплый цвет остаётся за остановленным предприятием: это
 * состояние редкое, конкретное и чинится одним рейсом.
 */
export function citySupplyStatus(city: City): string {
  if (city.suppliedDays > GROWTH_THRESHOLD_DAYS) {
    return `город растёт — снабжение ровное ${fmtDays(city.suppliedDays)} сут`
  }
  if (city.suppliedDays > 0) {
    return `снабжается ${fmtDays(city.suppliedDays)} из ${GROWTH_THRESHOLD_DAYS} сут до роста`
  }
  return 'снабжение прервано — город сжимается'
}
