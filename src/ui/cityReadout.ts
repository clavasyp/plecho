/**
 * Чтение города: снимок мира → ответы на вопросы игрока.
 *
 * Слой между симуляцией и панелью (ui/CityPanel.tsx). Здесь нет ни React, ни
 * цветов, ни разметки — только «что происходит с этим городом и почему». Панель
 * ниже лишь раскрашивает то, что ей отдали отсюда.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Формально — потому что Fast Refresh ломается, когда
 * .tsx экспортирует что-то кроме компонентов, и правка панели перезагружала бы
 * страницу целиком вместо горячей замены. По существу — потому что врать может
 * только этот слой. Разметку ломает дизайнер, и это видно глазом; диагноз
 * ломается молча: числа остаются правдоподобными, а смысл меняется на
 * противоположный. Отделённый, он проверяется тестом без браузера — и
 * проверяется против настоящего прогона производства (cityReadout.test.ts).
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: ни одной собственной формулы. Вместимость
 * складов, потолок мощности после простоя, суточный спрос, порог роста — всё
 * зовётся из src/sim теми же функциями, которыми это считает симуляция.
 * Панель, показывающая «осталось 4 тонны» по своей формуле, хуже, чем
 * отсутствие панели: она врёт убедительно. Как в этом проекте расходятся две
 * формулы одного и того же — разобрано в шапке sim/world/speed.ts.
 *
 * ВСЁ ПЕРЕВОДИТСЯ В СУТКИ. Тонны сами по себе не говорят ни о чём: «118 тонн
 * муки» — это много или мало? Правая колонка панели везде отвечает на один и
 * тот же вопрос — СКОЛЬКО СУТОК ДО БЕДЫ. Для склада города это голод, для входа
 * предприятия — остановка без сырья, для выхода — остановка от переполнения.
 * Столько у игрока есть времени доехать, и это единственная величина, из
 * которой он может строить расписание.
 */

import { CONSUMER_CARGO, RECIPE_BY_INDUSTRY } from '../data/recipes'
import { GROWTH_THRESHOLD_DAYS, demandPerDay } from '../sim/economy/consumption'
import {
  IDLE_UTILIZATION,
  capacityFactor,
  stockCapacity,
} from '../sim/economy/production'
import { cityCapacity } from '../sim/logistics/loading'
import { TICKS_PER_DAY } from '../sim/types'
import type {
  CargoType,
  City,
  Industry,
  IndustryId,
  IndustryType,
  Tons,
} from '../sim/types'

/**
 * Порог значимости тоннажа — тот же, что в симуляции.
 *
 * Склад с остатком 4.4e-16 тонны обязан читаться как пустой и здесь тоже:
 * панель, которая пишет «сырьё есть» там, где производство видит ноль, — это
 * худший вид расхождения, потому что обвинят в нём симуляцию.
 */
const TONS_EPSILON = 1e-9

// ─── Форматирование ────────────────────────────────────────────────────────

/**
 * Тонны для чтения глазом.
 *
 * До десяти тонн — с десятой долей: на этом масштабе разница между 0.4 и 4
 * тоннами решает, поедет машина или нет. Выше — целые: сотая доля от ста тонн
 * не значит ничего, а знаков в колонке съедает столько же.
 */
export function fmtTons(tons: Tons): string {
  if (!Number.isFinite(tons)) return '—'
  if (tons <= TONS_EPSILON) return '0'
  if (tons < 10) return tons.toFixed(1)
  return String(Math.round(tons))
}

/** Запас времени в сутках. Всё, что дальше трёх месяцев, — просто «много». */
export function fmtDays(days: number): string {
  if (!Number.isFinite(days)) return '—'
  if (days >= 99) return '99+'
  if (days >= 10) return String(Math.round(days))
  return days.toFixed(1)
}

/**
 * Население округляется только здесь, при выводе.
 *
 * В симуляции оно дробное намеренно (см. runConsumption): прирост за тик —
 * доли человека, и округление на каждом шаге убило бы рост совсем.
 */
export function fmtPopulation(population: number): string {
  return Math.round(population).toLocaleString('ru-RU')
}

// ─── Склады ────────────────────────────────────────────────────────────────

/** Строка склада: сколько лежит, сколько влезет и сколько осталось времени. */
export type StockLine = {
  cargo: CargoType
  tons: Tons
  capacity: Tons
  /**
   * Правая приписка: «3.0 сут», «нет», «полон», «—».
   *
   * Готовая строка, а не число, потому что «сколько суток осталось» и «уже
   * случилось» — разные сообщения, и второе бессмысленно выражать нулём: «0.0
   * сут» игрок прочитает как «почти пусто», хотя пусто уже совсем.
   */
  note: string
  /**
   * Приписка описывает УЖЕ случившееся, а не запас времени.
   *
   * Панель показывает это контрастом, а не цветом: строка становится обычной
   * яркости среди приглушённых. Этого хватает, чтобы поймать её взглядом, и это
   * не тратит акцент — он зарезервирован за причиной остановки.
   */
  urgent: boolean
}

/** Склад города по потребительским грузам. */
export function cityStockLines(city: City): StockLine[] {
  return CONSUMER_CARGO.map((cargo) => {
    const tons = city.stock[cargo] ?? 0
    const perDay = demandPerDay(city.population, cargo)

    // Спроса нет вовсе — город без населения или пробел в нормах. Прочерк
    // честнее любого числа: считать «на сколько хватит» тут не от чего.
    if (perDay <= 0) {
      return { cargo, tons, capacity: 0, note: '—', urgent: false }
    }

    return {
      cargo,
      tons,
      capacity: cityCapacity(city, cargo),
      note: tons <= TONS_EPSILON ? 'нет' : `${fmtDays(tons / perDay)} сут`,
      urgent: tons <= TONS_EPSILON,
    }
  })
}

// ─── Предприятия ───────────────────────────────────────────────────────────

export type IndustryStatus = 'работает' | 'снижает темп' | 'стоит'

export type IndustryView = {
  id: IndustryId
  type: IndustryType
  /** Загрузка последнего отработанного тика, 0..1. */
  utilization: number
  /** Доля паспортной мощности, оставшаяся после простоя, 0..1. */
  factor: number
  /** Накопленный простой в сутках. */
  idleDays: number
  status: IndustryStatus
  /**
   * Что именно режет темп, в порядке важности. Пусто — ничто не мешает.
   * Обычно причина ровно одна: два потолка одновременно — редкое совпадение.
   */
  reasons: string[]
  inputs: StockLine[]
  output: StockLine | null
}

/**
 * Диагноз предприятия — то, ради чего вся панель и написана.
 *
 * Мир в «ПЛЕЧЕ» не выдаёт заданий. Завод не пишет «нужно 50 тонн зерна» — он
 * просто останавливается, и игрок обязан САМ понять, что случилось: подвоза нет
 * или вывоза нет. Снаружи эти два состояния неотличимы — и там и там на карте
 * стоит город, в котором ничего не происходит. А действия игрока прямо
 * противоположны: в одном случае везти сырьё СЮДА, в другом забирать продукцию
 * ОТСЮДА. Ошибиться здесь — потерять сутки на рейс не в ту сторону.
 *
 * Расчёт повторяет stepIndustry из economy/production.ts шаг в шаг — три
 * потолка в том же порядке, — но вместо выпуска возвращает ПРИЧИНУ. Показатель
 * загрузки её не содержит: он одинаков и для «нет сырья», и для «некуда девать
 * продукцию».
 *
 * ПРИЧИНА СЧИТАЕТСЯ ПО ТЕКУЩЕМУ СКЛАДУ, А utilization — ФАКТ ПРОШЛОГО ТИКА.
 * Расхождение намеренное и полезное: «загрузка 100%, нет сырья» означает
 * «работал, но сырьё только что кончилось» — предупреждение за пятнадцать
 * игровых минут до остановки. Ровно то, что игроку нужно знать раньше, чем факт.
 *
 * Функция чистая: смотрит на один снимок и ничего не меняет, как и вся
 * симуляция.
 */
export function describeIndustry(industry: Industry): IndustryView {
  const base = {
    id: industry.id,
    type: industry.type,
    utilization: industry.utilization,
    factor: capacityFactor(industry.idleTicks),
    idleDays: industry.idleTicks / TICKS_PER_DAY,
  }

  const recipe = RECIPE_BY_INDUSTRY[industry.type]
  if (!recipe) {
    // Тип без рецепта — дыра в данных. Производство в этом случае молча ничего
    // не делает; панель обязана сказать вслух, иначе игрок будет искать причину
    // остановки в своих маршрутах и не найдёт её никогда.
    return {
      ...base,
      status: 'стоит',
      reasons: ['нет рецепта — ошибка в данных мира'],
      inputs: [],
      output: null,
    }
  }

  // Паспортная мощность за тик и мощность, доступная после простоя.
  const nameplate = recipe.dailyRate / TICKS_PER_DAY
  const capacity = nameplate * base.factor

  const reasons: string[] = []

  // Потолок «место на складе продукции». Разбирается первым, потому что это
  // фирменная остановка этой игры: завод душится тем, что сам произвёл.
  const stored = industry.stock[recipe.output] ?? 0
  const outputCapacity = stockCapacity(industry, recipe.output)
  const room = Math.max(0, outputCapacity - stored)

  let planned = Math.min(capacity, room)

  if (room <= TONS_EPSILON) {
    reasons.push('склад продукции полон — некуда производить')
  } else if (room < capacity) {
    reasons.push('склад продукции переполняется')
  }

  const output: StockLine = {
    cargo: recipe.output,
    tons: stored,
    capacity: outputCapacity,
    // Сутки ДО ЗАПОЛНЕНИЯ при паспортном темпе — дедлайн приезда за грузом.
    note:
      room <= TONS_EPSILON
        ? 'полон'
        : `${fmtDays(recipe.dailyRate > 0 ? room / recipe.dailyRate : Number.POSITIVE_INFINITY)} сут`,
    urgent: room <= TONS_EPSILON,
  }

  // Потолок «сырьё». У источников список пуст — их ничем не остановить, кроме
  // собственного склада, и в этом весь смысл связи с миром за краем карты.
  const inputs: StockLine[] = []
  for (const input of recipe.inputs) {
    const tons = industry.stock[input.type] ?? 0
    const perDay = recipe.dailyRate * input.perUnit

    inputs.push({
      cargo: input.type,
      tons,
      capacity: stockCapacity(industry, input.type),
      note:
        tons <= TONS_EPSILON
          ? 'нет'
          : `${fmtDays(perDay > 0 ? tons / perDay : Number.POSITIVE_INFINITY)} сут`,
      urgent: tons <= TONS_EPSILON,
    })

    // Тот же расчёт, что в производстве: доступное сырьё, делённое на расход на
    // тонну продукции, и есть максимально возможный выпуск по этому входу.
    const limit = tons / input.perUnit
    planned = Math.min(planned, limit)

    if (tons <= TONS_EPSILON) {
      reasons.push(`нет сырья — ${input.type}`)
    } else if (limit < capacity) {
      reasons.push(`сырья не хватает — ${input.type}`)
    }
  }

  /*
   * Порог «стоит» взят у симуляции (IDLE_UTILIZATION) и сравнивается с
   * ПАСПОРТНОЙ мощностью, а не с доступной после простоя — ровно как там.
   * Иначе изувеченный простоем завод рапортовал бы «работает», выдавая сорок
   * процентов от паспорта, и деградация перестала бы читаться.
   */
  const status: IndustryStatus =
    planned <= nameplate * IDLE_UTILIZATION
      ? 'стоит'
      : planned < capacity - TONS_EPSILON
        ? 'снижает темп'
        : 'работает'

  return { ...base, status, reasons, inputs, output }
}

