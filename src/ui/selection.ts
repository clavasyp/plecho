/**
 * Что игрок выбрал на карте.
 *
 * Отдельный store, а не поле в app/store.ts, и причина не в удобстве, а в
 * контракте состояния. GameState — это САВЕЙВ: «сохранение это
 * JSON.stringify(state)», прямая цитата из types.ts. Выбранный город к миру
 * отношения не имеет — он не переживает перезагрузку страницы, его нет смысла
 * восстанавливать и уж точно нельзя показывать конкуренту. Положи его в
 * GameState — и он немедленно окажется в сейве, в сравнении снимков для
 * интерполяции и в тестах симуляции, которым до курсора игрока дела нет.
 *
 * Второе следствие — подписки. Смена выбора не должна будить ни одного
 * подписчика игрового состояния: панель времени, машины и дороги перерисовываться
 * от клика по городу не обязаны. Отдельный store разделяет графы подписок
 * физически, а не по договорённости о том, какие селекторы писать.
 *
 * Сюда же переедет остальное состояние указателя, когда оно появится:
 * выделенная линия, режим прокладки маршрута, открытая вкладка отчёта. Всё это
 * одной природы — «на что игрок смотрит», а не «что в мире происходит».
 */

import { create } from 'zustand'
import type { CityId } from '../sim/types'

export type SelectionStore = {
  /** Город, по которому открыта панель. null — панели нет. */
  city: CityId | null

  /**
   * Выбрать город. Повторный клик по тому же городу СНИМАЕТ выбор.
   *
   * Переключение живёт здесь, а не в обработчике клика, потому что зависит от
   * текущего значения: обработчику пришлось бы читать store через getState и
   * решать за него. Заодно «клик по выбранному городу закрывает панель» —
   * правило игры, а не деталь слоя кликабельных сфер, и место ему рядом с самим
   * состоянием.
   */
  select: (city: CityId) => void

  /** Снять выбор: крестик в панели и Escape. */
  clear: () => void
}

export const useSelection = create<SelectionStore>((set) => ({
  city: null,

  select: (city) =>
    set((store) => ({ city: store.city === city ? null : city })),

  clear: () => set({ city: null }),
}))

/**
 * Выбор города из консоли и из e2e — только в разработке.
 *
 * Кликнуть по трёхмерной сцене из теста можно лишь по экранным координатам, а
 * они зависят от камеры и разрешения: такой тест ломался бы от любой правки
 * кадрирования, ничего не проверяя по существу. В продакшен-сборке ветка
 * вырезается целиком.
 */
if (import.meta.env.DEV) {
  ;(globalThis as unknown as { __plechoSelect?: unknown }).__plechoSelect = (
    id: string,
  ) => useSelection.getState().select(id as never)
}
