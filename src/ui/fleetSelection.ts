/**
 * Открыта ли панель парка.
 *
 * Отдельный store по той же причине, что ui/selection.ts и ui/lineSelection.ts,
 * и разбор там полный. Коротко: GameState — это сейв («сохранение это
 * JSON.stringify(state)», прямая цитата из types.ts), а «игрок открыл парк» к
 * миру отношения не имеет. Положи это в GameState — и оно немедленно окажется в
 * сохранении, в сравнении снимков для интерполяции и в тестах симуляции,
 * которым до курсора игрока дела нет.
 *
 * ПОЧЕМУ НЕ useState ВНУТРИ ПАНЕЛИ, раз потребитель как будто один. Потому что
 * их два, и это не случайность: у панели парка есть СОБСТВЕННАЯ кнопка вызова
 * (панель сама сворачивается в неё, как редактор линий), а открывает её ещё и
 * панель компании — из строки «столько-то машин не возит». Приборная доска
 * обязана уметь отправить игрока туда, где беду чинят; для этого ей нужно
 * дотянуться до чужого состояния, и общий store — единственный способ сделать
 * это, не пряча одну панель внутрь другой и не заводя второй флаг, который
 * рано или поздно разойдётся с первым (тогда игрок увидит две одинаковые
 * панели друг на друге и закроет их двумя нажатиями, не поняв, что случилось).
 *
 * ВЫБРАННОЙ МАШИНЫ ЗДЕСЬ НЕТ, и это осознанно. Она живёт в самой панели: за её
 * пределами выбор не значит ничего — в отличие от выбранной линии, которая
 * подсвечивается на карте и потому лежит в общем store. Состояние, которое
 * никому снаружи не видно, но хранится снаружи, однажды переживёт закрытие
 * панели, и объяснить это будет нечем.
 */

import { create } from 'zustand'

export type FleetPanelStore = {
  /** Развёрнута ли панель. false — на экране только кнопка вызова. */
  open: boolean

  /** Показать парк. Зовётся кнопкой панели компании. */
  openPanel: () => void

  /** Убрать панель с экрана. Крестик, Escape. */
  closePanel: () => void

  /** Кнопка вызова: открыть, если закрыт, и наоборот. */
  togglePanel: () => void
}

export const useFleetPanel = create<FleetPanelStore>((set) => ({
  open: false,

  openPanel: () => set({ open: true }),
  closePanel: () => set({ open: false }),
  togglePanel: () => set((store) => ({ open: !store.open })),
}))

/**
 * Управление панелью из консоли и из e2e — только в разработке.
 *
 * Тот же приём, что в ui/lineSelection.ts, и по той же причине: сквозной тест
 * обязан уметь привести игру в нужное состояние, не гадая по пикселям.
 * Разворачивать панель тест всё равно должен КЛИКОМ — иначе он не докажет, что
 * кнопка существует, — а эта дверь для отладки и для сценариев, которым парк
 * нужен уже открытым. В продакшен-сборке ветка вырезается целиком:
 * import.meta.env.DEV — константа этапа сборки.
 */
if (import.meta.env.DEV) {
  ;(globalThis as unknown as { __plechoFleet?: unknown }).__plechoFleet =
    useFleetPanel
}
