/**
 * Рёбра графа.
 *
 * Идентификатор выводится из пары городов, а не пишется руками: так он всегда
 * читается в отладке («moscow-tula») и физически не может разъехаться с
 * концами ребра.
 */
export const EDGES: Edge[] = ROADS.map(
  ([from, to, km, route, roadClass, quality]) => ({
    id: edgeId(`${from}-${to}`),
    from: cityId(from),
    to: cityId(to),
    km,
    class: roadClass,
    route,
    quality,
  }),
)

/** Рёбра по идентификатору — строится из EDGES, разойтись с ним не может. */
export const EDGES_BY_ID: Record<EdgeId, Edge> = Object.fromEntries(
  EDGES.map((edge) => [edge.id, edge]),
) as Record<EdgeId, Edge>
