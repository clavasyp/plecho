/**
 * Граф автодорог Центрального федерального округа — рёбра игрового мира.
 *
 * Главное в этом файле — километры. Здесь везде расстояние ПО ДОРОГЕ между
 * центрами городов, сверенное по маршрутизаторам, а не по прямой. Разница не
 * косметическая и не постоянная: Москва — Тула по прямой 173 км, по М-2
 * «Крым» — 185, а Ярославль — Тверь по прямой 255 против 328 через Углич и
 * Калязин. Коэффициент извилистости гуляет от 1.07 до 1.30, то есть даже
 * поправка «умножить прямую на 1.15» дала бы промах в обе стороны. Ошибка
 * копится в самом чувствительном месте экономики: выручка рейса считается от
 * километров, расход топлива и износ — тоже, и заниженный на 20% граф сделает
 * перевозки прибыльнее, чем они есть. Поэтому по прямой не считаем нигде.
 *
 * Класс ребра здесь — не выписка из реестра Росавтодора, а пропускная
 * способность. Формально Р-92, Р-120 и Р-132 — дороги федерального значения,
 * но это две встречные полосы через деревни, а не магистраль с разделителем.
 * В игре класс задаёт базовую скорость, поэтому М-трассы получают
 * 'федеральная', а Р-трассы — 'региональная'. Расхождение с формальным
 * статусом сознательное.
 *
 * Качество (0..1) — то же самое, но плавно: сколько времени реально теряется
 * на обгонах, светофорах в населённых пунктах и убитом покрытии. Разброс у
 * федеральных 0.78–0.88, у региональных 0.50–0.70, и внутри каждой группы он
 * содержательный: М-1 «Беларусь» на всём протяжении первой категории (0.88),
 * а М-2 южнее Тулы уже местами двухполосная (0.78); Тула — Калуга по Р-132
 * короткая и живая (0.65), а Ярославль — Тверь через Углич и Калязин —
 * худший участок «Золотого кольца» (0.50).
 *
 * Каких рёбер здесь намеренно нет:
 *
 * - Москва — Орёл. М-2 «Крым» идёт через Тулу, и сумма плеч 185 + 183 = 368
 *   совпадает с паспортными 367 км. Отдельное ребро было бы вторым экземпляром
 *   той же дороги и ломало бы поиск пути.
 * - Москва — Брянск. М-3 «Украина» проходит мимо Калуги в 15 км, поэтому
 *   маршрут через Калугу (190 + 226 = 416) длиннее прямого (380) ровно на
 *   заезд в город. Держим Калугу узлом коридора: десять узлов на округ — это
 *   и так грубая сетка, дублирующий радиус из Москвы делает её звездой.
 * - М-4 «Дон», М-9 «Балтия», М-11 «Нева». Ни один из десяти городов на них не
 *   стоит: М-4 уходит на Воронеж, М-9 — на Ржев и Великие Луки, М-11 обходит
 *   Тверь в 20 км и дублирует М-10. Появятся вместе с городами.
 *
 * Рёбра ненаправленные: одна пара городов — одно ребро. Направление движения
 * живёт в VehiclePosition.fromId, а не в графе.
 */

import { cityId, edgeId } from '../sim/types'
import type { Edge, EdgeId, RoadClass } from '../sim/types'

/** Строка таблицы дорог: откуда, куда, км по дороге, трасса, класс, качество. */
type RoadRow = readonly [
  from: string,
  to: string,
  km: number,
  route: string,
  roadClass: RoadClass,
  quality: number,
]

