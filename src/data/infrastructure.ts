import type { BuildingType, Tons } from '../sim/types'

/**
 * Пропускная способность и постройки.
 *
 * Смысл всего файла в одном числе — во ВРЕМЕНИ ПОГРУЗКИ. Пока оно было нулём,
 * очередей не существовало, и десятая машина на линии стоила ровно столько же,
 * сколько первая. Как только погрузка занимает часы, а постов конечное число,
 * у сети появляется пропускная способность, а у игрока — задача её расшивать.
 */

/**
 * Сколько тонн проходит через один пост за час.
 *
 * Шесть тонн ЗИЛа грузятся 24 минуты, двадцать тонн тягача — 80 минут. Погрузка
 * обязана быть ЗАМЕТНОЙ, но не главной.
 *
 * Ставка подбиралась дважды и оба раза вниз по времени. Шесть тонн в час
 * убивали тягача насмерть: узловая остановка кольца держит пост ДВАЖДЫ —
 * выгрузка плюс погрузка, — и при девятичасовой смене водителя машина почти не
 * ездила. Десять тонн в час всё ещё срезали пропускную способность настолько,
 * что постоянные расходы (зарплата и содержание построек) переставали
 * покрываться: рейсов стало меньше, а платить за сутки меньше не стали.
 *
 * Очередь при этом никуда не делась, и это ключевое наблюдение: она возникает
 * из числа ПОСТОВ, а не из длительности обслуживания. Вторая машина на том же
 * заводе ждёт освобождения рампы независимо от того, двадцать это минут или
 * два часа. Поэтому время можно было сокращать, не теряя саму механику.
 */
export const TONS_PER_POST_HOUR = 15

/**
 * Постов у предприятия и у города без построек игрока.
 *
 * Один. Это принципиально: вторая машина на том же заводе обязана вставать в
 * очередь СРАЗУ, а не после пятой. Узкое место должно обнаруживаться на втором
 * грузовике, пока сеть ещё маленькая и понятная, — иначе игрок узнает о нём,
 * когда у него двадцать машин и разбираться уже поздно.
 */
export const BASE_POSTS = 1

