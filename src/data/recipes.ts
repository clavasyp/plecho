/**
 * Надбавка за сложность обработки груза, множитель к тарифу.
 *
 * ЗДЕСЬ БЫЛА ГЛАВНАЯ ОШИБКА БАЛАНСА ВСЕГО ПРОЕКТА, и стоит объяснить, какая
 * именно.
 *
 * Раньше это была ставка за тонну: от 800 за кругляк до 2000 за топливо. Она
 * казалась разумной — продукция дороже сырья, — но разброс в два с половиной
 * раза полностью перебивал штраф за порожний пробег. Замеры ревизии:
 *
 *   Орёл ↔ Тула, оба плеча гружёные, 0.24% порожнего   →  −18 666 руб/сут
 *   Москва → Рязань, обратно пустым, 68.89% порожнего  →   +1 347 руб/сут
 *
 * То есть метрика, объявленная главной в игре, не предсказывала прибыль, а
 * местами показывала обратное, и оптимизация по ней уводила игрока в убыток.
 * Вся конструкция среза держалась на тезисе «порожний пробег превращает
 * прибыльный рейс в убыточный», а тезис не выполнялся.
 *
 * Причина в том, что ценность груза не имеет отношения к работе транспорта.
 * Перевозчику всё равно, что везти: он продаёт тонно-километры. В отрасли так
 * и есть — тариф считается за тонно-километр, а тип груза даёт умеренную
 * надбавку за сложность обработки: цистерна, допуск, длинномер, тара.
 *
 * Поэтому ставка переехала в TARIFF_PER_TON_KM (src/data/operating.ts), а
 * здесь остались множители в узком диапазоне. Диапазон не косметический: при
 * нём тезис держится для КАЖДОГО груза, разбор границ — в operating.ts.
 */
/*
 * ДИАПАЗОН СУЖЕН ПОСЛЕ ЗАМЕРА, И ВОТ ПОЧЕМУ.
 *
 * Прежний разброс 0.95…1.2 накладывался на потерю массы при переделе (perUnit
 * выше) и вместе с ней решал судьбу цепочки целиком. Считаем на кольце: из
 * кузова кругляка выходит 0.62 кузова пиломатериалов, из кузова нефти — 0.87
 * кузова топлива. Умножаем на надбавки — и обратное плечо лесной цепочки
 * приносит 0.62 × 1.0 = 0.62 против 0.87 × 1.2 = 1.04 у топливной, то есть в
 * ЛЬВОМ РАЗЕ БОЛЬШЕ. Замер планировщика на новых данных был однозначен:
 * прибыльных колец пятнадцать, и все пятнадцать — «нефть → топливо». Ни зерно,
 * ни лес не окупали водителя, а значит выбирать конкурентам было не из чего,
 * и ниша у нишевого характера могла быть ровно одна.
 *
 * Надбавка не должна складываться с физикой передела в один рычаг: за потерю
 * массы уже отвечает perUnit, и удваивать её ценой груза значит запретить
 * глубокие переделы навсегда. Поэтому разброс сжат до 1.05…1.15 — он
 * по-прежнему выражает возню с грузом, но перестал перевешивать всё остальное.
 *
 * ВЕРХНЯЯ ГРАНИЦА НЕ ПРОИЗВОЛЬНА: порог короткого плеча у ЗИЛа равен
 * m·h·p / (2c − m·t·p) и обязан остаться ниже самого короткого ребра карты в
 * 110 км (разбор — в шапке data/operating.ts). Отсюда p < 1.226; прежние 1.2
 * стояли почти вплотную к обрыву, нынешние 1.15 дают запас. Нижнюю границу
 * держит тягач: при p < 0.87 у него m·t·p проваливается ниже расходов на
 * километр, и гружёный рейс перестаёт окупать солярку.
 */
