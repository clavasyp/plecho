/**
 * Суточное потребление на тысячу жителей, тонн.
 *
 * ЭТО НЕ ПОЛНОЕ ПОТРЕБЛЕНИЕ ГОРОДА, а та его доля, которую закрывает
 * автомобильная доставка из промышленности внутри ЦФО. Остальное приходит по
 * железной дороге и из-за пределов округа — и в игре не моделируется, потому
 * что игра про автоперевозки.
 *
 * Разница принципиальная. Настоящая Москва съедает около 800 тонн муки в
 * сутки; один мукомольный комбинат в игре даёт 40. При «честных» нормах спрос
 * превышал выпуск мира в двадцать раз, все десять городов сжимались на 1% за
 * сто суток независимо от действий игрока, и главная петля среза — рост города
 * от снабжения — оказывалась недостижимой в принципе. Это была не сложность,
 * а сломанная механика: игрок не мог выиграть, что бы ни делал.
 *
 * Нормы подобраны так, чтобы суммарный спрос составлял примерно две трети
 * выпуска мира. Тогда есть запас на ошибки логистики, но нет права ничего не
 * делать. Проверка масштаба на краях:
 *
 *   Орёл (289 тыс.)   — 0.46 т муки в сутки: одна ходка ЗИЛа кормит две недели
 *   Москва (13.3 млн) — 21 т в сутки: половина выпуска единственного комбината
 *
 * Малые города берутся сразу, Москва остаётся целью на всю партию. Такой
 * градиент и нужен.
 */
export const CONSUMPTION_PER_1K: Record<string, number> = {
  мука: 0.0016,
  топливо: 0.005,
  пиломатериалы: 0.0022,
}

/**
 * Надбавка за сложность обработки груза, множитель к тарифу.
 *
 * ЗДЕСЬ БЫЛА ГЛАВНАЯ ОШИБКА БАЛАНСА ВСЕГО ПРОЕКТА, и стоит объяснить, какая
 * именно.
 *
 * Раньше это была ставка за тонну: от 800 за кругляк до 2000 за топливо. Она
 * казалась разумной — продукция дороже сырья, — но разброс в два с половиной
 * раза полностью перебивал штраф за порожний пробег. Замеры ревизии:
 *
 *   Орёл ↔ Тула, оба плеча гружёные, 0.24% порожнего   →  −18 666 руб/сут
 *   Москва → Рязань, обратно пустым, 68.89% порожнего  →   +1 347 руб/сут
 *
 * То есть метрика, объявленная главной в игре, не предсказывала прибыль, а
 * местами показывала обратное, и оптимизация по ней уводила игрока в убыток.
 * Вся конструкция среза держалась на тезисе «порожний пробег превращает
 * прибыльный рейс в убыточный», а тезис не выполнялся.
 *
 * Причина в том, что ценность груза не имеет отношения к работе транспорта.
 * Перевозчику всё равно, что везти: он продаёт тонно-километры. В отрасли так
 * и есть — тариф считается за тонно-километр, а тип груза даёт умеренную
 * надбавку за сложность обработки: цистерна, допуск, длинномер, тара.
 *
 * Поэтому ставка переехала в TARIFF_PER_TON_KM (src/data/operating.ts), а
 * здесь остались множители в узком диапазоне. Диапазон не косметический: при
 * нём тезис держится для КАЖДОГО груза, разбор границ — в operating.ts.
 */
