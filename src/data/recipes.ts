import type { CargoType, IndustryType, Recipe } from '../sim/types'

/**
 * Производственные цепочки.
 *
 * Три цепочки, каждая из трёх звеньев: источник → переработка → город.
 * Больше на срез 2 не нужно, а меньше — уже не экономика: при двух цепочках
 * игроку нечего между собой сравнивать, и оптимизация вырождается в «вози
 * то, что дороже».
 *
 *   зерно (элеватор)     → [мукомольный] → мука          → город
 *   кругляк (лесозагот.) → [ЦБК]         → пиломатериалы → город
 *   нефть (нефтебаза)    → [НПЗ]         → топливо       → город И ПАРК ИГРОКА
 *
 * Третья цепочка замыкается на самого игрока и этим отличается от первых двух.
 * Топливо, которое ты возишь, — то же самое топливо, которое жгут твои машины.
 * Наладил цепь нефть → НПЗ → город, и заправка рядом дешевеет; порвал — растут
 * издержки всего парка разом. Это первая петля обратной связи в игре, и она же
 * образец для остальных.
 *
 * ИСТОЧНИКИ производят без входного сырья. Так смоделирована связь с миром за
 * краем карты: зерно растёт в поле, лес валят в делянке, нефть приходит по
 * трубе. Моделировать это транспортом бессмысленно — игра про автоперевозки,
 * а не про сельское хозяйство.
 *
 * Всё в ТОННАХ. Единица одна на весь проект: грузоподъёмность, выпуск, склад,
 * ставка — всё сравнимо напрямую.
 */

/**
 * Расход сырья на тонну продукции.
 *
 * Всегда больше единицы: переработка теряет массу. Мука — отруби и усушка,
 * пиломатериалы — опилки и горбыль, топливо — потери при перегонке. Именно
 * поэтому вход по тоннажу всегда больше выхода, и подвозить надо больше, чем
 * вывозишь: несимметричность плеч заложена прямо в физике производства.
 */
export const RECIPES: Recipe[] = [
  // ─── Источники ───────────────────────────────────────────────────────────
  {
    industryType: 'элеватор',
    inputs: [],
    output: 'зерно',
    // Средний элеватор отгружает примерно столько, сколько увозят три-четыре
    // машины в сутки. Ниже — игроку нечего делать, выше — одна машина
    // физически не справится и цепочка встанет не по его вине.
    dailyRate: 60,
  },
  {
    industryType: 'лесозаготовка',
    inputs: [],
    output: 'кругляк',
    dailyRate: 50,
  },
  {
    industryType: 'нефтебаза',
    inputs: [],
    output: 'нефть',
    // Больше остальных: топливо потребляют и города, и весь парк игрока.
    dailyRate: 80,
  },

  // ─── Переработка ─────────────────────────────────────────────────────────
  {
    industryType: 'мукомольный',
    inputs: [{ type: 'зерно', perUnit: 1.25 }],
    output: 'мука',
    // 40 т муки требуют 50 т зерна — элеватор с его 60 закрывает потребность
    // с запасом, но только если игрок успевает вывозить. Запас намеренный:
    // цепочка должна прощать одну пропущенную ходку, а не рваться сразу.
    dailyRate: 40,
  },
  {
    industryType: 'ЦБК',
    inputs: [{ type: 'кругляк', perUnit: 1.6 }],
    output: 'пиломатериалы',
    // 30 т продукции требуют 48 т кругляка при выпуске лесозаготовки в 50.
    // Запас минимальный: самая требовательная к ритму цепочка из трёх.
    dailyRate: 30,
  },
  {
    industryType: 'НПЗ',
    inputs: [{ type: 'нефть', perUnit: 1.15 }],
    output: 'топливо',
    // 65 т топлива требуют 74.75 т нефти при выпуске нефтебазы в 80.
    dailyRate: 65,
  },
]

export const RECIPE_BY_INDUSTRY = Object.fromEntries(
  RECIPES.map((recipe) => [recipe.industryType, recipe]),
) as Record<IndustryType, Recipe>

