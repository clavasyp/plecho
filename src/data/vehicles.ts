import type { CargoRequirement, VehicleClass } from '../sim/types'
import { FUEL_PRICE_PER_LITER } from './operating'

/**
 * Справочник техники.
 *
 * ГЛАВНОЕ ЗДЕСЬ — не характеристики, а то, что КАЖДЫЙ класс отдельно
 * удовлетворяет инварианту баланса: кольцо с одним гружёным плечом убыточно,
 * с двумя — прибыльно. Разбор самого инварианта — в шапке ./operating.ts.
 *
 * Условие: c < m·t·p < 2c, где c — переменные расходы на километр, m —
 * тоннаж, t — тариф за тонно-километр, p — надбавка за груз (0.95…1.2).
 * И отдельно порог короткого плеча m·h·p / (2c − m·t·p) обязан быть меньше
 * самого короткого ребра карты (110 км, Тула — Калуга).
 *
 * Свести это одним тарифом на все классы невозможно: коридоры для шести и
 * двадцати тонн не пересекаются. Поэтому тариф и плата за погрузку падают с
 * размером партии — объёмная скидка, которая есть и в жизни. Расчёт по
 * каждому классу приведён рядом с ним и проверяется тестом.
 */

/** Переменные расходы класса, рубли на километр. */
export function costPerKm(vc: VehicleClass): number {
  return (vc.fuelPer100Km / 100) * FUEL_PRICE_PER_LITER + vc.maintenancePerKm
}

