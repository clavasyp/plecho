/**
 * ГЛАВНЫЙ ИНВАРИАНТ БАЛАНСА и вывод констант выше.
 *
 * Требование к игре одно: кольцо с одним гружёным плечом обязано быть
 * УБЫТОЧНЫМ, с двумя гружёными — прибыльным. На этом стоит весь замысел.
 *
 * Пусть плечо L километров, машина везёт m тонн, переменные расходы c рублей
 * на километр, тариф t за тонно-километр, погрузка h за тонну. Выручка за
 * гружёное плечо: m·(h + t·L). Кольцо из двух плеч стоит 2·L·c в любом случае.
 *
 *   одно гружёное плечо убыточно:   m·(h + t·L) < 2·L·c
 *   два гружёных плеча прибыльны:   2·m·(h + t·L) > 2·L·c
 *
 * На длинных плечах слагаемое с h исчезает, и оба условия сводятся к
 * неравенству, не зависящему ни от расстояния, ни от груза:
 *
 *                        c  <  m·t  <  2·c
 *
 * Подставляем: c = 10.5 (топливо) + 4.5 (обслуживание) = 15 руб/км, m = 6 т.
 *
 *      15  <  6 · t · надбавка  <  30
 *     2.5  <      t · надбавка  <  5
 *
 * При t = 3.3 и надбавках 0.95…1.2 (src/data/recipes.ts) произведение лежит
 * в 18.8…23.8 против коридора 15…30 — внутри с запасом по обе стороны. Значит
 * инвариант держится для КАЖДОГО груза и на ЛЮБОМ плече, а не в одном
 * разобранном примере. Именно на этом прошлая версия и сломалась: сходимость
 * считалась на зерне и не перепроверялась на топливе.
 *
 * ГРАНИЦА СНИЗУ. На коротких плечах постоянная часть h перевешивает, и кольцо
 * с порожним возвратом снова становится выгодным. Порог:
 *
 *     L < m·h·p / (2c − m·t·p)
 *
 * Связывает его МАКСИМАЛЬНАЯ надбавка, а не минимальная: чем дороже груз, тем
 * выше порог. При p = 1.2 это 504 / 6.24 ≈ 81 км против самого короткого ребра
 * карты в 110 км (Тула — Калуга). Проверяется тестом: появится ребро короче —
 * инвариант на нём сломается.
 *
 * ПОРОГ РЕГУЛИРУЕТСЯ ПЛАТОЙ ЗА ПОГРУЗКУ, А НЕ ТАРИФОМ. Это неочевидно и стоило
 * одной итерации: снижать t, чтобы опустить порог, бессмысленно — оно
 * одновременно уменьшает знаменатель, и порог почти не двигается, зато вся
 * экономика становится теснее и двух гружёных плеч перестаёт хватать на
 * зарплату. Двигать надо h.
 *
 * ЗАВИСИМОСТЬ ОТ ГРУЗОПОДЪЁМНОСТИ. Неравенство содержит массу m, то есть
 * привязано к стартовому ЗИЛу с его шестью тоннами. В срезе 4 появятся классы
 * техники, и у двадцатитонника произведение m·t·p вылетит за верхнюю границу:
 * он будет зарабатывать столько, что порожний возврат перестанет его пугать.
 * Лечится тем, что расходы тоже обязаны расти с классом машины — расход
 * топлива уже у машины, обслуживание пока нет. Тест инварианта покраснеет в
 * тот же день, когда это забудут, и это ровно то, зачем он написан.
 *
 * ЧИСЛЕННАЯ СВЕРКА. Орёл → Тула, 183 км, 6 тонн зерна (надбавка 1.0):
 *
 *   выручка     6 × (70 + 3.3 × 183)               ≈  4 043 руб
 *   расходы     183 км × 15 руб                    ≈  2 745 руб
 *   ────────────────────────────────────────────────────────────
 *   гружёное плечо                                 ≈ +1 298 руб
 *   порожний возврат                               ≈ −2 745 руб
 *   кольцо с одним гружёным плечом                 ≈ −1 447 руб
 *   кольцо с двумя гружёными плечами               ≈ +2 596 руб
 *
 * Зарплата в 1 400 за сутки сверху означает, что машина обязана делать больше
 * одного кольца в день.
 */
