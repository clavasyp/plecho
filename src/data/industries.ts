/**
 * Предприятия Центрального федерального округа — узлы производственных цепочек.
 *
 * Города дают спрос, дороги дают расстояние, а этот файл даёт ПРИЧИНУ ехать.
 * Без него карта — просто граф: ездить есть где, а незачем.
 *
 * ГЛАВНОЕ ПРАВИЛО РАЗМЕЩЕНИЯ: источник и переработка одной цепочки никогда не
 * стоят в одном городе. Правило не эстетическое, а экзистенциальное. Элеватор
 * рядом с мельницей — это цепочка, замкнутая внутри забора: зерно доходит до
 * жерновов транспортёром, машина не нужна, и вся игра в этом месте исчезает.
 * Ровно поэтому расстояние между звеньями — не декорация, а сам предмет игры.
 * Инвариант проверяется в industries.test.ts, а не держится на внимательности.
 *
 * ПОЧЕМУ В МОСКВЕ НЕТ НИ ОДНОГО ПРЕДПРИЯТИЯ.
 *
 * Тринадцать миллионов против трёх с половиной у остальных девяти городов
 * вместе. Любое предприятие, поставленное в Москве, отгружало бы продукцию
 * потребителю через дорогу — с нулевым плечом и нулевой выручкой, потому что
 * платят за тонны И километры. Хуже того, исчез бы главный конфликт игры,
 * заложенный ещё в cities.ts: в столицу едет всё, а обратно ехать не с чем.
 * Москва в срезе 2 — чистый спрос, и это её роль, а не пробел в данных.
 *
 * ПЛЕЧИ. Три цепочки намеренно дают три разных типа рейса:
 *
 *   зерно      Орёл → Тула            183 км, одно ребро М-2       короткое
 *   кругляк    Владимир → Рязань      230 км по убитой Р-132       медленное
 *              Тверь → Калуга         365 км через Москву          быстрое
 *   нефть      Брянск → Рязань        499 км южной рокадой         длинное
 *              Смоленск → Ярославль   660 км через Москву          дальнее
 *
 * Пара из середины таблицы — самый содержательный урок карты. ЗИЛ с
 * крейсерскими 70 идёт Владимир → Рязань (230 км, региональная, качество 0.55)
 * почти шесть часов, а Тверь → Калуга (365 км двумя федеральными плечами) —
 * шесть с четвертью. Плюс пять процентов времени за плюс шестьдесят процентов
 * километров, то есть за плюс шестьдесят процентов выручки. Километры и часы —
 * разные валюты, и здесь это видно на конкретных двух рейсах, а не в подсказке.
 *
 * ВНИМАНИЕ ДЛЯ СБОРКИ НАЧАЛЬНОГО СОСТОЯНИЯ. В отличие от CityStatic, тип
 * Industry содержит ИЗМЕНЯЕМОЕ состояние: склад, загрузку, счётчик простоя.
 * Объекты ниже — шаблоны мира, а не сам мир. Класть их в GameState можно
 * только копией (как это делает cloneCities в state.ts), иначе накопленное в
 * одной партии протечёт в следующую и в соседний тест.
 *
 * Всё в ТОННАХ — единица одна на весь проект.
 */

