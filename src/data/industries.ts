// ─── Стартовые склады ──────────────────────────────────────────────────────

/**
 * Сколько суток работы даёт переработке стартовый запас сырья.
 *
 * Партия начинается в 1994-м с ОДНОЙ машиной в Москве. При пустых складах вся
 * переработка встаёт на первом же тике и начинает копить idleTicks раньше, чем
 * игрок вообще успевает доехать: мир наказывал бы за расстояние, а не за
 * решения.
 *
 * Мера — полный круг по САМОЙ ДАЛЬНЕЙ цепочке. Москва → Смоленск порожняком,
 * Смоленск → Ярославль с нефтью через Москву, Ярославль → Москва с топливом:
 * 1320 км, около двадцати двух часов хода для ЗИЛа, то есть примерно сутки.
 * Трое суток запаса — это три таких круга: игрок успевает не только доехать,
 * но и дважды ошибиться маршрутом.
 *
 * Заведомо мало, чтобы спасти цепочку: мельница съедает 50 тонн зерна в сутки,
 * а ЗИЛ везёт шесть. Останавливаться заводам всё равно придётся — но по вине
 * игрока, а не по вине карты, и в этом вся разница.
 */
const STARTUP_INPUT_DAYS = 3

/**
 * Сколько суток выпуска лежит готовым на складе у каждого предприятия.
 *
 * Это «вчерашняя смена, которую никто не вывез». Год старта выбран в state.ts
 * ровно под эту картину — «разваленный автопарк, РАБОТАЮЩИЕ ЕЩЁ советские
 * заводы и пустая ниша частных перевозок». Работающий завод со стерильно
 * пустым складом этой картине противоречит: игрок открывал бы партию не в
 * живом мире, которому нужен транспорт, а на пепелище. Заодно первая машина не
 * стоит у ворот, пока накопится первая тонна.
 */
const STARTUP_OUTPUT_DAYS = 1

/**
 * Стартовый склад предприятия, выведенный из его рецепта.
 *
 * Считается ИЗ RECIPES, а не проставляется руками в таблице. Ставки выпуска
 * будут двигаться при балансировке, и набитый вручную запас разъехался бы с
 * ними молча: цифра «150 тонн зерна» перестала бы означать «три дня работы» и
 * никто бы этого не заметил. Здесь связь выражена формулой и разорваться не
 * может.
 *
 * Округление до целых тонн — сознательное: склад на старте это ДАННЫЕ, и в
 * отладке приятнее видеть 225, чем 224.24999999999997. Дальше производство
 * считает как считает, дробями.
 */
function startingStock(type: IndustryType): Partial<Record<CargoType, Tons>> {
  const recipe = RECIPE_BY_INDUSTRY[type]
  const stock: Partial<Record<CargoType, Tons>> = {}

  stock[recipe.output] = Math.round(recipe.dailyRate * STARTUP_OUTPUT_DAYS)

  // У источников inputs пуст — цикл просто не выполнится, и отдельная ветка
  // «если источник» не нужна: пустота входа уже и есть определение источника.
  for (const input of recipe.inputs) {
    stock[input.type] = Math.round(
      recipe.dailyRate * input.perUnit * STARTUP_INPUT_DAYS,
    )
  }

  return stock
}

