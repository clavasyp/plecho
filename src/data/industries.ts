/**
 * Предприятия мира.
 *
 * Собираются из таблицы, а не пишутся объектами: склад выводится из рецепта
 * (см. startingStock), а счётчики на старте нулевые у всех без исключения —
 * повторять это десять раз руками значило бы десять раз дать себе шанс
 * ошибиться.
 *
 * utilization и idleTicks — ноль, и это не «предприятие стоит». Загрузка
 * описывает ПОСЛЕДНИЙ отработанный тик, а его ещё не было; счётчик простоя
 * начинается с нуля, потому что мир не должен предъявлять игроку время до
 * начала партии.
 */
export const INDUSTRIES: Industry[] = PLACEMENTS.map(([id, type, city]) => ({
  id: industryId(id),
  type,
  cityId: cityId(city),
  stock: startingStock(type),
  utilization: 0,
  idleTicks: 0,
}))

/**
 * Предприятия по идентификатору.
 *
 * Строится из INDUSTRIES по той же причине, что CITIES_BY_ID из CITIES: два
 * независимых списка рано или поздно разъезжаются, а здесь рассинхронизация
 * невозможна по построению.
 */
export const INDUSTRIES_BY_ID: Record<IndustryId, Industry> =
  Object.fromEntries(
    INDUSTRIES.map((industry) => [industry.id, industry]),
  ) as Record<IndustryId, Industry>
