/**
 * Игровой цикл: превращает реальное время в тики симуляции.
 *
 * Шаг фиксированный. Скорость игры меняет только то, сколько тиков успевает
 * пройти за кадр, — сама симуляция про реальное время не знает вообще и потому
 * остаётся детерминированной: те же тики на слабой машине дадут тот же мир.
 */

import { useEffect } from 'react'
import { TICKS_PER_DAY } from '../sim/types'
import { useGameStore } from './store'

/**
 * Доля 0..1 до следующего тика.
 *
 * Обновляется каждый кадр напрямую, МИМО React. Это не оптимизация «на всякий
 * случай»: подписка стора на каждый кадр перерисовывала бы всё дерево 60 раз в
 * секунду ради одного числа, которое нужно только мешам. Рендер читает
 * `clock.alpha` внутри useFrame и двигает матрицы инстансов сам.
 */
export const clock = { alpha: 0 }

/**
 * За сколько реального времени проходят игровые сутки на скорости ×1.
 *
 * Двадцать секунд — масштаб из плана: рейс Москва → Тула (185 км, около трёх
 * игровых часов) виден несколько секунд, игровой год проходит за пару часов.
 * Величина подгоняемая, поэтому она здесь одна и с именем.
 */
const REAL_MS_PER_GAME_DAY = 20_000

/**
 * Длительность одного тика в реальных миллисекундах на скорости ×1.
 *
 * Тик — 15 игровых минут, значит в сутках их TICKS_PER_DAY = 96.
 * Отсюда 20 000 / 96 = 208.33 мс на тик, то есть примерно каждый третий кадр
 * при 60 Гц. Считаем из TICKS_PER_DAY, а не вбиваем числом: если шаг симуляции
 * когда-нибудь изменится, сутки обязаны остаться двадцатью секундами — иначе
 * вместе с точностью модели молча поедет темп всей игры.
 */
export const TICK_MS = REAL_MS_PER_GAME_DAY / TICKS_PER_DAY

/**
 * Потолок тиков за кадр — защита от «спирали смерти».
 *
 * Свёрнутая вкладка не получает кадров, и при возврате накопленный долг может
 * измеряться минутами. Отработать его целиком означает повесить вкладку, а
 * отрабатывать по чуть-чуть — несколько секунд смотреть, как мир мотает время
 * вперёд. Оба варианта хуже, чем просто потерять простой.
 */
const MAX_TICKS_PER_FRAME = 10

/** Крутит симуляцию через requestAnimationFrame, пока смонтирован компонент. */
export function useGameLoop(): void {
  useEffect(() => {
    let frame = 0
    /** Отметка предыдущего кадра; null — «времени ещё не прошло». */
    let last: number | null = null
    /** Недоработанное реальное время в масштабе ×1, миллисекунды. */
    let accumulator = 0

    const step = (now: number) => {
      frame = requestAnimationFrame(step)

      // Состояние читаем через getState, а не через хук: цикл не должен
      // перезапускаться при каждой смене скорости и уж тем более при каждом
      // тике — он живёт столько же, сколько приложение.
      const { speed, advance } = useGameStore.getState()

      if (speed === 0) {
        // Пауза: время не копится, alpha замирает — мир стоит ровно там, где
        // его поставили, а не доезжает остаток тика. Отметку сбрасываем, чтобы
        // после снятия паузы весь простой не влетел в аккумулятор одним куском.
        last = null
        return
      }

      const elapsed = last === null ? 0 : now - last
      last = now

      accumulator += elapsed * speed

      const due = Math.floor(accumulator / TICK_MS)
      if (due > 0) {
        // Долг списываем целиком, а догоняем не больше потолка: остаток из
        // свёрнутой вкладки не должен превратиться в очередь тиков, которую
        // цикл будет разгребать ещё несколько секунд после возврата.
        accumulator -= due * TICK_MS
        advance(Math.min(due, MAX_TICKS_PER_FRAME))
      }

      clock.alpha = accumulator / TICK_MS
    }

    frame = requestAnimationFrame(step)
    return () => cancelAnimationFrame(frame)
  }, [])
}
