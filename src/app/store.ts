/**
 * Сид мира. Зафиксирован константой, а не взят из времени запуска: пока идёт
 * разработка, каждый прогон должен показывать один и тот же мир — иначе
 * «машина проскочила Тверь» не воспроизводится ни в тесте, ни у соседа.
 * Выбор сида игроком появится вместе с экраном новой партии.
 */
export const WORLD_SEED = 20260808

/**
 * Готовое решение конкурента: что делать и почему.
 *
 * РОВНО ТО, ЧТО ВОЗВРАЩАЕТ АДАПТЕР МОДЕЛИ (askGemini в app/ai/gemini.ts), плюс
 * отметка о происхождении. Команды и объясняющая их мысль приходят ОДНОЙ
 * структурой и кладутся в состояние ОДНИМ действием намеренно: разнеси их по
 * двум вызовам, и однажды в ленте появится объяснение к командам, которые не
 * применились, — а это ровно тот случай, когда интерфейс врёт убедительно.
 */
export type RivalPlan = {
  commands: readonly Command[]
  thought: string
  /**
   * Ложь — план подставлен скриптовым запасным вариантом.
   *
   * Флаг доезжает до игрока (Thought.fromModel) и обязан быть честным: тихая
   * подмена модели скриптом обесценивает ленту рассуждений целиком.
   */
  fromModel: boolean
}

export type GameStore = {
  /** Текущее состояние симуляции. */
  state: GameState
  /** Состояние на предыдущем тике — только для интерполяции в рендере. */
  prev: GameState
  /** Ноль — пауза. Влияет лишь на число тиков за кадр, не на логику. */
  speed: GameSpeed
  setSpeed: (speed: GameSpeed) => void
  /** Продвинуть симуляцию на N тиков. Вызывается из игрового цикла. */
  advance: (ticks: number) => void
  /**
   * Отправить свободную машину игрока в город разовым рейсом.
   *
   * Разовые рейсы никуда не делись вместе с появлением линий: ими удобно
   * перегнать машину к началу будущего кольца и попробовать плечо руками до
   * того, как строить под него сеть.
   *
   * Команда достаётся машине БЕЗ ЛИНИИ. Машине на линии её выдавать
   * бессмысленно — фаза диспетчеризации следующего же тика перепишет маршрут
   * своим, и игрок увидел бы, что кнопка «отправить» просто не работает, без
   * малейшего намёка почему. Снимите машину с линии, и она снова слушается.
   */
  /**
   * Отправить машину игрока в город разовым рейсом.
   *
   * `vehicleId` необязателен: без него берётся первая свободная машина парка.
   * Появился он не для удобства, а потому что «машина игрока» перестала быть
   * однозначной — парк вырос, и выбор первой попавшейся оказался тихой
   * ошибкой: сквозной тест гонял по разовым рейсам ту самую машину, которая
   * работала на линии, и мерил в итоге не то, что думал.
   */
  dispatchTo: (destination: CityId, vehicleId?: VehicleId) => void

  /**
   * Завести линию. Возвращает идентификатор — по нему на неё ставят машины.
   *
   * Линию из одной остановки создать можно, и это не недосмотр: игрок собирает
   * кольцо по одной остановке, и запрещать промежуточное состояние значило бы
   * требовать заполнить форму целиком, прежде чем показать результат.
   * Неработающей такая линия становится сама собой — ездить между одной
   * остановкой и ей же некуда.
   */
  createLine: (name: string, stops: Stop[]) => LineId

  /** Переписать остановки существующей линии. Машины остаются на ней. */
  updateLine: (id: LineId, stops: Stop[]) => void

  /** Убрать линию. Её машины остаются в парке и встают без задания. */
  deleteLine: (id: LineId) => void

  /** Поставить машину на линию или снять с неё (lineId = null). */
  assignVehicle: (vehicleId: VehicleId, lineId: LineId | null) => void

  /**
   * Купить машину указанного класса в домашнем городе.
   *
   * Приезжает ГОЛЫЙ ТЯГАЧ: без прицепа и без водителя. Это не экономия на
   * реализации, а суть среза — машина в этой игре собирается из трёх решений, и
   * покупка только первое из них. Купивший один тягач видит, что тот не может
   * ни взять груз, ни тронуться с места, и узнаёт правило игры за один клик, а
   * не из справки.
   *
   * Не хватает денег или класс ещё не выпускается — ничего не происходит.
   */
  buyVehicle: (classId: string) => void

  /**
   * Поставить машине прицеп. Старый списывается без возврата денег.
   *
   * Прицеп, который классу не подходит, не ставится: полуприцеп-цистерну на
   * бортовой ЗИЛ не повесить, и подобрать «ближайший подходящий» за игрока
   * нельзя — он выбирает специализацию машины, а не просит помочь.
   */
  buyTrailer: (vehicleId: VehicleId, trailer: TrailerType) => void

  /** Посадить водителя за машину или отправить в резерв (vehicleId = null). */
  assignDriver: (driverId: DriverId, vehicleId: VehicleId | null) => void

  /** Нанять водителя. Он приходит в резерв, за руль его сажают отдельно. */
  hireDriver: () => void

  /** Уволить водителя. Его машина остаётся в парке и встаёт без водителя. */
  fireDriver: (driverId: DriverId) => void

  /**
   * Построить терминал, склад или хаб в городе.
   *
   * ЕДИНСТВЕННОЕ ДЕЙСТВИЕ СРЕЗА 5, И ОНО ЖЕ ПЕРВЫЙ В ИГРЕ РАСХОД, КОТОРЫЙ НЕ
   * КОНЧАЕТСЯ. Машину можно продать, водителя уволить, а постройка платит
   * содержание каждые сутки до самого сноса. Поэтому её и стоит строить только
   * туда, где машины реально стоят в очереди: терминал в тихом городе тихо
   * съедает прибыль, и это не наказание, а суть решения.
   *
   * Нет денег, город неизвестен, такая постройка уже стоит — ничего не
   * происходит. Молчаливый отказ здесь по тому же доводу, что и у покупки
   * машины: кнопка в интерфейсе недоступна по тем же условиям, и до сюда
   * доходит только гонка между кликом и уходящими на топливо деньгами.
   */
  build: (cityId: CityId, type: BuildingType) => void

  /**
   * Снести постройку. Груз, лежащий на её складе, пропадает.
   *
   * Своя, а не любая: чужие терминалы игроку не подчиняются. Проверка владельца
   * стоит здесь, а не в симуляции, — там снос законно требуется и конкуренту.
   */
  demolish: (buildingId: BuildingId) => void

  /** Провести плановое ТО за деньги: обнулить счётчик пробега до обслуживания. */
  serviceVehicle: (vehicleId: VehicleId) => void

  /**
   * Отремонтировать сломанную машину за деньги.
   *
   * В контракте среза этого действия нет, и оно всё равно здесь: без него
   * сломавшаяся машина стоит до конца партии, продолжая проедать зарплату
   * водителя. Кнопка, которой нет, — это не «меньше интерфейса», а тупик, из
   * которого игрок не выходит.
   */
  repairVehicle: (vehicleId: VehicleId) => void

  /**
   * Положить конкуренту готовое решение: команды в очередь, мысль в ленту.
   *
   * ЕДИНСТВЕННАЯ ДВЕРЬ ИЗ СЕТИ В СИМУЛЯЦИЮ, и ведёт она не в тик, а в СОСТОЯНИЕ.
   * Асинхронный адаптер (app/ai/gemini.ts) отвечает когда угодно и сколько
   * угодно раз; всё, что он может сделать, — оставить здесь список команд.
   * Разберёт их фаза команд на ближайшем тике, проверит теми же правилами, что и
   * ход игрока, и незаконное отбросит. Модель предлагает — симуляция решает.
   *
   * Команды ДОБАВЛЯЮТСЯ к очереди, а не заменяют её: два ответа, пришедшие между
   * двумя тиками, — это два решения одной компании, и молча потерять первое
   * нельзя. Обычно очередь пуста, потому что тик вычищает её каждый раз.
   *
   * ЗА ИГРОКА ПЛАН НЕ ПРИНИМАЕТСЯ НИКОГДА. Игрок — это тот, кто решает сам;
   * подставить ему команду отсюда значило бы сыграть за него, а разобраться,
   * почему грузовик уехал сам, он не смог бы ничем.
   */
  deliverPlan: (companyId: CompanyId, plan: RivalPlan) => void

  /**
   * Передать компанию модели или вернуть скрипту.
   *
   * Нужно ровно затем, чтобы у компании был ОДИН хозяин. Фаза решений в тике
   * ведёт компании со скриптом (runAi в sim/tick.ts) и не трогает помеченные
   * моделью, — значит адаптер, взявший компанию себе, обязан сказать об этом
   * состоянию. Иначе конкурент получит два решения в сутки и будет дёргаться
   * между двумя стратегиями, а игрок увидит в ленте спор двух голосов.
   *
   * Игрока перевести нельзя: 'человек' — это не одна из стратегий, а отсутствие
   * автомата за спиной.
   */
  setController: (companyId: CompanyId, controller: 'скрипт' | 'модель') => void
}

const initialState = createInitialState(WORLD_SEED)

export const useGameStore = create<GameStore>((set, get) => ({
  state: initialState,
  // До первого тика интерполировать нечего, поэтому оба снимка — один объект.
  prev: initialState,
  speed: 1,

  setSpeed: (speed) => set({ speed }),

  /*
   * РАЗОВЫЙ РЕЙС ОСТАЛСЯ СВОИМ, потому что такой команды в перечислении Command
   * нет вовсе — и это не пробел, а решение. Конкурент сетью не «щупает» плечи:
   * он либо строит кольцо, либо не строит. Разовый рейс существует ради человека,
   * который хочет попробовать направление руками, прежде чем проектировать под
   * него линию, и переносить его в общий набор значило бы дать модели способ
   * гонять машины мимо всякой сети.
   */
  dispatchTo: (destination, vehicleId) =>
    set((store) => {
      const state = store.state
      /*
       * Машина под погрузкой и машина в очереди на пост не отправляются никуда,
       * и это то же правило, по которому их не трогает диспетчеризация линий
       * (logistics/line.ts). Без него кнопка «отправить» становится способом
       * ОБОЙТИ пропускную способность: нажал — и машина уехала порожней прямо
       * из-под рампы, не отстояв своё и никого не пропустив вперёд. Срез 5
       * отменялся бы одним кликом.
       *
       * Такая машина в поиске просто пропускается, а не блокирует команду
       * целиком: свободная машина в парке, если она есть, поедет.
       */
      const free = (v: Vehicle) =>
        v.ownerId === state.playerId &&
        v.lineId === null &&
        v.serviceTicksLeft === 0 &&
        v.queuedTicks === 0

      // Указали машину — едет она и только она. Не указали — первая свободная.
      const vehicle =
        vehicleId === undefined
          ? Object.values(state.vehicles).find(free)
          : (() => {
              const named = state.vehicles[vehicleId]
              return named !== undefined && free(named) ? named : undefined
            })()
      if (vehicle === undefined) return store

      // Откуда считать путь: из города, если машина стоит, и из того города,
      // КУДА она едет, если она уже на ребре. Развернуть фуру посреди трассы
      // нельзя — она доедет до ближайшего узла и только там свернёт.
      const origin =
        vehicle.position.kind === 'узел'
          ? vehicle.position.nodeId
          : otherEndOf(state, vehicle.position.edgeId, vehicle.position.fromId)

      if (origin === null) return store

      const route = findRoute(
        buildGraph(state.world.edges),
        origin,
        destination,
        vehicle.cruiseKmh,
      )
      if (route === null) return store

      return {
        ...store,
        state: {
          ...state,
          vehicles: {
            ...state.vehicles,
            [vehicle.id]: setRoute(vehicle, route),
          },
        },
      }
    }),

  /*
   * СОЗДАНИЕ ЛИНИИ ОСТАЛОСЬ СВОИМ, ХОТЯ КОМАНДА «создать-линию» В ПЕРЕЧИСЛЕНИИ
   * ЕСТЬ. Два довода, и каждого хватило бы по отдельности.
   *
   *   ИДЕНТИФИКАТОР. Команда возвращает состояние, а не ключ созданной линии, —
   *   иначе она не была бы командой. Интерфейсу же ключ нужен НЕМЕДЛЕННО: на
   *   только что заведённое кольцо тут же ставят машины. Вылавливать его
   *   сравнением ключей до и после — приём, который работает ровно до того дня,
   *   когда команда начнёт создавать что-то ещё.
   *
   *   ПУСТАЯ ЛИНИЯ. Редактор заводит кольцо БЕЗ ОСТАНОВОК и наполняет его
   *   кликами по карте (LineEditor.tsx), и это не недосмотр, а способ работы:
   *   требовать заполненную форму до показа результата значит проектировать сеть
   *   вслепую. Для конкурента же «создать линию без остановок» — бессмыслица,
   *   которую isLegal обязана отбрасывать: у модели это первый способ потратить
   *   ход впустую. Одно и то же имя носят две разные операции, и сводить их в
   *   одну проверку — значит испортить обе.
   */
  createLine: (name, stops) => {
    const state = get().state
    const owner = state.companies[state.playerId]
    // Идентификатор считается ДО set: сигнатура обязана его вернуть, иначе
    // поставить машину на только что созданную линию будет нечем.
    const id = nextLineId(owner.lines)

    set((store) => {
      const line: Line = {
        id,
        name,
        stops: copyStops(stops),
        assignedVehicles: [],
      }
      return withPlayer(store, (company) => ({
        ...company,
        lines: { ...company.lines, [id]: line },
      }))
    })

    return id
  },

  /*
   * ПРАВКА ЛИНИИ ТОЖЕ ОСТАЛАСЬ СВОЕЙ, и здесь причина простая: команды «изменить
   * линию» в перечислении Command нет вовсе. Собрать её из «удалить» плюс
   * «создать» нельзя — удаление снимает с линии весь её парк (машины встают без
   * задания), то есть перестановка одной остановки останавливала бы кольцо.
   * Конкурент этого действия лишён и обходится пересозданием: у него правка
   * линии — редкое событие, у игрока — основная работа.
   */
  updateLine: (id, stops) =>
    set((store) => {
      const company = store.state.companies[store.state.playerId]
      const line = company.lines[id]
      if (line === undefined) return store

      const next = copyStops(stops)

      // Остановок стало меньше — индекс машины может смотреть за конец списка.
      // Такая машина не «поедет к остановке номер семь», её просто некуда
      // диспетчеризовать, и молча оставить битый индекс в сохранении нельзя.
      const vehicles = mapVehicles(store.state.vehicles, (vehicle) =>
        vehicle.lineId === id && vehicle.stopIndex >= next.length
          ? { ...vehicle, stopIndex: 0, route: [] }
          : vehicle,
      )

      return withPlayer(
        { ...store, state: { ...store.state, vehicles } },
        (target) => ({
          ...target,
          lines: { ...target.lines, [id]: { ...line, stops: next } },
        }),
      )
    }),

  deleteLine: (id) =>
    set((store) => playerCommand(store, { kind: 'удалить-линию', lineId: id })),

  assignVehicle: (vehicleId, lineId) =>
    set((store) => playerCommand(store, { kind: 'назначить-машину', vehicleId, lineId })),

  buyVehicle: (classId) =>
    set((store) => playerCommand(store, { kind: 'купить-машину', classId })),

  buyTrailer: (vehicleId, trailer) =>
    set((store) => playerCommand(store, { kind: 'купить-прицеп', vehicleId, trailer })),

  assignDriver: (driverId, vehicleId) =>
    set((store) => playerCommand(store, { kind: 'посадить-водителя', driverId, vehicleId })),

  hireDriver: () =>
    set((store) => playerCommand(store, { kind: 'нанять-водителя' })),

  fireDriver: (driverId) =>
    set((store) => playerCommand(store, { kind: 'уволить-водителя', driverId })),

  build: (cityId, type) =>
    set((store) => playerCommand(store, { kind: 'построить', cityId, type })),

  demolish: (buildingId) =>
    set((store) => playerCommand(store, { kind: 'снести', buildingId })),

  serviceVehicle: (vehicleId) =>
    set((store) => playerCommand(store, { kind: 'обслужить', vehicleId })),

  /*
   * ЕДИНСТВЕННОЕ ДЕЙСТВИЕ ПАРКА, ОСТАВШЕЕСЯ СВОИМ, и причина у него та же, что у
   * разового рейса: команды «починить» в перечислении Command нет. Заводить её
   * там было бы правильно — конкуренту тоже приходится чинить машины, и сейчас
   * он делает это... никак, — но types.ts в этом срезе контракт, и дописать в
   * него команду нельзя. Пока ремонт остаётся действием интерфейса, а проверка
   * «машина своя» — здесь, в applyToOwnVehicle.
   */
  repairVehicle: (vehicleId) =>
    set((store) => applyToOwnVehicle(store, vehicleId, simRepairVehicle)),

  deliverPlan: (companyId, plan) =>
    set((store) => {
      const state = store.state

      const company: Company | undefined = state.companies[companyId]
      if (company === undefined) return store
      // За игрока модель не играет. Разбор — у объявления действия выше.
      if (companyId === state.playerId) return store
      // Банкроту решать нечего: партия для него окончена, и очередь команд у
      // него разбиралась бы вечно без единого законного хода.
      if (company.bankrupt) return store

      const queued = [...(company.pendingCommands ?? []), ...plan.commands]

      const next = rememberThought(
        queued.length === company.pendingCommands?.length
          ? company
          : { ...company, pendingCommands: queued },
        { tick: state.tick, text: plan.thought, fromModel: plan.fromModel },
      )

      // Пустой план с пустой мыслью — не событие. Молча возвращаем тот же стор,
      // чтобы не будить подписчиков и не сбивать интерполяцию рендера.
      if (next === company) return store

      return {
        ...store,
        state: {
          ...state,
          companies: { ...state.companies, [companyId]: next },
        },
      }
    }),

  setController: (companyId, controller) =>
    set((store) => {
      const state = store.state

      const company: Company | undefined = state.companies[companyId]
      if (company === undefined) return store
      if (companyId === state.playerId) return store
      if (company.controller === controller) return store

      return {
        ...store,
        state: {
          ...state,
          companies: {
            ...state.companies,
            [companyId]: { ...company, controller },
          },
        },
      }
    }),

  advance: (ticks) =>
    set((store) => {
      // Кадр без тика — норма, а не исключение: тик длиннее кадра. Возвращаем
      // тот же объект, чтобы zustand не будил подписчиков впустую.
      if (ticks < 1) return store

      let prev = store.state
      let state = store.state
      for (let i = 0; i < ticks; i++) {
        prev = state
        state = tick(state)
      }

      // prev — ровно один тик до state, даже когда за кадр их прошло несколько:
      // интерполяции нужен последний отрезок пути, а не начало всей пачки.
      return { prev, state }
    }),
}))

// ─── Правка состояния из интерфейса ────────────────────────────────────────
//
// Все действия ниже меняют GameState в обход тика, и это единственное место в
// проекте, где так можно. Правило то же, что и в симуляции: НИКАКОЙ МУТАЦИИ.
// Состояние пересобирается новыми объектами до самого изменённого поля, потому
// что рендер сравнивает снимки по ссылке, а сохранение — это JSON того самого
// объекта, который сейчас в сторе.

/**
 * Сходить за игрока ОДНОЙ КОМАНДОЙ — теми же правилами, что и конкурент.
 *
 * ГЛАВНАЯ ФУНКЦИЯ ФАЙЛА ПОСЛЕ СРЕЗА 6, и вся её ценность в том, чего в ней нет:
 * ни цен, ни проверок владельца, ни лимитов застройки, ни календаря доступности
 * техники. Всё это переехало в isLegal (sim/ai/commands.ts) и живёт там в одном
 * экземпляре на игрока, скриптового конкурента и языковую модель. Пока правило
 * одно, «конкурент играет честно» проверяется одним тестом; заведи стор вторую
 * копию — и проверять пришлось бы совпадение двух копий, а совпадали бы они
 * ровно до первой перебалансировки.
 *
 * ЗАКОННОСТЬ ЗДЕСЬ НЕ СПРАШИВАЕТСЯ ОТДЕЛЬНО: applyCommand проверяет её сама и
 * при отказе возвращает ТОТ ЖЕ объект состояния по ссылке. Этого стору
 * достаточно, а второй вызов isLegal был бы второй нормализацией той же команды
 * на каждое нажатие кнопки. Молчаливый отказ вместо исключения — то же правило,
 * что и раньше: кнопка в интерфейсе недоступна по тем же условиям, и до сюда
 * доходит только гонка между кликом и уходящими на топливо деньгами; ронять на
 * ней стор значит терять всю партию из-за одного нажатия.
 *
 * Игрок ходит только за себя: идентификатор компании берётся из состояния, а не
 * из аргумента. Дать интерфейсу выбирать, за кого ходить, значило бы завести в
 * игре второй способ управлять конкурентом — мимо очереди команд и мимо
 * проверки.
 */
function playerCommand(store: GameStore, command: Command): GameStore {
  const state = store.state
  const next = applyCommand(state, state.playerId, command)
  return next === state ? store : { ...store, state: next }
}

/**
 * Заменить компанию игрока и вернуть новый стор.
 *
 * Обёртка существует затем, чтобы четыре действия не переписывали одну и ту же
 * лесенку `store → state → companies → player` каждое по-своему. Пропущенный
 * уровень копирования в такой лесенке — самый дорогой из тихих дефектов:
 * состояние выглядит правильным, а рендер перестаёт замечать изменения.
 */
function withPlayer(
  store: GameStore,
  patch: (company: Company) => Company,
): GameStore {
  const state = store.state
  const company = state.companies[state.playerId]
  if (company === undefined) return store

  return {
    ...store,
    state: {
      ...state,
      companies: { ...state.companies, [state.playerId]: patch(company) },
    },
  }
}

/**
 * Позвать команду симуляции для СВОЕЙ машины и завернуть результат в стор.
 *
 * Обёртка нужна ради одного правила, повторять которое в каждой команде дорого:
 * из интерфейса игрок распоряжается только своим парком. Проверка владельца
 * стоит здесь, а не в самой симуляции, потому что в симуляции этих команд может
 * законно требовать и конкурент — ремонтировать свои машины ему никто не
 * запрещает.
 *
 * Команды износа (ТО и ремонт) написаны в sim/logistics/wear.ts и деньги
 * списывают сами: цена работ считается от класса и износа машины, и повторять
 * этот расчёт в сторе значило бы завести вторую копию прейскуранта.
 */
function applyToOwnVehicle(
  store: GameStore,
  vehicleId: VehicleId,
  command: (state: GameState, id: VehicleId) => GameState,
): GameStore {
  const state = store.state
  const vehicle = state.vehicles[vehicleId]
  if (vehicle === undefined || vehicle.ownerId !== state.playerId) return store

  const next = command(state, vehicleId)
  // Команда вернула то же состояние (работы не требуется) — не будим
  // подписчиков впустую.
  return next === state ? store : { ...store, state: next }
}

/** Парк, прогнанный через преобразование. Неизменённые машины — по ссылке. */
function mapVehicles(
  vehicles: Record<VehicleId, Vehicle>,
  patch: (vehicle: Vehicle) => Vehicle,
): Record<VehicleId, Vehicle> {
  const next: Record<VehicleId, Vehicle> = {}
  for (const id of Object.keys(vehicles) as VehicleId[]) {
    next[id] = patch(vehicles[id])
  }
  return next
}

/**
 * Глубокая копия остановок.
 *
 * Массивы грузов копируются поимённо, а не спредом верхнего уровня. Остановки
 * приходят из формы интерфейса, которая продолжает жить своей жизнью после
 * нажатия «сохранить»: общий массив означал бы, что следующая правка формы
 * задним числом меняет уже работающую линию.
 */
function copyStops(stops: readonly Stop[]): Stop[] {
  return stops.map((stop) => ({
    nodeId: stop.nodeId,
    unload: [...stop.unload],
    load: [...stop.load],
  }))
}

/**
 * Следующий свободный номер в семействе идентификаторов вида «line-3».
 *
 * Считается МАКСИМУМ, а не количество. Количество после удаления линии выдало
 * бы номер, который уже занят: удалили «line-2» из трёх, и следующая линия
 * получила бы «line-3» — то есть чужой идентификатор, вместе с чужими машинами
 * в assignedVehicles.
 */
function nextNumber(keys: readonly string[], prefix: string): number {
  let max = 0
  for (const key of keys) {
    if (!key.startsWith(prefix)) continue
    const suffix = Number(key.slice(prefix.length))
    if (Number.isInteger(suffix) && suffix > max) max = suffix
  }
  return max + 1
}

function nextLineId(lines: Record<LineId, Line>): LineId {
  return toLineId(`line-${nextNumber(Object.keys(lines), 'line-')}`)
}

