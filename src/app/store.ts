/** Дальний конец ребра относительно того, откуда выехали. */
function otherEndOf(
  state: GameState,
  edgeId: EdgeId,
  fromId: CityId,
): CityId | null {
  const edge = state.world.edges[edgeId]
  if (edge === undefined) return null
  return edge.from === fromId ? edge.to : edge.from
}

