/**
 * Адаптер к Gemini — ЕДИНСТВЕННОЕ МЕСТО В ПРОЕКТЕ, ГДЕ ЕСТЬ СЕТЬ.
 *
 * Оно живёт в src/app именно поэтому. src/sim обязан оставаться чистым и
 * запускаться в Node без окружения: от этого зависят тесты экономики, прогоны
 * баланса на сотни игровых лет и воспроизведение багов по сохранению. Страж —
 * tests/sim-purity.test.ts, и он прямо запрещает fetch внутри симуляции.
 *
 * ГЛАВНОЕ СВОЙСТВО ФАЙЛА: ОН НЕ УМЕЕТ ЛОМАТЬ ИГРУ. Любая беда — нет ключа, нет
 * сети, таймаут, лимит, пятисотка, мусор вместо JSON, ответ на другом языке —
 * заканчивается одним и тем же: возвращается null, и вызывающий берёт скриптовый
 * путь (sim/ai/scripted.ts). Ни исключений наружу, ни записей в консоль: упавший
 * Gemini не должен ни останавливать конкурентов, ни засыпать игроку консоль
 * красным. «Модель недоступна» — это штатное состояние игры, а не происшествие.
 *
 * КЛЮЧ НИКОГДА НЕ ПОПАДАЕТ НИ В КОД, НИ В РЕПОЗИТОРИЙ. Он берётся только из
 * import.meta.env.VITE_GEMINI_API_KEY (.env лежит в .gitignore), читается в
 * момент вызова, а не при загрузке модуля, и уходит ЗАГОЛОВКОМ, а не параметром
 * адреса: адреса попадают в логи прокси, в историю и в отчёты об ошибках, и ключ
 * из них потом не вынуть.
 *
 * Нет ключа — сетевого вызова не происходит вовсе. Это не оптимизация: запрос
 * без ключа вернул бы 400 и красную строку в консоли на каждый игровой месяц у
 * каждого, кто просто запустил игру.
 */

import type { CompetitorPersonality } from '../../sim/types'
import { buildPrompt, parseResponse } from './prompt'
import type { ModelPlan, Snapshot } from './prompt'

/**
 * Модель.
 *
 * ВЫБРАН САМЫЙ ДЕШЁВЫЙ ИЗ ПРИГОДНЫХ, и пригодность здесь означает три вещи:
 * строгий JSON на выходе (responseMimeType), ответ за секунды, а не за минуты, и
 * цена, при которой конкуренты могут думать всю партию. Flash-lite — младшая
 * модель линейки: рассуждение у неё по умолчанию выключено, и это ровно то, что
 * нужно, — от конкурента требуется не доказательство теоремы, а выбор из
 * десятка ходов по готовому снимку.
 *
 * Задача при этом не «умная», а УЗКАЯ: правила в системной инструкции, состояние
 * в JSON, ответ — список из готового перечисления. Старшая модель здесь купила бы
 * чуть более связные фразы в ленте рассуждений за кратную цену и лишние секунды
 * ожидания.
 *
 * Имя лежит константой, потому что имена моделей живут недолго. Снятую с
 * обслуживания модель поставщик отвергнет ошибкой, ошибка превратится в null, и
 * игра продолжится на скриптовых конкурентах — то есть худшее последствие
 * устаревшей строки здесь это «модель молчит», а не сломанная партия.
 */
export const GEMINI_MODEL = 'gemini-2.5-flash-lite'

/** Адрес API. Прямой вызов Gemini, не Vertex: ключ вместо облачного проекта. */
export const GEMINI_ENDPOINT = `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`

/**
 * Сколько ждать ответа, миллисекунды.
 *
 * Пятнадцать секунд — это меньше, чем игровые сутки на самой медленной скорости
 * (двадцать реальных секунд на сутки, см. loop.ts), и вдвое больше типичного
 * ответа flash-модели. Смысл предела не в скорости, а в ОСВОБОЖДЕНИИ КАНАЛА:
 * пока запрос висит, конкурент не получает решения ни от модели, ни от скрипта,
 * и лучше сходить скриптом через пятнадцать секунд, чем ждать вечно.
 */
export const REQUEST_TIMEOUT_MS = 15_000

/**
 * Минимальный промежуток между запросами, миллисекунды.
 *
 * Конкурентов трое, и первый их месяц наступает в один и тот же день — то есть
 * запросы идут пачкой. Промежуток растаскивает пачку по времени и заодно
 * защищает от главного способа сжечь квоту: цикл, который на каждом кадре
 * решает, что пора спросить.
 *
 * Четыре секунды на скорости ×1 — это примерно пятая часть игровых суток. Ход
 * конкурента от такой задержки не страдает: думает он раз в игровой месяц.
 */
export const MIN_REQUEST_GAP_MS = 4_000

/**
 * Пауза после отказа поставщика, миллисекунды.
 *
 * Лимит (429) и пятисотка означают одно: сейчас не время. Долбиться дальше — это
 * либо квота в ноль, либо бан по адресу, и оба исхода стоят дороже, чем минута
 * тишины: партия на скриптовых конкурентах идёт как ни в чём не бывало.
 */
export const COOLDOWN_MS = 60_000

/**
 * Потолок ответа в токенах.
 *
 * План — это до двенадцати команд (MAX_COMMANDS_PER_TICK) и одна фраза. Две
 * тысячи токенов покрывают это с запасом втрое, а обрезанный по потолку ответ —
 * это порванный JSON, то есть потерянный ход. Запас дешёвый: платят за
 * фактические токены, а не за потолок.
 */
export const MAX_OUTPUT_TOKENS = 2_048

/**
 * Температура.
 *
 * Не ноль. Характеры обязаны отличаться не только выбором кольца, но и манерой
 * речи в ленте рассуждений, а нулевая температура делает всех конкурентов одним
 * и тем же вежливым голосом. И не единица: решение принимается по числам из
 * снимка, и фантазия здесь оборачивается незаконными командами, то есть
 * потерянным ходом.
 */
export const TEMPERATURE = 0.7

/**
 * Когда разрешён следующий запрос. Общий для всех компаний.
 *
 * Модульная переменная, а не поле объекта, и это осознанно: квота у ключа ОДНА
 * на всё приложение. Заведи счётчик на каждого конкурента — и трое сложат свои
 * «можно» в три раза больше запросов, чем разрешал каждый по отдельности.
 */
let nextAllowedAt = 0

/** Ключ или null. Читается при вызове: подмена в тестах обязана работать. */
export function geminiKey(): string | null {
  const key: unknown = import.meta.env?.VITE_GEMINI_API_KEY
  if (typeof key !== 'string') return null

  const trimmed = key.trim()
  return trimmed === '' ? null : trimmed
}

/**
 * Есть ли чем звонить.
 *
 * По этому ответу слой приложения решает, забирать ли конкурентов себе
 * (runner.ts). Нет ключа — компании остаются за скриптом, и тик ведёт их сам:
 * игра без ключа обязана быть полной, а не «игрой без конкурентов».
 */
export function hasGeminiKey(): boolean {
  return geminiKey() !== null
}

/**
 * Сбросить паузу между запросами.
 *
 * Нужно тестам и только им: модульное состояние переживает отдельный случай, и
 * тест, проверяющий отказ по лимиту, иначе испортил бы следующий за собой.
 */
export function resetGeminiThrottle(): void {
  nextAllowedAt = 0
}

/** Текст ответа модели, собранный из частей. Пусто — ответа не было. */
function textOf(body: unknown): string {
  if (typeof body !== 'object' || body === null) return ''

  const candidates = (body as { candidates?: unknown }).candidates
  if (!Array.isArray(candidates) || candidates.length === 0) return ''

  const content = (candidates[0] as { content?: unknown }).content
  if (typeof content !== 'object' || content === null) return ''

  const parts = (content as { parts?: unknown }).parts
  if (!Array.isArray(parts)) return ''

  let out = ''
  for (const part of parts) {
    const piece = (part as { text?: unknown }).text
    if (typeof piece === 'string') out += piece
  }
  return out
}

/**
 * Спросить модель. Возвращает план или null.
 *
 * NULL — ЭТО ПОЛОВИНА КОНТРАКТА, а не признак поломки: нет сети, нет ключа,
 * кончился лимит, пришёл невалидный ответ. Вызывающий обязан взять скриптовый
 * путь, и тогда игрок не заметит разницы (кроме честной отметки fromModel в
 * ленте рассуждений).
 *
 * Функция НИЧЕГО НЕ ЗНАЕТ ПРО СОСТОЯНИЕ ИГРЫ: на входе готовый снимок, на выходе
 * данные. Ни стора, ни тика, ни побочных эффектов, кроме самого запроса, — иначе
 * граница между сетью и симуляцией проходила бы не здесь, а где придётся.
 */
export async function askGemini(
  snapshot: Snapshot,
  personality: CompetitorPersonality | null,
): Promise<ModelPlan | null> {
  const key = geminiKey()
  // БЕЗ КЛЮЧА — БЕЗ ЗАПРОСА И БЕЗ ШУМА. Это самый частый случай на свете: игру
  // запустили из репозитория, где ключа нет и быть не может.
  if (key === null) return null

  const now = Date.now()
  if (now < nextAllowedAt) return null
  // Промежуток занимается ДО запроса, а не после ответа: иначе два вызова,
  // выпущенные в один момент, оба увидели бы свободный канал.
  nextAllowedAt = now + MIN_REQUEST_GAP_MS

  const prompt = buildPrompt(snapshot, personality)

  // Таймаут через AbortController, а не гонкой промисов: гонка оставляет запрос
  // висеть в сети и платить за токены ответа, который уже никто не прочитает.
  const abort = new AbortController()
  const timer = setTimeout(() => abort.abort(), REQUEST_TIMEOUT_MS)

  try {
    const response = await fetch(GEMINI_ENDPOINT, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        // Заголовком, а не в адресе: см. шапку файла.
        'x-goog-api-key': key,
      },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: prompt.system }] },
        contents: [{ role: 'user', parts: [{ text: prompt.user }] }],
        generationConfig: {
          // Строгий JSON запрашивается У ПОСТАВЩИКА, а не только словами в
          // промпте: так ответ приходит без ```json-ограды и без вступления
          // «Конечно! Вот план:». Разбор всё равно готов и к тому, и к другому
          // (parseJson в prompt.ts) — но чинить то, что можно не ломать, глупо.
          responseMimeType: 'application/json',
          temperature: TEMPERATURE,
          maxOutputTokens: MAX_OUTPUT_TOKENS,
        },
      }),
      signal: abort.signal,
    })

    if (!response.ok) {
      // 429 — квота, 5xx — у поставщика беда. И то и другое лечится паузой, а не
      // повтором. Прочие коды (400 на кривой запрос, 403 на мёртвый ключ)
      // повторять тем более бессмысленно, но и молчать минуту из-за них незачем:
      // они не пройдут и через минуту, а конкуренты в это время живут скриптом.
      if (response.status === 429 || response.status >= 500) {
        nextAllowedAt = Date.now() + COOLDOWN_MS
      }
      return null
    }

    const text = textOf(await response.json())
    if (text === '') return null

    // Ответ модели — НЕДОВЕРЕННЫЕ ДАННЫЕ. Разбор оборонительный и живёт в
    // prompt.ts; сюда возвращается либо готовый план, либо null.
    return parseResponse(text)
  } catch {
    /*
     * СЮДА ПРИХОДИТ ВСЁ ОСТАЛЬНОЕ: обрыв связи, таймаут (AbortError), отказ
     * CORS, невалидный JSON в теле ответа, отсутствующий fetch. Разбирать их по
     * отдельности незачем — ответ у игры на все один и тот же, и он уже написан
     * в sim/ai/scripted.ts.
     *
     * Молча и без console.error: игрок, у которого просто нет ключа или отвалился
     * вайфай, не должен видеть красную консоль каждый игровой месяц.
     */
    return null
  } finally {
    clearTimeout(timer)
  }
}
